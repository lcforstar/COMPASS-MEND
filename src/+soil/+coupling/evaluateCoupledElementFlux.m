function flux = evaluateCoupledElementFlux(SoilVariables, TransportCoefficient, cfg)
%EVALUATECOUPLEDELEMENTFLUX Evaluate one shared water-air-energy flux family.
%
%   Element orientation follows the active COMPASS MATLAB kernel: endpoint 1
%   is deeper, endpoint 2 is shallower, dz is positive, and positive flux is
%   toward endpoint 2 (upward). Gravity-only liquid drainage is negative.
%
%   This shared-flux owner evaluates, from one trial epoch and one set of
%   endpoint constitutive values:
%     - liquid- and gas-phase Darcy volume fluxes [cm s-1];
%     - liquid water, water vapor, and dry-air mass fluxes
%       [g cm-2 s-1];
%     - conductive and component-carried energy fluxes
%       [J cm-2 s-1].
%
%   It deliberately retains the current endpoint arithmetic FEM rule and all
%   active physical terms. It does not apply the legacy gas/heat-only
%   +/-1e5 pressure-gradient clip. raw and applied are therefore identical in
%   this production implementation; the legacy clipped liquid flux is exposed
%   separately
%   for diagnosis. No accepted or trial state is mutated.
%
%   The Darcy liquid pressure head is h=(P_l-P_g)/Gamma_w. The derived
%   Clapeyron shift h_frez belongs to phase equilibrium and the soil-freezing
%   characteristic curve; it is not an additional liquid-pressure potential.
%   grad(h+h_frez) is retained below only as a diagnostic of the inherited
%   gas/heat reconstruction that disagreed with the conservative water row.
%
%   Physical sources: Zeng (2013), Coupled Dynamics in Soil, Eqs. 4.2-4.15;
%   COMPASS V2.0 calculateWaterEquationCoefficients.m,
%   calculateDryAirParameters.m, calculateEnergyParameters.m, and
%   calculateGasDispersivity.m as reached on 2026-08-14.
%   Editor: Jizixing Zhu; Date: 2026-08-14.
    [NL, nD, dz] = validateFrame( ...
        SoilVariables, TransportCoefficient, cfg);
    NN = NL + 1;
    phys = equations.physicalConstants();
    RHOL = phys.RHOL;
    Hc = phys.Hc;
    GammaW = phys.Gamma_w;

    h = SoilVariables.hh(:);
    hFrez = SoilVariables.hh_frez(:);
    temperature = SoilVariables.TT(:);
    pressureGas = SoilVariables.P_gg(:);
    rhoVapor = SoilVariables.RHOV(:);
    rhoDryAir = SoilVariables.RHODA(:);
    latentVapor = SoilVariables.L(:);

    gradH = diff(h) ./ dz;
    gradLiquidHead = diff(h + hFrez) ./ dz;
    gradTemperature = diff(temperature) ./ dz;
    gradPressureGas = diff(pressureGas) ./ dz;

    conductivityLiquid = mean(SoilVariables.KfL_h, 2);
    conductivityThermalLiquid = mean(TransportCoefficient.KL_T, 2);
    diffusivityThermalLiquid = mean(TransportCoefficient.D_Ta, 2);
    gasMobility = mean(TransportCoefficient.Kg, 2);
    molecularDiffusivity = mean(TransportCoefficient.D_V, 2);
    gasVolumeFraction = mean(SoilVariables.Theta_g, 2);
    gasDispersion = gasVolumeFraction .* TransportCoefficient.D_Vg(:);

    klaEnabled = readSwitch(cfg, 'lKLa_Switch');
    vaporAdvectionEnabled = readSwitch(cfg, 'lDVa_Switch');
    dryAirEnabled = readSwitch(cfg, 'lSoilairefc');

    liquidFromHeadAndGravity = -conductivityLiquid .* (gradH + 1);
    liquidFromTemperature = -(conductivityThermalLiquid ...
        + diffusivityThermalLiquid) .* gradTemperature;
    liquidFromGasPressure = zeros(NL, 1);
    if klaEnabled
        liquidFromGasPressure = -(conductivityLiquid ./ GammaW) ...
            .* gradPressureGas;
    end
    liquidPhase = liquidFromHeadAndGravity + liquidFromTemperature ...
        + liquidFromGasPressure;

    gasPhase = -gasMobility .* gradPressureGas;
    if isfield(TransportCoefficient, 'V_A') ...
            && ~isempty(TransportCoefficient.V_A)
        gasPhaseLegacyDifference = gasPhase ...
            - TransportCoefficient.V_A(:);
    else
        gasPhaseLegacyDifference = NaN(NL, 1);
    end

    % Mean the complete endpoint coefficient, not separately averaged
    % factors. This is exactly the current water FEM's conservative physical
    % flux and becomes the authority consumed by heat as well.
    vaporDispersionEndpoint = SoilVariables.Theta_g ...
        .* TransportCoefficient.D_Vg(:);
    vaporHeadCoefficient = mean((TransportCoefficient.D_V ...
        + vaporDispersionEndpoint) ...
        .* [SoilVariables.DRHOVh(1:NL), ...
            SoilVariables.DRHOVh(2:NN)], 2);
    vaporTemperatureCoefficient = mean((TransportCoefficient.D_V ...
        .* TransportCoefficient.Eta + vaporDispersionEndpoint) ...
        .* [SoilVariables.DRHOVT(1:NL), ...
            SoilVariables.DRHOVT(2:NN)], 2);
    vaporFromHead = -vaporHeadCoefficient .* gradH;
    vaporFromTemperature = -vaporTemperatureCoefficient ...
        .* gradTemperature;
    vaporFromGasAdvection = zeros(NL, 1);
    if vaporAdvectionEnabled
        vaporPressureCoefficient = mean( ...
            [rhoVapor(1:NL), rhoVapor(2:NN)] ...
            .* TransportCoefficient.Kg, 2);
        vaporFromGasAdvection = -vaporPressureCoefficient ...
            .* gradPressureGas;
    end
    waterVaporMass = vaporFromHead + vaporFromTemperature ...
        + vaporFromGasAdvection;

    liquidWaterMass = RHOL .* liquidPhase;
    totalWaterMass = liquidWaterMass + waterVaporMass;
    totalWaterEquivalent = totalWaterMass ./ RHOL;

    freeDryAirMass = zeros(NL, 1);
    dissolvedDryAirMass = zeros(NL, 1);
    totalDryAirMass = zeros(NL, 1);
    % Retain the current coefficient kernel's lower-endpoint carrier density
    % here. Changing this to an arithmetic/upwind value is a later spatial
    % discretization decision, not an ownership refactor.
    rhoDryAirCarrier = rhoDryAir(1:NL);
    if dryAirEnabled
        freeDryAirMass = -(molecularDiffusivity + gasDispersion) ...
            .* SoilVariables.DRHODAz(:) ...
            + rhoDryAirCarrier .* gasPhase;
        dissolvedDryAirMass = Hc .* rhoDryAirCarrier ./ RHOL ...
            .* liquidPhase;
        totalDryAirMass = freeDryAirMass + dissolvedDryAirMass;
    end

    temperatureBar = 0.5 * (temperature(1:NL) + temperature(2:NN));
    latentVaporBar = 0.5 * (latentVapor(1:NL) + latentVapor(2:NN));
    conductivityHeat = mean(TransportCoefficient.Lambda_eff, 2);
    energyConduction = -conductivityHeat .* gradTemperature;
    energyLiquid = phys.c_L .* temperatureBar .* liquidWaterMass;
    energyVapor = (phys.c_L .* temperatureBar + latentVaporBar) ...
        .* waterVaporMass;
    energyDryAir = phys.c_a .* temperatureBar .* totalDryAirMass;
    energyTotal = energyConduction + energyLiquid + energyVapor ...
        + energyDryAir;

    raw = struct( ...
        'liquid_phase_cm_s', liquidPhase, ...
        'gas_phase_cm_s', gasPhase, ...
        'liquid_water_mass_g_cm2_s', liquidWaterMass, ...
        'water_vapor_mass_g_cm2_s', waterVaporMass, ...
        'total_water_mass_g_cm2_s', totalWaterMass, ...
        'total_water_equivalent_cm_s', totalWaterEquivalent, ...
        'free_dry_air_mass_g_cm2_s', freeDryAirMass, ...
        'dissolved_dry_air_mass_g_cm2_s', dissolvedDryAirMass, ...
        'total_dry_air_mass_g_cm2_s', totalDryAirMass, ...
        'conductive_energy_J_cm2_s', energyConduction, ...
        'liquid_energy_J_cm2_s', energyLiquid, ...
        'vapor_energy_J_cm2_s', energyVapor, ...
        'dry_air_energy_J_cm2_s', energyDryAir, ...
        'total_energy_J_cm2_s', energyTotal);

    legacyGradient = min(max(gradPressureGas, -1e5), 1e5);
    legacyLiquidPressure = zeros(NL, 1);
    if klaEnabled
        legacyLiquidPressure = -(conductivityLiquid ./ GammaW) ...
            .* legacyGradient;
    end
    legacyLiquid = liquidFromHeadAndGravity + liquidFromTemperature ...
        + legacyLiquidPressure;

    flux = struct();
    flux.schema_version = 1;
    flux.orientation = 'positive_deeper_to_shallower';
    flux.spatial_rule = 'endpoint_total_coefficient_arithmetic_mean';
    flux.phase = struct('liquid_cm_s', liquidPhase, ...
        'gas_cm_s', gasPhase);
    flux.component = struct( ...
        'liquid_water_mass_g_cm2_s', liquidWaterMass, ...
        'water_vapor_mass_g_cm2_s', waterVaporMass, ...
        'total_water_mass_g_cm2_s', totalWaterMass, ...
        'total_water_equivalent_cm_s', totalWaterEquivalent, ...
        'free_dry_air_mass_g_cm2_s', freeDryAirMass, ...
        'dissolved_dry_air_mass_g_cm2_s', dissolvedDryAirMass, ...
        'total_dry_air_mass_g_cm2_s', totalDryAirMass);
    flux.energy = struct('conduction_J_cm2_s', energyConduction, ...
        'liquid_J_cm2_s', energyLiquid, ...
        'vapor_J_cm2_s', energyVapor, ...
        'dry_air_J_cm2_s', energyDryAir, ...
        'total_J_cm2_s', energyTotal);
    flux.decomposition = struct( ...
        'liquid_head_gravity_cm_s', liquidFromHeadAndGravity, ...
        'liquid_temperature_cm_s', liquidFromTemperature, ...
        'liquid_gas_pressure_cm_s', liquidFromGasPressure, ...
        'vapor_head_g_cm2_s', vaporFromHead, ...
        'vapor_temperature_g_cm2_s', vaporFromTemperature, ...
        'vapor_gas_advection_g_cm2_s', vaporFromGasAdvection);
    flux.gradients = struct('head_per_cm', gradH, ...
        'liquid_pressure_head_per_cm', gradH, ...
        'retention_shifted_head_per_cm', gradLiquidHead, ...
        'temperature_K_per_cm', gradTemperature, ...
        'gas_pressure_per_cm', gradPressureGas);
    flux.raw = raw;
    flux.applied = raw;
    flux.modifiers = struct( ...
        'kla_enabled', klaEnabled, ...
        'vapor_advection_enabled', vaporAdvectionEnabled, ...
        'dry_air_enabled', dryAirEnabled, ...
        'pressure_gradient_limit_applied', false, ...
        'pressure_gradient_limit_value', 1e5, ...
        'legacy_pressure_gradient_clip_count', ...
            nnz(abs(gradPressureGas) > 1e5), ...
        'dry_air_carrier_density_rule', 'lower_endpoint_legacy');
    flux.legacy = struct( ...
        'clipped_gas_pressure_gradient_per_cm', legacyGradient, ...
        'clipped_liquid_phase_cm_s', legacyLiquid, ...
        'shared_minus_clipped_liquid_cm_s', liquidPhase - legacyLiquid, ...
        'gas_phase_cache_difference_cm_s', gasPhaseLegacyDifference);

    validateFluxFamily(flux, NL);
end

function [NL, nD, dz] = validateFrame(SV, TC, cfg)
% Validate every input consumed by the pure shared-flux evaluator.
    assert(isstruct(cfg) && isfield(cfg, 'Grid'), ...
        'evaluateCoupledElementFlux:badGrid', 'cfg.Grid is required.');
    NL = cfg.Grid.NL;
    nD = cfg.Grid.nD;
    dz = cfg.Grid.DeltZ(:);
    assert(nD == 2 && numel(dz) == NL && all(isfinite(dz)) ...
            && all(dz > 0), ...
        'evaluateCoupledElementFlux:badGrid', ...
        'Shared flux evaluation requires NL positive two-endpoint elements.');
    nodeNames = {'hh','hh_frez','TT','P_gg','RHOV','DRHOVh', ...
        'DRHOVT','RHODA','L'};
    for i = 1:numel(nodeNames)
        value = SV.(nodeNames{i});
        assert(numel(value) == NL + 1 && all(isfinite(value(:))), ...
            'evaluateCoupledElementFlux:badNodeField', ...
            '%s must contain NL+1 finite nodal values.', nodeNames{i});
    end
    endpointNames = {'KfL_h','Theta_g'};
    for i = 1:numel(endpointNames)
        value = SV.(endpointNames{i});
        assert(isequal(size(value), [NL, nD]) ...
                && all(isfinite(value(:))), ...
            'evaluateCoupledElementFlux:badEndpointField', ...
            '%s must be a finite NL-by-2 endpoint array.', endpointNames{i});
    end
    coefficientNames = {'KL_T','D_Ta','Kg','D_V','Eta','Lambda_eff'};
    for i = 1:numel(coefficientNames)
        value = TC.(coefficientNames{i});
        assert(isequal(size(value), [NL, nD]) ...
                && all(isfinite(value(:))), ...
            'evaluateCoupledElementFlux:badCoefficientField', ...
            '%s must be a finite NL-by-2 endpoint array.', ...
            coefficientNames{i});
    end
    assert(numel(TC.D_Vg) == NL && all(isfinite(TC.D_Vg(:))) ...
            && numel(SV.DRHODAz) == NL ...
            && all(isfinite(SV.DRHODAz(:))), ...
        'evaluateCoupledElementFlux:badElementField', ...
        'D_Vg and DRHODAz must contain NL finite element values.');
end

function value = readSwitch(cfg, name)
% Read one active integer/logical switch without inventing an enabled default.
    value = isfield(cfg, name) && logical(cfg.(name));
end

function validateFluxFamily(flux, NL)
% Fail before any consumer can assemble a partial or non-finite family.
    groups = {flux.raw, flux.applied};
    for g = 1:numel(groups)
        names = fieldnames(groups{g});
        for i = 1:numel(names)
            value = groups{g}.(names{i});
            assert(isequal(size(value), [NL, 1]) ...
                    && all(isfinite(value)), ...
                'evaluateCoupledElementFlux:nonfiniteFlux', ...
                '%s must be a finite NL-by-1 element flux.', names{i});
        end
    end
    assert(isequaln(flux.raw, flux.applied), ...
        'evaluateCoupledElementFlux:unrecordedModifier', ...
        'Shared raw/applied fluxes differ without a named modifier.');
end
