function result = evaluateResidualLedger(built, ctx, prepared)
%EVALUATERESIDUALLEDGER Evaluate exact coupled residuals and ledgers once.
%
%   This function refreshes one detached candidate, assembles the water,
%   dry-air, and energy rows from the shared flux family, and recovers the
%   matching boundary reactions and column conservation ledgers.  It neither
%   solves nor accepts a state.  The caller model must remain unchanged.
%
%   Residual blocks retain the active COMPASS equation-rate units.  Ledger
%   residuals are extensive over ctx.dt_s.  Dirichlet constraint residuals
%   are deliberately retained in the merit but are not reinterpreted as
%   boundary mass or energy input.
%
%   Optional PREPARED is an immediate, same-alpha coefficient-refresh pair:
%     .schema_version = 1; .source_candidate = BUILT before that refresh;
%     .candidate and .equations = its unmodified refresh outputs;
%     .refresh_opts = the exact options used by that refresh.
%   This local handoff skips only the duplicate constitutive refresh. It is
%   not a cache: parameters, grid, switches and forcing must remain frozen
%   in the caller, and the pair must not cross a trial/retry or parameter
%   rebuild. Trial coordinates, accepted soil anchors, phase input seeds and
%   refresh options are checked below. All assembly, physical admissibility,
%   boundary reactions and conservation ledgers are still evaluated here.
%
%   Editor: Jizixing Zhu; Date: 2026-08-14.
%   Change: 2026-08-15 Jizixing Zhu -- make this the unique candidate-state
%           owner for soil ledgers, physical admissibility, and the exact
%           top state/flux consumed by surface complementarity.
%   Change: 2026-08-15 Jizixing Zhu -- return the exact dry-air and energy
%           boundary fluxes used by their ledgers so outer accumulation
%           cannot fall back to the preceding frozen Picard map.
%   Change: 2026-10-07 Wenjie Liu -- accept an explicitly owned same-alpha
%           refresh pair without repeating its constitutive calculation;
%           retain the default interface and every exact acceptance ledger.

    validateContext(ctx);
    before = fingerprint(built);
    if nargin < 3 || isempty(prepared)
        cand = built;
        [cand, equationBank] = soil.refreshSoilCoefficients( ...
            cand, ctx.refresh_opts);
    else
        [cand, equationBank] = readPreparedCandidate(built, ctx, prepared);
    end
    assert(isfield(equationBank, 'flux_family') ...
            && equationBank.flux_family.schema_version == 1, ...
        'evaluateResidualLedger:missingSharedFluxFamily', ...
        'Exact evaluation requires shared flux family schema version 1.');

    matrixWaterSink = ctx.water_root_sink;
    if enabled(cand, 'lDualPor') ...
            && isfield(cand.workspace.step, 'trial_aux') ...
            && isfield(cand.workspace.step.trial_aux, 'dual_porosity') ...
            && isfield(cand.workspace.step.trial_aux.dual_porosity, ...
                'SinkIm_current') ...
            && ~isempty(cand.workspace.step.trial_aux.dual_porosity.SinkIm_current)
        matrixWaterSink = matrixWaterSink ...
            + cand.workspace.step.trial_aux.dual_porosity.SinkIm_current;
    end
    matrices = soil.assembleEquationMatrices( ...
        equationBank, cand.domain.dz, matrixWaterSink);

    [assembly, ~, waterDirect, waterApplied, waterSystem] = ...
        soil.water.solveWaterTrial(cand, ctx.dt_s, ctx.kt, ...
            ctx.water_boundary_flux, ctx.theta_equivalent_accepted, ...
            ctx.water_root_sink, ctx.water_boundary_request, ...
            equationBank.water, matrices.water, true);
    systems = struct('water', waterSystem);
    state = struct('h', cand.workspace.step.trial.h(:), ...
        'T', cand.workspace.step.trial.T(:), ...
        'P', cand.workspace.step.trial.p_gas(:));
    waterExact = recoverWaterFlux(cand, equationBank, matrices, ...
        waterSystem, state, waterDirect, waterApplied, ctx);

    airApplied = struct();
    if ctx.air_enabled
        [assembly, ~, ~, airSystem, airApplied] = ...
            soil.gas.solveDryAirTrial(assembly, equationBank.dry_air, ...
                matrices.dry_air, ctx.dry_air_storage_accepted, ...
                ctx.dt_s, ctx.kt, true, ctx.air_boundary_request);
        systems.air = airSystem;
    else
        systems.air = struct();
    end

    heatApplied = struct();
    heatRequest = ctx.heat_boundary_request;
    if ctx.heat_enabled
        heatRequest = applyRealizedSurfaceEvaporation( ...
            ctx.heat_boundary_request, ctx.water_boundary_request, ...
            waterExact);
        [~, ~, ~, heatSystem, heatApplied] = ...
            soil.thermal.solveThermalTrial(assembly, equationBank.heat, ...
                matrices.heat, ctx.energy_storage_accepted, ctx.dt_s, ...
                ctx.kt, waterExact, ctx.water_boundary_flux, true, ...
                heatRequest);
        systems.heat = heatSystem;
    else
        systems.heat = struct();
    end

    rows = solver.buildSoilCorrectionRows( ...
        matrices, systems, state, ctx.dt_s, ...
        ctx.heat_enabled, ctx.air_enabled);
    blocks = buildBlocks(rows, ctx);
    ledgers = buildLedgers(cand, equationBank, matrices, systems, ...
        state, waterExact, waterApplied, airApplied, heatApplied, ...
        heatRequest, ctx);

    result = struct();
    result.schema_version = 1;
    result.flux_family_schema_version = ...
        equationBank.flux_family.schema_version;
    result.flux_family = equationBank.flux_family;
    result.blocks = blocks;
    result.linearization = buildPrimaryLinearization( ...
        equationBank, rows, cand.domain.dz, ctx);
    result.merit = scaledMerit(blocks, ctx.scales, ctx.scale_id);
    result.ledgers = ledgers;
    result.equation_integrals = struct( ...
        'water_residual_mm', ...
            -sum(blocks.water.value) * ctx.dt_s * 10, ...
        'dry_air_residual_g_cm2', ...
            sum(blocks.dry_air.value) * ctx.dt_s, ...
        'energy_residual_J_cm2', ...
            sum(blocks.energy.value) * ctx.dt_s);
    result.ledger_equation_difference = struct( ...
        'water_mm', ledgers.water.residual_mm ...
            - result.equation_integrals.water_residual_mm, ...
        'dry_air_g_cm2', ledgerResidual(ledgers.dry_air, ...
            'residual_g_cm2') ...
            - result.equation_integrals.dry_air_residual_g_cm2, ...
        'energy_J_cm2', ledgerResidual(ledgers.energy, ...
            'residual_J_cm2') ...
            - result.equation_integrals.energy_residual_J_cm2);
    result.feasibility = candidateFeasibility(cand, equationBank);
    result.surface_state = buildSurfaceState(cand, waterExact);
    result.boundary_signature = struct('water', waterApplied, ...
        'dry_air', airApplied, 'energy', heatApplied);
    result.state_hash = soil.coupling.hashTrialState(cand);
    result.caller_unchanged = isequaln(before, fingerprint(built));
    assert(result.caller_unchanged, ...
        'evaluateResidualLedger:callerMutated', ...
        'Detached exact evaluation mutated the caller model.');
end

function [cand, equationBank] = readPreparedCandidate(built, ctx, prepared)
% Consume an immediate local refresh pair, never a cross-state cache entry.
% The solver freezes static configuration inside the alpha loop. This check
% therefore visits only bounded soil-state/seed arrays, not full parameters,
% accepted ecosystem state, or multi-year forcing/diagnostic trees.
% Editor: Wenjie Liu; Date: 2026-10-07.
    required = {'schema_version','source_candidate','candidate', ...
        'equations','refresh_opts'};
    assert(isstruct(prepared) && isscalar(prepared) ...
            && all(isfield(prepared, required)) ...
            && isequal(prepared.schema_version, 1), ...
        'evaluateResidualLedger:badPreparedCandidate', ...
        'A complete immediate same-alpha refresh pair is required.');
    assert(isequaln(prepared.refresh_opts, ctx.refresh_opts) ...
            && isequaln(refreshSourceState(prepared.source_candidate), ...
                refreshSourceState(built)), ...
        'evaluateResidualLedger:stalePreparedCandidate', ...
        'The refresh pair does not belong to this trial, anchors, seeds or options.');
    cand = prepared.candidate;
    equationBank = prepared.equations;
    assert(isequaln(primaryTrialState(cand), primaryTrialState(built)) ...
            && isequaln(acceptedSoilAnchors(cand), acceptedSoilAnchors(built)), ...
        'evaluateResidualLedger:changedPreparedState', ...
        'Constitutive refresh must preserve primary trial and accepted soil state.');
end

function state = refreshSourceState(built)
% Retain the bounded dynamic inputs read by the production refresh chain.
% Static configuration is owned/frozen by the immediate alpha-loop caller.
% Editor: Wenjie Liu; Date: 2026-10-07.
    state = struct('trial', built.workspace.step.trial, ...
        'accepted', acceptedSoilAnchors(built));
    d = built.workspace.derived;
    seeds = {'EHCAP','c_unsat','Lambda_eff','TT_CRIT', ...
        'DhFrezDh','DhFrezDT','Theta_II'};
    state.seeds = selectedFields(d, seeds);
    state.root_sink = built.workspace.flux.Srt;
    state.step = selectedFields(built.workspace.step, {'L_f','trial_aux'});
end

function state = acceptedSoilAnchors(built)
% Bound identity to the accepted water/thermal/gas time-layer inputs only.
% Editor: Wenjie Liu; Date: 2026-10-07.
    state = selectedFields(built.Y, {'h','T','U','p_gas','Theta_L','Theta_I'});
end

function state = primaryTrialState(built)
% Freezing-head mirrors are refreshed; prognostic coordinates are unchanged.
% Editor: Wenjie Liu; Date: 2026-10-07.
    state = selectedFields(built.workspace.step.trial, {'h','T','U','p_gas'});
end

function out = selectedFields(in, names)
% Copy a fixed, bounded field set without traversing unrelated run services.
% Editor: Wenjie Liu; Date: 2026-10-07.
    out = struct();
    for i = 1:numel(names)
        if isfield(in, names{i})
            out.(names{i}) = in.(names{i});
        end
    end
end

function linearization = buildPrimaryLinearization(eq, rows, dz, ctx)
% Convert the frozen h/T/P rows once to the h/U/P Picard coordinates.
    linearization = struct('available', false, ...
        'coordinate_order', {{'h','U','P_g'}}, ...
        'equation_order', {{'water','energy','dry_air'}}, ...
        'rows', struct(), 'constitutive_U_J_cm3', []);
    if ~(ctx.heat_enabled && ctx.air_enabled)
        return;
    end
    [constitutiveU, U_T, U_h, U_P] = ...
        soil.thermal.assembleNodalInternalEnergy( ...
            eq.heat.energyStorage, eq.heat.CTh, eq.heat.CTT, ...
            eq.heat.CTa, dz);
    transformed = struct();
    transformed.water = solver.transformTemperatureEquationColumns( ...
        rows.water, U_h, U_T, U_P);
    transformed.energy = solver.transformTemperatureEquationColumns( ...
        rows.heat, U_h, U_T, U_P);
    transformed.dry_air = solver.transformTemperatureEquationColumns( ...
        rows.air, U_h, U_T, U_P);
    linearization.available = true;
    linearization.rows = transformed;
    linearization.constitutive_U_J_cm3 = constitutiveU(:);
    linearization.U_T_J_cm3_K = U_T(:);
end

function blocks = buildBlocks(rows, ctx)
    blocks = struct();
    blocks.water = struct('value', -rows.water.rhs(:), ...
        'units', 'cm_s', 'dirichlet_rows', rows.water.dirichletRows);
    if ctx.air_enabled
        blocks.dry_air = struct('value', -rows.air.rhs(:), ...
            'units', 'g_cm2_s', 'dirichlet_rows', rows.air.dirichletRows);
    else
        blocks.dry_air = struct('value', zeros(0,1), ...
            'units', 'g_cm2_s', 'dirichlet_rows', false(0,1));
    end
    if ctx.heat_enabled
        blocks.energy = struct('value', -rows.heat.rhs(:), ...
            'units', 'J_cm2_s', 'dirichlet_rows', rows.heat.dirichletRows);
    else
        blocks.energy = struct('value', zeros(0,1), ...
            'units', 'J_cm2_s', 'dirichlet_rows', false(0,1));
    end
end

function ledgers = buildLedgers(cand, eq, matrices, systems, state, ...
        waterFlux, waterApplied, airApplied, heatApplied, heatRequest, ctx)
    dz = cand.domain.dz(:);
    thetaCurrent = waterEquivalentEndpoints(cand.workspace.derived);
    currentState = state;
    storageBefore = solver.integrateRichardsEquivalentWaterMm( ...
        ctx.theta_equivalent_accepted, dz, ...
        ctx.active_richards_first_node);
    storageAfter = solver.integrateRichardsEquivalentWaterMm( ...
        thetaCurrent, dz, ctx.active_richards_first_node);
    rootSink = solver.integrateRichardsRootSinkCmS( ...
        ctx.water_root_sink, dz, ctx.active_richards_first_node);
    waterBalance = solver.computeWaterBalanceResidual( ...
        waterFlux, storageBefore, storageAfter, rootSink, ctx.dt_s);

    airBalance = soil.gas.emptyColumnMassBalance();
    airFlux = struct();
    if ctx.air_enabled
        currentAirStorage = eq.dry_air.dryAirStorage;
        admissibility = soil.gas.evaluateDryAirAdmissibility( ...
            cand.workspace.derived.RHODA, currentAirStorage);
        if admissibility.admissible
            [QAT, QAB] = soil.gas.calculateCoupledBoundaryFlux( ...
                systems.air.SAVE, matrices.dry_air, currentState, ...
                currentState, currentAirStorage, currentAirStorage, ...
                dz, ctx.dt_s);
            [QAT, QAB] = resolveDryAirBoundaryFlux( ...
                QAT, QAB, ctx.air_boundary_request, airApplied);
            airFlux = struct('QAT', QAT, 'QAB', QAB);
            % Exact evaluation uses an unconstrained feasible candidate. A dry-air
            % lower-bound reaction belongs to a later explicit active-set
            % contract and is never silently inferred from the ledger.
            airBalance = soil.gas.computeColumnMassBalance( ...
                ctx.dry_air_storage_accepted, currentAirStorage, dz, ...
                struct('QAT', QAT, 'QAB', QAB), ctx.dt_s);
        end
    end

    energyBalance = soil.thermal.emptyColumnEnergyBalance();
    energyFlux = struct();
    energyStateMismatch = NaN;
    if ctx.heat_enabled
        NL = numel(dz);
        zerosEndpoint = zeros(NL,2);
        acceptedU = soil.thermal.assembleNodalInternalEnergy( ...
            ctx.energy_storage_accepted, zerosEndpoint, zerosEndpoint, ...
            zerosEndpoint, dz);
        currentU = soil.thermal.assembleNodalInternalEnergy( ...
            eq.heat.energyStorage, zerosEndpoint, zerosEndpoint, ...
            zerosEndpoint, dz);
        trialU = cand.workspace.step.trial.U(:);
        energyStateMismatch = max(abs(currentU(:) - trialU));
        zeroNode = zeros(size(currentU));
        [QET, QEB] = soil.thermal.calculateCoupledBoundaryFlux( ...
            systems.heat.SAVE, matrices.heat, currentState.T, ...
            zeroNode, zeroNode, zeroNode, zeroNode, dz, ctx.dt_s);
        [QET, QEB] = resolveEnergyBoundaryFlux( ...
            QET, QEB, heatRequest, heatApplied, currentState.T);
        energyFlux = struct('QET', QET, 'QEB', QEB);
        energyBalance = soil.thermal.computeColumnEnergyBalance( ...
            acceptedU, currentU, eq.heat.rootEnergySink, dz, ...
            struct('QET', QET, 'QEB', QEB), ctx.dt_s);
    end

    ledgers = struct('water', waterBalance, 'dry_air', airBalance, ...
        'energy', energyBalance, ...
        'energy_coordinate_mismatch_J_cm3', energyStateMismatch, ...
        'water_boundary_flux', waterFlux, ...
        'dry_air_boundary_flux', airFlux, ...
        'energy_boundary_flux', energyFlux, ...
        'water_boundary_applied', waterApplied, ...
        'dry_air_boundary_applied', airApplied, ...
        'energy_boundary_applied', heatApplied);
end

function [QAT, QAB] = resolveDryAirBoundaryFlux( ...
        QAT, QAB, request, applied)
% Preserve prescribed Neumann data; use reactions only for pressure rows.
    if isempty(request) || ~isstruct(request) || isempty(fieldnames(applied))
        return;
    end
    if strcmp(applied.top_kind, 'fixed_mass_flux')
        if strcmp(request.top.kind, 'zero_mass_flux')
            QAT = 0;
        else
            QAT = -request.top.requested_flux_into_domain_g_cm2_s;
        end
    end
    if strcmp(applied.bottom_kind, 'fixed_mass_flux')
        if strcmp(request.bottom.kind, 'zero_mass_flux')
            QAB = 0;
        else
            QAB = request.bottom.requested_flux_into_domain_g_cm2_s;
        end
    end
end

function [QET, QEB] = resolveEnergyBoundaryFlux( ...
        QET, QEB, request, applied, temperature)
% Preserve imposed heat data and evaluate an affine top response at T_top.
    if isempty(request) || ~isstruct(request) || isempty(fieldnames(applied))
        return;
    end
    switch char(applied.top_kind)
        case 'fixed_total_energy_flux'
            QET = -request.top.requested_flux_into_domain_J_cm2_s;
        case 'linearized_surface_energy_flux'
            qIn = request.top.requested_flux_into_domain_J_cm2_s ...
                + request.top.flux_temperature_derivative_J_cm2_s_K ...
                * (temperature(end) - request.top.reference_temperature_C);
            QET = -qIn;
    end
    if strcmp(char(applied.bottom_kind), 'fixed_total_energy_flux')
        QEB = request.bottom.requested_flux_into_domain_J_cm2_s;
    end
end

function waterFlux = recoverWaterFlux(cand, eq, matrices, system, ...
        state, waterDirect, waterApplied, ctx)
% Recover one h/T/P_g-consistent boundary flux before any heat mapping.
    thetaCurrent = waterEquivalentEndpoints(cand.workspace.derived);
    [qTop, qBottom] = soil.water.calculateCoupledBoundaryFlux( ...
        system.SAVE, matrices.water, state, state, thetaCurrent, ...
        thetaCurrent, cand.domain.dz, ctx.dt_s, ...
        ctx.active_richards_first_node);
    waterFlux = waterDirect;
    waterFlux.QMT = qTop;
    waterFlux.QMB = qBottom;
    if ~isempty(ctx.water_boundary_request)
        waterFlux = soil.water.resolveCandidateBoundaryFlux( ...
            waterFlux, ctx.water_boundary_request, waterApplied);
    end
    assert(isfield(eq, 'flux_family'), ...
        'evaluateResidualLedger:missingSharedFlux', ...
        'Exact water recovery requires the shared flux family.');
end

function merit = scaledMerit(blocks, scales, scaleId)
    merit = struct();
    merit.scale_id = scaleId;
    merit.rho_water = blockRho( ...
        blocks.water.value, scales.water_cm_s);
    merit.rho_dry_air = blockRho( ...
        blocks.dry_air.value, scales.dry_air_g_cm2_s);
    merit.rho_energy = blockRho( ...
        blocks.energy.value, scales.energy_J_cm2_s);
    merit.phi = 0.5 * (merit.rho_water^2 ...
        + merit.rho_dry_air^2 + merit.rho_energy^2);
end

function rho = blockRho(value, scale)
    if isempty(value)
        rho = 0;
    else
        rho = norm(value(:) ./ scale, 2) / sqrt(numel(value));
    end
end

function value = ledgerResidual(ledger, name)
    value = NaN;
    if isstruct(ledger) && isfield(ledger, 'has_data') ...
            && ledger.has_data && isfield(ledger, name)
        value = ledger.(name);
    end
end

function out = candidateFeasibility(cand, eq)
    tr = cand.workspace.step.trial;
    allState = [tr.h(:); tr.T(:); tr.U(:); tr.p_gas(:)];
    out = struct('finite_state', all(isfinite(allState)), ...
        'temperature_above_absolute_zero', all(tr.T(:) > -273.15), ...
        'dry_air_admissible', true, ...
        'dry_air', neutralDryAirAdmissibility(), ...
        'admissible', true);
    if enabled(cand, 'lSoilairefc')
        air = soil.gas.evaluateDryAirAdmissibility( ...
            cand.workspace.derived.RHODA, eq.dry_air.dryAirStorage);
        out.dry_air_admissible = air.admissible;
        out.dry_air = air;
    end
    out.admissible = out.finite_state ...
        && out.temperature_above_absolute_zero ...
        && out.dry_air_admissible;
end

function surface = buildSurfaceState(cand, waterFlux)
% Expose the exact top-node state paired with the water ledger.
%
% The surface active set must not reconstruct moisture from a second
% constitutive refresh.  This record and waterFlux come from the same
% detached candidate and therefore describe one discrete interface state.
% Editor: Jizixing Zhu; Date: 2026-08-15.
    d = cand.workspace.derived;
    thetaR = double(cand.parameters.soil.theta_r(end));
    thetaS = double(cand.parameters.soil.theta_s(end));
    thetaL = double(d.Theta_LL(end, end));
    thetaU = double(d.Theta_UU(end, end));
    thetaTol = max(1e-10, 1e-8 * max(thetaS - thetaR, 1e-3));
    surface = struct( ...
        'head_cm', double(cand.workspace.step.trial.h(end)), ...
        'liquid_water_content', thetaL, ...
        'total_water_content', thetaU, ...
        'residual_water_content', thetaR, ...
        'residual_tolerance', thetaTol, ...
        'dry_state_depleted', thetaL <= thetaR + thetaTol ...
            && thetaU <= thetaR + thetaTol, ...
        'water_flux', waterFlux);
end

function status = neutralDryAirAdmissibility()
% Return a schema-compatible neutral result when dry air is disabled.
% Editor: Jizixing Zhu; Date: 2026-08-15.
    status = struct('admissible', true, ...
        'minimum_density_g_cm3', NaN, ...
        'minimum_storage_g_cm3', NaN, ...
        'failure_reason', '', ...
        'remaining_fraction', 0);
end

function request = applyRealizedSurfaceEvaporation( ...
        request, waterRequest, waterFlux)
    if isempty(request) || ~isstruct(request) || ~isfield(request, 'top') ...
            || ~strcmp(request.top.kind, 'surface_energy_response') ...
            || isempty(waterRequest) || ~isstruct(waterRequest) ...
            || ~isfield(waterRequest, 'top') ...
            || ~isfield(waterRequest.top, 'surface') ...
            || ~strcmp(waterRequest.top.kind, 'atmospheric') ...
            || ~strcmp(waterRequest.top.surface.regime, ...
                'dry_evaporation_limited')
        return;
    end
    demand = scalarField(request.top, ...
        'soil_evaporation_demand_cm_s', NaN);
    latent = scalarField(request.top, ...
        'soil_evaporation_latent_heat_flux_W_m2', NaN);
    derivative = scalarField(request.top, ...
        'soil_evaporation_latent_heat_flux_temperature_derivative_W_m2_K', ...
        NaN);
    if ~(isfinite(demand) && demand > 0 && isfinite(latent) ...
            && latent >= 0 && isfinite(derivative) && derivative >= 0 ...
            && isfield(waterFlux, 'QMT') && isfinite(waterFlux.QMT))
        return;
    end
    supply = waterRequest.top.liquid_supply_cm_s;
    actual = min(max(supply + waterFlux.QMT, 0), demand);
    unmet = min(max((demand - actual) / demand, 0), 1);
    request.top.requested_flux_into_domain_J_cm2_s = ...
        request.top.requested_flux_into_domain_J_cm2_s ...
        + unmet * latent * 1e-4;
    request.top.flux_temperature_derivative_J_cm2_s_K = ...
        request.top.flux_temperature_derivative_J_cm2_s_K ...
        + unmet * derivative * 1e-4;
end

function value = scalarField(container, name, fallback)
    value = fallback;
    if isfield(container, name) && isscalar(container.(name)) ...
            && isfinite(container.(name))
        value = container.(name);
    end
end

function thetaEq = waterEquivalentEndpoints(derived)
    NL = size(derived.Theta_UU, 1);
    rhoVapor = derived.RHOV(:);
    vaporEndpoints = [rhoVapor(1:NL), rhoVapor(2:NL + 1)];
    rhoLiquid = equations.getPhysicalConstant('RHOL');
    thetaEq = derived.Theta_UU + derived.Theta_V ...
        .* vaporEndpoints / rhoLiquid;
end

function validateContext(ctx)
    required = {'schema_version','dt_s','kt','refresh_opts', ...
        'theta_equivalent_accepted','water_root_sink', ...
        'water_boundary_flux','active_richards_first_node','scales'};
    assert(isstruct(ctx) && all(isfield(ctx, required)) ...
            && ctx.schema_version == 1 && isfinite(ctx.dt_s) ...
            && ctx.dt_s > 0, ...
        'evaluateResidualLedger:badContext', ...
        'A complete exact residual context schema version 1 is required.');
end

function tf = enabled(built, name)
    tf = isfield(built.control.switches, name) ...
        && built.control.switches.(name) == 1;
end

function fp = fingerprint(built)
    trial = built.workspace.step.trial;
    fp = struct('h', trial.h, 'T', trial.T, 'U', trial.U, ...
        'P', trial.p_gas, 'Y', built.Y);
    if isfield(built.workspace, 'derived')
        fp.derived = built.workspace.derived;
    end
    if isfield(built.workspace, 'solver')
        fp.solver = built.workspace.solver;
    end
end
