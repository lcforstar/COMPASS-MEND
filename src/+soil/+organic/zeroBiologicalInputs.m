function inputs = zeroBiologicalInputs(nCells)
%ZEROBIOLOGICALINPUTS Stable litter and root AOM coupling interface.
%
%   Flux profiles are top-down [g C or N cm^-3 bulk soil h^-1]. They remain
%   zero until vegetation litter and root turnover are coupled explicitly.
%   Editor: Jizixing Zhu; Date: 2026-08-16.
    inputs = struct( ...
        'litter_C_g_cm3_h', zeros(nCells,1), ...
        'litter_N_g_cm3_h', zeros(nCells,1), ...
        'root_C_g_cm3_h', zeros(nCells,1), ...
        'root_N_g_cm3_h', zeros(nCells,1));
end
