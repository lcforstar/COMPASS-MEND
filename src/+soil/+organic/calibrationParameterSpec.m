function spec=calibrationParameterSpec()
%CALIBRATIONPARAMETERSPEC Ordered staged contract for organic-model fitting.
%
%   Returns a table; it does not mutate parameters or invoke an optimizer.
%   Water and inorganic-N parameters are deliberately absent because they are
%   treated as frozen prerequisites for this calibration sequence.
%   Stage 4 lists site-global MEND configuration inputs. Derived Vm,
%   rMORT and VmD and the three-component input-fraction vector are excluded.
%
%   Editor: Jizixing Zhu; Date: 2026-09-02.
% Change: 2026-09-14 Codex -- replace retired MEMC keys with independent
%   hourly MEND inputs consumed by init.buildSoilMicrobes.
% Change: 2026-09-29 Wenjie Liu -- mark the four carbon kinetic profiles as
%   soil-owned. Candidate listing does not override active solver restrictions.
% Change: 2026-10-11 Wenjie Liu -- restore the four Changwu MEND kinetic
%   traits to site-global ownership; depth-resolved DOM sorption/transport
%   remains soil-owned.
    mendNames=["active_fraction_initial";"mend_lci_initial"; ...
        "mend_vd_pom_h";"mend_ks_pom1_mg_g";"mend_ks_pom_ratio"; ...
        "mend_enzyme_turnover_h";"mend_penzp";"mend_penzm_ratio"; ...
        "mend_frac_pom_to_dom";"mend_frac_mortality_to_dom"; ...
        "mend_vg_h";"mend_alpha";"mend_ks_dom_mg_g"; ...
        "mend_cue_20";"mend_cue_slope_per_c"; ...
        "mend_mortality_multiplier";"mend_dormant_maintenance_ratio"; ...
        "mend_swp_a2d_mpa";"mend_tau";"mend_wdorm"; ...
        "mend_vnup_mb_h";"mend_ks_nh4_mb_mg_g"; ...
        "mend_ks_no3_mb_mg_g";"mend_cn_mb_min"; ...
        "mend_cn_mb_max";"mend_cn_pom2"; ...
        "mend_cn_enzp";"mend_cn_enzm"];
    nMend=numel(mendNames);
    stage=[ones(4,1);2*ones(6,1);3*ones(3,1); ...
        4*ones(nMend,1);5*ones(4,1)];
    group=[repmat("SOC initialization",4,1);repmat("AOM",6,1); ...
        repmat("DOM",3,1);repmat("MEND",nMend,1); ...
        repmat("BIOPARTICLE",4,1)];
    owner=[repmat("organic_initial_pools.csv",4,1); ...
        repmat("site.toml [organic]",6,1);repmat("soil.csv",3,1); ...
        repmat("site.toml [microbe]",nMend,1);repmat("soil.csv",4,1)];
    name=["frac_POC";"frac_MOC";"frac_MB";"frac_IOM"; ...
        "k_litter_1d";"k_straw_1d";"k_manure_1d";"doc_leach_1d"; ...
        "respiration_fraction";"depth_efolding_m"; ...
        "kd_doc_cm3_g";"kd_don_cm3_g";"dom_disp_cm"; ...
        mendNames; ...
        "attachment_1d";"detachment_1d"; ...
        "straining_1d";"microbe_disp_cm"];
    depthResolved=[true(4,1);false(6,1);true(3,1); ...
        false(nMend,1);true(4,1)];
    status=[repmat("calibrate_with_SOC_constraint",4,1); ...
        repmat("calibrate",6,1);repmat("calibrate_by_depth_group",3,1); ...
        repmat("sensitivity_then_calibrate",nMend,1); ...
        repmat("sensitivity_then_calibrate",4,1)];
    spec=table(stage,group,owner,name,depthResolved,status, ...
        'VariableNames',{'stage','group','owner','parameter', ...
        'depth_resolved','status'});
end
