function [summary, detail] = maxRelativePoolCarbonChange(startY,endY,absoluteFloor)
%MAXRELATIVEPOOLCARBONCHANGE Compare independent periodic C/N states by phase.
%
%   Compares two complete accepted states at the same forcing-calendar phase.
%   It covers native AOM, DOC/DON, MEND subpools, BIOPARTICLE phases,
%   NEC/IOM, and dissolved, frozen, and granule mineral N.
%   Reconstructable Tot/POC/EP/PON and cumulative respiratory carbon IC and
%   flux ledgers are excluded. IC is an output accumulator with
%   dIC/dt=F4+F5 plus dormant maintenance, not a periodic carbon store.
%   Stores retain owner-native units and grid order because the metric is
%   element-wise and dimensionless. Both states must have equal topology.
%
% Editor: Codex; Date: 2026-08-20.
% Change: 2026-08-29 Codex -- replace retired DAISY SMB/SOM/AM topology
%   with the native COMPASS AOM/DOM/MEMC/MEND carbon-state contract.
% Change: 2026-09-05 Codex -- exclude cumulative respiratory carbon IC from
%   periodic pool convergence without changing the MEMC reaction equations.
% Change: 2026-09-08 Jizixing Zhu -- compare persistent litter components,
%   so offsetting component changes cannot masquerade as convergence.
% Change: 2026-09-14 Codex -- include authoritative MEND subpools and
%   organic/mineral nitrogen in the default spin-up convergence gate.
% Change: 2026-09-14 Codex -- include AOM component/bulk N and urea.
% Change: 2026-09-14 Jizixing Zhu -- include source-hour free/sorbed DOM
%   and intracellular enzyme phase C/N in periodic convergence.
    if nargin<3 || isempty(absoluteFloor), absoluteFloor=1e-18; end
    assert(isscalar(absoluteFloor)&&isfinite(absoluteFloor) ...
        &&absoluteFloor>0,'maxRelativePoolCarbonChange:badFloor', ...
        'absoluteFloor must be finite and positive.');

    required={'soil_organic','soil_dom','soil_microbes'};
    for i=1:numel(required)
        name=required{i};
        assert(isfield(startY,name)&&isfield(endY,name), ...
            'maxRelativePoolCarbonChange:missingOwner', ...
            'Both accepted states must contain %s.',name);
    end

    statePath=strings(0,1); elementIndex=zeros(0,1);
    startC=zeros(0,1); endC=zeros(0,1);
    function appendStore(path,a,b)
        assert(isnumeric(a)&&isnumeric(b)&&isequal(size(a),size(b)), ...
            'maxRelativePoolCarbonChange:topology', ...
            'Carbon-store topology differs at %s.',path);
        a=a(:); b=b(:); count=numel(a);
        statePath=[statePath;repmat(string(path),count,1)];
        elementIndex=[elementIndex;(1:count)'];
        startC=[startC;a]; endC=[endC;b];
    end

    materials={'litter','straw','manure'};
    for i=1:numel(materials)
        material=materials{i};
        assert(isfield(startY.soil_organic.aom,material) ...
            &&isfield(endY.soil_organic.aom,material), ...
            'maxRelativePoolCarbonChange:topology', ...
            'AOM material topology differs at %s.',material);
        a=startY.soil_organic.aom.(material);
        b=endY.soil_organic.aom.(material);
        assert(isfield(a,'components')==isfield(b,'components'), ...
            'maxRelativePoolCarbonChange:topology', ...
            'AOM component topology differs at %s.',material);
        if isfield(a,'components')
            a=soil.litter.componentTotals(a,true);
            b=soil.litter.componentTotals(b,true);
            for component={'metabolic','cellulose','lignin','cwd'}
                key=component{1};
                path="soil_organic.aom."+material+".components."+key;
                appendStore(path+".surface_C", ...
                    a.components.(key).surface_C,b.components.(key).surface_C);
                appendStore(path+".element_C", ...
                    a.components.(key).element_C,b.components.(key).element_C);
                appendStore(path+".surface_N", ...
                    a.components.(key).surface_N,b.components.(key).surface_N);
                appendStore(path+".element_N", ...
                    a.components.(key).element_N,b.components.(key).element_N);
            end
        else
            appendStore("soil_organic.aom."+material+".surface_C", ...
                a.surface_C,b.surface_C);
            appendStore("soil_organic.aom."+material+".element_C", ...
                a.element_C,b.element_C);
            appendStore("soil_organic.aom."+material+".surface_N", ...
                a.surface_N,b.surface_N);
            appendStore("soil_organic.aom."+material+".element_N", ...
                a.element_N,b.element_N);
        end
    end
    appendStore('soil_organic.NEC_C',startY.soil_organic.NEC_C, ...
        endY.soil_organic.NEC_C);
    appendStore('soil_organic.IOM_C',startY.soil_organic.IOM_C, ...
        endY.soil_organic.IOM_C);
    appendStore('soil_dom.doc_total_g_cm3', ...
        startY.soil_dom.doc_total_g_cm3,endY.soil_dom.doc_total_g_cm3);
    appendStore('soil_dom.don_total_g_cm3', ...
        startY.soil_dom.don_total_g_cm3,endY.soil_dom.don_total_g_cm3);

    microbeFields={'POM1','POM2','MOC','MB','BD','MB_mobile', ...
        'MB_attached','MB_retained','BD_mobile','BD_attached', ...
        'BD_retained','ENZP1','ENZP2','EM'};
    for kind={'doc','don'}
        k=kind{1};field=[k '_sorbed_g_cm3'];
        assert(isfield(startY.soil_dom,field)==isfield(endY.soil_dom,field), ...
            'maxRelativePoolCarbonChange:topology','Dynamic DOM topology differs.');
        if isfield(startY.soil_dom,field)
            appendStore(['soil_dom.' field],startY.soil_dom.(field),endY.soil_dom.(field));
            appendStore(['soil_dom.' k '_free_g_cm3'], ...
                startY.soil_dom.([k '_total_g_cm3'])-startY.soil_dom.(field), ...
                endY.soil_dom.([k '_total_g_cm3'])-endY.soil_dom.(field));
        end
    end
    assert(isfield(startY.soil_microbes,'ENZN')==isfield(endY.soil_microbes,'ENZN'), ...
        'maxRelativePoolCarbonChange:topology','Intracellular enzyme topology differs.');
    if isfield(startY.soil_microbes,'ENZN')
        microbeFields=[microbeFields {'ENZN','ENZN_mobile','ENZN_attached','ENZN_retained'}];
    end
    for i=1:numel(microbeFields)
        name=microbeFields{i};
        assert(isfield(startY.soil_microbes,name) ...
            &&isfield(endY.soil_microbes,name), ...
            'maxRelativePoolCarbonChange:topology', ...
            'Microbial carbon topology differs at %s.',name);
        appendStore("soil_microbes."+name,startY.soil_microbes.(name), ...
            endY.soil_microbes.(name));
    end
    organicNFields={'PON1','PON2','MON','MB_N','BD_N', ...
        'MB_mobile_N','MB_attached_N','MB_retained_N', ...
        'BD_mobile_N','BD_attached_N','BD_retained_N', ...
        'ENZP1_N','ENZP2_N','EM_N','NEC_N'};
    if isfield(startY.soil_microbes,'ENZN')
        organicNFields=[organicNFields {'ENZN_N','ENZN_mobile_N','ENZN_attached_N','ENZN_retained_N'}];
    end
    for i=1:numel(organicNFields)
        name=organicNFields{i};
        assert(isfield(startY.soil_organic,name) ...
            &&isfield(endY.soil_organic,name), ...
            'maxRelativePoolCarbonChange:topology', ...
            'Organic nitrogen topology differs at %s.',name);
        appendStore("soil_organic."+name,startY.soil_organic.(name), ...
            endY.soil_organic.(name));
    end
    mineralFields={'nh4','no3','urea','C_NH4_ice','C_NO3_ice','C_NH4_granule'};
    for i=1:numel(mineralFields)
        name=mineralFields{i};
        assert(isfield(startY,name)&&isfield(endY,name), ...
            'maxRelativePoolCarbonChange:topology', ...
            'Mineral nitrogen topology differs at %s.',name);
        appendStore("mineral_nitrogen."+name,startY.(name),endY.(name));
    end

    assert(~isempty(startC)&&all(isfinite(startC))&&all(isfinite(endC)) ...
        &&all(startC>=-absoluteFloor)&&all(endC>=-absoluteFloor), ...
        'maxRelativePoolCarbonChange:invalidPool', ...
        'Native C/N states must be finite and nonnegative.');
    change=abs(endC-startC); denominator=abs(startC);
    relative=zeros(size(change)); regular=denominator>absoluteFloor;
    relative(regular)=change(regular)./denominator(regular);
    relative(~regular&change>absoluteFloor)=Inf;
    detail=table(statePath,elementIndex,startC,endC,relative, ...
        'VariableNames',{'state_path','element_index','C_start', ...
        'C_end','relative_change'});
    [maximum,index]=max(relative);
    summary=struct('max_relative_change',maximum, ...
        'state_path',char(statePath(index)), ...
        'element_index',elementIndex(index), ...
        'C_start',startC(index),'C_end',endC(index), ...
        'absolute_floor_native_units',absoluteFloor, ...
        'n_compared_states',height(detail));
end
