function spec=mendLayerCalibrationCandidateSpec()
%MENDLAYERCALIBRATIONCANDIDATESPEC Auditable 8+2 layered candidate contract.
% This table declares interface capability and staged scientific release; it
% is not an optimizer search space and intentionally supplies no invented
% numeric bounds. Derived Vm, rMORT and VmD are never independent rows.
% Editor: Wenjie Liu; Date: 2026-10-12.
    canonical=io.adapters.mendLayerParameterSpec();
    parameter=string(canonical.names(:));
    units=string(canonical.units(:));
    family=["decomposition";"decomposition";"growth";"DOC uptake"; ...
        "substrate relation";"maintenance";"mortality";"carbon allocation"; ...
        "dormancy";"reactivation"];
    release_stage=[1;2;1;1;2;3;3;3;4;4];
    default_scope=[repmat("site_shared",8,1);repmat("site_shared",2,1)];
    release_condition=[ ...
        "first shared sensitivity axis with DOC/SOC constraints"; ...
        "release after Vd; do not free with ratio initially"; ...
        "first shared sensitivity axis with DOC and mineral-N constraints"; ...
        "first shared sensitivity axis with DOC constraint"; ...
        "POC/MAOC information; do not free with KsPOM1 initially"; ...
        "respiration or microbial-biomass information"; ...
        "microbial-biomass or turnover information"; ...
        "joint DOC, respiration or microbial-growth information"; ...
        "wet-dry microbial or respiration dynamics"; ...
        "wet-dry microbial or respiration dynamics"];
    structural_constraint=[ ...
        "shared Vd for POM1/POM2/MOM"; ...
        "KsPOM2=KsPOM1/ratio; KsMOM=KsPOM1*ratio"; ...
        "Vm=Vg*alpha/(1-alpha)"; ...
        "DOC biological uptake; not transport"; ...
        "controls both derived POM2 and MOM half-saturation"; ...
        "Vm is derived jointly with Vg"; ...
        "rMORT=min(0.99,Vm*multiplier)"; ...
        "temperature-adjusted CUE reference"; ...
        "paired with tau and water-potential response"; ...
        "dimensionless threshold ratio; not a time constant"];
    layer_capable=true(10,1);
    free_by_default=false(10,1);
    spec=table(parameter,family,units,layer_capable,default_scope, ...
        release_stage,release_condition,structural_constraint,free_by_default);
end
