function [candidate, result] = stageDualPorosityCandidate( ...
        accepted, thetaMobile, parameters, dt_s)
%STAGEDUALPOROSITYCANDIDATE Stage one conservative mobile-immobile exchange.
%
%   [candidate,result] = soil.preferential_flow.stageDualPorosityCandidate(...)
%   advances the immobile water content from an accepted substep snapshot.
%   It never writes accepted state.  `result.SinkIm_current` is the frozen
%   mobile-to-immobile volumetric sink [1/s] consumed by the Richards trial.
%
%   Inputs:
%     accepted   [struct] Soil-owned dual-porosity state at substep start.
%     thetaMobile [-]     Accepted mobile water content [NL x nD].
%     parameters [struct] Immutable theta_s/theta_r/theta_s_im/theta_r_im
%                         and OmegaExch [1/h].
%     dt_s       [s]      Trial substep duration.
%
%   Closure for every element:
%     candidate.Theta_im - accepted.Theta_im
%       = result.SinkIm_current * dt_s.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
    requiredState = {'Theta_im','Theta_im_old','Theta_m_old'};
    for i = 1:numel(requiredState)
        assert(isfield(accepted, requiredState{i}), ...
            'stageDualPorosityCandidate:missingState', ...
            'Accepted dual-porosity state lacks %s.', requiredState{i});
    end
    requiredParameters = ...
        {'theta_s','theta_r','theta_s_im','theta_r_im','OmegaExch'};
    for i = 1:numel(requiredParameters)
        assert(isfield(parameters, requiredParameters{i}), ...
            'stageDualPorosityCandidate:missingParameter', ...
            'Dual-porosity parameters lack %s.', requiredParameters{i});
    end
    assert(isnumeric(dt_s) && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'stageDualPorosityCandidate:badTimeStep', ...
        'dt_s must be a finite positive scalar [s].');

    NL = size(thetaMobile, 1);
    frame = struct( ...
        'Theta_L', thetaMobile, ...
        'Theta_im', accepted.Theta_im, ...
        'theta_s_im', parameters.theta_s_im(:), ...
        'theta_r_im', parameters.theta_r_im(:));
    retention = struct( ...
        'Theta_s', parameters.theta_s(:), ...
        'Theta_r', parameters.theta_r(:));
    cfg = struct( ...
        'Grid', struct('NL', NL), ...
        'lDualPor', 1, ...
        'OmegaExch', parameters.OmegaExch);
    frame = soil.water.dualporosity.dualPorExchange( ...
        frame, retention, cfg, dt_s);

    candidate = accepted;
    candidate.Theta_im = frame.Theta_im;
    candidate.Theta_im_old = frame.Theta_im_old;
    candidate.Theta_m_old = frame.Theta_m_old;
    result = struct('SinkIm_current', frame.SinkIm_current, ...
        'unit', '1/s', 'sign_convention', ...
        'positive_mobile_to_immobile');

    closure = candidate.Theta_im - accepted.Theta_im ...
        - result.SinkIm_current .* dt_s;
    assert(max(abs(closure(:))) <= 64 * eps(max(1, ...
        max(abs(candidate.Theta_im(:))))), ...
        'stageDualPorosityCandidate:massClosure', ...
        'Dual-porosity exchange does not close at the trial time level.');
end
