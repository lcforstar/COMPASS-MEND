function out=partitionExternalInput(carbon,nitrogen,fractions,cnPOM2,ratio)
%PARTITIONEXTERNALINPUT Conservatively split supplied organic C/N for MEND.
%   CARBON and NITROGEN are same-shaped, finite nonnegative element amounts
%   or inventories in the same mass unit. FRACTIONS is [POM1 POM2 DOC] for
%   carbon; CNPOM2 is input POM2 C:N and RATIO is input POM1 C:N / DOC C:N.
%   OUT contains C_POM1, C_POM2, C_DOC, N_PON1, N_PON2 and N_DON, each in
%   the input unit and shape. No state or inorganic-N inventory is changed.
%   The fixed POM2 N requirement is paid from the supplied N. Remaining N
%   follows the source-MEND lignin-to-labile C:N relationship. Incompatible
%   input C:N, N without C, and invalid parameters raise explicit errors.
%   Source: MEND-main/src/MOD_MEND.F90, lines 204--214, 852--854;
%   MOD_MEND_TYPE.F90 constant CN_Cellulose=500; SOIL_INI.dat rCN_LIG2LAB=2.
%   These source defaults remain caller-owned parameters. Zero remaining N
%   is evaluated directly as N amounts, without division by infinite C:N.
%   Editor: Wenjie Liu; Date: 2026-10-10.
    assert(isnumeric(carbon)&&isreal(carbon)&&~isempty(carbon) ...
        &&isnumeric(nitrogen)&&isreal(nitrogen) ...
        &&isequal(size(carbon),size(nitrogen)) ...
        &&all(isfinite(carbon(:)))&&all(carbon(:)>=0) ...
        &&all(isfinite(nitrogen(:)))&&all(nitrogen(:)>=0), ...
        'soil:mend:externalInputValues', ...
        'External organic C/N must be aligned finite nonnegative amounts.');
    assert(isnumeric(fractions)&&isreal(fractions)&&numel(fractions)==3 ...
        &&all(isfinite(fractions(:)))&&all(fractions(:)>=0) ...
        &&all(fractions(:)<=1)&&abs(sum(fractions(:))-1)<=1e-12, ...
        'soil:mend:externalInputFractions', ...
        'MEND external carbon fractions must be three values summing to one.');
    assert(isnumeric(cnPOM2)&&isreal(cnPOM2)&&isscalar(cnPOM2) ...
        &&isfinite(cnPOM2)&&cnPOM2>0 ...
        &&isnumeric(ratio)&&isreal(ratio)&&isscalar(ratio) ...
        &&isfinite(ratio)&&ratio>0, ...
        'soil:mend:externalInputParameters', ...
        'Input POM2 C:N and lignin-to-labile C:N ratio must be positive scalars.');
    assert(all(carbon(:)>0|nitrogen(:)==0), ...
        'soil:mend:externalInputNitrogenOnly', ...
        'A plant/residue organic input cannot contain N without C.');
    carbon=double(carbon);nitrogen=double(nitrogen);
    f=double(fractions(:));
    % Native MEND reads the third fraction as the complement of the first
    % two. Preserve that closure rather than renormalizing all parameters.
    f(3)=1-(f(1)+f(2));
    assert(f(3)>=0,'soil:mend:externalInputFractions', ...
        'POM1 plus POM2 fractions cannot exceed one.');
    out=struct('C_POM1',f(1).*carbon,'C_POM2',f(2).*carbon, ...
        'C_DOC',f(3).*carbon,'N_PON1',zeros(size(carbon)), ...
        'N_PON2',zeros(size(carbon)),'N_DON',zeros(size(carbon)));
    out.N_PON2=out.C_POM2./cnPOM2;
    remaining=nitrogen-out.N_PON2;
    assert(all(remaining(:)>=0), ...
        'soil:mend:externalInputInfeasibleCN', ...
        ['Supplied organic N cannot meet the input POM2 C:N requirement; ' ...
         'change the explicit input assumptions, not the N inventory.']);
    weight=out.C_POM1./ratio+out.C_DOC;
    assert(all(weight(:)>0|remaining(:)==0), ...
        'soil:mend:externalInputInfeasibleCN', ...
        'Surplus input N has no POM1 or DOC carbon recipient.');
    active=weight>0;
    out.N_PON1(active)=remaining(active).* ...
        ((out.C_POM1(active)./ratio)./weight(active));
    out.N_DON=remaining-out.N_PON1;
    assert(all(isfinite(out.N_PON1(:)))&&all(out.N_PON1(:)>=0) ...
        &&all(isfinite(out.N_DON(:)))&&all(out.N_DON(:)>=0), ...
        'soil:mend:externalInputArithmetic', ...
        'External N partition produced an invalid amount.');
    residualC=out.C_POM1+out.C_POM2+out.C_DOC-carbon;
    residualN=out.N_PON1+out.N_PON2+out.N_DON-nitrogen;
    assert(all(abs(residualC(:))<=32.*eps(max(carbon(:),realmin))) ...
        &&all(abs(residualN(:))<=32.*eps(max(nitrogen(:),realmin))), ...
        'soil:mend:externalInputClosure', ...
        'External MEND partition failed independent C or N conservation.');
end
