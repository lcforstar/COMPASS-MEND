function r=reserveRootDIN(available,rootNH4,rootNO3)
%RESERVEROOTDIN Reserve COMPASS root demand in a temporary DIN inventory.
%   All vectors are top-down integrated [mg N g-1 dry soil]. The physical
%   NH4/NO3 state is not modified; only the returned shadow inventory is.
%   Editor: Jizixing Zhu; Date: 2026-09-12.
    assert(isfield(available,'nh4_mg_g')&&isfield(available,'no3_mg_g') ...
        &&isfield(available,'root_nh4_mg_g')&&isfield(available,'root_no3_mg_g'), ...
        'soil:mend:rootShape','Root DIN reservation fields are incomplete.');
    nh4=available.nh4_mg_g(:); no3=available.no3_mg_g(:);
    take4=available.root_nh4_mg_g(:); take3=available.root_no3_mg_g(:);
    assert(isequal(size(nh4),size(take4))&&isequal(size(no3),size(take3)) ...
        &&all(isfinite([nh4;no3;take4;take3]))&&all([nh4;no3;take4;take3]>=0) ...
        &&all(take4<=nh4+1e-12)&&all(take3<=no3+1e-12), ...
        'soil:mend:rootOverdraw','Root DIN exceeds temporary available inventory.');
    r=struct('nh4_mg_g',nh4-take4,'no3_mg_g',no3-take3, ...
        'root_nh4_mg_g',take4,'root_no3_mg_g',take3, ...
        'physical_state_unchanged',true,'source','COMPASS_root_priority_shadow');
end
