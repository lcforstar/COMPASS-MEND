function m=fromCompass(organic,dom,temperatureC,headCm,theta,bulkDensity,dt_s,mode)
%FROMCOMPASS Build a native-unit MEND reaction input from COMPASS candidates.
%   Organic pools are top-down [mg C g-1 dry soil]; DOM is bottom-up
%   [g C cm-3 bulk soil]; theta is bottom-up [-], bulk density is bottom-up
%   [g cm-3], temperature is [degC], head is [cm], and dt_s is [s].
%   This adapter is the only boundary at which COMPASS grid/unit conventions
%   are converted for MEND. It does not mutate any input.
%   Editor: Jizixing Zhu; Date: 2026-09-12.
    assert(ismember(string(mode),["reference","compass_coupled"]), ...
        'soil:mend:adapterMode','Unknown MEND mode.');
    n=numel(bulkDensity(:));
    assert(numel(theta)==n&&numel(temperatureC)==n&&numel(headCm)==n ...
        &&numel(dom.doc_total_g_cm3)==n&&isscalar(dt_s)&&isfinite(dt_s)&&dt_s>0, ...
        'soil:mend:adapterShape','MEND adapter input shapes are invalid.');
    assert(all(isfinite([theta(:);bulkDensity(:);temperatureC(:);headCm(:)])) ...
        &&all(theta(:)>=0)&&all(bulkDensity(:)>0), ...
        'soil:mend:adapterValues','MEND adapter drivers are invalid.');
    m=struct('organic',organic,'dom',dom,'temperature_C',temperatureC(:), ...
        'head_cm',headCm(:),'theta_bottom_up',theta(:), ...
        'bulk_density_bottom_up',bulkDensity(:),'dt_s',double(dt_s), ...
        'mode',char(string(mode)),'rate_time_basis','hour', ...
        'source_model','MEND','source_commit', ...
        '92323c7326e9a30ae44e794d114612b90a9e3b1c');
end
