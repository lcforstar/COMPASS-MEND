function request = materializeGasBoundaryTrial( ...
        carrierSpec, speciesSpecs, drivers, tStart_s, dt_s)
%MATERIALIZEGASBOUNDARYTRIAL Freeze carrier and species forcing for one trial.
%
%   Carrier pressure/mass and species composition remain separate conserved
%   quantities under one inward-positive interval contract. Production O2
%   forcing is adapted to the reusable materializeSpeciesRequest kernel.
%   No other species is silently accepted until its complete input, state,
%   source, ledger, and diagnostics path exists.
%
%   Editor: Jizixing Zhu; Date: 2026-08-20.
%   Change: 2026-08-21 Jizixing Zhu -- route O2 through the reusable species
%   request kernel and fail fast on unimplemented species fields.

    assert(isscalar(tStart_s) && isfinite(tStart_s) && tStart_s >= 0 ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'materializeGasBoundaryTrial:badInterval', ...
        'Gas boundary materialization requires finite tStart_s >= 0 and dt_s > 0.');
    assert(isstruct(speciesSpecs), ...
        'materializeGasBoundaryTrial:badSpeciesSpecs', ...
        'Species boundary specifications must be a struct.');

    carrierEnabled = true;
    if isfield(drivers, 'carrier_enabled')
        carrierEnabled = logical(drivers.carrier_enabled);
    end
    carrierRequest = soil.gas.boundary.materializeRequest( ...
        carrierSpec, drivers, tStart_s, dt_s);
    carrierRequest.enabled = carrierEnabled;
    request = struct('schema_version', 1, 'enabled', true, ...
        'sign_convention', 'flux_into_domain_positive', ...
        't_start_s', tStart_s, 't_end_s', tStart_s + dt_s, 'dt_s', dt_s, ...
        'carrier', carrierRequest, 'species', struct());

    names = fieldnames(speciesSpecs);
    unsupported = setdiff(names, {'O2'});
    assert(isempty(unsupported), ...
        'materializeGasBoundaryTrial:unsupportedSpecies', ...
        'Gas species %s is not implemented and cannot be materialized.', ...
        strjoin(unsupported, ', '));
    if isfield(speciesSpecs, 'O2')
        required = {'o2_dry_mole_fraction'};
        assert(all(isfield(drivers, required)), ...
            'materializeGasBoundaryTrial:missingOxygenDriver', ...
            'O2 materialization requires atmospheric composition forcing.');
        driver = struct('species', 'O2', ...
            'dry_mole_fraction', drivers.o2_dry_mole_fraction);
        if isfield(drivers, 'bottom_liquid_flux_into_domain_cm_s')
            driver.bottom_liquid_flux_into_domain_cm_s = ...
                drivers.bottom_liquid_flux_into_domain_cm_s;
        end
        request.species.O2 = ...
            soil.gas.boundary.materializeSpeciesRequest( ...
                speciesSpecs.O2, driver, tStart_s, dt_s);
    end
end

