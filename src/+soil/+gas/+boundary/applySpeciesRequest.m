function applied = applySpeciesRequest(request, candidate)
%APPLYSPECIESREQUEST Apply one frozen dilute-species request to a candidate.
%
%   The request is immutable during the trial. This adapter alone may use
%   candidate endpoint pressure, temperature, and vapor density to convert a
%   dry mole fraction into gas molar concentration. Public flux signs are
%   positive into the soil column.
%
%   Editor: Jizixing Zhu; Date: 2026-08-20.
%   Change: 2026-08-21 Jizixing Zhu -- remove O2 hard-coding from the applied
%   boundary kernel while preserving the production O2 request/result values.

    assert(isstruct(request) && isfield(request, 'species') ...
            && ~isempty(char(string(request.species))), ...
        'applyGasSpeciesBoundary:badRequest', ...
        'The species boundary adapter requires one typed species request.');
    species = char(string(request.species));
    required = {'gas_pressure_Pa','temperature_C','vapor_density_g_cm3'};
    assert(isstruct(candidate) && all(isfield(candidate, required)), ...
        'applyGasSpeciesBoundary:missingCandidate', ...
        'Species boundary application requires pressure, temperature, and vapor density.');
    n = numel(candidate.gas_pressure_Pa);
    assert(n >= 2 && numel(candidate.temperature_C) == n ...
            && numel(candidate.vapor_density_g_cm3) == n ...
            && all(isfinite(candidate.gas_pressure_Pa(:))) ...
            && all(candidate.gas_pressure_Pa(:) > 0) ...
            && all(isfinite(candidate.temperature_C(:))) ...
            && all(isfinite(candidate.vapor_density_g_cm3(:))) ...
            && all(candidate.vapor_density_g_cm3(:) >= 0), ...
        'applyGasSpeciesBoundary:badCandidate', ...
        'Candidate gas endpoint fields have incompatible shape or invalid values.');

    top = fixedEndpoint(request.top);
    switch request.bottom.kind
        case 'fixed_atmospheric_dry_mole_fraction'
            bottom = fixedEndpoint(request.bottom);
        case 'zero_total_flux'
            bottom = fluxEndpoint(request.bottom, 0);
        case 'zero_gas_phase_flux_with_liquid_outflow'
            assert(isfield(request.bottom, ...
                    'requested_liquid_flux_into_domain_cm_s'), ...
                'applyGasSpeciesBoundary:missingBottomLiquidFlux', ...
                ['The zero-free-gas species boundary requires the frozen ', ...
                 'bottom free-drainage liquid flux.']);
            liquidFlux = double( ...
                request.bottom.requested_liquid_flux_into_domain_cm_s);
            assert(isscalar(liquidFlux) && isfinite(liquidFlux) ...
                    && liquidFlux <= 0, ...
                'applyGasSpeciesBoundary:badBottomLiquidFlux', ...
                'Bottom free-drainage liquid flux must be finite and outward (<=0).');
            bottom = endpointBase(request.bottom, ...
                'zero_gas_phase_flux_with_liquid_outflow');
            bottom.liquid_flux_into_domain_cm_s = liquidFlux;
        case 'external_composition_required'
            error('applyGasSpeciesBoundary:missingInflowComposition', ...
                ['A nonzero carrier bottom flux requires an explicit %s ', ...
                 'external composition before that species can advance.'], ...
                species);
        otherwise
            error('applyGasSpeciesBoundary:unsupportedBottomKind', ...
                'Unsupported %s bottom boundary kind: %s.', ...
                species, request.bottom.kind);
    end
    applied = struct('schema_version', 1, 'species', species, ...
        'quantity', 'molar', ...
        'sign_convention', 'flux_into_domain_positive', ...
        'top', top, 'bottom', bottom);
end

function out = fixedEndpoint(request)
    y = request.requested_external_dry_mole_fraction;
    assert(isscalar(y) && isfinite(y) && y >= 0 && y <= 1, ...
        'applyGasSpeciesBoundary:badDryMoleFraction', ...
        'A fixed dry-gas mole fraction must be finite and in [0,1].');
    out = endpointBase(request, 'fixed_dry_mole_fraction');
    out.dry_mole_fraction = y;
end

function out = fluxEndpoint(request, flux)
    out = endpointBase(request, 'fixed_total_molar_flux');
    out.flux_into_domain_mol_cm2_s = flux;
end

function out = endpointBase(request, appliedKind)
    out = struct('requested_kind', request.kind, ...
        'applied_kind', appliedKind, ...
        'composition_source', request.composition_source, ...
        'requested_external_dry_mole_fraction', ...
            request.requested_external_dry_mole_fraction, ...
        'dry_mole_fraction', NaN, ...
        'concentration_mol_cm3', NaN, ...
        'flux_into_domain_mol_cm2_s', NaN, ...
        'liquid_flux_into_domain_cm_s', NaN);
end

