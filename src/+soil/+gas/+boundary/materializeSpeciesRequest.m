function request = materializeSpeciesRequest( ...
        spec, driver, tStart_s, dt_s)
%MATERIALIZESPECIESREQUEST Freeze one dilute gas-species boundary request.
%
%   SPEC supplies the static endpoint policy. DRIVER supplies the species
%   identity, dry mole fraction [-], and, when required, accepted bottom liquid flux
%   [cm s^-1, into-domain positive]. No candidate state is read here.
%
%   This is a reusable boundary kernel, not evidence that a particular new
%   species is initialized, coupled, or enabled in production.
%
%   Editor: Jizixing Zhu; Date: 2026-08-21.

    requiredDriver = {'species','dry_mole_fraction'};
    assert(isstruct(spec) && isfield(spec, 'species') ...
            && isstruct(driver) && all(isfield(driver, requiredDriver)), ...
        'materializeGasSpeciesRequest:missingDriver', ...
        'Species materialization requires a typed spec and atmospheric composition.');
    species = char(string(driver.species));
    assert(strcmp(char(string(spec.species)), species), ...
        'materializeGasSpeciesRequest:speciesMismatch', ...
        'The species boundary spec and driver identify different species.');
    y = double(driver.dry_mole_fraction);
    assert(isscalar(y) && isfinite(y) && y >= 0 && y <= 1, ...
        'materializeGasSpeciesRequest:badDriver', ...
        'Species dry mole fraction is invalid.');
    assert(isscalar(tStart_s) && isfinite(tStart_s) && tStart_s >= 0 ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'materializeGasSpeciesRequest:badInterval', ...
        'Species materialization requires finite tStart_s >= 0 and dt_s > 0.');

    request = struct('schema_version', 1, 'enabled', true, ...
        'species', species, 'quantity', 'molar', ...
        'sign_convention', 'flux_into_domain_positive', ...
        't_start_s', tStart_s, 't_end_s', tStart_s + dt_s, 'dt_s', dt_s, ...
        'top', endpoint(spec.top, y), ...
        'bottom', endpoint(spec.bottom, y));
    if strcmp(spec.bottom.kind, ...
            'zero_gas_phase_flux_with_liquid_outflow')
        assert(isfield(driver, 'bottom_liquid_flux_into_domain_cm_s'), ...
            'materializeGasSpeciesRequest:missingBottomLiquidFlux', ...
            ['Zero-free-gas species materialization requires the accepted ', ...
             'bottom liquid free-drainage flux.']);
        qLiquid = double(driver.bottom_liquid_flux_into_domain_cm_s);
        assert(isscalar(qLiquid) && isfinite(qLiquid) && qLiquid <= 0, ...
            'materializeGasSpeciesRequest:badBottomLiquidFlux', ...
            'Bottom free-drainage liquid flux must be finite and outward (<=0).');
        request.bottom.requested_liquid_flux_into_domain_cm_s = qLiquid;
    end
end

function out = endpoint(spec, moleFraction)
    out = struct('kind', spec.kind, ...
        'composition_source', spec.composition_source, ...
        'candidate_state_dependent', logical(spec.candidate_state_dependent), ...
        'requested_external_dry_mole_fraction', moleFraction, ...
        'requested_flux_into_domain_mol_cm2_s', NaN, ...
        'requested_liquid_flux_into_domain_cm_s', NaN);
end

