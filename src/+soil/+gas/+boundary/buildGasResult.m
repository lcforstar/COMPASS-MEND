function result = buildGasResult(request, carrierSummary, speciesResults, accepted)
%BUILDGASRESULT Join carrier and species boundary results for one interval.
%
%   The carrier retains its dry-air mass units while each species retains
%   molar units. The shared parent records only time, sign, provenance, and
%   acceptance; it never adds unlike fluxes together.
%
%   Reference: accepted carrier summary from
%   src/+solver/advanceSoilEquationOuterStep.m and species result from
%   src/+soil/+gas/+boundary/buildSpeciesResult.m.
%
%   Editor: Jizixing Zhu; Date: 2026-08-20.

    assert(isstruct(request) && isfield(request, 'carrier') ...
            && isstruct(carrierSummary) && isstruct(speciesResults), ...
        'buildGasBoundaryResult:badInput', ...
        'Gas boundary result requires carrier request/result and species results.');
    result = struct('schema_version', 1, 'has_data', true, ...
        'sign_convention', 'flux_into_domain_positive', ...
        't_start_s', request.t_start_s, 't_end_s', request.t_end_s, ...
        'dt_s', request.dt_s, 'accepted', logical(accepted), ...
        'carrier', struct('quantity', 'dry_air_mass', ...
            'unit', 'g_cm2_s', 'request', request.carrier, ...
            'result', carrierSummary), ...
        'species', speciesResults);
end

