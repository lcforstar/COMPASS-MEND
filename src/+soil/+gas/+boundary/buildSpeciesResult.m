function result = buildSpeciesResult(request, applied, ledger, accepted)
%BUILDSPECIESRESULT Package one solved gas-species boundary result.
%
%   Applied fluxes are recovered from the exact discrete species ledger and
%   reported as inward-positive molar rates [mol cm^-2 s^-1]. No rejected
%   result is accumulated by this function.
%
%   Reference: exact discrete boundary reactions returned by
%   src/+soil/+gas/solveO2Transport.m.
%
%   Editor: Jizixing Zhu; Date: 2026-08-20.

    required = {'top_input_mol_cm2','bottom_input_mol_cm2'};
    assert(isstruct(request) && isfield(request, 'dt_s') ...
            && isstruct(applied) && isstruct(ledger) ...
            && all(isfield(ledger, required)), ...
        'buildGasSpeciesBoundaryResult:badInput', ...
        'Species result requires request, applied endpoints, and boundary ledger.');
    dt_s = request.dt_s;
    result = struct('schema_version', 1, 'species', request.species, ...
        'quantity', 'molar', ...
        'sign_convention', 'flux_into_domain_positive', ...
        't_start_s', request.t_start_s, 't_end_s', request.t_end_s, ...
        'dt_s', dt_s, 'accepted', logical(accepted), ...
        'top', endpoint(request.top, applied.top, ...
            ledger.top_input_mol_cm2 / dt_s), ...
        'bottom', endpoint(request.bottom, applied.bottom, ...
            ledger.bottom_input_mol_cm2 / dt_s));
end

function out = endpoint(request, applied, actualFlux)
% Join requested policy, applied equation, and solved flux.
% Editor: Jizixing Zhu; Date: 2026-08-20.
    out = struct('requested_kind', request.kind, ...
        'applied_kind', applied.applied_kind, ...
        'composition_source', request.composition_source, ...
        'requested_external_dry_mole_fraction', ...
            request.requested_external_dry_mole_fraction, ...
        'requested_dry_mole_fraction', ...
            request.requested_external_dry_mole_fraction, ...
        'applied_dry_mole_fraction', applied.dry_mole_fraction, ...
        'requested_flux_into_domain_mol_cm2_s', ...
            request.requested_flux_into_domain_mol_cm2_s, ...
        'actual_flux_into_domain_mol_cm2_s', actualFlux);
end

