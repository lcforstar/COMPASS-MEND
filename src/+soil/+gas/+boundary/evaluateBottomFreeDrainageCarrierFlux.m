function flux = evaluateBottomFreeDrainageCarrierFlux(built)
%EVALUATEBOTTOMFREEDRAINAGECARRIERFLUX Materialize the bottom carrier split.
%
%   The bottom free-gas flux is zero. Liquid water still leaves under the
%   Richards free-drainage condition q_l^in=-K_l,b, and carries equilibrium
%   dissolved dry air:
%
%     q_a,total^in = 0 + H_c rho_a,b q_l^in.       [g cm^-2 s^-1]
%
%   Values come from the same refreshed Picard candidate used to assemble the
%   water and dry-air rows. This function does not mutate state.
%
%   Editor: Jizixing Zhu; Date: 2026-08-20.

    assert(isfield(built, 'boundary') && isfield(built.boundary, 'water') ...
            && strcmp(built.boundary.water.bottom.kind, 'free_drainage'), ...
        'evaluateBottomFreeDrainageCarrierFlux:incompatibleWaterBoundary', ...
        'zero_gas_phase_flux requires water_bottom_kind=free_drainage.');
    assert(isfield(built, 'workspace') && isfield(built.workspace, 'derived') ...
            && isfield(built.workspace.derived, 'KfL_h') ...
            && isfield(built.workspace.derived, 'RHODA'), ...
        'evaluateBottomFreeDrainageCarrierFlux:missingCandidate', ...
        'Bottom carrier flux requires refreshed KfL_h and RHODA.');
    conductivity = double(built.workspace.derived.KfL_h(1,1));
    rhoDryAir = double(built.workspace.derived.RHODA(1));
    assert(all(isfinite([conductivity, rhoDryAir])) ...
            && conductivity >= 0 && rhoDryAir >= 0, ...
        'evaluateBottomFreeDrainageCarrierFlux:badCandidate', ...
        'Bottom KfL_h and RHODA must be finite and nonnegative.');
    liquidFluxInto = -conductivity;
    Hc = equations.getPhysicalConstant('Hc');
    dissolvedFluxInto = Hc * rhoDryAir * liquidFluxInto;
    flux = struct('schema_version', 1, ...
        'free_gas_flux_into_domain_g_cm2_s', 0, ...
        'liquid_flux_into_domain_cm_s', liquidFluxInto, ...
        'dissolved_flux_into_domain_g_cm2_s', dissolvedFluxInto, ...
        'total_flux_into_domain_g_cm2_s', dissolvedFluxInto, ...
        'dry_air_density_bottom_g_cm3', rhoDryAir, ...
        'henry_mass_partition', Hc);
end

