function [built, tile] = advanceOxygenSubstep( ...
        built, snapshot, outcome, kt, tStart_s, dt_s)
%ADVANCEOXYGENSUBSTEP Solve O2 after one converged h/U/P_g adaptive tile.
%
% The carrier endpoint and its authoritative shared flux family are frozen.
% A local Picard loop closes y_O2 with the instantaneous nitrification sink;
% hourly nitrogen pools are read but never advanced here. Failure returns an
% unaccepted tile so the parent soil scheduler restores the identical snapshot
% and retries at a smaller timestep.
% Change: 2026-10-28 Wenjie Liu -- pass current trial matric head to the
% shared dry-side nitrification kernel before computing its O2 demand.
%
% Editor: Jizixing Zhu; Date: 2026-08-21.
% Change: 2026-08-22 Jizixing Zhu -- advect O2 with the conservative
% accepted-carrier interface flux reconstructed from nodal dry-air storage
% and applied boundary reactions; retain the constitutive point flux only as
% a diagnostic comparison.

    assert(isfield(snapshot, 'oxygen_phase') ...
            && isfield(snapshot.Y, 'soil_gas') ...
            && isfield(snapshot.Y.soil_gas, 'y_O2'), ...
        'advanceOxygenSubstep:missingAcceptedOxygenState', ...
        'O2 requires an accepted y_O2 state and accepted phase snapshot.');
    diagnostics = outcome.solverDiagnostics;
    required = {'QL','QL_h','QL_T','QL_a','Qa_free'};
    assert(all(isfield(diagnostics, required)), ...
        'advanceOxygenSubstep:missingSharedFlux', ...
        'O2 requires the accepted shared liquid and free dry-air flux family.');
    assert(isfield(outcome, 'dryAirStorageBefore') ...
            && ~isempty(outcome.dryAirStorageBefore) ...
            && isfield(outcome, 'dryAirStorageAfter') ...
            && ~isempty(outcome.dryAirStorageAfter) ...
            && isfield(outcome, 'airFlux') ...
            && isstruct(outcome.airFlux) ...
            && all(isfield(outcome.airFlux, {'QAT','QAB'})), ...
        'advanceOxygenSubstep:missingCarrierStorage', ...
        ['O2 requires accepted before/after dry-air storage and applied ', ...
         'carrier boundary reactions.']);

    phaseOld = phaseFromSnapshot(built, snapshot);
    phaseNew = phaseFromCandidate(built);
    props = soil.gas.species.oxygenProperties();
    carrierFlux = soil.gas.reconstructConservativeCarrierFlux( ...
        outcome.dryAirStorageBefore, outcome.dryAirStorageAfter, ...
        built.domain.dz, outcome.airFlux, dt_s, diagnostics.QL(:), ...
        phaseNew.theta_g, phaseNew.theta_l, ...
        props.dry_air_molar_mass_g_mol);
    request = materializeBoundary(built, kt, tStart_s, dt_s, diagnostics.QL(1));
    applied = soil.gas.boundary.applySpeciesRequest( ...
        request.species.O2, struct( ...
        'gas_pressure_Pa', phaseNew.gas_pressure_Pa, ...
        'temperature_C', phaseNew.temperature_C, ...
        'vapor_density_g_cm3', built.workspace.derived.RHOV(:)));
    transport = struct( ...
        'free_dry_air_mass_flux_g_cm2_s', ...
            carrierFlux.free_mass_flux_g_cm2_s, ...
        'gas_dispersion_cm2_s', built.workspace.derived.D_Vg(:), ...
        'liquid_flux_cm_s', diagnostics.QL(:));

    yOld = snapshot.Y.soil_gas.y_O2(:);
    yReference = yOld;
    sinkReference = acceptedSinkSeed(built);
    yRelative = Inf;
    sinkRelative = Inf;
    maxIterations = 30;
    for iteration = 1:maxIterations
        [yCandidate, dissolved, fAerobic, fAnaerobic, ledger] = ...
            soil.gas.solveO2Transport(yOld, yReference, phaseOld, phaseNew, ...
                transport, sinkReference, built.domain.dz, dt_s, applied);
        [Snit, SnitN2O] = instantaneousNitrification( ...
            built, kt, fAerobic);
        sinkCandidate = soil.gas.calcO2Sink(Snit, built.domain.NL);
        yScale = max([1e-12; abs(yCandidate); abs(yReference)]);
        sinkScale = max([1e-30; abs(sinkCandidate); abs(sinkReference)]);
        yRelative = max(abs(yCandidate - yReference)) / yScale;
        sinkRelative = max(abs(sinkCandidate - sinkReference)) / sinkScale;
        yReference = yCandidate;
        sinkReference = sinkCandidate;
        if yRelative <= 1e-6 && sinkRelative <= 1e-6
            break;
        end
    end
    converged = yRelative <= 1e-6 && sinkRelative <= 1e-6;
    consistency = carrierConsistency( ...
        phaseNew, yCandidate, outcome.dryAirStorageAfter, ...
        ledger.reaction_loss_mol_cm2, built.domain.dz);
    admissible = consistency.minimum_background_storage_g_cm3 >= -1e-15 ...
        && abs(ledger.balance_residual_mol_cm2) <= ...
            1e-12 + 1e-8 * max(ledger.storage_after_mol_cm2, 1e-20);
    tile = struct('converged', converged, 'admissible', admissible, ...
        'iterations', iteration, 'y_relative_change', yRelative, ...
        'sink_relative_change', sinkRelative, 'y_O2', yCandidate, ...
        'C_O2_liq', dissolved, 'f_aerobic', fAerobic, ...
        'f_anaerobic', fAnaerobic, 'Snit', Snit, ...
        'Snit_N2O', SnitN2O, 'R_O2_sink', sinkCandidate, ...
        'QL', diagnostics.QL(:), 'QL_h', diagnostics.QL_h(:), ...
        'QL_T', diagnostics.QL_T(:), 'QL_a', diagnostics.QL_a(:), ...
        'ledger', ledger, 'boundary_request', request.species.O2, ...
        'boundary_applied', applied, 'carrier_consistency', consistency);
    tile.carrier_flux_reconstruction = carrierFlux;
    tile.constitutive_free_dry_air_mass_flux_g_cm2_s = diagnostics.Qa_free(:);
    if converged && admissible
        built.workspace.step.trial.soil_gas.y_O2 = yCandidate;
    end
end

function phase = phaseFromSnapshot(built, snapshot)
    phys = equations.physicalConstants();
    T = snapshot.Y.T(:);
    rhoV = snapshot.oxygen_phase.vapor_density_g_cm3(:);
    phase = struct('theta_l', snapshot.oxygen_phase.theta_l, ...
        'theta_g', repmat(built.parameters.soil.porosity(:),1,2) ...
            - snapshot.oxygen_phase.theta_l - snapshot.oxygen_phase.theta_i, ...
        'temperature_C', T, 'porosity', built.parameters.soil.porosity(:), ...
        'gas_pressure_Pa', snapshot.Y.p_gas(:) / 10, ...
        'vapor_pressure_Pa', rhoV .* phys.Rv .* (T + phys.C_to_K) / 10);
end

function phase = phaseFromCandidate(built)
    phys = equations.physicalConstants();
    T = built.workspace.step.trial.T(:);
    rhoV = built.workspace.derived.RHOV(:);
    phase = struct('theta_l', built.workspace.derived.Theta_LL, ...
        'theta_g', built.workspace.derived.Theta_g, ...
        'temperature_C', T, 'porosity', built.parameters.soil.porosity(:), ...
        'gas_pressure_Pa', built.workspace.step.trial.p_gas(:) / 10, ...
        'vapor_pressure_Pa', rhoV .* phys.Rv .* (T + phys.C_to_K) / 10);
end

function request = materializeBoundary(built, kt, tStart, dt, bottomLiquidFlux)
    atmospheric = atmosphere.sliceForcing(built.forcing, kt);
    y = forcingAt(built.forcing.hourly.Oa, kt, NaN) * 1e-3;
    drivers = struct('atmospheric_pressure_Pa', atmospheric.pressure_Pa, ...
        'column_depth_cm', built.domain.grid.Tot_Depth, ...
        'carrier_enabled', true, 'o2_dry_mole_fraction', y);
    if strcmp(built.boundary.gas_species.O2.bottom.kind, ...
            'zero_gas_phase_flux_with_liquid_outflow')
        assert(isfinite(bottomLiquidFlux) && bottomLiquidFlux <= 1e-14, ...
            'advanceOxygenSubstep:inwardBottomLiquidFlux', ...
            'The sealed-free-drainage O2 boundary requires outward bottom liquid flux.');
        drivers.bottom_liquid_flux_into_domain_cm_s = min(bottomLiquidFlux, 0);
    end
    request = soil.gas.boundary.materializeGasBoundaryTrial( ...
        built.boundary.dry_air, built.boundary.gas_species, ...
        drivers, tStart, dt);
end

function sink = acceptedSinkSeed(built)
    sink = zeros(built.domain.NL, 1);
    if isfield(built.Y, 'soil_nitrogen') ...
            && isfield(built.Y.soil_nitrogen, 'variables') ...
            && isfield(built.Y.soil_nitrogen.variables, 'Snit') ...
            && ~isempty(built.Y.soil_nitrogen.variables.Snit)
        sink = soil.gas.calcO2Sink( ...
            built.Y.soil_nitrogen.variables.Snit, built.domain.NL);
    end
end

function [Snit, SnitN2O] = instantaneousNitrification(built, kt, fAerobic)
    p = built.parameters.soil_n;
    % Change: 2026-10-23 Wenjie Liu -- optional biological pH rate factor;
    % keep the original response for reference callers without the switch.
    phResponseEnabled=~isfield(p,'ph_response_enabled')||p.ph_response_enabled;
    phys = equations.physicalConstants();
    [Snit, ~, ~, ~, ~, ~, SnitN2O] = ...
        soil.nitrogen.chemistry.nitrification( ...
        built.workspace.step.trial.T(:), ...
        built.workspace.step.trial.nh4(:), built.domain.NL, ...
        built.workspace.derived.Theta_LL, p.Theta_f, ...
        built.parameters.soil.theta_s(:), p.RHOKG, p.Vmax_nit, p.Km_nit, ...
        zeros(built.domain.NL,2), phys.R, phys.Tr, ones(built.domain.NL,2), ...
        zeros(max(1,kt),1), p.pH, zeros(built.domain.NL,2), kt, ...
        built.domain.dz, fAerobic, phResponseEnabled,built.workspace.step.trial.h(:));
end

function consistency = carrierConsistency(phase, y, dryAirStorage, reactionMol, dz)
    props = soil.gas.species.oxygenProperties();
    NL = numel(phase.porosity);
    T = [phase.temperature_C(1:NL), phase.temperature_C(2:NL+1)] + 273.15;
    Pg = [phase.gas_pressure_Pa(1:NL), phase.gas_pressure_Pa(2:NL+1)];
    Pv = [phase.vapor_pressure_Pa(1:NL), phase.vapor_pressure_Pa(2:NL+1)];
    cd = (Pg - Pv) ./ (8.31446261815324 .* T) * 1e-6;
    KH = props.henry_reference_mol_L_atm .* exp( ...
        props.henry_enthalpy_over_R_K .* (1 ./ T ...
        - 1 / props.henry_reference_temperature_K));
    beta = KH .* props.gas_constant_cm3_atm_mol_K .* T / 1000;
    yEndpoints = [y(1:NL), y(2:NL+1)];
    o2Storage = (phase.theta_g .* cd + phase.theta_l .* beta .* cd) ...
        .* yEndpoints * props.species_molar_mass_g_mol;
    background = dryAirStorage - o2Storage;
    columnCarrier = sum(dz(:) .* mean(dryAirStorage,2));
    consistency = struct( ...
        'minimum_background_storage_g_cm3', min(background(:)), ...
        'omitted_reaction_feedback_g_cm2', ...
            reactionMol * props.species_molar_mass_g_mol, ...
        'omitted_reaction_feedback_ratio', ...
            reactionMol * props.species_molar_mass_g_mol ...
            / max(columnCarrier, realmin));
end

function value = forcingAt(series, kt, fallback)
    value = fallback;
    if ~isempty(series), value = series(min(kt, numel(series))); end
    assert(isscalar(value) && isfinite(value), ...
        'advanceOxygenSubstep:missingOxygenForcing', ...
        'Atmospheric dry O2 mole-fraction forcing is required.');
end

