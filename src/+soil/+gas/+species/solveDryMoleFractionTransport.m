function [dryMoleFraction, dissolvedConcentration, diagnostic] = ...
        solveDryMoleFractionTransport(dryMoleFractionOld, ...
        dryMoleFractionReference, phaseOld, phaseNew, transport, ...
        reactionSinkReference, DeltZ, Delt_t, boundary, properties)
%SOLVEDRYMOLEFRACTIONTRANSPORT Advance one conservative dilute gas species.
%
% Nodes are bottom-to-surface and positive element flux points upward.  The
% sole unknown is dry-gas mole fraction y_i [-].  Per bulk-soil volume,
%
%   S_i = (theta_g + beta_i theta_l) c_d y_i,
%   c_d = (P_g-P_v)/(R T) 1e-6                         [mol cm^-3 gas].
%
% The element flux is dry-carrier advection, relative-composition molecular
% diffusion/mechanical dispersion, and equilibrium dissolved liquid
% advection.  Both advective terms use first-order upwinding.  Storage is
% mass-lumped on the existing linear two-node elements and time integration
% is backward Euler.  This kernel owns no accepted state and performs no
% commit.
%
% Editor: Jizixing Zhu; Date: 2026-08-21.
% Change: 2026-08-28 Jizixing Zhu -- consume gas_dispersion_cm2_s as the
% bulk coefficient alpha_Lg*abs(Darcy gas flux), without another theta_g.
% Change: 2026-11-01 Wenjie Liu -- return dissolved concentration in mol/L;
% KH*R*T already converts gas mol/cm3 to liquid mol/L. Retain the separate
% /1000 conversion in phaseCapacity for conservative mol/cm3 storage.

    [NL, NN, dz] = validateInputs(dryMoleFractionOld, ...
        dryMoleFractionReference, phaseOld, phaseNew, transport, ...
        reactionSinkReference, DeltZ, Delt_t, boundary, properties);
    [capacityOld, ~, ~, ~] = phaseCapacity(phaseOld, properties);
    [capacityNew, dissolvedStorageRatio, dissolvedConcentrationRatio, ...
        dryMolarDensity] = phaseCapacity(phaseNew, properties);

    lower = zeros(NL, 1);
    diagonal = zeros(NN, 1);
    upper = zeros(NN, 1);
    rhs = zeros(NN, 1);
    reactionCoefficient = reactionLinearization( ...
        reactionSinkReference, dryMoleFractionReference, NL);
    molecularDiffusion = effectiveMolecularDiffusion(phaseNew, properties);

    for element = 1:NL
        lo = element;
        hi = element + 1;
        halfVolume = dz(element) / 2;
        diagonal(lo) = diagonal(lo) ...
            + capacityNew(element, 1) * halfVolume / Delt_t ...
            + reactionCoefficient(element) * halfVolume;
        diagonal(hi) = diagonal(hi) ...
            + capacityNew(element, 2) * halfVolume / Delt_t ...
            + reactionCoefficient(element) * halfVolume;
        rhs(lo) = rhs(lo) + capacityOld(element, 1) * halfVolume ...
            * dryMoleFractionOld(lo) / Delt_t;
        rhs(hi) = rhs(hi) + capacityOld(element, 2) * halfVolume ...
            * dryMoleFractionOld(hi) / Delt_t;

        diffusionConductance = mean(dryMolarDensity(element, :) ...
            .* (molecularDiffusion(element, :) ...
            + transport.gas_dispersion_cm2_s(element))) / dz(element);
        [fluxLo, fluxHi] = elementFluxCoefficients( ...
            diffusionConductance, ...
            transport.free_dry_air_mass_flux_g_cm2_s(element) ...
                / properties.dry_air_molar_mass_g_mol, ...
            transport.liquid_flux_cm_s(element), ...
            dissolvedStorageRatio(element, 1), ...
            dissolvedStorageRatio(element, 2));
        diagonal(lo) = diagonal(lo) + fluxLo;
        upper(lo) = upper(lo) + fluxHi;
        lower(element) = lower(element) - fluxLo;
        diagonal(hi) = diagonal(hi) - fluxHi;
    end

    original = struct('lower', lower, 'diagonal', diagonal, ...
        'upper', upper, 'rhs', rhs);
    [lower, diagonal, upper, rhs] = applyBoundaryConditions( ...
        lower, diagonal, upper, rhs, boundary, ...
        dissolvedStorageRatio(1, 1), NN);
    dryMoleFraction = solver.solveTridiagonal( ...
        lower, diagonal, upper, rhs, [1, NN]);

    scale = max([1; dryMoleFractionOld(:); ...
        boundary.top.dry_mole_fraction]);
    tolerance = 256 * eps(scale);
    assert(all(isfinite(dryMoleFraction)) ...
            && min(dryMoleFraction) >= -tolerance ...
            && max(dryMoleFraction) <= 1 + tolerance, ...
        'solveO2Transport:inadmissibleDryMoleFraction', ...
        'O2 dry mole fraction must remain finite and in [0,1].');
    roundoffLow = dryMoleFraction < 0;
    roundoffHigh = dryMoleFraction > 1;
    weights = nodalLumped(capacityNew, dz);
    positivityCorrection = sum(weights .* ...
        (-dryMoleFraction .* roundoffLow ...
        + (1 - dryMoleFraction) .* roundoffHigh));
    dryMoleFraction(roundoffLow) = 0;
    dryMoleFraction(roundoffHigh) = 1;

    yEndpoint = [dryMoleFraction(1:NL), dryMoleFraction(2:NN)];
    dissolvedEndpointMolL = dissolvedConcentrationRatio ...
        .* dryMolarDensity .* yEndpoint;
    dissolvedConcentration = mean(dissolvedEndpointMolL, 2);
    diagnostic = buildLedger(dryMoleFractionOld, dryMoleFraction, ...
        capacityOld, capacityNew, reactionCoefficient, dz, Delt_t, ...
        original, boundary, dissolvedStorageRatio(1, 1), ...
        positivityCorrection);
end

function [NL, NN, dz] = validateInputs(yOld, yReference, oldPhase, ...
        newPhase, transport, sink, DeltZ, dt, boundary, properties)
    requiredProperties = {'species','free_diffusivity_reference_cm2_s', ...
        'diffusion_reference_temperature_K','pressure_reference_Pa', ...
        'diffusion_temperature_exponent','henry_reference_temperature_K', ...
        'henry_reference_mol_L_atm','henry_enthalpy_over_R_K', ...
        'gas_constant_cm3_atm_mol_K','dry_air_molar_mass_g_mol'};
    assert(isstruct(properties) && all(isfield(properties, requiredProperties)), ...
        'solveO2Transport:missingProperties', ...
        'Dry-mole-fraction transport properties are incomplete.');
    dz = DeltZ(:);
    NL = numel(dz);
    NN = NL + 1;
    assert(NL >= 1 && all(isfinite(dz)) && all(dz > 0) ...
            && isscalar(dt) && isfinite(dt) && dt > 0, ...
        'solveO2Transport:badGrid', 'Require positive finite dz and dt.');
    for value = {yOld, yReference}
        assert(numel(value{1}) == NN && all(isfinite(value{1}(:))) ...
                && all(value{1}(:) >= 0 & value{1}(:) <= 1), ...
            'solveO2Transport:badDryMoleFraction', ...
            'Accepted and reference y_O2 must be finite NN vectors in [0,1].');
    end
    validatePhase(oldPhase, NL, NN, 'old');
    validatePhase(newPhase, NL, NN, 'new');
    requiredTransport = {'free_dry_air_mass_flux_g_cm2_s', ...
        'gas_dispersion_cm2_s','liquid_flux_cm_s'};
    assert(isstruct(transport) && all(isfield(transport, requiredTransport)), ...
        'solveO2Transport:missingTransport', ...
        'Transport must provide shared free dry-air, gas dispersion, and liquid flux.');
    for i = 1:numel(requiredTransport)
        value = transport.(requiredTransport{i});
        assert(numel(value) == NL && all(isfinite(value(:))), ...
            'solveO2Transport:badTransport', ...
            'Transport field %s must contain NL finite values.', ...
            requiredTransport{i});
    end
    assert(all(transport.gas_dispersion_cm2_s(:) >= 0), ...
        'solveO2Transport:negativeDispersion', ...
        'Gas mechanical dispersion must be nonnegative.');
    assert(numel(sink) == NL && all(isfinite(sink(:))) ...
            && all(sink(:) >= 0), ...
        'solveO2Transport:badSink', ...
        'O2 reaction demand must be one finite nonnegative NL vector.');
    assert(isstruct(boundary) && isfield(boundary, 'species') ...
            && strcmp(boundary.species, properties.species) ...
            && isfield(boundary, 'top') && isfield(boundary, 'bottom') ...
            && strcmp(boundary.top.applied_kind, 'fixed_dry_mole_fraction') ...
            && isscalar(boundary.top.dry_mole_fraction) ...
            && isfinite(boundary.top.dry_mole_fraction) ...
            && boundary.top.dry_mole_fraction >= 0 ...
            && boundary.top.dry_mole_fraction <= 1, ...
        'solveO2Transport:badTopBoundary', ...
        'Top O2 boundary must provide a finite dry mole fraction in [0,1].');
    fixedBottom = strcmp(boundary.bottom.applied_kind, ...
        'fixed_dry_mole_fraction') ...
        && isfield(boundary.bottom, 'dry_mole_fraction') ...
        && isfinite(boundary.bottom.dry_mole_fraction) ...
        && boundary.bottom.dry_mole_fraction >= 0 ...
        && boundary.bottom.dry_mole_fraction <= 1;
    zeroFluxBottom = strcmp(boundary.bottom.applied_kind, ...
        'fixed_total_molar_flux') ...
        && boundary.bottom.flux_into_domain_mol_cm2_s == 0;
    zeroGasBottom = strcmp(boundary.bottom.applied_kind, ...
        'zero_gas_phase_flux_with_liquid_outflow') ...
        && isfinite(boundary.bottom.liquid_flux_into_domain_cm_s) ...
        && boundary.bottom.liquid_flux_into_domain_cm_s <= 0;
    assert(fixedBottom || zeroFluxBottom || zeroGasBottom, ...
        'solveO2Transport:badBottomBoundary', ...
        'Unsupported O2 bottom boundary.');
end

function validatePhase(phase, NL, NN, label)
    required = {'theta_g','theta_l','temperature_C','porosity', ...
        'gas_pressure_Pa','vapor_pressure_Pa'};
    assert(isstruct(phase) && all(isfield(phase, required)) ...
            && isequal(size(phase.theta_g), [NL, 2]) ...
            && isequal(size(phase.theta_l), [NL, 2]) ...
            && numel(phase.temperature_C) == NN ...
            && numel(phase.porosity) == NL ...
            && numel(phase.gas_pressure_Pa) == NN ...
            && numel(phase.vapor_pressure_Pa) == NN, ...
        'solveO2Transport:badPhaseShape', ...
        '%s phase contract has incompatible fields or shapes.', label);
    porosity = repmat(phase.porosity(:), 1, 2);
    dryPressure = phase.gas_pressure_Pa(:) - phase.vapor_pressure_Pa(:);
    assert(all(isfinite([phase.theta_g(:); phase.theta_l(:); ...
            phase.temperature_C(:); dryPressure])) ...
            && all(phase.theta_g(:) >= 0) && all(phase.theta_l(:) >= 0) ...
            && all(phase.theta_g(:) + phase.theta_l(:) ...
                <= porosity(:) + 1e-10) ...
            && all(phase.temperature_C(:) + 273.15 > 0) ...
            && all(dryPressure > 0), ...
        'solveO2Transport:inadmissiblePhase', ...
        '%s phase fractions, temperature, or dry pressure are inadmissible.', label);
end

function [capacity, dissolvedRatio, concentrationRatio, cd] = ...
        phaseCapacity(phase, properties)
    NL = size(phase.theta_g, 1);
    T = [phase.temperature_C(1:NL), ...
        phase.temperature_C(2:NL+1)] + 273.15;
    Pg = [phase.gas_pressure_Pa(1:NL), ...
        phase.gas_pressure_Pa(2:NL+1)];
    Pv = [phase.vapor_pressure_Pa(1:NL), ...
        phase.vapor_pressure_Pa(2:NL+1)];
    cd = (Pg - Pv) ./ (8.31446261815324 .* T) * 1e-6;
    KH = properties.henry_reference_mol_L_atm .* exp( ...
        properties.henry_enthalpy_over_R_K .* (1 ./ T ...
        - 1 / properties.henry_reference_temperature_K));
    concentrationRatio = KH .* properties.gas_constant_cm3_atm_mol_K .* T;
    beta = concentrationRatio / 1000;
    dissolvedRatio = beta .* cd;
    capacity = phase.theta_g .* cd + phase.theta_l .* dissolvedRatio;
end

function D = effectiveMolecularDiffusion(phase, properties)
    NL = size(phase.theta_g, 1);
    T = [phase.temperature_C(1:NL), ...
        phase.temperature_C(2:NL+1)] + 273.15;
    pressure = [phase.gas_pressure_Pa(1:NL), ...
        phase.gas_pressure_Pa(2:NL+1)];
    porosity = repmat(phase.porosity(:), 1, 2);
    Dfree = properties.free_diffusivity_reference_cm2_s ...
        .* (T / properties.diffusion_reference_temperature_K) ...
        .^ properties.diffusion_temperature_exponent ...
        .* properties.pressure_reference_Pa ./ pressure;
    D = Dfree .* phase.theta_g .^ (10 / 3) ./ porosity .^ 2;
end

function k = reactionLinearization(sink, yReference, NL)
    ybar = mean([yReference(1:NL), yReference(2:NL+1)], 2);
    assert(~any(sink(:) > 0 & ybar <= 0), ...
        'solveO2Transport:positiveSinkWithoutOxygen', ...
        'A positive O2 sink cannot be linearized about y_O2=0.');
    k = zeros(NL, 1);
    active = sink(:) > 0;
    k(active) = sink(active) ./ ybar(active);
end

function [lo, hi] = elementFluxCoefficients( ...
        conductance, carrierMolarFlux, liquidFlux, dissolvedLo, dissolvedHi)
    lo = conductance;
    hi = -conductance;
    if carrierMolarFlux >= 0, lo = lo + carrierMolarFlux;
    else, hi = hi + carrierMolarFlux; end
    if liquidFlux >= 0, lo = lo + liquidFlux * dissolvedLo;
    else, hi = hi + liquidFlux * dissolvedHi; end
end

function [lower, diagonal, upper, rhs] = applyBoundaryConditions( ...
        lower, diagonal, upper, rhs, boundary, dissolvedBottom, NN)
    if strcmp(boundary.bottom.applied_kind, 'fixed_dry_mole_fraction')
        value = boundary.bottom.dry_mole_fraction;
        rhs(2) = rhs(2) - lower(1) * value;
        lower(1) = 0; upper(1) = 0; diagonal(1) = 1; rhs(1) = value;
    elseif strcmp(boundary.bottom.applied_kind, ...
            'zero_gas_phase_flux_with_liquid_outflow')
        diagonal(1) = diagonal(1) ...
            - boundary.bottom.liquid_flux_into_domain_cm_s * dissolvedBottom;
    end
    value = boundary.top.dry_mole_fraction;
    rhs(NN - 1) = rhs(NN - 1) - upper(NN - 1) * value;
    upper(NN - 1) = 0; lower(NN - 1) = 0;
    diagonal(NN) = 1; rhs(NN) = value;
end

function weights = nodalLumped(endpointValue, dz)
    weights = zeros(numel(dz) + 1, 1);
    for element = 1:numel(dz)
        halfVolume = dz(element) / 2;
        weights(element) = weights(element) ...
            + endpointValue(element, 1) * halfVolume;
        weights(element + 1) = weights(element + 1) ...
            + endpointValue(element, 2) * halfVolume;
    end
end

function diagnostic = buildLedger(yOld, yNew, capacityOld, capacityNew, ...
        reactionCoefficient, dz, dt, original, boundary, ...
        dissolvedBottom, positivityCorrection)
    storageBefore = sum(nodalLumped(capacityOld, dz) .* yOld(:));
    storageAfter = sum(nodalLumped(capacityNew, dz) .* yNew(:));
    reactionRate = sum(dz(:) .* reactionCoefficient(:) ...
        .* mean([yNew(1:end-1), yNew(2:end)], 2));
    bottomRate = 0;
    if strcmp(boundary.bottom.applied_kind, 'fixed_dry_mole_fraction')
        bottomRate = original.diagonal(1) * yNew(1) ...
            + original.upper(1) * yNew(2) - original.rhs(1);
    elseif strcmp(boundary.bottom.applied_kind, ...
            'zero_gas_phase_flux_with_liquid_outflow')
        bottomRate = boundary.bottom.liquid_flux_into_domain_cm_s ...
            * dissolvedBottom * yNew(1);
    end
    NN = numel(yNew);
    topRate = original.lower(end) * yNew(NN - 1) ...
        + original.diagonal(NN) * yNew(NN) - original.rhs(NN);
    diagnostic = struct( ...
        'storage_before_mol_cm2', storageBefore, ...
        'storage_after_mol_cm2', storageAfter, ...
        'storage_change_mol_cm2', storageAfter - storageBefore, ...
        'top_input_mol_cm2', topRate * dt, ...
        'bottom_input_mol_cm2', bottomRate * dt, ...
        'reaction_loss_mol_cm2', reactionRate * dt, ...
        'positivity_correction_mol_cm2', positivityCorrection);
    diagnostic.balance_residual_mol_cm2 = ...
        diagnostic.storage_change_mol_cm2 ...
        - diagnostic.top_input_mol_cm2 ...
        - diagnostic.bottom_input_mol_cm2 ...
        + diagnostic.reaction_loss_mol_cm2;
    diagnostic.minimum_dry_mole_fraction = min(yNew);
    diagnostic.maximum_dry_mole_fraction = max(yNew);
end

