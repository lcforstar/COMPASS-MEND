function concentration = dryMoleFractionConcentration( ...
        totalPressure_Pa, temperature_C, dryMoleFraction, vaporPressure_Pa)
%DRYMOLEFRACTIONCONCENTRATION Convert dry composition to gas molar density.
%
%   c_i = x_i (P_g - P_v) / (R T) converts a dry-gas mole
%   fraction [-] to gas-phase concentration [mol cm^-3]. Inputs may be
%   scalar or conformable arrays. Unit conversion from m^3 to cm^3 is
%   applied exactly once here.
%
%   Editor: Jizixing Zhu; Date: 2026-08-21.

    phys = equations.physicalConstants();
    assert(all(isfinite(totalPressure_Pa(:))) ...
            && all(totalPressure_Pa(:) > 0), ...
        'gasSpecies:badTotalPressure', ...
        'Total gas pressure must be finite and positive.');
    assert(all(isfinite(temperature_C(:))) ...
            && all(temperature_C(:) + phys.C_to_K > 0), ...
        'gasSpecies:badTemperature', ...
        'Gas temperature must be finite with positive absolute temperature.');
    assert(all(isfinite(dryMoleFraction(:))) ...
            && all(dryMoleFraction(:) >= 0) ...
            && all(dryMoleFraction(:) <= 1), ...
        'gasSpecies:badDryMoleFraction', ...
        'Dry-gas mole fraction must be finite and lie in [0,1].');
    assert(all(isfinite(vaporPressure_Pa(:))) ...
            && all(vaporPressure_Pa(:) >= 0), ...
        'gasSpecies:badVaporPressure', ...
        'Water-vapor pressure must be finite and nonnegative.');

    T_K = temperature_C + phys.C_to_K;
    dryPressure_Pa = totalPressure_Pa - vaporPressure_Pa;
    assert(all(dryPressure_Pa(:) > 0), ...
        'gasSpecies:nonpositiveDryPressure', ...
        'Total gas pressure must exceed water-vapor pressure.');
    partialPressure_Pa = dryMoleFraction .* dryPressure_Pa;
    concentration = partialPressure_Pa ./ (phys.R .* T_K) * 1e-6;
end

