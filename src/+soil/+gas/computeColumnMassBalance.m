function balance = computeColumnMassBalance( ...
        storageBefore, storageAfter, dz, airFlux, dt_s)
%COMPUTECOLUMNMASSBALANCE  Close one accepted dry-air mass substep.
%
%   The endpoint constitutive storage is
%
%     B_a = rho_a (theta_g + H_c theta_l)                 [g cm^-3].
%
%   Linear finite elements with endpoint mass lumping give the column mass
%
%     M_a = sum_e dz_e [B_a(e,1) + B_a(e,2)] / 2         [g cm^-2].
%
%   With the public convention that both boundary fluxes are positive into
%   the soil, the accepted discrete conservation residual is
%
%     R_a = M_a^(n+1) - M_a^n
%           - dt (q_a,top^in + q_a,bottom^in)              [g cm^-2].
%
%   Legacy QAT is positive outward at the top, whereas QAB is positive into
%   the bottom. Therefore q_a,top^in=-QAT and q_a,bottom^in=QAB. A correctly
%   accepted dry-air solve has R_a approximately zero up to solver tolerance.
%
%   Inputs:
%     storageBefore [g cm^-3, NL x 2] accepted endpoint storage at t^n
%     storageAfter  [g cm^-3, NL x 2] accepted endpoint storage at t^(n+1)
%     dz            [cm, NL x 1] bottom-up element thickness
%     airFlux.QAT   [g cm^-2 s^-1] legacy top outward-positive mass flux
%     airFlux.QAB   [g cm^-2 s^-1] legacy bottom inward-positive mass flux
%     dt_s          [s] accepted substep duration
%
%   Returns:
%     balance       [struct] extensive storage, boundary input, and residual
%
%   The storage definition is shared with
%   soil.gas.assembleConservativeDryAirEquation; this function adds no new
%   physical parameterization.
%   Editor: Jizixing Zhu; Date: 2026-07-16.
%   Change: 2026-08-12 Jizixing Zhu -- reject negative accepted dry-air
%           storage before constructing a conservation ledger.

    dz = dz(:);
    NL = numel(dz);
    assert(isequal(size(storageBefore), [NL,2]) ...
            && isequal(size(storageAfter), [NL,2]) ...
            && all(isfinite(storageBefore(:))) ...
            && all(isfinite(storageAfter(:))) ...
            && all(storageBefore(:) >= 0) ...
            && all(storageAfter(:) >= 0), ...
        'computeColumnDryAirMassBalance:badStorage', ...
        ['Accepted dry-air storage must be finite, nonnegative NL-by-2 ', ...
         'endpoint arrays.']);
    assert(all(isfinite(dz)) && all(dz > 0) ...
            && isnumeric(dt_s) && isscalar(dt_s) ...
            && isfinite(dt_s) && dt_s > 0, ...
        'computeColumnDryAirMassBalance:badGridOrTime', ...
        'Element thicknesses and dt_s must be finite and positive.');
    assert(isstruct(airFlux) && all(isfield(airFlux, {'QAT','QAB'})) ...
            && all(isfinite([airFlux.QAT, airFlux.QAB])), ...
        'computeColumnDryAirMassBalance:badBoundaryFlux', ...
        'airFlux must contain finite scalar QAT and QAB values.');
    % M_a = integral B_a dz, evaluated with the same endpoint-lumped rule as
    % the conservative time term in assembleConservativeDryAirEquation.
    massBefore = sum(dz .* sum(storageBefore, 2) / 2); % [g cm^-2]
    massAfter = sum(dz .* sum(storageAfter, 2) / 2);   % [g cm^-2]
    massChange = massAfter - massBefore;               % [g cm^-2]

    % Public boundary inputs are positive into the column at both ends.
    topInput = -double(airFlux.QAT) * dt_s;             % [g cm^-2]
    bottomInput = double(airFlux.QAB) * dt_s;           % [g cm^-2]
    boundaryNetInput = topInput + bottomInput;          % [g cm^-2]

    balance = struct( ...
        'has_data', true, ...
        'elapsed_s', dt_s, ...
        'storage_before_g_cm2', massBefore, ...
        'storage_after_g_cm2', massAfter, ...
        'storage_change_g_cm2', massChange, ...
        'top_input_g_cm2', topInput, ...
        'bottom_input_g_cm2', bottomInput, ...
        'boundary_net_input_g_cm2', boundaryNetInput, ...
        'residual_g_cm2', massChange - boundaryNetInput);
end
