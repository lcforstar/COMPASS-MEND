function reconstruction = reconstructConservativeCarrierFlux( ...
        storageBefore, storageAfter, dz, airFlux, dt_s, ...
        liquidFlux, thetaGas, thetaLiquid, dryAirMolarMass)
%RECONSTRUCTCONSERVATIVECARRIERFLUX Recover one discrete carrier flux family.
%
% The accepted dry-air finite-element solve owns endpoint storage and the
% applied boundary reactions. This function mass-lumps the accepted storage
% on the same two-node elements and integrates the nodal balance upward from
% the bottom boundary:
%
%   dM_i/dt = F_(i-1/2) - F_(i+1/2).
%
% Internal arrays are bottom-to-surface; positive flux is upward. QAB is the
% bottom inward/upward dry-air mass flux and QAT is the top outward/upward
% flux [g cm^-2 s^-1]. The reconstructed total interface flux is therefore
% the unique field consistent with the accepted nodal storage changes and
% QAB. The difference at QAT is exactly the already accepted column dry-air
% residual divided by dt and is reported, never hidden.
%
% For gas-species transport the total carrier flux is split into dissolved
% and free-gas parts. The dissolved carrier uses the same upwind liquid
% endpoint rule as the species kernel. This guarantees the constant-
% composition invariant when a species uses the carrier partition Hc.
%
% Inputs:
%   storageBefore/After [g cm^-3, NL x 2] accepted endpoint dry-air storage
%   dz                  [cm, NL] positive element thickness
%   airFlux.QAB/QAT     [g cm^-2 s^-1] applied boundary reactions
%   dt_s                [s] accepted substep duration
%   liquidFlux          [cm s^-1, NL] positive upward
%   thetaGas/thetaLiquid[-, NL x 2] accepted candidate phase fractions
%   dryAirMolarMass     [g mol^-1]
%
% Output fields are trial diagnostics only; this function mutates no state.
%
% Physical source: COMPASS dry-air balance, Zeng (2013), Eqs. 4.11-4.13.
% Numerical source: soil.gas.computeColumnMassBalance and the accepted
% endpoint-lumped dry-air storage contract.
% Editor: Jizixing Zhu; Date: 2026-08-22.

    dz = dz(:);
    liquidFlux = liquidFlux(:);
    NL = numel(dz);
    NN = NL + 1;
    validateInputs(storageBefore, storageAfter, dz, airFlux, dt_s, ...
        liquidFlux, thetaGas, thetaLiquid, dryAirMolarMass, NL);

    nodalBefore = lumpEndpointStorage(storageBefore, dz);
    nodalAfter = lumpEndpointStorage(storageAfter, dz);
    storageRate = (nodalAfter - nodalBefore) / dt_s;

    totalFlux = zeros(NL, 1);
    lowerFaceFlux = double(airFlux.QAB);
    for node = 1:NL
        totalFlux(node) = lowerFaceFlux - storageRate(node);
        lowerFaceFlux = totalFlux(node);
    end
    reconstructedTopFlux = totalFlux(end) - storageRate(NN);

    phys = equations.physicalConstants();
    Hc = phys.Hc;
    storageVolume = thetaGas + Hc .* thetaLiquid;
    assert(all(storageVolume(:) > 0), ...
        'reconstructConservativeCarrierFlux:zeroStorageVolume', ...
        'Carrier phase storage volume must be positive at every endpoint.');
    dryAirDensity = storageAfter ./ storageVolume;

    upwindDensity = dryAirDensity(:, 1);
    downward = liquidFlux < 0;
    upwindDensity(downward) = dryAirDensity(downward, 2);
    dissolvedFlux = Hc .* upwindDensity .* liquidFlux;
    freeFlux = totalFlux - dissolvedFlux;

    columnResidual = sum(nodalAfter - nodalBefore) ...
        - dt_s * (double(airFlux.QAB) - double(airFlux.QAT));
    topFluxMismatch = reconstructedTopFlux - double(airFlux.QAT);
    assert(all(isfinite([totalFlux; dissolvedFlux; freeFlux])) ...
            && isfinite(columnResidual) && isfinite(topFluxMismatch), ...
        'reconstructConservativeCarrierFlux:nonfiniteResult', ...
        'The reconstructed carrier flux family must be finite.');

    reconstruction = struct( ...
        'schema_version', 1, ...
        'orientation', 'positive_bottom_to_surface', ...
        'source', 'accepted_nodal_storage_and_applied_bottom_flux', ...
        'total_mass_flux_g_cm2_s', totalFlux, ...
        'free_mass_flux_g_cm2_s', freeFlux, ...
        'dissolved_mass_flux_g_cm2_s', dissolvedFlux, ...
        'total_molar_flux_mol_cm2_s', totalFlux ./ dryAirMolarMass, ...
        'nodal_storage_before_g_cm2', nodalBefore, ...
        'nodal_storage_after_g_cm2', nodalAfter, ...
        'nodal_storage_rate_g_cm2_s', storageRate, ...
        'applied_bottom_flux_g_cm2_s', double(airFlux.QAB), ...
        'applied_top_flux_g_cm2_s', double(airFlux.QAT), ...
        'reconstructed_top_flux_g_cm2_s', reconstructedTopFlux, ...
        'top_flux_mismatch_g_cm2_s', topFluxMismatch, ...
        'column_residual_g_cm2', columnResidual);
end

function validateInputs(storageBefore, storageAfter, dz, airFlux, dt_s, ...
        liquidFlux, thetaGas, thetaLiquid, dryAirMolarMass, NL)
    assert(isequal(size(storageBefore), [NL, 2]) ...
            && isequal(size(storageAfter), [NL, 2]) ...
            && isequal(size(thetaGas), [NL, 2]) ...
            && isequal(size(thetaLiquid), [NL, 2]) ...
            && all(isfinite([storageBefore(:); storageAfter(:); ...
                thetaGas(:); thetaLiquid(:)])) ...
            && all(storageBefore(:) >= 0) && all(storageAfter(:) >= 0) ...
            && all(thetaGas(:) >= 0) && all(thetaLiquid(:) >= 0), ...
        'reconstructConservativeCarrierFlux:badEndpointState', ...
        'Storage and phase fractions must be finite nonnegative NL-by-2 arrays.');
    assert(all(isfinite(dz)) && all(dz > 0) ...
            && numel(liquidFlux) == NL && all(isfinite(liquidFlux)) ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0 ...
            && isscalar(dryAirMolarMass) && isfinite(dryAirMolarMass) ...
            && dryAirMolarMass > 0, ...
        'reconstructConservativeCarrierFlux:badGridOrTime', ...
        'Grid, liquid flux, timestep, and molar mass must be finite and valid.');
    assert(isstruct(airFlux) && all(isfield(airFlux, {'QAT','QAB'})) ...
            && all(isfinite([airFlux.QAT, airFlux.QAB])), ...
        'reconstructConservativeCarrierFlux:badBoundaryFlux', ...
        'Applied dry-air boundary fluxes QAT and QAB are required.');
end

function nodal = lumpEndpointStorage(endpointStorage, dz)
    NL = numel(dz);
    nodal = zeros(NL + 1, 1);
    nodal(1:NL) = nodal(1:NL) ...
        + endpointStorage(:, 1) .* dz / 2;
    nodal(2:NL + 1) = nodal(2:NL + 1) ...
        + endpointStorage(:, 2) .* dz / 2;
end

