function tile = captureOxygenReplayTile(built, oldPhase, outcome, kt, tStart_s, dt_s)
%CAPTUREOXYGENREPLAYTILE Freeze one accepted carrier tile for same-hour O2.
% oldPhase is captured before the carrier attempt; new phase/fluxes are its
% converged endpoint. No O2 solve, state mutation, or rejected tile is stored.
% Sources: COMPASS-COMPASS_MATLAB advanceOxygenSubstep and carrier reconstruction.
% Editor: Wenjie Liu; Date: 2026-10-23.
% Change: 2026-10-28 Wenjie Liu -- freeze matric head on every accepted
% carrier tile for the independent dry-side nitrification response.
    head=built.workspace.step.trial.h(:);
    assert(numel(head)==built.domain.NN&&isreal(head)&&all(isfinite(head)), ...
        'captureOxygenReplayTile:matricHead','Finite NN-node matric head [cm] is required.');
    d=outcome.solverDiagnostics;
    assert(all(isfield(d,{'QL','QL_h','QL_T','QL_a'})), ...
        'captureOxygenReplayTile:missingLiquidFlux','Accepted liquid flux decomposition is required.');
    if isfield(built,'control')&&built.control.switches.lSoilairefc==0
        tile=struct('dt_s',dt_s,'t_start_s',tStart_s, ...
            'matric_head_cm',head, ...
            'temperature_C',built.workspace.step.trial.T(:), ...
            'theta_liquid',built.workspace.derived.Theta_LL, ...
            'nh4',built.workspace.step.trial.nh4(:), ...
            'QL',d.QL(:),'QL_h',d.QL_h(:),'QL_T',d.QL_T(:),'QL_a',d.QL_a(:));
        return;
    end
    phase=soil.gas.captureOxygenPhase(built,true);
    p=soil.gas.species.oxygenProperties();
    carrier=soil.gas.reconstructConservativeCarrierFlux( ...
        outcome.dryAirStorageBefore,outcome.dryAirStorageAfter,built.domain.dz, ...
        outcome.airFlux,dt_s,d.QL(:),phase.theta_g,phase.theta_l,p.dry_air_molar_mass_g_mol);
    y=built.forcing.hourly.Oa(min(kt,numel(built.forcing.hourly.Oa)))*1e-3;
    driver=struct('species','O2','dry_mole_fraction',y);
    spec=built.boundary.gas_species.O2;
    if strcmp(spec.bottom.kind,'zero_gas_phase_flux_with_liquid_outflow')
        assert(d.QL(1)<=1e-14,'captureOxygenReplayTile:inwardBottomFlow', ...
            'The selected O2 bottom boundary requires liquid outflow.');
        driver.bottom_liquid_flux_into_domain_cm_s=min(d.QL(1),0);
    end
    request=soil.gas.boundary.materializeSpeciesRequest(spec,driver,tStart_s,dt_s);
    applied=soil.gas.boundary.applySpeciesRequest(request,struct( ...
        'gas_pressure_Pa',phase.gas_pressure_Pa,'temperature_C',phase.temperature_C, ...
        'vapor_density_g_cm3',built.workspace.derived.RHOV(:)));
    tile=struct('dt_s',dt_s,'t_start_s',tStart_s,'phase_old',oldPhase,'phase_new',phase, ...
        'matric_head_cm',head, ...
        'transport',struct('free_dry_air_mass_flux_g_cm2_s',carrier.free_mass_flux_g_cm2_s, ...
            'gas_dispersion_cm2_s',built.workspace.derived.D_Vg(:), ...
            'liquid_flux_cm_s',d.QL(:)), ...
        'boundary_request',request,'boundary_applied',applied, ...
        'nh4',built.workspace.step.trial.nh4(:), ...
        'dry_air_storage_after',outcome.dryAirStorageAfter, ...
        'QL',d.QL(:),'QL_h',d.QL_h(:),'QL_T',d.QL_T(:),'QL_a',d.QL_a(:));
end
