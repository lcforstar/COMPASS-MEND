function oxygen = finalizeOxygenAccumulator(accumulator)
%FINALIZEOXYGENACCUMULATOR Publish hour-mean kinetics and exact O2 ledger.
% Editor: Jizixing Zhu; Date: 2026-08-21.
    oxygen = accumulator;
    if ~accumulator.has_data || accumulator.elapsed_s <= 0
        return;
    end
    dt = accumulator.elapsed_s;
    oxygen.Snit = accumulator.Snit_integral / dt;
    oxygen.Snit_N2O = accumulator.Snit_N2O_integral / dt;
    oxygen.f_aerobic = accumulator.f_aerobic_integral / dt;
    oxygen.f_anaerobic = accumulator.f_anaerobic_integral / dt;
    oxygen.C_O2_liq = accumulator.C_O2_liq_integral / dt;
    oxygen.QL = accumulator.QL_integral / dt;
    oxygen.QL_abs = accumulator.QL_abs_integral / dt;
    oxygen.QL_h = accumulator.QL_h_integral / dt;
    oxygen.QL_T = accumulator.QL_T_integral / dt;
    oxygen.QL_a = accumulator.QL_a_integral / dt;
    oxygen.ledger = struct( ...
        'storage_before_mol_cm2', accumulator.storage_before_mol_cm2, ...
        'storage_after_mol_cm2', accumulator.storage_after_mol_cm2, ...
        'storage_change_mol_cm2', accumulator.storage_after_mol_cm2 ...
            - accumulator.storage_before_mol_cm2, ...
        'top_input_mol_cm2', accumulator.top_input_mol_cm2, ...
        'bottom_input_mol_cm2', accumulator.bottom_input_mol_cm2, ...
        'reaction_loss_mol_cm2', accumulator.reaction_loss_mol_cm2, ...
        'positivity_correction_mol_cm2', ...
            accumulator.positivity_correction_mol_cm2);
    oxygen.ledger.balance_residual_mol_cm2 = ...
        oxygen.ledger.storage_change_mol_cm2 ...
        - oxygen.ledger.top_input_mol_cm2 ...
        - oxygen.ledger.bottom_input_mol_cm2 ...
        + oxygen.ledger.reaction_loss_mol_cm2;
    oxygen.boundary_result = aggregateBoundaryResult(accumulator, dt);
end

function result = aggregateBoundaryResult(accumulator, dt)
    request = accumulator.last_boundary_request;
    applied = accumulator.last_boundary_applied;
    result = struct('schema_version', 1, 'species', 'O2', ...
        'quantity', 'molar', 'sign_convention', 'flux_into_domain_positive', ...
        't_start_s', request.t_end_s - dt, 't_end_s', request.t_end_s, ...
        'dt_s', dt, 'accepted', true, ...
        'top', endpoint(request.top, applied.top, accumulator.top_input_mol_cm2 / dt), ...
        'bottom', endpoint(request.bottom, applied.bottom, accumulator.bottom_input_mol_cm2 / dt));
end

function out = endpoint(request, applied, flux)
    out = struct('requested_kind', request.kind, ...
        'applied_kind', applied.applied_kind, ...
        'composition_source', request.composition_source, ...
        'requested_dry_mole_fraction', request.requested_external_dry_mole_fraction, ...
        'applied_dry_mole_fraction', applied.dry_mole_fraction, ...
        'requested_flux_into_domain_mol_cm2_s', ...
            request.requested_flux_into_domain_mol_cm2_s, ...
        'actual_flux_into_domain_mol_cm2_s', flux);
end

