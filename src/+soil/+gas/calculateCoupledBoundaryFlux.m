function [QAT, QAB] = calculateCoupledBoundaryFlux( ...
        SAVE, matrix, stateBefore, stateAfter, ...
        storageBefore, storageAfter, dz, dt_s)
%CALCULATECOUPLEDBOUNDARYFLUX  Recover dry-air flux from the full correction row.
%
%   The dry-air equation is assembled at one Picard state, while the
%   distributed h/P_g/U sweep changes h, P_g, and the diagnostic temperature.
%   Boundary reaction fluxes must therefore include the spatial h/T column
%   corrections and the actual dry-air storage change. The pressure-tangent
%   storage already contained in SAVE is replaced, not added a second time.
%
%   Inputs:
%     SAVE          [g cm^-2 s^-1] unconstrained boundary-row snapshot
%     matrix        raw dry-air FEM bank with C3/C4/C4_a/C5/C5_a
%     stateBefore   h [cm], T [degC], P [g cm^-1 s^-2], each NN x 1
%     stateAfter    accepted correction state with the same fields and units
%     storageBefore [g cm^-3, NL x 2] endpoint dry-air storage at assembly
%     storageAfter  [g cm^-3, NL x 2] endpoint storage after the correction
%     dz            [cm, NL x 1] bottom-up element thickness
%     dt_s          [s] accepted trial duration
%
%   Returns:
%     QAT [g cm^-2 s^-1] legacy top outward-positive dry-air mass flux
%     QAB [g cm^-2 s^-1] legacy bottom inward-positive dry-air mass flux
%
%   Zeng 2013, Coupled Dynamics in Soil, Eqs. 4.11-4.13 and 4.56.
%   Editor: Jizixing Zhu; Date: 2026-07-15.

    dz = dz(:);
    NL = numel(dz);
    NN = NL + 1;
    before = normalizeState(stateBefore, NN, 'stateBefore');
    after = normalizeState(stateAfter, NN, 'stateAfter');
    assert(isequal(size(storageBefore), [NL,2]) ...
            && isequal(size(storageAfter), [NL,2]) ...
            && all(isfinite(storageBefore(:))) ...
            && all(isfinite(storageAfter(:))) ...
            && all(isfinite(dz)) && all(dz > 0) ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'calculateCoupledDryAirBoundaryFlux:badStorage', ...
        'Endpoint storage must be finite NL-by-2; dz and dt_s must be positive.');
    required = {'C3','C4','C4_a','C5','C5_a'};
    assert(isstruct(matrix) && all(isfield(matrix, required)) ...
            && isequal(size(matrix.C3), [NN,2]) ...
            && isequal(size(matrix.C4), [NN,2]) ...
            && isequal(size(matrix.C5), [NN,2]) ...
            && numel(matrix.C4_a) >= NL && numel(matrix.C5_a) >= NL ...
            && all(matrix.C3(:,2) == 0) ...
            && all(isfinite(SAVE(1:2,1:3,3)), 'all'), ...
        'calculateCoupledDryAirBoundaryFlux:badMatrix', ...
        'SAVE and the raw dry-air FEM banks do not satisfy the boundary contract.');

    dh = after.h - before.h;
    dT = after.T - before.T;
    dP = after.P - before.P;

    deltaStorage = storageAfter - storageBefore;
    storageChange = zeros(NN,1);
    storageChange(1:NL) = storageChange(1:NL) ...
        + deltaStorage(:,1) .* dz / 2;
    storageChange(2:NN) = storageChange(2:NN) ...
        + deltaStorage(:,2) .* dz / 2;
    storageReplacement = ...
        (storageChange - matrix.C3(:,1) .* dP) / dt_s;

    bottomCross = matrix.C4(1,1) * dh(1) ...
        + matrix.C4(1,2) * dh(2) ...
        + matrix.C5(1,1) * dT(1) ...
        + matrix.C5(1,2) * dT(2) ...
        + storageReplacement(1);
    topCross = matrix.C4_a(NL) * dh(NN-1) ...
        + matrix.C4(NN,1) * dh(NN) ...
        + matrix.C5_a(NL) * dT(NN-1) ...
        + matrix.C5(NN,1) * dT(NN) ...
        + storageReplacement(NN);

    QAT = SAVE(2,1,3) ...
        - SAVE(2,2,3) * after.P(NN-1) ...
        - SAVE(2,3,3) * after.P(NN) - topCross;
    QAB = -SAVE(1,1,3) ...
        + SAVE(1,2,3) * after.P(1) ...
        + SAVE(1,3,3) * after.P(2) + bottomCross;
end

function state = normalizeState(raw, NN, name)
%NORMALIZESTATE  Validate and orient one dry-air boundary-reaction state.
% Editor: Jizixing Zhu; Date: 2026-07-15.
    assert(isstruct(raw) && all(isfield(raw, {'h','T','P'})), ...
        'calculateCoupledDryAirBoundaryFlux:badState', ...
        '%s must contain h, T, and P.', name);
    state = struct('h', raw.h(:), 'T', raw.T(:), 'P', raw.P(:));
    assert(numel(state.h) == NN && numel(state.T) == NN ...
            && numel(state.P) == NN && all(isfinite(state.h)) ...
            && all(isfinite(state.T)) && all(isfinite(state.P)), ...
        'calculateCoupledDryAirBoundaryFlux:badState', ...
        '%s fields must be finite NN-by-1 vectors.', name);
end
