function balance = emptyColumnMassBalance()
%EMPTYCOLUMNMASSBALANCE  Return an undefined accepted dry-air mass ledger.
%
%   Every extensive term is expressed in g cm^-2 over the accepted interval.
%   Boundary inputs are positive into the soil column. NaN is deliberate when
%   dry-air transport is disabled or no complete substep is accepted.
%
%   Editor: Jizixing Zhu; Date: 2026-07-16.

    balance = struct( ...
        'has_data', false, ...
        'elapsed_s', 0, ...
        'storage_before_g_cm2', NaN, ...
        'storage_after_g_cm2', NaN, ...
        'storage_change_g_cm2', NaN, ...
        'top_input_g_cm2', NaN, ...
        'bottom_input_g_cm2', NaN, ...
        'boundary_net_input_g_cm2', NaN, ...
        'residual_g_cm2', NaN);
end
