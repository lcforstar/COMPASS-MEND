function faces=acceptedBottomDrivers(soilAdvance,parameters,dt)
%ACCEPTEDBOTTOMDRIVERS Validate water-owned chronological bottom liquid faces.
% Output: one cell per accepted driver tile, [cm/s] upward into the column.
% Closed configurations need no external face driver. Open configurations
% have no fallback to mean QMB or element-centre QL. No state is changed.
% Editor: Wenjie Liu; Date: 2026-09-29.
% Change: 2026-09-29 Wenjie Liu -- the same read-only water-face validator is
% also used by BIOPARTICLE; parameters.boundary supplies the caller's policy.
    faces={};
    if ~isfield(parameters,'boundary')||strcmp(parameters.boundary.bottom_kind,'closed'),return;end
    assert(isfield(soilAdvance,'solver_diagnostics') ...
        &&isfield(soilAdvance.solver_diagnostics,'accepted_transport_schedule') ...
        &&isfield(soilAdvance.solver_diagnostics.accepted_transport_schedule,'bottom_liquid_faces'), ...
        'soil:dom:missingBottomSchedule','Open DOM requires accepted bottom-face records.');
    schedule=soilAdvance.solver_diagnostics.accepted_transport_schedule;faces=schedule.bottom_liquid_faces;
    assert(iscell(faces)&&numel(faces)==numel(dt)&&isequal(schedule.dt_s(:),dt(:)), ...
        'soil:dom:bottomScheduleTime','Bottom faces must match all chronological DOM tiles.');
    for k=1:numel(faces)
        f=faces{k};
        assert(f.schema_version==1&&strcmp(f.kind,'advective_outflow') ...
            &&strcmp(f.phase_contract,'free_drainage_liquid_only_zero_vapor') ...
            &&strcmp(f.position,'physical_column_bottom') ...
            &&strcmp(f.positive_direction,'into_domain') ...
            &&f.q_vapor_cm_s==0&&isfinite(f.q_liquid_cm_s)&&f.q_liquid_cm_s<=0 ...
            &&f.dt_s==dt(k),'soil:dom:bottomScheduleContract', ...
            'Invalid physical bottom liquid-face contract.');
        % Change: 2026-09-29 Wenjie Liu -- DIN's element-to-node adapter
        % copies the top liquid QL endpoint. Do not use total QMT (vapor).
        if parameters.boundary.schema_version==2
            assert(size(schedule.QL,2)==numel(dt)&&isfinite(schedule.QL(end,k)), ...
                'soil:dom:topScheduleContract','Missing accepted liquid top driver.');
            faces{k}.q_top_cm_s=schedule.QL(end,k);
        end
    end
end
