function phase = equilibrate(total_g_cm3, theta, bulk_density_g_cm3, kd_cm3_g, rewetting)
%EQUILIBRATE Recover aqueous and sorbed DOM under linear equilibrium.
%
%   total = (theta + rho_b Kd) C_aq, where total is [g cm^-3 bulk
%   soil], C_aq [g cm^-3 water], rho_b [g cm^-3], and Kd [cm^3 g^-1].
%   The returned sorbed concentration is [g g^-1 dry soil].
%
%   Editor: Jizixing Zhu; Date: 2026-08-21.
%   Change: 2026-09-02 Codex -- accept scalar or depth-resolved Kd while
%   preserving the same elementwise linear-equilibrium equation.
    total_g_cm3 = total_g_cm3(:);
    theta = theta(:); bulk_density_g_cm3 = bulk_density_g_cm3(:);
    if isscalar(kd_cm3_g)
        kd_cm3_g=repmat(double(kd_cm3_g),numel(total_g_cm3),1);
    else
        kd_cm3_g=double(kd_cm3_g(:));
    end
    assert(numel(total_g_cm3)==numel(theta) ...
        && numel(theta)==numel(bulk_density_g_cm3), ...
        'soil:dom:equilibrateSize','DOM equilibrium arrays must align.');
    assert(all(isfinite(total_g_cm3)) && all(total_g_cm3>=0) ...
        && all(isfinite(theta)) && all(theta>=0) ...
        && all(isfinite(bulk_density_g_cm3)) ...
        && all(bulk_density_g_cm3>0) ...
        && numel(kd_cm3_g)==numel(total_g_cm3) ...
        && all(isfinite(kd_cm3_g)) && all(kd_cm3_g>=0), ...
        'soil:dom:equilibrateValues','DOM equilibrium inputs are invalid.');
    capacity = theta + bulk_density_g_cm3.*kd_cm3_g;
    if nargin<5,rewetting=false(size(theta));end
    assert(islogical(rewetting)&&isequal(size(rewetting),size(theta)), ...
        'soil:dom:rewettingShape','The rewetting mask must match the soil cells.');
    emptyRewet=rewetting & capacity==0 & total_g_cm3==0;
    assert(all(capacity>0|emptyRewet),'soil:dom:zeroCapacity', ...
        'Each DOM element requires positive aqueous+sorbed capacity.');
    % An initially empty dry cell supplies zero solute during its first
    % incoming water increment. An existing dry inventory is never erased.
    aqueous=zeros(size(total_g_cm3));wet=capacity>0;
    aqueous(wet)=total_g_cm3(wet)./capacity(wet);
    phase = struct('aqueous_g_cm3_water',aqueous, ...
        'aqueous_mg_L',aqueous*1e6, ...
        'sorbed_g_g_soil',kd_cm3_g.*aqueous, ...
        'total_g_cm3_bulk',total_g_cm3, ...
        'closure_residual_g_cm3', ...
            total_g_cm3-(theta.*aqueous ...
            +bulk_density_g_cm3.*kd_cm3_g.*aqueous));
end
