function p=partitionMendProducts(poc,pon,inputFraction,cnPom2)
%PARTITIONMENDPRODUCTS Split AOM release into paired MEND particulate pools.
% poc/pon: aligned bottom-up columns [g C/N cm^-3 bulk soil], nonnegative.
% inputFraction: configured POM1/POM2/DOM carbon fractions. Only the first
% two are normalized here. POM2 receives C/CN_POM2 nitrogen when affordable;
% otherwise both particulate pools share donor N by their carbon fractions.
% Remaining-first N allocation conserves donor N without negative stocks,
% DIN borrowing or clipping. Output C/N columns retain input units/order.
% No accepted state is mutated. Invalid inputs reject before allocation.
% Editor: Wenjie Liu; Date: 2026-10-17.
    assert(isnumeric(poc)&&isreal(poc)&&iscolumn(poc) ...
        &&isnumeric(pon)&&isreal(pon)&&isequal(size(poc),size(pon)) ...
        &&all(isfinite([poc;pon]))&&all([poc;pon]>=0), ...
        'soil:aom:particulateInput','AOM particulate C/N must be nonnegative finite columns.');
    assert(isnumeric(inputFraction)&&isreal(inputFraction)&&numel(inputFraction)==3 ...
        &&all(isfinite(inputFraction(:)))&&all(inputFraction(:)>=0) ...
        &&sum(inputFraction(1:2))>0 ...
        &&isnumeric(cnPom2)&&isreal(cnPom2)&&isscalar(cnPom2) ...
        &&isfinite(cnPom2)&&cnPom2>0,'soil:aom:particulateParameters', ...
        'Require a positive particulate carbon fraction and positive finite CN_POM2.');
    f=inputFraction(1:2)./sum(inputFraction(1:2));
    p.C_POM1=f(1).*poc;p.C_POM2=f(2).*poc;
    target=p.C_POM2./cnPom2;
    p.N_PON2=min(pon,target);
    lowN=pon<target;p.N_PON2(lowN)=f(2).*pon(lowN);
    p.N_PON1=pon-p.N_PON2;
    assert(all(p.N_PON1>=0)&&all(p.N_PON2>=0) ...
        &&all(abs(p.N_PON1+p.N_PON2-pon)<=eps(pon)), ...
        'soil:aom:particulateClosure','AOM-to-MEND particulate N must close to machine precision.');
end
