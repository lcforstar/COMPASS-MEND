function balance = computeColumnEnergyBalance( ...
        UBefore, UAfter, rootEnergySink, dz, heatFlux, dt_s)
%COMPUTECOLUMNENERGYBALANCE  Close one accepted soil-energy substep.
%
%   The finite-element column balance is
%
%     Delta E = (-QET + QEB) Delta t - E_root,
%
%   where legacy QET is positive upward/out of the top boundary and QEB is
%   positive upward/into the bottom boundary. The returned public boundary
%   terms are instead positive into the soil domain at both endpoints.
%
%   Inputs:
%     UBefore/UAfter  [J cm^-3, NN x 1] accepted nodal internal energy
%     rootEnergySink [J cm^-3 s^-1, NL x 2] signed root-carried energy sink;
%                    positive removes energy, negative returns energy to soil
%     dz             [cm, NL x 1] element thickness, bottom element first
%     heatFlux.QET   [J cm^-2 s^-1] legacy top outward flux
%     heatFlux.QEB   [J cm^-2 s^-1] legacy bottom inward flux
%     dt_s           [s] accepted substep duration
%
%   The residual is storage change minus boundary input plus the signed root
%   sink. It therefore vanishes for the accepted discrete equation.
%
%   Editor: Jizixing Zhu; Date: 2026-07-15.

    dz = dz(:);
    UBefore = UBefore(:);
    UAfter = UAfter(:);
    NL = numel(dz);
    NN = NL + 1;
    assert(isequal(size(UBefore), [NN,1]) && isequal(size(UAfter), [NN,1]) ...
            && all(isfinite(UBefore)) && all(isfinite(UAfter)), ...
        'computeColumnEnergyBalance:badStorage', ...
        'UBefore and UAfter must be finite NN-by-1 nodal internal energies.');
    assert(isequal(size(rootEnergySink), [NL,2]) ...
            && all(isfinite(rootEnergySink(:))), ...
        'computeColumnEnergyBalance:badRootSink', ...
        'rootEnergySink must be a finite NL-by-2 endpoint field.');
    assert(all(isfinite(dz)) && all(dz > 0) ...
            && isnumeric(dt_s) && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'computeColumnEnergyBalance:badGridOrTime', ...
        'Element thicknesses and dt_s must be finite and positive.');
    assert(isstruct(heatFlux) && isfield(heatFlux, 'QET') ...
            && isfield(heatFlux, 'QEB') ...
            && all(isfinite([heatFlux.QET, heatFlux.QEB])), ...
        'computeColumnEnergyBalance:badBoundaryFlux', ...
        'heatFlux must contain finite scalar QET and QEB values.');

    controlVolume = [dz(1) / 2; ...
        (dz(1:end-1) + dz(2:end)) / 2; dz(end) / 2];
    storageBefore = sum(controlVolume .* UBefore);
    storageAfter = sum(controlVolume .* UAfter);
    storageChange = storageAfter - storageBefore;
    topInput = -double(heatFlux.QET) * dt_s;
    bottomInput = double(heatFlux.QEB) * dt_s;
    boundaryNetInput = topInput + bottomInput;
    rootSink = sum(dz .* sum(rootEnergySink, 2) / 2) * dt_s;

    balance = struct( ...
        'has_data', true, ...
        'elapsed_s', dt_s, ...
        'storage_before_J_cm2', storageBefore, ...
        'storage_after_J_cm2', storageAfter, ...
        'storage_change_J_cm2', storageChange, ...
        'top_input_J_cm2', topInput, ...
        'bottom_input_J_cm2', bottomInput, ...
        'boundary_net_input_J_cm2', boundaryNetInput, ...
        'root_sink_J_cm2', rootSink, ...
        'residual_J_cm2', storageChange - boundaryNetInput + rootSink);
end
