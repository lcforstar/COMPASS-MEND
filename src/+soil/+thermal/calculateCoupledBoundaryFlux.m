function [QET, QEB] = calculateCoupledBoundaryFlux( ...
        SAVE, matrix, temperatureAfter, deltaT, deltaH, deltaU, deltaP, ...
        dz, dt_s)
%CALCULATECOUPLEDBOUNDARYFLUX  Recover heat flux from the complete correction row.
%
%   The legacy heat-flux recovery uses only the temperature column because
%   h and P_g were fixed while the scalar thermal equation was solved.  In
%   the current h/U/P_g sweep, the same Picard map also applies deltaH and
%   deltaP.  Their spatial and storage-tangent contributions must therefore
%   be included when recovering the reaction flux at a temperature boundary.
%
%   SAVE contains the unconstrained bottom/top temperature-row right-hand
%   sides and temperature coefficients captured before boundary elimination.
%   matrix supplies the matching spatial h and P_g correction columns.  The
%   legacy CTT*deltaT boundary storage is replaced by the exact lumped
%   V*deltaU correction used by the U-primary equation.  CTh*deltaH and
%   CTa*deltaP are not added because those storage changes are already inside
%   deltaU.  The returned signs retain the legacy contract: QET is positive
%   upward/out of the top, and QEB is positive upward/into the bottom.
%
%   Inputs:
%     SAVE             legacy boundary snapshot; energy bank is SAVE(:,:,2)
%     matrix           raw heat FEM bank with C2/C4/C4_a/C6/C6_a
%     temperatureAfter [degC, NN x 1] corrected temperature
%     deltaT           [degC, NN x 1] applied temperature correction
%     deltaH           [cm, NN x 1] applied head correction
%     deltaU           [J cm^-3, NN x 1] applied internal-energy correction
%     deltaP           [internal pressure, NN x 1] applied gas correction
%     dz               [cm, NL x 1] bottom-up element thickness
%     dt_s             [s] current accepted trial duration
%
%   Reference: docs/compass_soil_water_heat_physics.md, Sec. 5.7.
%   Editor: Jizixing Zhu; Date: 2026-07-15.

    T = temperatureAfter(:);
    dT = deltaT(:);
    dh = deltaH(:);
    dU = deltaU(:);
    dp = deltaP(:);
    dz = dz(:);
    NN = numel(T);
    NL = NN - 1;
    assert(NN >= 2 && numel(dT) == NN && numel(dh) == NN ...
            && numel(dU) == NN && numel(dp) == NN && numel(dz) == NL ...
            && all(isfinite(T)) && all(isfinite(dT)) ...
            && all(isfinite(dh)) && all(isfinite(dU)) ...
            && all(isfinite(dp)) && all(isfinite(dz)) && all(dz > 0) ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'calculateCoupledBoundaryFlux:badState', ...
        'T and all corrections must be finite; dz and dt_s must be positive.');
    required = {'C2','C4','C4_a','C6','C6_a'};
    assert(isstruct(matrix) && all(isfield(matrix, required)) ...
            && isequal(size(matrix.C2), [NN,2]) ...
            && isequal(size(matrix.C4), [NN,2]) ...
            && isequal(size(matrix.C6), [NN,2]) ...
            && numel(matrix.C4_a) >= NL && numel(matrix.C6_a) >= NL ...
            && all(isfinite(SAVE(1:2,1:3,2)), 'all'), ...
        'calculateCoupledBoundaryFlux:badMatrix', ...
        'SAVE and the raw heat FEM banks do not satisfy the boundary contract.');

    volume = [dz(1)/2; (dz(1:end-1)+dz(2:end))/2; dz(end)/2];
    storageReplacement = (volume .* dU - matrix.C2(:,1) .* dT) / dt_s;

    bottomCross = matrix.C4(1,1) * dh(1) + matrix.C4(1,2) * dh(2) ...
        + matrix.C6(1,1) * dp(1) + matrix.C6(1,2) * dp(2) ...
        + storageReplacement(1);
    topCross = matrix.C4_a(NL) * dh(NN-1) ...
        + matrix.C4(NN,1) * dh(NN) ...
        + matrix.C6_a(NL) * dp(NN-1) ...
        + matrix.C6(NN,1) * dp(NN) + storageReplacement(NN);

    QET = SAVE(2,1,2) ...
        - SAVE(2,2,2) * T(NN-1) - SAVE(2,3,2) * T(NN) ...
        - topCross;
    QEB = -SAVE(1,1,2) ...
        + SAVE(1,2,2) * T(1) + SAVE(1,3,2) * T(2) ...
        + bottomCross;
end
