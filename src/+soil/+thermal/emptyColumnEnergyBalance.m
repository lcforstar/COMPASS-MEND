function balance = emptyColumnEnergyBalance()
%EMPTYCOLUMNENERGYBALANCE  Return an undefined accepted-step soil-energy ledger.
%
%   Every extensive term is expressed in J cm^-2 over the accepted interval.
%   Boundary inputs use one public convention: positive values add energy to
%   the soil column. NaN is deliberate when heat is disabled or no complete
%   soil step is accepted; a missing solve must never look like exact closure.
%
%   Editor: Jizixing Zhu; Date: 2026-07-15.

    balance = struct( ...
        'has_data', false, ...
        'elapsed_s', 0, ...
        'storage_before_J_cm2', NaN, ...
        'storage_after_J_cm2', NaN, ...
        'storage_change_J_cm2', NaN, ...
        'top_input_J_cm2', NaN, ...
        'bottom_input_J_cm2', NaN, ...
        'boundary_net_input_J_cm2', NaN, ...
        'root_sink_J_cm2', NaN, ...
        'residual_J_cm2', NaN);
end
