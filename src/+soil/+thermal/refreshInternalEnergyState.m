function [estate, ederiv] = refreshInternalEnergyState( ...
        template, h, T, P_g, dt_s, L_f, Tmin)
%REFRESHINTERNALENERGYSTATE  Refresh the full SFCC state used by U(T) inversion.
%
%   [estate, ederiv] = soil.thermal.refreshInternalEnergyState(
%       template, h, T, P_g, dt_s, L_f, Tmin)
%   evaluates one candidate temperature column on a value-copy of the
%   current model. It runs the production water/phase refresh and the exact
%   internal-energy subset of the production thermal-gas kernels, then
%   marshals their outputs into the single internal-energy kernel contract.
%
%   Inputs:
%     template [struct] current scalar-column built container (read only)
%     h        [cm, NN x 1] matric head
%     T        [degC, NN x 1] candidate temperature
%     P_g      [g cm^-1 s^-2, NN x 1] gas pressure in solver units
%     dt_s     [s] positive trial time step
%     L_f      [J kg^-1] active fusion latent heat (zero when disabled)
%     Tmin     [degC] freeze-point temperature floor used by the normal B1 refresh
%
%   Returns estate/ederiv only.  The copied model and all refreshed caches
%   are discarded.  No thermodynamic formula is duplicated here;
%   evaluateInternalEnergyEndpoints remains the single state-function
%   implementation used by the inverter.
%
%   Editor: Jizixing Zhu; Date: 2026-07-14.
%   Change: 2026-07-15 Jizixing Zhu -- expose the current scalar-column
%           production contract with a dedicated regional-unsupported error.
%   Change: 2026-07-17 Jizixing Zhu -- use the internal-energy-only thermal-
%           gas refresh while retaining the same state and derivative kernels.

    h = h(:); T = T(:); P_g = P_g(:);
    NN = template.domain.NN;
    NL = template.domain.NL;
    nCell = 1;
    if isfield(template.domain, 'nCell') && ~isempty(template.domain.nCell)
        nCell = template.domain.nCell;
    end
    assert(nCell == 1, ...
        'refreshInternalEnergyState:regionalUnsupported', ...
        ['The h/U/P_g production solver currently supports nCell=1 only. ' ...
         'Regional U containers are initialized, but the regional solve path is not implemented.']);
    assert(numel(h) == NN && numel(T) == NN ...
        && numel(P_g) == NN && all(isfinite(h)) && all(isfinite(T)) ...
        && all(isfinite(P_g)) && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0 ...
        && isscalar(L_f) && isfinite(L_f) && L_f >= 0 ...
        && isscalar(Tmin) && isfinite(Tmin), ...
        'refreshInternalEnergyState:badInput', ...
        'A finite scalar-column state and positive dt_s are required.');

    candidate = template;
    candidate.workspace.step.trial.h = reshape( ...
        h, size(candidate.workspace.step.trial.h));
    candidate.workspace.step.trial.T = reshape( ...
        T, size(candidate.workspace.step.trial.T));
    candidate.workspace.step.trial.p_gas = reshape( ...
        P_g, size(candidate.workspace.step.trial.p_gas));
    candidate = soil.refreshWaterAux(candidate, dt_s, L_f, Tmin);
    candidate = soil.refreshThermalGasTransport( ...
        candidate, dt_s, 'internal_energy');

    d = candidate.workspace.derived;
    T_endpoint = [T(1:NL), T(2:NL+1)];
    estate = struct('T', T_endpoint, ...
        'Theta_LL', d.Theta_LL, 'Theta_II', d.Theta_II, ...
        'Theta_g', d.Theta_g, 'RHOV', d.RHOV, 'RHODA', d.RHODA, ...
        'L_vap', d.L, 'WW', d.WW, 'c_unsat', d.c_unsat);
    ederiv = struct('DThetaLiquidDh', d.DThetaLiquidDh, ...
        'DThetaLiquidDT', d.DThetaLiquidDT, ...
        'DThetaIceDh', d.DThetaIceDh, 'DThetaIceDT', d.DThetaIceDT, ...
        'DThetaGasDh', d.DThetaGasDh, 'DThetaGasDT', d.DThetaGasDT, ...
        'DRHOVh', d.DRHOVh, 'DRHOVT', d.DRHOVT, ...
        'Xah', d.Xah, 'XaT', d.XaT, 'Xaa', d.Xaa, ...
        'dW_dh', d.dW_dh, 'dW_dTheta', d.dW_dTheta);
end
