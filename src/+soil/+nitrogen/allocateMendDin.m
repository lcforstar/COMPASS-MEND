function allocation=allocateMendDin(request,remaining)
%ALLOCATEMENDDIN Apply root-first, NH4-first microbial DIN allocation.
%   REQUEST is top-down NL-by-2 [mg N g-1 dry soil] for NH4/NO3. REMAINING contains
%   post-root NH4/NO3 inventories on the same basis. COMPASS retains both
%   mineral species; this pure adapter returns applied and unmet amounts.
%   Editor: Jizixing Zhu; Date: 2026-09-12.
    request=request(:,:);
    nh4=max(remaining.nh4_mg_g(:),0);
    no3=max(remaining.no3_mg_g(:),0);
    assert(isequal(size(request),[numel(nh4),2])&&isequal(size(nh4),size(no3)) ...
        &&all(isfinite([request(:);nh4;no3]))&&all(request>=0,'all'), ...
        'soil:nitrogen:mendDinAllocation', ...
        'MEND DIN request and post-root inventories must align.');
    nh4Actual=min(request(:,1),nh4);
    no3Actual=min(request(:,2),no3);
    allocation=struct('requested_mg_g',request, ...
        'nh4_actual_mg_g',nh4Actual,'no3_actual_mg_g',no3Actual, ...
        'actual_mg_g',nh4Actual+no3Actual, ...
        'unmet_by_species_mg_g',request-[nh4Actual,no3Actual], ...
        'unmet_mg_g',sum(request,2)-nh4Actual-no3Actual, ...
        'policy','root_first_then_MEND_species_specific_MM');
end
