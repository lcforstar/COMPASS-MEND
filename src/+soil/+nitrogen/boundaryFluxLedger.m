function ledger=boundaryFluxLedger(topFluxUpward,bottomFluxUpward)
%BOUNDARYFLUXLEDGER Interpret raw vertical solute fluxes at column boundaries.
%
%   The nitrogen transport kernel uses one global vertical sign: positive is
%   upward at both boundaries. Consequently, a negative top flux enters the
%   soil, while a negative bottom flux leaves it. This adapter preserves the
%   raw signed values and exposes nonnegative, physically named input/loss
%   components for conservation ledgers and public diagnostics.
%
%   Inputs and outputs retain the caller's mass-flux units.
%
% Editor: Wenjie Liu; Date: 2026-09-21.
    assert(isnumeric(topFluxUpward)&&isreal(topFluxUpward) ...
            &&isnumeric(bottomFluxUpward)&&isreal(bottomFluxUpward) ...
            &&isequal(size(topFluxUpward),size(bottomFluxUpward)) ...
            &&all(isfinite(topFluxUpward(:))) ...
            &&all(isfinite(bottomFluxUpward(:))), ...
        'soil:nitrogen:boundaryFluxLedgerInput', ...
        'Top and bottom raw boundary fluxes must be finite arrays of equal size.');

    topInput=max(-topFluxUpward,0);
    topLoss=max(topFluxUpward,0);
    bottomInput=max(bottomFluxUpward,0);
    bottomLoss=max(-bottomFluxUpward,0);
    netIntoColumn=bottomFluxUpward-topFluxUpward;
    interpretedNet=topInput+bottomInput-topLoss-bottomLoss;
    tolerance=32*eps(max(1,max(abs([netIntoColumn(:);interpretedNet(:)]))));
    assert(all(abs(netIntoColumn(:)-interpretedNet(:))<=tolerance), ...
        'soil:nitrogen:boundaryFluxLedgerClosure', ...
        'Directional boundary components do not reproduce the raw signed fluxes.');

    ledger=struct( ...
        'sign_convention','raw vertical flux positive upward', ...
        'raw_top_upward',topFluxUpward, ...
        'raw_bottom_upward',bottomFluxUpward, ...
        'top_input',topInput,'top_loss',topLoss, ...
        'bottom_input',bottomInput,'bottom_loss',bottomLoss, ...
        'net_into_column',netIntoColumn);
end
