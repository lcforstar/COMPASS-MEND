function [rootDin,tagReservation]=reserveRootDin(totalNh4,totalNo3, ...
        tagNh4,tagNo3,thetaLiquid,rhokg,bulkDensity,rootReservation,rootRemaining)
%RESERVEROOTDIN Attribute the already accepted root-first DIN reservation.
%
% No root demand is recomputed.  Each accepted NH4/NO3 gross reservation is
% assigned by that species' fertilizer-label fraction in the step-start
% donor inventory.  Outputs are top-down [mg N g-1 dry soil].
% Editor: Wenjie Liu; Date: 2026-09-21.
    [total4,total3]=soil.organic_n.availableDinMgG( ...
        totalNh4,totalNo3,thetaLiquid,rhokg,bulkDensity);
    [tag4,tag3]=soil.organic_n.availableDinMgG( ...
        tagNh4,tagNo3,thetaLiquid,rhokg,bulkDensity);
    f4=sourceFraction(tag4,total4,'NH4');
    f3=sourceFraction(tag3,total3,'NO3');
    r4=rootReservation.nh4_mg_g(:);r3=rootReservation.no3_mg_g(:);
    tr4=r4.*f4;tr3=r3.*f3;
    remainTag4=tag4-tr4;remainTag3=tag3-tr3;
    tol=2e-12.*max(1,[total4,total3]);
    assert(all([remainTag4,remainTag3]>=-tol,'all'), ...
        'soil:nitrogen:tracer:rootOverdraw', ...
        'Attributed root uptake overdraws fertilizer-labelled DIN.');
    remainTag4=max(remainTag4,0);remainTag3=max(remainTag3,0);
    totalRemain=[rootRemaining.nh4_mg_g(:),rootRemaining.no3_mg_g(:)];
    assert(all([remainTag4,remainTag3]<=totalRemain+tol,'all'), ...
        'soil:nitrogen:tracer:rootBound', ...
        'Post-root fertilizer-labelled DIN exceeds total post-root DIN.');
    rootDin=struct('total_mg_g',totalRemain, ...
        'tag_mg_g',[remainTag4,remainTag3]);
    tagReservation=struct('nh4_mg_g',tr4,'no3_mg_g',tr3, ...
        'total_mg_g',tr4+tr3);
end

function fraction=sourceFraction(tag,total,name)
    tag=tag(:);total=total(:);tol=2e-12.*max(1,abs(total));
    assert(all(isfinite(tag))&&all(isfinite(total))&&all(total>=0) ...
        &&all(tag>=-tol)&&all(tag<=total+tol), ...
        'soil:nitrogen:tracer:donorBound', ...
        'Fertilizer-labelled %s donor is outside [0,total].',name);
    fraction=zeros(size(total));positive=total>0;
    fraction(positive)=tag(positive)./total(positive);
    assert(all(tag(~positive)==0), ...
        'soil:nitrogen:tracer:zeroDonor', ...
        'A zero total %s donor cannot contain fertilizer label.',name);
    fraction=min(1,max(0,fraction));
end
