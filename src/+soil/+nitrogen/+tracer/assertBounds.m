function assertBounds(tag,total)
%ASSERTBOUNDS Enforce finite 0 <= fertilizer label <= corresponding total.
% Editor: Wenjie Liu; Date: 2026-09-21.
% Change: 2026-10-28 Wenjie Liu -- bound dynamic free and sorbed DON labels.
% Change: 2026-10-30 Wenjie Liu -- bound independent manure AOM labels.
    pairs={ ...
        'nh4','nh4';'no3','no3';'urea','urea'; ...
        'nh4_granule','nh4_granule';'nh4_ice','nh4_ice'; ...
        'no3_ice','no3_ice'};
    for i=1:size(pairs,1)
        check(tag.(pairs{i,1}),total.(pairs{i,2}),pairs{i,1});
    end
    fields={'PON1','PON2','MON','MB_N','BD_N', ...
        'MB_mobile_N','MB_attached_N','MB_retained_N', ...
        'BD_mobile_N','BD_attached_N','BD_retained_N', ...
        'ENZP1_N','ENZP2_N','EM_N','ENZN_N', ...
        'ENZN_mobile_N','ENZN_attached_N','ENZN_retained_N'};
    for i=1:numel(fields)
        check(tag.organic_n.(fields{i}),total.organic_n.(fields{i}),fields{i});
    end
    check(tag.dom.don_total_g_cm3,total.dom.don_total_g_cm3,'DON');
    if isfield(tag,'aom')
        assert(isfield(total,'aom')&&isfield(total.aom,'manure'), ...
            'soil:nitrogen:tracer:aomBound','Total manure AOM owner is required.');
        check(tag.aom.manure.surface_N,total.aom.manure.surface_N,'manure surface AOM');
        check(tag.aom.manure.element_N,total.aom.manure.element_N,'manure element AOM');
    end
    if isfield(total.dom,'don_sorbed_g_cm3')
        assert(isfield(tag.dom,'don_sorbed_g_cm3'), ...
            'soil:nitrogen:tracer:dynamicSchema','Dynamic DON requires a sorbed label.');
        check(tag.dom.don_sorbed_g_cm3,total.dom.don_sorbed_g_cm3,'sorbed DON');
        check(tag.dom.don_total_g_cm3-tag.dom.don_sorbed_g_cm3, ...
            total.dom.don_total_g_cm3-total.dom.don_sorbed_g_cm3,'free DON');
    end
    pon=tag.organic_n.PON1+tag.organic_n.PON2;
    ep=tag.organic_n.ENZP1_N+tag.organic_n.ENZP2_N;
    assert(all(abs(tag.organic_n.PON-pon)<=2e-14.*max(1,abs(pon))) ...
        &&all(abs(tag.organic_n.EP_N-ep)<=2e-14.*max(1,abs(ep))), ...
        'soil:nitrogen:tracer:aggregateCache', ...
        'Fertilizer organic-N aggregate caches are inconsistent.');
end

function check(label,total,name)
    label=label(:);total=total(:);tol=2e-11.*max(1,abs(total));
    assert(isequal(size(label),size(total))&&all(isfinite(label)) ...
        &&all(isfinite(total))&&all(total>=-tol) ...
        &&all(label>=-tol)&&all(label<=total+tol), ...
        'soil:nitrogen:tracer:poolBound', ...
        'Fertilizer label %s is outside [0,total].',name);
end
