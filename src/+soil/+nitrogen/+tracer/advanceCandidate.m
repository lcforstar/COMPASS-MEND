function candidate=advanceCandidate(built,Y,fertilizer,soilVariables, ...
        ~,nitrogenDiagnostics,rootReservation,rootRemaining, ...
        totalBeforeReaction,totalAfterReaction,organicFinal,domCandidate, ...
        microbeCandidate,sourceLedger,transportTheta,transportQ,transportDt,dt_s)
%ADVANCECANDIDATE Advance and audit the passive fertilizer-N source label.
%
% The complete label trajectory is rebuilt from the same accepted total
% state whenever oxygen coupling retries.  It reads accepted gross routes,
% frozen transport operators and exact management increments; no labelled
% quantity is ever supplied to a total-N rate, matrix or convergence test.
%
% Current scope is one aggregated cohort containing all mineral-fertilizer
% schedule events. Organic fertilizer, atmospheric/groundwater N, BNF and
% litter are unlabelled. Perfect mixing and no source preference/fractionation
% are the explicit attribution assumptions.
%
% Editor: Wenjie Liu; Date: 2026-09-21.
% Change: 2026-09-22 Wenjie Liu -- DON and particle labels consume bounded
% accepted-total exchange maps, not the nonpositive explicit total operator.
% Change: 2026-09-29 Wenjie Liu -- retain particle bottom losses by cargo group.
% Change: 2026-09-29 Wenjie Liu -- add DON and particle top terminal label
% routes; leave mineral ADE/source-label solve unchanged.
    assert(isfield(Y,'soil_fertilizer_n_tracer') ...
        &&isfield(nitrogenDiagnostics,'fertilizer_tracer_frozen_ade'), ...
        'soil:nitrogen:tracer:productionContext', ...
        'Enabled fertilizer tracer lacks accepted state or frozen ADE.');
    accepted=Y.soil_fertilizer_n_tracer;
    frozen=nitrogenDiagnostics.fertilizer_tracer_frozen_ade;
    dz=built.domain.dz(:);bd=built.parameters.soil.bulk_density(:);
    assertNoActiveFreezePartition(nitrogenDiagnostics);

    eventIncrement=zeros(built.domain.NN,1);
    if fertilizer.applied
        eventIncrement=fertilizer.tracer_increment.nh4_granule(:);
    end
    totalStaged=struct('nh4',frozen.nh4.old_total_ug_cm3, ...
        'no3',frozen.no3.old_total_ug_cm3, ...
        'urea',soilVariables.C_Urea(:), ...
        'nh4_granule',Y.C_NH4_granule(:)+eventIncrement);
    [work,inputAmount]=soil.nitrogen.tracer.stageMineralEvent( ...
        accepted,fertilizer,totalStaged);

    % DON precedes source-hour reaction. Attribute the accepted total-DON
    % exchanges without selecting another total timestep or changing totals.
    [work.dom.don_total_g_cm3,donTransport]= ...
        soil.nitrogen.tracer.transportDonFrozen( ...
        accepted.dom.don_total_g_cm3,transportTheta,transportQ,transportDt, ...
        bd,dz,built.parameters.soil_dom,domCandidate.transport.don, ...
        totalBeforeReaction.don_total_g_cm3);

    % Current management is intentionally unavailable to root/MEND until the
    % inorganic solve, matching the accepted total call order.
    thetaOld=Y.soil_nitrogen.theta_liquid_prev;
    [rootDin,tagRootReservation]=soil.nitrogen.tracer.reserveRootDin( ...
        Y.nh4,Y.no3,accepted.nh4,accepted.no3,thetaOld, ...
        built.parameters.soil_n.RHOKG,bd,rootReservation,rootRemaining);
    tagBundle=struct('organic_n',work.organic_n, ...
        'don_total_g_cm3',work.dom.don_total_g_cm3, ...
        'sorption_model','linear_equilibrium');
    [tagBundle,mendExchange,mendRoutes]=soil.nitrogen.tracer.replaySourceHour( ...
        tagBundle,totalBeforeReaction,sourceLedger,rootDin, ...
        totalAfterReaction,bd);
    work.organic_n=tagBundle.organic_n;
    work.dom.don_total_g_cm3=tagBundle.don_total_g_cm3;

    bioparticle=[];
    if isfield(built.control.switches,'lMicrobialTransport') ...
            &&built.control.switches.lMicrobialTransport==1
        assert(isfield(microbeCandidate,'bioparticle_transport'), ...
            'soil:nitrogen:tracer:missingBioparticleLedger', ...
            'Enabled microbial transport lacks accepted total diagnostics.');
        [work.organic_n,bioparticle]= ...
            soil.nitrogen.tracer.transportBioparticleFrozen( ...
            work.organic_n,transportTheta,transportQ,transportDt,bd,dz, ...
            built.parameters.soil_microbes.bioparticle, ...
            microbeCandidate.bioparticle_transport.diagnostics,organicFinal);
    end

    % Urea and solid-granule donors lose the exact accepted total amount in
    % proportion to their source labels. Their labelled products enter the
    % frozen dissolved-N solve as named gross NH4 sources.
    deltaUrea=nitrogenDiagnostics.fertilizer_tracer_delta_urea(:);
    deltaGranule=nitrogenDiagnostics.fertilizer_tracer_delta_granule(:);
    [tagUreaDelta,ureaFraction]=taggedDonorChange( ...
        deltaUrea,soilVariables.C_Urea(:),work.urea,'urea hydrolysis');
    [tagGranuleDelta,granuleFraction]=taggedDonorChange( ...
        deltaGranule,totalStaged.nh4_granule,work.nh4_granule, ...
        'granule dissolution');
    work.urea=work.urea-tagUreaDelta;
    work.nh4_granule=work.nh4_granule-tagGranuleDelta;
    rates=taggedRates(frozen,work,ureaFraction,granuleFraction, ...
        mendExchange,tagRootReservation,rootReservation,bd,dt_s);
    request=struct('old',struct('nh4_ug_cm3',work.nh4, ...
        'no3_ug_cm3',work.no3),'rates',rates);
    [din,adeLedger]=iterateDenitrification(frozen,request);
    work.nh4=din.nh4_ug_cm3;work.no3=din.no3_ug_cm3;

    % The total owner removes sub-microgram granule concentrations after
    % accepted dissolution. Mirror that truncation and account it explicitly.
    granuleCorrection=0;
    zeroTotal=soilVariables.C_NH4_granule(:)==0;
    if any(zeroTotal)
        capacity=[dz;0]./2+[0;dz]./2;
        granuleCorrection=sum(capacity(zeroTotal).*work.nh4_granule(zeroTotal))*1e-6;
        work.nh4_granule(zeroTotal)=0;
    end

    totalFinal=struct('nh4',soilVariables.C_NH4_new, ...
        'no3',soilVariables.C_NO3_new,'urea',soilVariables.C_Urea_new, ...
        'nh4_granule',soilVariables.C_NH4_granule, ...
        'nh4_ice',soilVariables.C_NH4_ice,'no3_ice',soilVariables.C_NO3_ice, ...
        'organic_n',organicFinal,'dom',struct( ...
        'don_total_g_cm3',domCandidate.state.don_total_g_cm3));
    soil.nitrogen.tracer.assertBounds(work,totalFinal);

    storage=soil.nitrogen.tracer.columnStorage(work, ...
        soilVariables.Theta_LL_for_N_prev,soilVariables.Theta_II_for_N_prev, ...
        built.parameters.soil_n.RHOKG,dz);
    stepLedger=assembleStepLedger(adeLedger,mendExchange,mendRoutes, ...
        inputAmount,granuleCorrection,bd,dz);
    % Change: 2026-09-29 Wenjie Liu -- DON export is a terminal source-label
    % loss, not an internal organic/mineral exchange or numerical correction.
    stepLedger.don_bottom_loss_g_cm2=donTransport.bottom_outflow_g_cm2;
    stepLedger.don_top_loss_g_cm2=donTransport.top_outflow_g_cm2;
    for group={'MB','BD','ENZN'}
        key=group{1};amount=0;
        if ~isempty(bioparticle),amount=bioparticle.(key).bottom_outflow_g_cm2;end
        stepLedger.(['bioparticle_' lower(key) '_bottom_loss_g_cm2'])=amount;
        topAmount=0;if ~isempty(bioparticle),topAmount=bioparticle.(key).top_outflow_g_cm2;end
        stepLedger.(['bioparticle_' lower(key) '_top_loss_g_cm2'])=topAmount;
    end
    work.cumulative=accumulate(work.cumulative,stepLedger);
    terminal=cumulativeTerminal(work.cumulative);
    closure=work.cumulative.fertilizer_input_g_cm2 ...
        +work.cumulative.nh4_top_input_g_cm2+work.cumulative.nh4_bottom_input_g_cm2 ...
        +work.cumulative.no3_top_input_g_cm2+work.cumulative.no3_bottom_input_g_cm2 ...
        -storage.total_g_cm2-terminal-work.cumulative.numerical_correction_g_cm2;
    tolerance=2e-12*max(1,work.cumulative.fertilizer_input_g_cm2);
    assert(abs(closure)<=tolerance, ...
        'soil:nitrogen:tracer:columnClosure', ...
        'Fertilizer source-label column balance failed (%.6g g N cm-2).',closure);

    candidate=struct('state',work,'diagnostics',struct( ...
        'schema_version',1,'storage',storage,'step',stepLedger, ...
        'cumulative_closure_residual_g_cm2',closure, ...
        'don_transport',donTransport,'bioparticle_transport',bioparticle, ...
        'mend_routes',mendRoutes,'ade',adeLedger, ...
        'root_reservation',tagRootReservation, ...
        'attribution_assumption',work.mixing_assumption));
end

function assertNoActiveFreezePartition(diagnostics)
% Total-N freeze partition is currently disabled upstream. Fail explicitly
% if that physical route is restored before its label replay is implemented.
    assert(isfield(diagnostics,'partition')&&isstruct(diagnostics.partition), ...
        'soil:nitrogen:tracer:freezePartitionContract', ...
        'Fertilizer tracing requires the accepted total freeze-partition ledger.');
    partition=diagnostics.partition;
    names={'delta_NH4_to_ice','delta_NH4_from_ice', ...
        'delta_NO3_to_ice','delta_NO3_from_ice'};
    transfer=0;
    for i=1:numel(names)
        assert(isfield(partition,names{i})&&isscalar(partition.(names{i})) ...
                &&isfinite(partition.(names{i})), ...
            'soil:nitrogen:tracer:freezePartitionContract', ...
            'Accepted total freeze-partition ledger lacks %s.',names{i});
        transfer=max(transfer,abs(partition.(names{i})));
    end
    assert(transfer<=1e-14, ...
        'soil:nitrogen:tracer:freezePartitionUnsupported', ...
        ['Total-N liquid/ice transfer became active, but fertilizer-label ', ...
         'freeze/thaw replay has not been implemented.']);
end

function rates=taggedRates(frozen,state,ureaFraction,granuleFraction, ...
        mend,tagRoot,totalRoot,bdBottom,dt_s)
    nl=frozen.NL;
    nh4Fraction=nodeFraction(state.nh4,frozen.nh4.old_total_ug_cm3,'NH4');
    no3Fraction=nodeFraction(state.no3,frozen.no3.old_total_ug_cm3,'NO3');
    f4=[nh4Fraction(1:nl),nh4Fraction(2:nl+1)];
    f3=[no3Fraction(1:nl),no3Fraction(2:nl+1)];
    gross=frozen.gross_rates;
    rates=struct();
    rates.nh4.sources=struct( ...
        'urea_hydrolysis',gross.nh4.sources.urea_hydrolysis.* ...
            [ureaFraction(1:nl),ureaFraction(2:nl+1)], ...
        'organic_release',amountToRate(mend.total_nh4_release_mg_g,bdBottom,dt_s), ...
        'granule_dissolution',gross.nh4.sources.granule_dissolution.* ...
            [granuleFraction(1:nl),granuleFraction(2:nl+1)]);
    rates.nh4.sinks=struct( ...
        'organic_immobilization',amountToRate( ...
            mend.total_uptake_mg_g(:,1),bdBottom,dt_s), ...
        'volatilization',gross.nh4.sinks.volatilization.*f4, ...
        'nitrification',gross.nh4.sinks.nitrification.*f4, ...
        'root_uptake',scaleRootRate(gross.nh4.sinks.root_uptake, ...
            tagRoot.nh4_mg_g,totalRoot.nh4_mg_g));
    rates.no3.sources=struct( ...
        'nitrification',0.98*rates.nh4.sinks.nitrification, ...
        'organic_release',zeros(nl,2));
    rates.no3.sinks=struct( ...
        'organic_immobilization',amountToRate( ...
            mend.total_uptake_mg_g(:,2),bdBottom,dt_s), ...
        'denitrification',gross.no3.sinks.denitrification.*f3, ...
        'root_uptake',scaleRootRate(gross.no3.sinks.root_uptake, ...
            tagRoot.no3_mg_g,totalRoot.no3_mg_g));
end

function [candidate,ledger]=iterateDenitrification(frozen,request)
    for iteration=1:20
        [next,nextLedger]=soil.nitrogen.transport.solveFrozenFertilizerTracer( ...
            frozen,request);
        fraction=nodeFraction(next.no3_ug_cm3, ...
            frozen.no3.projected_total_ug_cm3,'accepted NO3');
        updated=frozen.gross_rates.no3.sinks.denitrification.* ...
            [fraction(1:frozen.NL),fraction(2:frozen.NN)];
        change=max(abs(updated-request.rates.no3.sinks.denitrification),[],'all');
        scale=max(1,max(abs(updated),[],'all'));
        candidate=next;ledger=nextLedger;
        if change<=1e-11*scale
            ledger.denitrification_label_iterations=iteration;
            return
        end
        request.rates.no3.sinks.denitrification=updated;
    end
    error('soil:nitrogen:tracer:denitrificationIteration', ...
        'Passive fertilizer-N denitrification attribution did not converge.');
end

function rate=amountToRate(amountTop,bdBottom,dt_s)
    bottom=flip(amountTop(:).*flip(bdBottom(:)).*1000./dt_s);
    rate=repmat(bottom,1,2);
end

function tagged=scaleRootRate(totalRate,tagAmount,totalAmount)
    fraction=zeros(size(totalAmount(:)));positive=totalAmount(:)>0;
    fraction(positive)=tagAmount(positive)./totalAmount(positive);
    assert(all(tagAmount(~positive)==0) ...
        &&all(fraction>=0&fraction<=1+2e-11), ...
        'soil:nitrogen:tracer:rootFraction','Invalid fertilizer root fraction.');
    tagged=totalRate.*repmat(flip(min(1,max(0,fraction))),1,2);
end

function fraction=nodeFraction(tag,total,label)
    tag=tag(:);total=total(:);tol=2e-11.*max(1,abs(total));
    assert(all(isfinite([tag;total]))&&all(total>=0) ...
        &&all(tag>=-tol)&&all(tag<=total+tol), ...
        'soil:nitrogen:tracer:nodeFraction', ...
        'Invalid fertilizer fraction in %s.',label);
    fraction=zeros(size(total));positive=total>0;
    fraction(positive)=tag(positive)./total(positive);
    assert(all(tag(~positive)==0), ...
        'soil:nitrogen:tracer:zeroNodeDonor', ...
        'Zero total %s donor contains fertilizer label.',label);
    fraction=min(1,max(0,fraction));
end

function [tagDelta,fraction]=taggedDonorChange(delta,total,tag,label)
    fraction=nodeFraction(tag,total,label);
    tol=2e-11.*max(1,abs(total));
    assert(all(delta>=-tol)&&all(delta<=total+tol), ...
        'soil:nitrogen:tracer:donorChange', ...
        'Accepted %s change overdraws its total donor.',label);
    tagDelta=max(delta,0).*fraction;
    assert(all(tagDelta<=tag+tol), ...
        'soil:nitrogen:tracer:tagDonorOverdraw', ...
        'Accepted %s change overdraws its fertilizer label.',label);
end

function step=assembleStepLedger(ade,mend,routes,input,granuleCorrection,bd,dz)
    step=struct();step.fertilizer_input_g_cm2=input;
    step.root_nh4_g_cm2=ade.nh4.sinks_ug_cm2.root_uptake*1e-6;
    step.root_no3_g_cm2=ade.no3.sinks_ug_cm2.root_uptake*1e-6;
    step.nh3_volatilization_g_cm2=ade.nh4.sinks_ug_cm2.volatilization*1e-6;
    step.nitrification_n2o_g_cm2=ade.combined_din.nitrification_n2o_loss_ug_cm2*1e-6;
    denit=ade.no3.sinks_ug_cm2.denitrification*1e-6;
    step.denitrification_n2o_g_cm2=.11*denit;
    step.denitrification_n2_g_cm2=.89*denit;
    for species={'nh4','no3'}
        name=species{1};b=ade.(name).boundary_amount_ug_cm2;
        for route={'top_input','top_loss','bottom_input','bottom_loss'}
            key=route{1};step.([name '_' key '_g_cm2'])=b.(key)*1e-6;
        end
    end
    step.organic_entry_gross_g_cm2=columnAmount( ...
        sum(mend.total_uptake_mg_g,2),bd,dz);
    step.organic_release_gross_g_cm2=columnAmount( ...
        mend.total_nh4_release_mg_g,bd,dz);
    step.numerical_correction_g_cm2=granuleCorrection;
    step.mend_closure_residual_g_cm2=columnAmount( ...
        routes.closure_residual_mg_g,bd,dz);
    step.din_closure_residual_g_cm2=ade.combined_din.residual_ug_cm2*1e-6;
end

function value=columnAmount(amountTop,bdBottom,dzBottom)
    value=sum(amountTop(:).*flip(bdBottom(:)).*flip(dzBottom(:)))./1000;
end

function cumulative=accumulate(cumulative,step)
    names=fieldnames(cumulative);
    for i=1:numel(names)
        name=names{i};
        if isfield(step,name)
            cumulative.(name)=cumulative.(name)+step.(name);
        end
    end
end

function value=cumulativeTerminal(c)
    names={'root_nh4_g_cm2','root_no3_g_cm2','nh3_volatilization_g_cm2', ...
        'nitrification_n2o_g_cm2','denitrification_n2o_g_cm2', ...
        'denitrification_n2_g_cm2','nh4_top_loss_g_cm2', ...
        'nh4_bottom_loss_g_cm2','no3_top_loss_g_cm2','no3_bottom_loss_g_cm2', ...
        'don_bottom_loss_g_cm2','bioparticle_mb_bottom_loss_g_cm2', ...
        'bioparticle_bd_bottom_loss_g_cm2','bioparticle_enzn_bottom_loss_g_cm2', ...
        'don_top_loss_g_cm2','bioparticle_mb_top_loss_g_cm2', ...
        'bioparticle_bd_top_loss_g_cm2','bioparticle_enzn_top_loss_g_cm2'};
    value=0;for i=1:numel(names),value=value+c.(names{i});end
end
