function state=emptyState(built)
%EMPTYSTATE Initialize the accepted mineral-fertilizer N source label.
%
% The tracer is a passive mass label.  Every prognostic concentration uses
% the same spatial order and unit as its corresponding COMPASS owner.  It is
% initialized to zero because native soil N, atmospheric deposition,
% groundwater, litter, straw and manure are outside this source definition.
%
% Source definition: every event in the mineral fertilization schedule.
% Organic fertilizer TAN and organic N are deliberately not labelled.
%
% Editor: Wenjie Liu; Date: 2026-09-21.
% Change: 2026-09-29 Wenjie Liu -- schema 2 includes DON bottom terminal loss.
% Change: 2026-09-29 Wenjie Liu -- schema 3 separates MB/BD/ENZN bottom losses.
% Change: 2026-09-29 Wenjie Liu -- schema 4 adds organic top exports only.
    n=built.domain.NL;nn=built.domain.NN;
    z=zeros(n,1);zn=zeros(nn,1);z2=zeros(n,2);
    organic=struct( ...
        'PON1',z,'PON2',z,'PON',z,'MON',z, ...
        'MB_N',z,'BD_N',z, ...
        'MB_mobile_N',z,'MB_attached_N',z,'MB_retained_N',z, ...
        'BD_mobile_N',z,'BD_attached_N',z,'BD_retained_N',z, ...
        'ENZP1_N',z,'ENZP2_N',z,'EP_N',z,'EM_N',z, ...
        'ENZN_N',z,'ENZN_mobile_N',z,'ENZN_attached_N',z, ...
        'ENZN_retained_N',z);
    terminalNames={ ...
        'fertilizer_input','root_nh4','root_no3','nh3_volatilization', ...
        'nitrification_n2o','denitrification_n2o','denitrification_n2', ...
        'nh4_top_input','nh4_top_loss','nh4_bottom_input','nh4_bottom_loss', ...
        'no3_top_input','no3_top_loss','no3_bottom_input','no3_bottom_loss', ...
        'don_bottom_loss','bioparticle_mb_bottom_loss','bioparticle_bd_bottom_loss', ...
        'bioparticle_enzn_bottom_loss','don_top_loss','bioparticle_mb_top_loss', ...
        'bioparticle_bd_top_loss','bioparticle_enzn_top_loss', ...
        'organic_entry_gross','organic_release_gross','numerical_correction'};
    cumulative=struct();
    for i=1:numel(terminalNames)
        cumulative.([terminalNames{i} '_g_cm2'])=0;
    end
    state=struct( ...
        'schema_version',4, ...
        'enabled',true, ...
        'source_definition','mineral_fertilization_schedule_all_events', ...
        'unlabelled_sources',{{'atmospheric_deposition','groundwater', ...
            'biological_fixation','litter','straw','manure','organic_fertilizer_TAN'}}, ...
        'mixing_assumption','perfect_mixing_no_source_preference_no_isotope_fractionation', ...
        'grid_order','bottom_up', ...
        'nh4',zn,'no3',zn,'urea',zn,'nh4_granule',zn, ...
        'nh4_ice',z2,'no3_ice',z2, ...
        'organic_n',organic, ...
        'dom',struct('don_total_g_cm3',z), ...
        'cumulative',cumulative);
end
