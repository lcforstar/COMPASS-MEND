function result=allocateMendDinStages( ...
        firstRequest,stoichiometricDemand,remaining,nh4Release)
%ALLOCATEMENDDINSTAGES Apply MEND first and second microbial DIN uptake.
%   All arrays are top-down [mg N g-1 dry soil]. FIRSTREQUEST is the
%   species-specific kinetic request after COMPASS root reservation.
%   NH4RELEASE is same-stage microbial mineralization, made available only
%   after first uptake. The second request fills the remaining MBA C:N
%   deficit in proportion to the then-available NH4/NO3 stocks. The result
%   is a pure temporary ledger; COMPASS later applies one net source/sink.
%   Reference: MOD_MEND.F90 commit 92323c7, two-stage MBA immobilization.
%   Editor: Jizixing Zhu; Date: 2026-09-12.
% Change: 2026-09-13 Codex -- account for first-stage kinetic requests
%   independently of the later C:N correction demand in the unmet ledger.
    stoichiometricDemand=stoichiometricDemand(:);
    nh4Release=nh4Release(:);
    first=soil.nitrogen.allocateMendDin(firstRequest,remaining);
    nh4=max(remaining.nh4_mg_g(:)-first.nh4_actual_mg_g+nh4Release,0);
    no3=max(remaining.no3_mg_g(:)-first.no3_actual_mg_g,0);
    assert(isequal(size(stoichiometricDemand),size(nh4),size(nh4Release)) ...
        &&all(isfinite([stoichiometricDemand;nh4Release])) ...
        &&all(stoichiometricDemand>=0)&&all(nh4Release>=0), ...
        'soil:nitrogen:mendDinStages','Invalid staged MEND DIN inputs.');
    residualDemand=max(stoichiometricDemand-first.actual_mg_g,0);
    available=nh4+no3; secondRequest=zeros(numel(nh4),2);
    active=available>0;
    secondRequest(active,1)=residualDemand(active).*nh4(active)./available(active);
    secondRequest(active,2)=residualDemand(active).*no3(active)./available(active);
    second=soil.nitrogen.allocateMendDin(secondRequest, ...
        struct('nh4_mg_g',nh4,'no3_mg_g',no3));
    nh4Actual=first.nh4_actual_mg_g+second.nh4_actual_mg_g;
    no3Actual=first.no3_actual_mg_g+second.no3_actual_mg_g;
    actual=nh4Actual+no3Actual;
    firstUnmet=sum(first.unmet_by_species_mg_g,2);
    secondUnmet=max(residualDemand-second.actual_mg_g,0);
    unmet=firstUnmet+secondUnmet;
    result=struct('first',first,'second',second, ...
        'requested_mg_g',actual+unmet, ...
        'nh4_actual_mg_g',nh4Actual,'no3_actual_mg_g',no3Actual, ...
        'actual_mg_g',actual,'unmet_mg_g',unmet, ...
        'nh4_release_mg_g',nh4Release, ...
        'net_nh4_sink_mg_g',nh4Actual-nh4Release, ...
        'net_no3_sink_mg_g',no3Actual, ...
        'policy','root_first_then_MEND_kinetic_then_release_then_CN_correction');
    assert(all(result.net_nh4_sink_mg_g<=remaining.nh4_mg_g(:)+1e-12) ...
        &&all(result.net_no3_sink_mg_g<=remaining.no3_mg_g(:)+1e-12), ...
        'soil:nitrogen:mendDinStagesClosure', ...
        'Staged MEND net sink exceeded the post-root accepted inventory.');
end
