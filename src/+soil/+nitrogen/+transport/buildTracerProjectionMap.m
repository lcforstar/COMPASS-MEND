function map=buildTracerProjectionMap(rawTotal,projectedTotal,projectionDiagnostic, ...
        thetaElement,storageCoefficient,dz)
%BUILDTRACERPROJECTIONMAP Freeze the total-N admissibility projection.
%
% Inputs are one solute's raw and projected nodal concentrations
% [ug N cm-3 water], its [NL x 2] end-step liquid contents, the [NL x 1]
% adsorbed-storage coefficient, and layer thickness [cm].  The returned map
% is immutable solver evidence used by COPROJECTTRACERBOUNDED.  It carries
% the exact trapezoidal storage weights of the total solve, so a passive
% source label can be projected without changing total nitrogen.
%
% The map records, but does not re-run, the total projection.  A tracer is
% subsequently constrained to 0 <= tracer <= projected total while its own
% column inventory is preserved whenever that inventory is feasible.
%
% Editor: Wenjie Liu; Date: 2026-09-21.

    rawTotal=rawTotal(:);
    projectedTotal=projectedTotal(:);
    storageCoefficient=storageCoefficient(:);
    dz=dz(:);
    nl=numel(dz);
    assert(numel(rawTotal)==nl+1&&numel(projectedTotal)==nl+1 ...
            &&isequal(size(thetaElement),[nl,2]) ...
            &&numel(storageCoefficient)==nl, ...
        'soil:nitrogen:tracerProjectionMapSize', ...
        'Total solution and storage geometry are not aligned.');
    assert(all(isfinite(rawTotal))&&all(isfinite(projectedTotal)) ...
            &&all(isfinite(thetaElement),'all') ...
            &&all(isfinite(storageCoefficient))&&all(isfinite(dz)) ...
            &&all(projectedTotal>=0)&&all(thetaElement>=0,'all') ...
            &&all(storageCoefficient>=0)&&all(dz>0), ...
        'soil:nitrogen:tracerProjectionMapDomain', ...
        'Projection-map inputs must be finite and physically admissible.');

    weights=zeros(nl+1,1);
    for element=1:nl
        weights(element)=weights(element)+0.5*dz(element) ...
            *(thetaElement(element,1)+storageCoefficient(element));
        weights(element+1)=weights(element+1)+0.5*dz(element) ...
            *(thetaElement(element,2)+storageCoefficient(element));
    end
    rawMass=weights.'*rawTotal;
    projectedMass=weights.'*projectedTotal;
    scale=max(1,abs(weights).'*abs(rawTotal));
    tolerance=256*eps(scale)*scale;
    assert(abs(projectedMass-rawMass)<=tolerance, ...
        'soil:nitrogen:tracerProjectionMapClosure', ...
        'The frozen total projection does not preserve column inventory.');

    positiveMass=weights.'*max(rawTotal,0);
    if positiveMass>0
        positiveScale=max(rawMass,0)/positiveMass;
    else
        positiveScale=0;
    end
    map=struct( ...
        'schema_version',1, ...
        'method','total-active-set bounded conservative co-projection', ...
        'raw_total_ug_cm3',rawTotal, ...
        'projected_total_ug_cm3',projectedTotal, ...
        'storage_weights_cm',weights, ...
        'raw_total_mass_ug_cm2',rawMass, ...
        'projected_total_mass_ug_cm2',projectedMass, ...
        'positive_active_nodes',rawTotal>0, ...
        'positive_scale',positiveScale, ...
        'mass_tolerance_ug_cm2',tolerance, ...
        'total_projection_diagnostic',projectionDiagnostic);
end
