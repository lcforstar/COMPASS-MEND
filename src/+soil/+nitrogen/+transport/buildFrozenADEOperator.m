function frozen=buildFrozenADEOperator( ...
        matrixNH4,lowerNH4,matrixNO3,lowerNO3,oldMassNH4,oldMassNO3, ...
        preMatrixNH4,preLowerNH4,preMatrixNO3,preLowerNO3, ...
        preRhsNH4,preRhsNO3,oldNH4,oldNO3,rawNH4,rawNO3, ...
        projectedNH4,projectedNO3,projectionNH4,projectionNO3, ...
        R1,R1O,E1,B1,F1,R2,R2O,E2,B2,F2,QLNodes, ...
        thetaNew,rhoKd,dz,dt,boundary,cfg,nitrogen,kt)
%BUILDFROZENADEOPERATOR Export an accepted total-N ADE linearization.
%
% This helper packages the matrices after boundary application, the
% pre-boundary rows needed for realized flux reconstruction, total raw and
% projected solutions, R/Rold, Dsh-derived E, liquid-flux B, and the final
% accepted gross reaction rates.  Every array belongs to the same Picard
% linearization and physical interval.  The package is read-only evidence
% for SOLVEFROZENFERTILIZERTRACER; it is never an input to total-N dynamics.
%
% Nodal concentrations use [ug N cm-3 water], endpoint reaction rates use
% [ug N cm-3 soil s-1], QL uses [cm s-1], dz [cm], and dt [s].  Nodes and
% elements retain the COMPASS bottom-to-surface order.
%
% Editor: Wenjie Liu; Date: 2026-09-21.

    nn=numel(oldNH4);
    nl=numel(dz);
    assert(nn==nl+1&&numel(oldNO3)==nn&&numel(QLNodes)==nn, ...
        'soil:nitrogen:frozenADESize', ...
        'Frozen ADE node and element dimensions are inconsistent.');
    assert(isscalar(dt)&&isfinite(dt)&&dt>0&&isscalar(kt)&&kt>=1, ...
        'soil:nitrogen:frozenADETime', ...
        'Frozen ADE time index and interval must be valid.');

    nh4Projection=soil.nitrogen.transport.buildTracerProjectionMap( ...
        rawNH4,projectedNH4,projectionNH4,thetaNew,rhoKd,dz);
    no3Projection=soil.nitrogen.transport.buildTracerProjectionMap( ...
        rawNO3,projectedNO3,projectionNO3,thetaNew,zeros(nl,1),dz);

    [gross,grossBasis]=acceptedGrossRates(nitrogen,nl);
    frozen=struct();
    frozen.schema_version=1;
    frozen.contract='one-way fertilizer-N source tracer; never drives total-N rates';
    frozen.kt=kt;
    frozen.dt_s=dt;
    frozen.NL=nl;
    frozen.NN=nn;
    frozen.dz_cm=dz(:);
    frozen.theta_new=thetaNew;
    frozen.ql_nodes_cm_s=QLNodes(:);
    frozen.boundary=struct( ...
        'NBCN',boundary.NBCN,'NBCNB',boundary.NBCNB, ...
        'lThmrlefc',cfg.lThmrlefc,'lBNF',cfg.lBNF, ...
        'QMB_now',boundary.QMB(kt), ...
        'tracer_external_concentration_ug_cm3',0, ...
        'sign_convention','raw vertical flux positive upward');
    frozen.nh4=soluteRecord(matrixNH4,lowerNH4,oldMassNH4, ...
        preMatrixNH4,preLowerNH4,preRhsNH4,oldNH4,rawNH4, ...
        projectedNH4,R1,R1O,E1,B1,F1,nh4Projection,rhoKd);
    frozen.no3=soluteRecord(matrixNO3,lowerNO3,oldMassNO3, ...
        preMatrixNO3,preLowerNO3,preRhsNO3,oldNO3,rawNO3, ...
        projectedNO3,R2,R2O,E2,B2,F2,no3Projection,zeros(nl,1));
    frozen.gross_rates=gross;
    frozen.gross_rate_basis=grossBasis;
end

function record=soluteRecord(matrix,lower,oldMass,preMatrix,preLower,preRhs, ...
        oldTotal,rawTotal,projectedTotal,R,Rold,E,B,F,projection,storage)
% Keep the frozen public schema identical for NH4 and NO3.
    record=struct( ...
        'matrix_diag_upper',matrix, ...
        'matrix_lower',lower(:), ...
        'old_storage_lumped',oldMass(:), ...
        'pre_boundary_matrix_diag_upper',preMatrix, ...
        'pre_boundary_matrix_lower',preLower(:), ...
        'pre_boundary_total_rhs',preRhs(:), ...
        'old_total_ug_cm3',oldTotal(:), ...
        'raw_total_ug_cm3',rawTotal(:), ...
        'projected_total_ug_cm3',projectedTotal(:), ...
        'R',R,'Rold',Rold,'E_cm2_s',E,'B_cm_s',B, ...
        'implicit_reaction_coefficient_s_1',F, ...
        'storage_coefficient',storage(:), ...
        'projection_map',projection);
end

function [gross,basis]=acceptedGrossRates(nitrogen,nl)
% Split accepted signed exchange into nonnegative, named gross pathways.
    zero=zeros(nl,2);
    signedNH4=signedField(nitrogen,'Smin',zero);
    signedNO3=signedField(nitrogen,'SorgNO3',zero);
    [organicNH4Source,organicNH4Sink,organicNO3Source,organicNO3Sink,basis]= ...
        acceptedOrganicGross(nitrogen,signedNH4,signedNO3,zero);
    gross=struct();
    gross.nh4.sources=struct( ...
        'urea_hydrolysis',nonnegativeField(nitrogen,'Shys',zero), ...
        'organic_release',organicNH4Source, ...
        'granule_dissolution',nonnegativeField(nitrogen,'Sdis',zero));
    gross.nh4.sinks=struct( ...
        'organic_immobilization',organicNH4Sink, ...
        'volatilization',nonnegativeField(nitrogen,'Svol',zero), ...
        'nitrification',nonnegativeField(nitrogen,'Snit',zero), ...
        'root_uptake',nonnegativeSlice(nitrogen,'SinkS',1,zero));
    gross.no3.sources=struct( ...
        'nitrification',0.98*nonnegativeField(nitrogen,'Snit',zero), ...
        'organic_release',organicNO3Source);
    gross.no3.sinks=struct( ...
        'organic_immobilization',organicNO3Sink, ...
        'denitrification',nonnegativeField(nitrogen,'Sden',zero), ...
        'root_uptake',nonnegativeSlice(nitrogen,'SinkS',2,zero));
end

function [nh4Source,nh4Sink,no3Source,no3Sink,basis]= ...
        acceptedOrganicGross(nitrogen,signedNH4,signedNO3,zero)
% Preserve simultaneous MEND release and immobilization when supplied.
    if ~isfield(nitrogen,'fertilizer_tracer_total_gross') ...
            ||isempty(nitrogen.fertilizer_tracer_total_gross)
        nh4Source=max(signedNH4,0);
        nh4Sink=max(-signedNH4,0);
        no3Source=max(signedNO3,0);
        no3Sink=max(-signedNO3,0);
        basis='fallback split of accepted net Smin/SorgNO3';
        return
    end
    owner=nitrogen.fertilizer_tracer_total_gross;
    nh4Source=readNestedGross(owner,'nh4','sources','organic_release',zero);
    nh4Sink=readNestedGross(owner,'nh4','sinks','organic_immobilization',zero);
    no3Source=readNestedGross(owner,'no3','sources','organic_release',zero);
    no3Sink=readNestedGross(owner,'no3','sinks','organic_immobilization',zero);
    assertGrossNet(nh4Source,nh4Sink,signedNH4,'NH4 Smin');
    assertGrossNet(no3Source,no3Sink,signedNO3,'NO3 SorgNO3');
    basis='accepted simultaneous MEND gross release and immobilization';
end

function value=readNestedGross(owner,species,direction,name,zero)
    assert(isstruct(owner)&&isfield(owner,species)&&isstruct(owner.(species)) ...
            &&isfield(owner.(species),direction) ...
            &&isstruct(owner.(species).(direction)) ...
            &&isfield(owner.(species).(direction),name), ...
        'soil:nitrogen:frozenADEOrganicGrossContract', ...
        'Injected fertilizer-tracer total gross exchange is incomplete.');
    value=owner.(species).(direction).(name);
    scale=max(1,max(abs(value),[],'all'));
    tolerance=256*eps(scale)*scale;
    assert(isequal(size(value),size(zero))&&all(isfinite(value),'all') ...
            &&all(value>=-tolerance,'all'), ...
        'soil:nitrogen:frozenADEOrganicGrossDomain', ...
        'Injected organic gross exchange must be finite, nonnegative [NL x 2].');
    value=max(value,0);
end

function assertGrossNet(source,sink,acceptedNet,label)
    reconstructed=source-sink;
    scale=max(1,max(abs([source(:);sink(:);acceptedNet(:)])));
    tolerance=1024*eps(scale)*scale;
    assert(all(abs(reconstructed-acceptedNet)<=tolerance,'all'), ...
        'soil:nitrogen:frozenADEOrganicGrossNetMismatch', ...
        'Injected organic gross exchange does not reconstruct accepted %s.',label);
end

function value=signedField(owner,name,fallback)
    if isfield(owner,name)&&~isempty(owner.(name))
        value=owner.(name);
    else
        value=fallback;
    end
    assert(isequal(size(value),size(fallback))&&all(isfinite(value),'all'), ...
        'soil:nitrogen:frozenADERateShape', ...
        'Accepted gross-rate fields must be finite [NL x 2] arrays.');
end

function value=nonnegativeField(owner,name,fallback)
    value=signedField(owner,name,fallback);
    tolerance=256*eps(max(1,max(abs(value),[],'all')));
    assert(all(value>=-tolerance,'all'), ...
        'soil:nitrogen:frozenADENegativeGrossRate', ...
        'Accepted one-way gross-rate fields cannot be materially negative.');
    value=max(value,0);
end

function value=nonnegativeSlice(owner,name,index,fallback)
    if isfield(owner,name)&&~isempty(owner.(name))
        raw=owner.(name);
        assert(ndims(raw)==3&&size(raw,3)>=index, ...
            'soil:nitrogen:frozenADERateShape', ...
            'Accepted root-uptake rates must be [NL x 2 x species].');
        value=raw(:,:,index);
    else
        value=fallback;
    end
    tolerance=256*eps(max(1,max(abs(value),[],'all')));
    assert(isequal(size(value),size(fallback))&&all(isfinite(value),'all') ...
            &&all(value>=-tolerance,'all'), ...
        'soil:nitrogen:frozenADENegativeGrossRate', ...
        'Accepted root-uptake gross rates must be finite and nonnegative.');
    value=max(value,0);
end
