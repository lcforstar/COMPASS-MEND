function inputs = normalizeOrganicExternalInputs(candidate)
%NORMALIZEEXTERNALINPUTS  Validate accepted management-source masses.
%   Masses use the retained nitrogen-ledger unit [ug cm^-2].
% Editor: Jizixing Zhu; Date: 2026-07-20.
% Change: 2026-10-23 Wenjie Liu -- preserve the reference accepted-tile
%   oxygen result independently of fertilizer and organic-source switches.
    inputs = struct('nh4_added',0,'no3_added',0,'urea_added',0, ...
        'organic_enabled',false,'organic_nh4_rate',[], ...
        'organic_no3_rate',[],'organic_co2_c_rate',[], ...
        'root_reservation_mg_g',zeros(0,2), ...
        'pre_reaction_reservation_mg_g',zeros(0,2));
    if isfield(candidate,'oxygen_hour')
        inputs.oxygen_hour=candidate.oxygen_hour;
    end
    % Change: 2026-09-11 Jizixing Zhu -- fertilizer occurrence must not gate
    % continuous organic C/N exchange. Only event masses are suppressed.
    eventApplied=~isfield(candidate,'applied') || logical(candidate.applied);
    names = {'nh4_added','no3_added','urea_added'};
    for i = 1:numel(names)
        name = names{i};
        if eventApplied && isfield(candidate, name)
            value = candidate.(name);
            assert(isscalar(value) && isfinite(value) && value >= 0, ...
                'soil:nitrogen:badExternalInput', ...
                'External nitrogen inputs must be finite nonnegative scalars.');
            inputs.(name) = value;
        end
    end
    if isfield(candidate,'organic_enabled')
        inputs.organic_enabled = logical(candidate.organic_enabled);
    end
    rateNames = {'organic_nh4_rate','organic_no3_rate','organic_co2_c_rate'};
    for i=1:numel(rateNames)
        name=rateNames{i};
        if isfield(candidate,name), inputs.(name)=candidate.(name)(:); end
    end
    if isfield(candidate,'root_reservation_mg_g')
        inputs.root_reservation_mg_g=candidate.root_reservation_mg_g;
    end
    if isfield(candidate,'pre_reaction_reservation_mg_g')
        inputs.pre_reaction_reservation_mg_g=...
            candidate.pre_reaction_reservation_mg_g;
    end
    if inputs.organic_enabled
        n=numel(inputs.organic_nh4_rate);
        assert(n>0 && numel(inputs.organic_no3_rate)==n ...
            && numel(inputs.organic_co2_c_rate)==n ...
            && all(isfinite(inputs.organic_nh4_rate)) ...
            && all(isfinite(inputs.organic_no3_rate)) ...
            && all(isfinite(inputs.organic_co2_c_rate)) ...
            && all(inputs.organic_co2_c_rate>=0), ...
            'soil:nitrogen:badOrganicExchange', ...
            'Native organic exchange profiles must be finite and aligned.');
    end
    if ~isempty(inputs.root_reservation_mg_g)
        assert(isnumeric(inputs.root_reservation_mg_g) ...
            &&size(inputs.root_reservation_mg_g,2)==2 ...
            &&all(isfinite(inputs.root_reservation_mg_g(:))) ...
            &&all(inputs.root_reservation_mg_g(:)>=0), ...
            'soil:nitrogen:badRootReservation', ...
            'Root DIN reservation must be finite and nonnegative NL-by-2.');
    end
    if ~isempty(inputs.pre_reaction_reservation_mg_g)
        assert(isnumeric(inputs.pre_reaction_reservation_mg_g) ...
            &&size(inputs.pre_reaction_reservation_mg_g,2)==2 ...
            &&all(isfinite(inputs.pre_reaction_reservation_mg_g(:))) ...
            &&all(inputs.pre_reaction_reservation_mg_g(:)>=0), ...
            'soil:nitrogen:badReactionReservation', ...
            'Pre-reaction DIN reservation must be finite nonnegative NL-by-2.');
    end
end
