function [QMT, QMB] = calculateCoupledBoundaryFlux( ...
        SAVE, matrix, stateBefore, stateAfter, ...
        storageBefore, storageAfter, dz, dt_s, bottomNode)
%CALCULATECOUPLEDBOUNDARYFLUX  Recover total-water boundary reactions.
%
%   The mixed Richards equation is assembled at one Picard state, while the
%   distributed correction changes h, T (through U), and P_g together. The
%   accepted boundary reaction must therefore include the spatial T/P_g
%   corrections and the exact condensed-plus-vapor water storage change.
%   The h-storage tangent already contained in SAVE is replaced, not counted
%   a second time.
%
%   Inputs use the COMPASS cm-s water-equation convention:
%     state*.h       [cm], state*.T [degC], state*.P [internal pressure]
%     storage*       [-, NL x 2] endpoint total-water equivalent content
%     dz             [cm, NL x 1]
%     dt_s           [s]
%
%   bottomNode [optional, -] bottom Richards node represented by SAVE(1,:,:).
%       Default 1 is the physical column bottom. MODFLOW coupling supplies
%       its fixed water-table node instead; the saturated continuation below
%       it is external to the Richards water ledger.
%
%   Returns preserve the legacy boundary signs: QMT is positive outward at
%   the top and QMB is positive inward at the active Richards bottom, both
%   [cm s^-1].
%
%   References: Zeng (2013), Coupled Dynamics in Soil, Eqs. 4.47-4.60;
%   Celia et al. (1990), WRR 26:1483-1496.
%   Editor: Jizixing Zhu; Date: 2026-07-17.
%   Change: 2026-07-20 Jizixing Zhu -- parameterize the saved lower reaction by the
%           active MODFLOW Richards interface rather than always node 1.
%   Change: 2026-08-11 Jizixing Zhu -- require the saved top reaction to use
%           the water matrix's actual strict-lower C4_a(NL) coefficient.

    dz = dz(:);
    NL = numel(dz);
    NN = NL + 1;
    if nargin < 9 || isempty(bottomNode)
        bottomNode = 1;
    end
    assert(isscalar(bottomNode) && isfinite(bottomNode) ...
            && bottomNode == floor(bottomNode) ...
            && bottomNode >= 1 && bottomNode < NN, ...
        'calculateCoupledWaterBoundaryFlux:badBottomNode', ...
        'bottomNode must be an integer Richards node in 1:NN-1.');
    before = normalizeState(stateBefore, NN, 'stateBefore');
    after = normalizeState(stateAfter, NN, 'stateAfter');
    assert(isequal(size(storageBefore), [NL,2]) ...
            && isequal(size(storageAfter), [NL,2]) ...
            && all(isfinite(storageBefore(:))) ...
            && all(isfinite(storageAfter(:))) ...
            && all(isfinite(dz)) && all(dz > 0) ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'calculateCoupledWaterBoundaryFlux:badStorage', ...
        'Endpoint storage must be finite NL-by-2; dz and dt_s must be positive.');
    required = {'C1','C4_a','C5','C5_a','C6'};
    assert(isstruct(matrix) && all(isfield(matrix, required)) ...
            && isequal(size(matrix.C1), [NN,2]) ...
            && isequal(size(matrix.C5), [NN,2]) ...
            && isequal(size(matrix.C6), [NN,2]) ...
            && numel(matrix.C4_a) >= NL ...
            && numel(matrix.C5_a) >= NL ...
            && all(matrix.C1(:,2) == 0) ...
            && all(isfinite(matrix.C1(:))) ...
            && all(isfinite(matrix.C4_a(1:NL))) ...
            && all(isfinite(matrix.C5(:))) ...
            && all(isfinite(matrix.C5_a(1:NL))) ...
            && all(isfinite(matrix.C6(:))) ...
            && all(isfinite(SAVE(1:2,1:3,1)), 'all'), ...
        'calculateCoupledWaterBoundaryFlux:badMatrix', ...
        'SAVE and the raw water FEM banks do not satisfy the boundary contract.');
    assert(isequal(SAVE(2,2,1), matrix.C4_a(NL)), ...
        'calculateCoupledWaterBoundaryFlux:topRowMismatch', ...
        ['The saved top water reaction must use C4_a(NL), the actual ', ...
         'strict-lower coefficient of the top equation row.']);

    dh = after.h - before.h;
    dT = after.T - before.T;
    dP = after.P - before.P;

    deltaStorage = storageAfter - storageBefore;
    storageChange = zeros(NN,1);
    storageChange(1:NL) = storageChange(1:NL) ...
        + deltaStorage(:,1) .* dz / 2;
    storageChange(2:NN) = storageChange(2:NN) ...
        + deltaStorage(:,2) .* dz / 2;
    storageReplacement = ...
        (storageChange - matrix.C1(:,1) .* dh) / dt_s;

    bottomCross = matrix.C5(bottomNode,1) * dT(bottomNode) ...
        + matrix.C5(bottomNode,2) * dT(bottomNode + 1) ...
        + matrix.C6(bottomNode,1) * dP(bottomNode) ...
        + matrix.C6(bottomNode,2) * dP(bottomNode + 1) ...
        + storageReplacement(bottomNode);
    topCross = matrix.C5_a(NL) * dT(NN-1) ...
        + matrix.C5(NN,1) * dT(NN) ...
        + matrix.C6(NN-1,2) * dP(NN-1) ...
        + matrix.C6(NN,1) * dP(NN) ...
        + storageReplacement(NN);

    QMT = SAVE(2,1,1) ...
        - SAVE(2,2,1) * after.h(NN-1) ...
        - SAVE(2,3,1) * after.h(NN) - topCross;
    QMB = -SAVE(1,1,1) ...
        + SAVE(1,2,1) * after.h(bottomNode) ...
        + SAVE(1,3,1) * after.h(bottomNode + 1) + bottomCross;
end

function state = normalizeState(raw, NN, name)
%NORMALIZESTATE  Validate and orient one water boundary-reaction state.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    assert(isstruct(raw) && all(isfield(raw, {'h','T','P'})), ...
        'calculateCoupledWaterBoundaryFlux:badState', ...
        '%s must contain h, T, and P.', name);
    state = struct('h', raw.h(:), 'T', raw.T(:), 'P', raw.P(:));
    assert(numel(state.h) == NN && numel(state.T) == NN ...
            && numel(state.P) == NN && all(isfinite(state.h)) ...
            && all(isfinite(state.T)) && all(isfinite(state.P)), ...
        'calculateCoupledWaterBoundaryFlux:badState', ...
        '%s fields must be finite NN-by-1 vectors.', name);
end
