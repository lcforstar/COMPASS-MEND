function result = buildResult(request, waterFlux, accepted, applied)
%BUILDRESULT  Package requested, applied, and actual water boundary values.
%
%   Public actual fluxes are [cm/s], positive into the soil domain. The
%   current Richards kernel reports legacy QMT (top upward-positive) and QMB
%   (bottom into-domain-positive), so the sign translation is confined here.
%   applied.top_kind/bottom_kind optionally records the active mathematical
%   condition selected by the solver adapter. In particular, an atmospheric
%   request may currently apply either fixed_head or fixed_flux. If applied is
%   omitted, static requested kinds are used.
%
%   Editor: Jizixing Zhu; Date: 2026-07-11.

    assert(isstruct(request) && isfield(request, 'top') && isfield(request, 'bottom'), ...
        'buildWaterBoundaryResult:badRequest', 'request must contain top and bottom endpoints.');
    assert(isstruct(waterFlux) && isfield(waterFlux, 'QMT') && isfield(waterFlux, 'QMB'), ...
        'buildWaterBoundaryResult:badFlux', 'waterFlux must contain actual QMT and QMB.');
    if nargin < 4 || isempty(applied)
        applied = struct('top_kind', request.top.kind, 'bottom_kind', request.bottom.kind);
    end
    assert(isstruct(applied) && isfield(applied, 'top_kind') && isfield(applied, 'bottom_kind'), ...
        'buildWaterBoundaryResult:badApplied', ...
        'applied must contain top_kind and bottom_kind.');

    result = struct( ...
        'schema_version', 1, ...
        'sign_convention', 'flux_into_domain_positive', ...
        't_start_s', request.t_start_s, ...
        't_end_s', request.t_end_s, ...
        'dt_s', request.dt_s, ...
        'accepted', logical(accepted), ...
        'top', endpointResult(request.top, applied.top_kind, -double(waterFlux.QMT)), ...
        'bottom', endpointResult(request.bottom, applied.bottom_kind, double(waterFlux.QMB)));
end

% -------------------------------------------------------------------------
function endpoint = endpointResult(requested, appliedKind, actualFlux)
% Keep request and actual values separate even when a static policy applies.
    endpoint = struct( ...
        'requested_kind', requested.kind, ...
        'applied_kind', appliedKind, ...
        'requested_head_cm', requested.head_cm, ...
        'requested_flux_into_domain_cm_s', requested.requested_flux_into_domain_cm_s, ...
        'actual_flux_into_domain_cm_s', actualFlux);
end
