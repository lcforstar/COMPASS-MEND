function boundary = stageBoundary(built, kt, t_start_s, dt_s, external_driver)
%STAGEBOUNDARY Expose current soil-bottom policies without inventing groundwater state.
%
%   Inputs:
%     built     [struct] Model shell with normalized soil boundary policies.
%     kt        [-] Current forcing index.
%     t_start_s [s] Accepted outer-step start.
%     dt_s      [s] Trial duration.
%     external_driver [struct, optional] Current MODFLOW/BMI water-table
%               driver. It is read-only over this trial interval.
%
%   Returns:
%     boundary [struct] Read-only lower-boundary policy snapshot, including
%               the active Richards node for an external MODFLOW head.
%
%   Physical contract:
%     COMPASS does not own a saturated-aquifer prognostic state. When a
%     MODFLOW/BMI driver is enabled, it supplies the water-table head and
%     layer position. The unsaturated Richards solve is restricted to the
%     nodes above that interface; rows below are the legacy hydrostatic
%     continuation. Recharge is returned through the soil-to-groundwater
%     ledger for the external receiver.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
% Change: 2026-07-20 Jizixing Zhu — materialize the legacy MODFLOW fixed-head
%   interface as an explicit, trial-frozen groundwater boundary.
% Change: 2026-07-20 Jizixing Zhu — reject an interface without an active
%   Richards element above it and label water-only external coupling.
    if nargin < 5 || isempty(external_driver)
        external_driver = struct('GroundwaterCoupling', 0);
    end
    assert(isstruct(built) && isfield(built, 'boundary'), ...
        'groundwater:stageBoundary:missingBoundary', ...
        'Normalized built.boundary is required.');
    assert(isscalar(kt) && isfinite(kt) && kt >= 1 ...
        && isscalar(t_start_s) && isfinite(t_start_s) ...
        && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'groundwater:stageBoundary:badTime', ...
        'kt, t_start_s, and positive dt_s are required.');
    waterBottom = struct();
    heatBottom = struct();
    if isfield(built.boundary, 'water') && isfield(built.boundary.water, 'bottom')
        waterBottom = built.boundary.water.bottom;
    end
    if isfield(built.boundary, 'heat') && isfield(built.boundary.heat, 'bottom')
        heatBottom = built.boundary.heat.bottom;
    end
    modflow = materializeModflowDriver(external_driver, built.domain);
    boundary = struct( ...
        'schema_version', 1, ...
        'has_prognostic_state', false, ...
        't_start_s', t_start_s, ...
        't_end_s', t_start_s + dt_s, ...
        'forcing_index', kt, ...
        'water_bottom_policy', waterBottom, ...
        'heat_bottom_policy', heatBottom, ...
        'modflow', modflow);
end

function modflow = materializeModflowDriver(driver, domain)
% Normalize an external MODFLOW snapshot without mutating it.
    enabled = isfield(driver, 'GroundwaterCoupling') ...
        && driver.GroundwaterCoupling == 1;
    modflow = struct('enabled', enabled);
    if ~enabled
        return;
    end
    required = {'headBotmLayer','topLevel','indexBotmLayer','indexBotmLayer_R'};
    for i = 1:numel(required)
        name = required{i};
        assert(isfield(driver, name) && isscalar(driver.(name)) ...
                && isfinite(driver.(name)), ...
            'groundwater:stageBoundary:missingModflowDriverField', ...
            'Enabled MODFLOW driver.%s must be one finite scalar.', name);
    end
    node = driver.indexBotmLayer;
    layerTopDown = driver.indexBotmLayer_R;
    assert(node == floor(node) && node >= 1 && node <= domain.NL ...
            && layerTopDown == floor(layerTopDown) && layerTopDown >= 1 ...
            && layerTopDown <= domain.NL, ...
        'groundwater:stageBoundary:badModflowIndex', ...
        'MODFLOW active node/layer indices are outside the soil column.');
    assert(isfield(driver, 'soilLayerThickness'), ...
        'groundwater:stageBoundary:missingModflowDriverField', ...
        'Enabled MODFLOW driver.soilLayerThickness is required.');
    thickness = driver.soilLayerThickness;
    assert(numel(thickness) >= layerTopDown && isfinite(thickness(layerTopDown)), ...
        'groundwater:stageBoundary:badModflowThickness', ...
        'soilLayerThickness must contain the active MODFLOW top-down layer.');
    fixedHead = driver.headBotmLayer - driver.topLevel + thickness(layerTopDown);
    modflow = struct( ...
        'enabled', true, ...
        'active_node', node, ...
        'active_layer_top_down', layerTopDown, ...
        'fixed_head_cm', fixedHead, ...
        'head_bottom_layer_cm', driver.headBotmLayer, ...
        'aquifer_top_elevation_cm', driver.topLevel, ...
        'soil_layer_thickness_cm', thickness(:), ...
        'temperature_C', readTemperature(driver));
    modflow.coupling_mode = 'water_only_external_boundary';
end

function value = readTemperature(driver)
    value = NaN;
    if isfield(driver, 'tempBotm') && isscalar(driver.tempBotm) ...
            && isfinite(driver.tempBotm)
        value = driver.tempBotm;
    end
end
