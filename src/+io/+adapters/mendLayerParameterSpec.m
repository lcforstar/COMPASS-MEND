function spec=mendLayerParameterSpec()
%MENDLAYERPARAMETERSPEC Layer-capable MEND reaction candidate catalogue.
% Public soil.csv values retain the source hourly clock and dry-soil basis.
% The historical four kinetic columns remain an atomic ownership group.
% Physiological, dormancy, uptake and sorption candidates each have one soil
% column or legacy site scalar. This interface does not make any parameter a free
% calibration coordinate by itself.
% Editor: Wenjie Liu; Date: 2026-09-29.
% Change: 2026-10-12 Wenjie Liu — register the 8+2 layer-capable reaction
% candidate set while retaining atomic ownership of the historical four.
% Change: 2026-10-12 Wenjie Liu — require a sole owner for every candidate;
% a soil profile no longer requires a duplicate site fallback scalar.
% Change: 2026-10-27 Wenjie Liu — add layered dormancy exponent and DIN uptake parameters.
% Change: 2026-10-31 Wenjie Liu -- add layer-capable source-hour Qmax, Kba
% and Kdes; legacy RK4 sites need not supply inactive kinetic sorption inputs.
    base={'mend_vd_pom_h','mend_ks_pom1_mg_g', ...
        'mend_vg_h','mend_ks_dom_mg_g'};
    extended={'mend_ks_pom_ratio','mend_alpha', ...
        'mend_mortality_multiplier','mend_cue_20', ...
        'mend_swp_a2d_mpa','mend_tau','mend_wdorm', ...
        'mend_vnup_mb_h','mend_ks_nh4_mb_mg_g','mend_ks_no3_mb_mg_g', ...
        'mend_qmax_mg_g','mend_kba_g_mg','mend_kdes_mg_g_h'};
    names=[base,extended];
    units={'h^-1','mg C/g dry soil','h^-1','mg C/g dry soil', ...
        '-','-','-','-','MPa','-', ...
        '-','h^-1','mg N/g dry soil','mg N/g dry soil', ...
        'mg C/g dry soil','g dry soil/mg C','mg C/g dry soil/h'};
    spec=struct('names',{names},'units',{units}, ...
        'base_atomic_names',{base},'extended_optional_names',{extended}, ...
        'decomposition_growth_names',{names(1:8)}, ...
        'dormancy_names',{{names{9:10},'mend_wdorm'}}, ...
        'nitrogen_uptake_names',{names(12:14)}, ...
        'sorption_names',{names(15:17)});
end
