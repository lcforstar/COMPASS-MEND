function spec = tableSpec(kind)
%TABLESPEC  Column catalogue ("read directory") for COMPASS site CSV tables.
%
%   spec = io.adapters.tableSpec(kind) returns the canonical column contract for
%   one CSV table kind. This is the SINGLE SOURCE OF TRUTH for what columns a
%   table may contain: io.checkSite validates a freshly read table against it.
%   Matching is BY NAME (not position), so the user may reorder columns or add
%   new ones (e.g. a 'soil_type' column) without breaking the read -- any column
%   not listed here is reported as "extra" and carried through untouched, never
%   silently mis-assigned.
%
%   Inputs:
%     kind   [char]  one of: 'soil' | 'initial' | 'root' | 'plant' | 'forcing' |
%                    'water_boundary'
%
%   Returns a struct with fields:
%     spec.kind      [char]      echo of the requested kind
%     spec.layout    [char]      'wide' (one column per quantity) or
%                                'long' (pool/value/unit rows; key column = 'pool')
%     spec.required  {cellstr}   column names (wide) / row keys (long) that MUST be
%                                present; a missing one is a hard error
%     spec.optional  {cellstr}   recognised but non-mandatory columns / keys
%     spec.units     struct      name -> unit string [char], for documentation
%
%   To support a new measured column: add it here (optional or required). Until
%   then it still reads fine, just flagged "extra" by io.checkSite.
%
%   Reference: column names mirror data/sites/changwu/{soil,initial,root,
%   initial_plant}.csv generated from the legacy *.xlsx (2026-06-20).
%   Editor: Jizixing Zhu; Date: 2026-06-26.
%   Change: 2026-07-11 Jizixing Zhu -- add the optional prescribed water-boundary table contract.
%   Change: 2026-07-11 Jizixing Zhu -- reference the single flat [boundary] water series-column fields.
%   Change: 2026-07-11 Jizixing Zhu -- define fixed top_value/bottom_value columns for the one-mode water-boundary schema.
%   Change: 2026-08-16 Codex -- register measured total SOC in the initial-state
%     table so soil-organic initialization no longer sources initial mass from
%     the static soil-parameter table.
%   Change: 2026-09-02 Codex -- remove site-global organic-model and retired
%     DON-MM fields; soil.csv now contains only depth-resolved quantities.

    switch lower(kind)
        case 'soil'
            spec.kind   = 'soil';
            spec.layout = 'wide';
            spec.required = { ...
                'depth_cm', 'theta_s', 'theta_r', 'vg_n', 'vg_alpha_1cm', ...
                'ks_cmd', 'clay_pct', 'sand_pct', 'bulk_density_gcm3'};
            spec.optional = { ...
                'msoc_mgkg', 'ph', 'difnh4_cm2d', 'difno3_cm2d', 'disp_cm', ...
                'kg_cm3g', 'vmax_denit_ugn_cm3d', 'km_denit_ugn_cm3', 'kurea_1d', ...
                'vmax_nit_ugn_cm3d', 'km_nit_ugn_cm3', 'kmineralization_1d', ...
                'k_nh4_dissolve_1d','kd_doc_cm3_g','kd_don_cm3_g', ...
                'dom_disp_cm','attachment_1d','detachment_1d', ...
                'straining_1d','microbe_disp_cm'};
            spec.units = struct( ...
                'depth_cm','cm', 'theta_s','m3/m3', 'theta_r','m3/m3', 'vg_n','-', ...
                'vg_alpha_1cm','1/cm', 'ks_cmd','cm/d', 'clay_pct','%', 'sand_pct','%', ...
                'bulk_density_gcm3','g/cm3', 'msoc_mgkg','mg/kg', 'ph','-', ...
                'difnh4_cm2d','cm2/d', 'difno3_cm2d','cm2/d', 'disp_cm','cm', ...
                'kg_cm3g','cm3/g', 'vmax_denit_ugn_cm3d','ugN/cm3/d', ...
                'km_denit_ugn_cm3','ugN/cm3', 'kurea_1d','1/d', ...
                'vmax_nit_ugn_cm3d','ugN/cm3/d', 'km_nit_ugn_cm3','ugN/cm3', ...
                'kmineralization_1d','1/d', 'k_nh4_dissolve_1d','1/d', ...
                'kd_doc_cm3_g','cm3/g','kd_don_cm3_g','cm3/g', ...
                'dom_disp_cm','cm','attachment_1d','1/d', ...
                'detachment_1d','1/d','straining_1d','1/d', ...
                'microbe_disp_cm','cm');

        case 'initial'
            spec.kind   = 'initial';
            spec.layout = 'wide';
            spec.required = {'depth_cm', 'theta', 'T_C'};
            spec.optional = {'nh4', 'no3', 'p_atm_pa', 'bulk_density_gcm3', ...
                'soc_total_mgkg', 'doc_mgkg', 'don_mgkg', 'doc_mgL', 'don_mgL'};
            spec.units = struct( ...
                'depth_cm','cm', 'theta','m3/m3', 'T_C','degC', 'nh4','mg/L', ...
                'no3','mg/L', 'p_atm_pa','Pa', 'bulk_density_gcm3','g/cm3', ...
                'soc_total_mgkg','mg C/kg dry soil', 'doc_mgL','mg C/L', ...
                'don_mgL','mg N/L','doc_mgkg','mg C/kg dry soil (total DOM)', ...
                'don_mgkg','mg N/kg dry soil (total DOM)');

        case 'root'
            spec.kind   = 'root';
            spec.layout = 'wide';
            spec.required = {'depth_cm', 'root_length_density_m_m3'};
            spec.optional = {};
            spec.units = struct('depth_cm','cm', 'root_length_density_m_m3','m/m3');

        case 'forcing'
            spec.kind   = 'forcing';
            spec.layout = 'wide';
            % one row per forcing step (here: daily). Columns keep RAW Excel units;
            % unit conversions happen in init.buildForcing (ported from MeteoData).
            spec.required = { ...
                'date', 'tmax_c', 'tmin_c', 'tmean_c', 'rh_mean_pct', ...
                'wind_ms', 'precip_mm', 'rin_wm2', 'rli_wm2'};
            spec.optional = { ...
                'tdew_c', 'rh_max_pct', 'rh_min_pct', 'wind_u_ms', 'wind_v_ms', ...
                'sunshine_h', 'ts_c', 'tb_c', 'h_sur_cm', 'pg_hpa', 'rn_mjm2', 'ca_ppm', ...
                'nh4_dep_mgm2d', 'no3_dep_mgm2d', 'nh4_bot_mgl', 'no3_bot_mgl'};
            spec.units = struct( ...
                'date','ISO-date', 'tmax_c','degC', 'tmin_c','degC', 'tmean_c','degC', ...
                'tdew_c','degC', 'rh_mean_pct','%', 'rh_max_pct','%', 'rh_min_pct','%', ...
                'wind_u_ms','m/s', 'wind_v_ms','m/s', 'wind_ms','m/s', 'sunshine_h','h', ...
                'precip_mm','mm', 'ts_c','degC', 'tb_c','degC', 'h_sur_cm','cm', ...
                'pg_hpa','hPa', 'rn_mjm2','MJ/m2', 'rin_wm2','W/m2', 'rli_wm2','W/m2', ...
                'ca_ppm','ppm', 'nh4_dep_mgm2d','mgN/m2/day', 'no3_dep_mgm2d','mgN/m2/day', ...
                'nh4_bot_mgl','mg/L', 'no3_bot_mgl','mg/L');

        case 'water_boundary'
            spec.kind   = 'water_boundary';
            spec.layout = 'wide';
            % One public value column per endpoint; the selected boundary mode
            % determines whether its values are head [cm] or flux [cm/s].
            spec.required = {'time_s','top_value','bottom_value'};
            spec.optional = {};
            spec.units = struct('time_s', 's', ...
                'top_value', 'mode-dependent: cm or cm/s', ...
                'bottom_value', 'mode-dependent: cm or cm/s');

        case 'plant'
            spec.kind    = 'plant';
            spec.layout  = 'long';
            spec.keyCol  = 'pool';          % row-key column for long layout
            spec.valCol  = 'value';
            spec.required = { ...
                'C_labile', 'C_leaf', 'C_root_fine', 'C_stem_wood', ...
                'C_fruit', 'N_storage', 'C_storage'};
            spec.optional = {};
            spec.units = struct();          % units live in the table's own 'unit' column

        otherwise
            error('tableSpec:unknownKind', ...
                ['Unknown table kind "%s" (expected soil|initial|root|plant|' ...
                 'forcing|water_boundary)'], kind);
    end
end
