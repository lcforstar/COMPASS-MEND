function slice = sliceForcing(forcing, kt)
%SLICEFORCING Return one explicit atmospheric boundary slice for a model step.
%
%   Inputs:
%     forcing [struct] Immutable model forcing container.
%     kt      [-] One-based atmospheric forcing index.
%
%   Returns:
%     slice [struct] Atmospheric values used by current boundary interfaces.
%
%   The atmosphere has no prognostic state in the present COMPASS column.  It
%   owns only this read-only forcing slice.  Values retain their source units:
%   temperature [degC], pressure [Pa], wind [m s-1], relative humidity [-],
%   radiation [W m-2], and precipitation [mm or source forcing unit].
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
    assert(isstruct(forcing) && isfield(forcing, 'hourly') ...
        && isstruct(forcing.hourly), ...
        'atmosphere:sliceForcing:missingHourly', ...
        'forcing.hourly is required for an atmospheric slice.');
    assert(isscalar(kt) && isfinite(kt) && kt >= 1 && kt == floor(kt), ...
        'atmosphere:sliceForcing:badIndex', ...
        'kt must be a positive integer.');
    hourly = forcing.hourly;
    slice = struct( ...
        'schema_version', 1, ...
        'kind', 'prescribed_atmospheric_forcing', ...
        'temperature_C', requiredValue(hourly, 'Ta', kt), ...
        'pressure_Pa', requiredValue(hourly, 'Pg', kt), ...
        'relative_humidity', optionalValue(hourly, 'RH', kt), ...
        'wind_speed_m_s', optionalValue(hourly, 'U', kt), ...
        'shortwave_W_m2', optionalValue(hourly, 'Rin', kt), ...
        'longwave_W_m2', optionalValue(hourly, 'Rli', kt), ...
        'precipitation', optionalValue(hourly, 'Precip', kt));
end

function value = requiredValue(hourly, name, kt)
% Read a finite scalar driver that is mandatory for boundary materialization.
% Editor: Jizixing Zhu; Date: 2026-07-20.
    assert(isfield(hourly, name) && numel(hourly.(name)) >= kt ...
            && isfinite(hourly.(name)(kt)), ...
        'atmosphere:sliceForcing:missingDriver', ...
        'forcing.hourly.%s(%d) must be finite.', name, kt);
    value = double(hourly.(name)(kt));
end

function value = optionalValue(hourly, name, kt)
% Read an optional finite scalar without manufacturing unavailable forcing.
% Editor: Jizixing Zhu; Date: 2026-07-20.
    value = NaN;
    if isfield(hourly, name) && numel(hourly.(name)) >= kt ...
            && isfinite(hourly.(name)(kt))
        value = double(hourly.(name)(kt));
    end
end
