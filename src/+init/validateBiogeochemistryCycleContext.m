function validateBiogeochemistryCycleContext(context,built,completedKt)
%VALIDATEBIOGEOCHEMISTRYCYCLECONTEXT Check optional replay memory and phase.
% completedKt is the authoritative accepted runtime/checkpoint index; it is
% not duplicated inside context. No physical state or model time is changed.
% Editor: Wenjie Liu; Date: 2026-09-29.
    fields={'schema_version','active','cycle_index','forcing_cycle_steps', ...
        'previous_cycle_completed_kt','previous_air_temperature_tail_C', ...
        'identity','forcing_start_time'};
    assert(isstruct(context)&&isscalar(context)&&all(isfield(context,fields)), ...
        'validateBiogeochemistryCycleContext:schema','Incomplete cycle context.');
    assert(context.schema_version==1&&islogical(context.active)&&context.active ...
        &&isscalar(context.cycle_index)&&context.cycle_index>=2 ...
        &&context.cycle_index==fix(context.cycle_index), ...
        'validateBiogeochemistryCycleContext:schema','Invalid cycle context metadata.');
    n=context.forcing_cycle_steps;
    assert(isscalar(n)&&isfinite(n)&&n>=1&&n==fix(n) ...
        &&n<=built.control.time.tS ...
        &&context.previous_cycle_completed_kt==n ...
        &&isscalar(completedKt)&&completedKt>=0&&completedKt<=n ...
        &&completedKt==fix(completedKt) ...
        &&isequal(context.forcing_start_time,built.control.time.start_time), ...
        'validateBiogeochemistryCycleContext:phase','Cycle phase/forcing window mismatch.');
    tail=context.previous_air_temperature_tail_C;
    window=built.p.plant_acclimation.leaf_resp_Tgrowth_window;
    assert(isnumeric(tail)&&iscolumn(tail)&&all(isfinite(tail)) ...
        &&numel(tail)<=window-1, ...
        'validateBiogeochemistryCycleContext:temperatureHistory','Invalid accepted temperature tail.');
end
