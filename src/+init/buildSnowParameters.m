function snow = buildSnowParameters(rawConfig)
%BUILDSNOWPARAMETERS  Build the conservative bulk-snow parameter set.
%
%   Defaults follow the ClimaLand v1.0 bulk SnowModel (Apache-2.0,
%   California Institute of Technology): prognostic snow water equivalent,
%   liquid water and total energy, minimum-density diagnostics, Wu-Wu cover
%   fraction, wet-snow drainage, and the Jennings et al. (2018) rain/snow
%   partition used by ClimaLand's forcing adapters. The optional site.toml
%   [snow] table overrides site-sensitive parameters.
%
%   Editor: Jizixing Zhu; Date: 2026-07-17.
%   Change: 2026-07-18 Jizixing Zhu -- add the default latent-energy
%     resolution used to distinguish resolved from numerical solid tails.
%   Change: 2026-07-18 Jizixing Zhu -- add an explicit snow-process switch;
%     disabled snow keeps all ground precipitation liquid and must recover
%     the exposed-bare-surface model exactly.

    raw = struct();
    if isstruct(rawConfig) && isfield(rawConfig, 'snow') ...
            && isstruct(rawConfig.snow)
        raw = rawConfig.snow;
    end
    snow = struct( ...
        'enabled', readLogical(raw, 'enabled', true), ...
        'precipitation_phase_model', ...
            readString(raw, 'precipitation_phase_model', 'climaland_jennings2018'), ...
        'phase_alpha', -10.04, ...
        'phase_beta_C_inverse', 1.41, ...
        'phase_gamma_rh_fraction_inverse', 9.0, ...
        'rho_liquid_kg_m3', 1000, ...
        'rho_ice_kg_m3', 916.7, ...
        'specific_heat_liquid_J_kg_K', 4181, ...
        'specific_heat_ice_J_kg_K', 2070, ...
        'latent_heat_fusion_J_kg', 333600, ...
        'reference_temperature_K', 273.16, ...
        'freezing_temperature_K', 273.15, ...
        'thermal_conductivity_air_W_m_K', 0.024, ...
        'thermal_conductivity_ice_W_m_K', 2.21, ...
        'minimum_density_kg_m3', readPositive(raw, 'minimum_density_kg_m3', 200), ...
        'albedo', readBounded(raw, 'albedo', 0.8, 0, 1), ...
        'emissivity', readBounded(raw, 'emissivity', 0.97, 0, 1), ...
        'liquid_holding_capacity', ...
            readBounded(raw, 'liquid_holding_capacity', 0.08, 0, 1), ...
        'wet_snow_hydraulic_conductivity_m_s', ...
            readPositive(raw, 'wet_snow_hydraulic_conductivity_m_s', 1e-3), ...
        'regularization_swe_m', readPositive(raw, 'regularization_swe_m', 0.1), ...
        'cover_depth_scale_m', readPositive(raw, 'cover_depth_scale_m', 0.106), ...
        'cover_fraction_beta', readPositive(raw, 'cover_fraction_beta', 1.81), ...
        'minimum_exchange_depth_m', ...
            readPositive(raw, 'minimum_exchange_depth_m', 0.1), ...
        'solid_phase_energy_resolution_J_cm2', 1e-2);

    assert(strcmp(snow.precipitation_phase_model, 'climaland_jennings2018'), ...
        'buildSnowParameters:badPhaseModel', ...
        ['snow.precipitation_phase_model must be climaland_jennings2018; ', ...
         'explicit prescribed liquid/snow forcing is not part of this interface.']);
end

function value = readLogical(s, name, fallback)
% Read one logical or numeric 0/1 switch.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    value = readField(s, name, fallback);
    assert((islogical(value) || isnumeric(value)) && isscalar(value) ...
            && isfinite(double(value)) && any(double(value) == [0, 1]), ...
        'buildSnowParameters:badLogical', ...
        'snow.%s must be true/false or numeric 0/1.', name);
    value = logical(value);
end

function value = readField(s, name, fallback)
% Read an optional field.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    value = fallback;
    if isfield(s, name) && ~isempty(s.(name)), value = s.(name); end
end

function value = readScalar(s, name, fallback)
% Read one finite scalar.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    value = double(readField(s, name, fallback));
    assert(isscalar(value) && isfinite(value), ...
        'buildSnowParameters:badScalar', 'snow.%s must be finite scalar.', name);
end

function value = readString(s, name, fallback)
% Read one lower-case string scalar.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    value = readField(s, name, fallback);
    if isstring(value), value = char(value); end
    assert(ischar(value) && isrow(value), ...
        'buildSnowParameters:badString', 'snow.%s must be a string.', name);
    value = lower(strtrim(value));
end

function value = readPositive(s, name, fallback)
% Read one positive scalar.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    value = readScalar(s, name, fallback);
    assert(value > 0, 'buildSnowParameters:badPositive', ...
        'snow.%s must be positive.', name);
end

function value = readBounded(s, name, fallback, lo, hi)
% Read one scalar on a closed interval.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    value = readScalar(s, name, fallback);
    assert(value >= lo && value <= hi, 'buildSnowParameters:badBounded', ...
        'snow.%s must lie in [%g,%g].', name, lo, hi);
end
