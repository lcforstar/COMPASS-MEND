function payload = captureBiogeochemistryCycleCarry(model,cycleIndex)
%CAPTUREBIOGEOCHEMISTRYCYCLECARRY Capture a completed accepted forcing cycle.
% Full Y and accepted root-water memory retain their native units/grid order.
% Air-temperature tail [degC, oldest to newest] contains accepted hours only.
% Clock and event flags are NOT carried to the next replay: the adapter starts
% forcing at KT=1 and intentionally re-arms the frozen management schedule.
% Passive fertilizer labels retain all prior replay-cycle mineral inputs.
% No state is changed and no time or flux is advanced here.
% Editor: Wenjie Liu; Date: 2026-09-29.
    if nargin<2, cycleIndex=1; end
    assert(isscalar(cycleIndex)&&isfinite(cycleIndex)&&cycleIndex>=1 ...
        &&cycleIndex==fix(cycleIndex), ...
        'captureBiogeochemistryCycleCarry:cycleIndex','Invalid cycle index.');
    rt=model.runtime; built=model.built;
    completed=rt.run_control.last_completed_kt;
    assert(completed==rt.run_control.n_steps&&completed>0 ...
        &&rt.step.KT==completed ...
        &&rt.step.TIME==completed*built.control.time.Delt_t, ...
        'captureBiogeochemistryCycleCarry:incompleteCycle', ...
        'Capture requires the accepted endpoint of the requested forcing cycle.');
    rootWater=built.workspace.flux.Srt;
    assert(all(isfinite(rootWater(:))), ...
        'captureBiogeochemistryCycleCarry:rootWater','Nonfinite accepted root-water history.');
    history=built.Y.plant_acclimation.leaf_resp.Ta_history(:);
    assert(numel(history)>=completed&&all(isfinite(history(1:completed))), ...
        'captureBiogeochemistryCycleCarry:temperatureHistory', ...
        'Every accepted cycle hour must have a finite air-temperature history.');
    tail=zeros(0,1);
    if isfield(rt,'biogeochemistry_cycle')
        context=rt.biogeochemistry_cycle;
        init.validateBiogeochemistryCycleContext(context,built,completed);
        assert(context.cycle_index==cycleIndex, ...
            'captureBiogeochemistryCycleCarry:cycleIndex','Cycle index differs from runtime.');
        tail=context.previous_air_temperature_tail_C(:);
    end
    tail=[tail;history(1:completed)];
    window=built.p.plant_acclimation.leaf_resp_Tgrowth_window;
    tail=tail(max(1,numel(tail)-window+2):end);
    payload=struct('schema_version',1, ...
        'identity',init.buildBiogeochemistryCycleIdentity(model), ...
        'Y',built.Y,'root_water_element_endpoint_rate_1_s',rootWater, ...
        'completed_cycle_index',cycleIndex,'completed_kt',completed, ...
        'completed_clock_time',rt.step.clock_time, ...
        'forcing_cycle_steps',rt.run_control.n_steps, ...
        'complete_configured_window',completed==built.control.time.tS, ...
        'previous_air_temperature_tail_C',tail);
end
