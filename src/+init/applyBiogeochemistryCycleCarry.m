function [model,audit] = applyBiogeochemistryCycleCarry(model,payload,options)
%APPLYBIOGEOCHEMISTRYCYCLECARRY Start a forcing replay from accepted full Y.
% model must be a fresh initialized/prepared shell at KT=0, with resume off.
% Model identity must match exactly. Rebuild disposable soil caches without
% changing Y, retain accepted root-water memory, and attach explicit canopy
% replay history. New runtime clock and re-armed management flags remain as
% allocated. All cumulative Y ledgers (including passive fertilizer origin)
% remain historical; cycle fluxes must be differenced at the endpoints.
% This is NOT a measured-constrained production t0 materializer.
% Editor: Wenjie Liu; Date: 2026-09-29.
% Change: 2026-10-23 Wenjie Liu -- 增加显式慢库锚定选项，默认仍完整继承；
%   重置库存及账本参照的差异独立审计，不记为轮内物理输入输出。
    if nargin<3||isempty(options),options=struct();end
    if ~isfield(options,'mode'),options.mode='full_state';end
    mode=string(options.mode);
    assert(isscalar(mode)&&ismember(mode,["full_state","anchored"]), ...
        'applyBiogeochemistryCycleCarry:mode','跨轮模式必须为 full_state 或 anchored。');
    assert(isfield(model,'runtime')&&model.runtime.step.KT==0 ...
        &&model.runtime.step.TIME==0&&model.runtime.run_control.next_kt==1 ...
        &&~model.runtime.resume.requested, ...
        'applyBiogeochemistryCycleCarry:notFresh','A fresh non-resume KT=0 shell is required.');
    required={'schema_version','identity','Y','root_water_element_endpoint_rate_1_s', ...
        'completed_cycle_index','completed_kt','forcing_cycle_steps', ...
        'previous_air_temperature_tail_C'};
    assert(isstruct(payload)&&isscalar(payload)&&all(isfield(payload,required)) ...
        &&payload.schema_version==1, ...
        'applyBiogeochemistryCycleCarry:schema','Invalid cycle carry payload.');
    identity=init.buildBiogeochemistryCycleIdentity(model);
    assert(isequaln(identity,payload.identity), ...
        'applyBiogeochemistryCycleCarry:identity', ...
        'Cycle model/source/forcing identity differs; rebuild this initialization campaign.');
    assert(payload.forcing_cycle_steps==model.runtime.run_control.n_steps ...
        &&payload.completed_kt==payload.forcing_cycle_steps, ...
        'applyBiogeochemistryCycleCarry:phase','Previous and next cycle lengths differ.');
    rootWater=payload.root_water_element_endpoint_rate_1_s;
    assert(isequal(size(rootWater),size(model.built.workspace.flux.Srt)) ...
        &&all(isfinite(rootWater(:))), ...
        'applyBiogeochemistryCycleCarry:rootWater','Accepted root-water history is incompatible.');
    initialRuntime=model.runtime;
    model.built.Y=payload.Y;
    anchorAudit=struct();
    if mode=="anchored"
        assert(isfield(options,'anchor_Y'), ...
            'applyBiogeochemistryCycleCarry:anchor','锚定模式必须提供第一轮初始接受状态。');
        [model.built.Y,anchorAudit]=init.applyAnchoredBiogeochemistryState( ...
            model.built,payload.Y,options.anchor_Y);
    end
    carriedY=model.built.Y;
    model.built=init.rebuildSoilAuxiliaryFromAccepted(model.built,0);
    model.built.workspace.flux.Srt=rootWater;
    assert(isequaln(model.built.Y,carriedY), ...
        'applyBiogeochemistryCycleCarry:stateChanged','Cycle cache rebuild changed accepted Y.');
    context=struct('schema_version',1,'active',true, ...
        'cycle_index',payload.completed_cycle_index+1, ...
        'forcing_cycle_steps',payload.forcing_cycle_steps, ...
        'previous_cycle_completed_kt',payload.completed_kt, ...
        'forcing_start_time',model.built.control.time.start_time, ...
        'previous_air_temperature_tail_C',payload.previous_air_temperature_tail_C, ...
        'identity',identity, ...
        'fertilizer_tracer_scope','all_replayed_mineral_fertilization_events');
    init.validateBiogeochemistryCycleContext(context,model.built,0);
    model.runtime.biogeochemistry_cycle=context;
    assert(isequaln(initialRuntime.management,model.runtime.management), ...
        'applyBiogeochemistryCycleCarry:managementChanged','Fresh management state changed.');
    audit=struct('accepted_Y_bitwise',true,'root_water_history_exact',true, ...
        'clock_restarted_at_zero',true,'management_rearmed_for_replay',true, ...
        'production_t0_materialization',false,'identity_signature',identity.signature);
    if mode=="anchored"
        audit.accepted_Y_bitwise=isequaln(model.built.Y,payload.Y);
        audit.mode='anchored';audit.anchor=anchorAudit;
        audit.anchored_Y_cache_rebuild_bitwise=true;
    end
end
