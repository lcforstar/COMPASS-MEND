function [state, parameters] = buildSoilMicrobes(built, config)
% Editor: Wenjie Liu; Date: 2026-10-17.
%BUILDSOILMICROBES Initialize source-defined MEND pools and parameters.
%
%   The mapping preserves total carbon exactly on each top-down COMPASS soil
%   element. DOC is deliberately absent from this accepted store;
%   Y.soil_dom is its sole owner and supplies the aqueous DOM coordinate during
%   each reaction solve. Pool units are [mg C g^-1 dry soil]. Parameters map
%   explicitly to MEND commit 92323c7326e9a30ae44e794d114612b90a9e3b1c.
%
%   Editor: Jizixing Zhu; Date: 2026-08-21.
%   Change: 2026-08-29 Codex -- consume the native COMPASS SOC partition
%   produced by buildSoilCarbon.
%   Change: 2026-08-30 Codex -- expose the MIMICS-CN NUE and numerical N floor.
%   Change: 2026-08-31 Codex -- require nonzero straining whenever microbial
%     transport is enabled so the retained phase cannot be structurally zero.
%   Change: 2026-09-02 Codex -- read site-global MEMC/MEND physiology from
%     site.toml and depth-resolved BIOPARTICLE medium parameters from soil.csv.
%   Change: 2026-09-12 Jizixing Zhu -- replace the MEMC parameter/state map
%     with the complete MEND POM/MOM/MBA/MBD/enzyme carbon topology.
%   Change: 2026-09-21 Wenjie Liu -- propagate the microbial-dormancy
%     process switch without changing the configured initial MB/BD partition.
%   Change: 2026-09-29 Wenjie Liu -- read layer-resolved carbon kinetics from
%     soil (bottom-up -> top-down). Legacy scalar sites remain supported only
%     without the soil group; common POM/MOM and derived-rate relations remain.
%   Change: 2026-09-29 Wenjie Liu -- numbered mobile C/N boundary policy and
%     disjoint cumulative input/top-output routes; stationary phases unchanged.
%   Change: 2026-10-10 Wenjie Liu -- declare direct plant/manure input
%     fractions and the source-MEND external-input C:N closure.
%   Change: 2026-10-12 Wenjie Liu -- consume the 8+2 layer-candidate
%     interface, retain the shared POM/MOM relations and rebuild derived
%     maintenance, mortality and dormancy rates elementwise by layer.
%   Change: 2026-10-12 Wenjie Liu -- resolve all ten layer candidates solely
%     through the soil-or-site adapter; no duplicate site defaults required.
% Change: 2026-10-17 Wenjie Liu -- materialize resolved CSV C and phases;
%   preserve the original four-pool cold-start arithmetic.
% Change: 2026-10-17 Wenjie Liu -- optional pH switch; AOM-first input route
%   and configurable common enzyme C:N in the source-hour map.
% Change: 2026-10-27 Wenjie Liu -- resolve layered wdorm and DIN uptake by sole owner.
% Change: 2026-10-30 Wenjie Liu -- optional paired manure fast DOC/DON input;
%   absent/false keeps the original AOM-first parameter identity.
% Change: 2026-10-31 Wenjie Liu -- carry sole-owner sorption references in
%   top-down layer order; keep legacy RK4 sites without these inputs valid.
    assert(isfield(built.parameters,'soil_organic') ...
        &&isfield(built.parameters.soil_organic,'initial_carbon_top_down'), ...
        'buildSoilMicrobes:missingNativeCarbon', ...
        'Explicit microbes require native COMPASS SOC partition priors.');
    assert(isfield(config, 'microbe') && isstruct(config.microbe), ...
        'buildSoilMicrobes:missingConfig', '[microbe] is required.');
    c = config.microbe;
    required = {'reaction_substep_s','active_fraction_initial', ...
        'mend_lci_initial', ...
        'mend_enzyme_turnover_h','mend_penzp', ...
        'mend_penzm_ratio','mend_frac_pom_to_dom', ...
        'mend_frac_mortality_to_dom','mend_cue_slope_per_c', ...
        'mend_dormant_maintenance_ratio', ...
        'mend_cn_mb_min','mend_cn_mb_max','mend_cn_pom2', ...
        'mend_cn_enzp','mend_cn_enzm','epsilon_n_mg_g', ...
        'mend_input_cn_lignin_to_labile'};
    for i = 1:numel(required)
        assert(isfield(c, required{i}), 'buildSoilMicrobes:missingParameter', ...
            'microbe.%s is required.', required{i});
    end
    values=struct();
    for i = 1:numel(required)
        value = c.(required{i});
        assert(isnumeric(value) && isscalar(value) && isfinite(value), ...
            'buildSoilMicrobes:badParameter', ...
            'microbe.%s must be a finite scalar.', required{i});
        values.(required{i}) = double(value);
    end
    % Change: 2026-10-12 Wenjie Liu -- optional fpH0 shape controls; absent
    % keys keep the frozen source response so legacy sites stay compatible.
    optional={'mend_ph_sensitivity_scale','mend_ph_optimum_adapt_per_ph'};
    for i=1:numel(optional)
        if isfield(c,optional{i})
            value=c.(optional{i});
            assert(isnumeric(value)&&isscalar(value)&&isfinite(value), ...
                'buildSoilMicrobes:badParameter', ...
                'microbe.%s must be a finite scalar.',optional{i});
            values.(optional{i})=double(value);
        end
    end
    values.ph_response_enabled=true;
    if isfield(c,'mend_ph_response')
        flag=c.mend_ph_response;
        assert(isscalar(flag)&&(islogical(flag) ...
            ||(isnumeric(flag)&&isreal(flag)&&isfinite(flag)&&ismember(flag,[0 1]))), ...
            'buildSoilMicrobes:badPhSwitch', ...
            'mend_ph_response must be a scalar logical or numeric zero/one.');
        values.ph_response_enabled=logical(flag);
    end
    values.manure_fast_input_enabled=false;
    if isfield(c,'mend_manure_fast_input_enabled')
        flag=c.mend_manure_fast_input_enabled;
        assert(isscalar(flag)&&(islogical(flag) ...
            ||(isnumeric(flag)&&isreal(flag)&&isfinite(flag)&&ismember(flag,[0 1]))), ...
            'buildSoilMicrobes:badManureFastSwitch', ...
            'mend_manure_fast_input_enabled must be a scalar logical or numeric zero/one.');
        values.manure_fast_input_enabled=logical(flag);
    end
    [kinetic,kineticOwner,kineticOwners]= ...
        io.adapters.resolveMendLayerParameters(built.parameters.soil,c);
    for key=fieldnames(kinetic)'
        name=key{1};value=kinetic.(name);
        if strcmp(kineticOwners.(name),'soil')
            assert(isequal(size(value),[built.domain.NL,1]), ...
                'buildSoilMicrobes:kineticShape','Mapped soil.%s must be bottom-up NL-by-1.',name);
            value=flip(value);
        end
        values.(name)=value;
    end
    textKeys={'mend_biome','mend_som'};
    for i=1:numel(textKeys)
        key=textKeys{i};
        assert(isfield(c,key)&&(ischar(c.(key))||isstring(c.(key))) ...
            &&isscalar(string(c.(key))),'buildSoilMicrobes:badParameter', ...
            'microbe.%s must be scalar text.',key);
    end
    assert(isfield(c,'mend_input_fraction')&&isnumeric(c.mend_input_fraction) ...
        &&numel(c.mend_input_fraction)==3 ...
        &&all(isfinite(c.mend_input_fraction)) ...
        &&all(c.mend_input_fraction>=0) ...
        &&abs(sum(c.mend_input_fraction)-1)<1e-12, ...
        'buildSoilMicrobes:inputFraction', ...
        'microbe.mend_input_fraction must contain three fractions summing to one.');
    assert(isfield(c,'mend_manure_input_fraction') ...
        &&isnumeric(c.mend_manure_input_fraction) ...
        &&numel(c.mend_manure_input_fraction)==3 ...
        &&all(isfinite(c.mend_manure_input_fraction)) ...
        &&all(c.mend_manure_input_fraction>=0) ...
        &&abs(sum(c.mend_manure_input_fraction)-1)<1e-12, ...
        'buildSoilMicrobes:manureInputFraction', ...
        'microbe.mend_manure_input_fraction must contain three fractions summing to one.');
    if values.manure_fast_input_enabled
        assert(all(c.mend_manure_input_fraction<=1) ...
            &&sum(c.mend_manure_input_fraction(1:2))>0, ...
            'buildSoilMicrobes:manureFastFraction', ...
            'Fast manure input requires fractions in [0,1] and a positive particulate share.');
        assert(isfield(built.control.switches,'lSoilDOM') ...
            &&built.control.switches.lSoilDOM==1, ...
            'buildSoilMicrobes:manureFastDom','Fast manure input requires the active DOM owner.');
    end
    assert(values.mend_input_cn_lignin_to_labile>0, ...
        'buildSoilMicrobes:inputCnRatio', ...
        'microbe.mend_input_cn_lignin_to_labile must be positive.');
    parameters=mapMendParameters(values,c,built);
    parameters.kinetic_input_owner=kineticOwner;
    parameters.layer_candidate_owners=kineticOwners;
    parameters.layer_mapping=built.parameters.soil.mend_layer_mapping;
    parameters.dormancy_enabled=isfield(built.control.switches, ...
        'lMicrobialDormancy')&&built.control.switches.lMicrobialDormancy==1;
    parameters.transport_enabled=isfield(built.control.switches, ...
        'lMicrobialTransport')&&built.control.switches.lMicrobialTransport==1;
    parameters.bioparticle=buildBioparticleParameters(config, ...
        built.parameters.soil,parameters.transport_enabled);
    % Change: 2026-09-29 Wenjie Liu -- site-owned mobile-particle boundary.
    parameters.bioparticle.boundary=soil.microbe.normalizeTransportBoundary(config.boundary);
    validateParameters(parameters);

    n = built.domain.NL;
    bd = flip(built.parameters.soil.bulk_density(:)); % top-down [g cm^-3]
    initial=built.parameters.soil_organic.initial_carbon_top_down;
    pom1=initial.POM1(:); pom2=initial.POM2(:);
    poc=pom1+pom2; mb=initial.MB(:); moc=initial.MOC(:);
    qoc=initial.QOC(:); ep=initial.EP(:); em=initial.EM(:);
    scale = 1000 ./ bd; % [g cm^-3] -> [mg g^-1]
    detailed=isfield(built.parameters.soil_organic,'initialization_mode') ...
        &&strcmp(built.parameters.soil_organic.initialization_mode,'detailed_soc_fractions');
    if detailed,active=mb;dormant=initial.BD;
    else,active=mb.*values.active_fraction_initial;dormant=mb-active;end
    mobileFraction=parameters.bioparticle.mobile_fraction_initial;
    if detailed,enzp1=initial.ENZP1;enzp2=initial.ENZP2;
    else,enzp1=parameters.lci_initial.*ep;enzp2=(1-parameters.lci_initial).*ep;end
    state = struct('schema_version',3,'model','MEND_92323c7', ...
        'grid_order','top_down', 'units','mg_C_g_dry_soil', ...
        'POM1',pom1.*scale,'POM2',pom2.*scale,'POC',poc.*scale, ...
        'MOC',moc.*scale, 'QOC',qoc.*scale, ...
        'MB',active.*scale,'BD',dormant.*scale, ...
        'ENZP1',enzp1.*scale,'ENZP2',enzp2.*scale, ...
        'EP',ep.*scale, 'EM',em.*scale, ...
        'IC',zeros(n,1), 'Tot',(poc+moc+qoc+mb).*scale);
    if detailed
        for group={'MB','BD','ENZN'}
            g=group{1};
            for phase={'mobile','attached','retained'}
                k=[g '_' phase{1}];state.(k)=initial.(k).*scale;
            end
        end
        state.ENZN=initial.ENZN.*scale;
        total=zeros(n,1);
        for key={'POM1','POM2','MOC','QOC','MB','BD','ENZP1','ENZP2','EM','ENZN'}
            total=total+state.(key{1});
        end
        state.Tot=total;
    else
        for group={'MB','BD'}
            g=group{1};value=active;if strcmp(g,'BD'),value=dormant;end
            state.([g '_mobile'])=mobileFraction.*value.*scale;
            state.([g '_attached'])=(1-mobileFraction).*value.*scale;
            state.([g '_retained'])=zeros(n,1);
        end
    end
    if parameters.transport_enabled ...
        &&~strcmp(parameters.bioparticle.boundary.bottom_kind,'closed')
        state.bottom_export_cumulative=soil.microbe.emptyParticleExport();
        if parameters.bioparticle.boundary.schema_version==2
            state.boundary_exchange_cumulative=soil.dom.emptyBoundaryExchange( ...
                {'MB_carbon','MB_nitrogen','BD_carbon','BD_nitrogen','ENZN_carbon','ENZN_nitrogen'});
        end
    end
    fields = {'POM1','POM2','POC','MOC','QOC','MB','BD', ...
        'ENZP1','ENZP2','EP','EM','IC','Tot'};
    for i = 1:numel(fields)
        assert(all(isfinite(state.(fields{i}))) && all(state.(fields{i}) >= 0), ...
            'buildSoilMicrobes:invalidState', ...
            'Mapped MEND pool %s is invalid.', fields{i});
    end
    assert(all(abs(state.POC-state.POM1-state.POM2)<=1e-12) ...
        &&all(abs(state.EP-state.ENZP1-state.ENZP2)<=1e-12), ...
        'buildSoilMicrobes:mendAggregate', ...
        'MEND carbon compatibility aggregates are inconsistent.');
end

function p=mapMendParameters(v,c,built)
% Map named site values to the source MEND hourly parameter contract.
% Editor: Jizixing Zhu; Date: 2026-09-12.
% Change: 2026-10-12 Wenjie Liu -- broadcast a scalar KsPOM1 when only its
% independently owned ratio is a profile, retaining the same layer values.
    kinetics='MM';
    if isfield(c,'mend_kinetics'), kinetics=char(string(c.mend_kinetics)); end
    ksPOM1=v.mend_ks_pom1_mg_g;
    ksPOM2=ksPOM1./v.mend_ks_pom_ratio;
    if isscalar(ksPOM1)&&~isscalar(ksPOM2)
        ksPOM1=repmat(ksPOM1,size(ksPOM2));
    end
    p=struct('source_commit','92323c7326e9a30ae44e794d114612b90a9e3b1c', ...
        'kinetics',kinetics,'temperature_function','Arrhenius', ...
        'rate_time_basis','hour','rate_unit_seconds',3600, ...
        'reaction_substep_s',v.reaction_substep_s, ...
        'lci_initial',v.mend_lci_initial, ...
        'VdPOM_ref_h',[v.mend_vd_pom_h v.mend_vd_pom_h], ...
        'KsPOM_ref_mg_g',[ksPOM1,ksPOM2], ...
        'VdMOM_ref_h',v.mend_vd_pom_h, ...
        'KsMOM_ref_mg_g',v.mend_ks_pom1_mg_g.*v.mend_ks_pom_ratio, ...
        'rENZP_h',[v.mend_enzyme_turnover_h v.mend_enzyme_turnover_h], ...
        'rENZM_h',v.mend_enzyme_turnover_h, ...
        'pENZP',v.mend_penzp,'pENZM',v.mend_penzp*v.mend_penzm_ratio, ...
        'frPOM2DOM',v.mend_frac_pom_to_dom, ...
        'frMB2DOM',v.mend_frac_mortality_to_dom, ...
        'Vg_ref_h',v.mend_vg_h,'alpha',v.mend_alpha, ...
        'KsDOM_ref_mg_g',v.mend_ks_dom_mg_g, ...
        'Yg_ref',v.mend_cue_20,'Yg_slope_per_C',v.mend_cue_slope_per_c, ...
        'gamma',v.mend_mortality_multiplier, ...
        'beta',v.mend_dormant_maintenance_ratio, ...
        'SWP_A2D_MPa',v.mend_swp_a2d_mpa,'tau',v.mend_tau, ...
        'wdorm',v.mend_wdorm,'VNup_MB_ref_h',v.mend_vnup_mb_h, ...
        'KsNH4_MB_ref_mg_g',v.mend_ks_nh4_mb_mg_g, ...
        'KsNO3_MB_ref_mg_g',v.mend_ks_no3_mb_mg_g, ...
        'CN_MB_min',v.mend_cn_mb_min,'CN_MB_max',v.mend_cn_mb_max, ...
        'CN_POM2',v.mend_cn_pom2, ...
        'CN_ENZP',[v.mend_cn_enzp v.mend_cn_enzp], ...
        'CN_ENZM',v.mend_cn_enzm,'epsilon_n_mg_g',v.epsilon_n_mg_g, ...
        'biome',char(upper(string(c.mend_biome))), ...
        'som',char(upper(string(c.mend_som))), ...
        'input_fraction',double(c.mend_input_fraction(:).'), ...
        'manure_input_fraction',double(c.mend_manure_input_fraction(:).'), ...
        'input_cn_lignin_to_labile',v.mend_input_cn_lignin_to_labile, ...
        'external_input_route','aom_first_plant_manure_straw_v2', ...
        'management_placement','uniform_depth_surface_top_cell_v1');
    sorptionKeys={'mend_qmax_mg_g','mend_kba_g_mg','mend_kdes_mg_g_h'};
    sorptionRefs={'Qmax_ref_mg_g','Kba_ref_g_mg','Kdes_ref_mg_g_h'};
    for j=1:numel(sorptionKeys)
        if isfield(v,sorptionKeys{j})
            p.(sorptionRefs{j})=v.(sorptionKeys{j});
        end
    end
    p.manure_fast_input_enabled=v.manure_fast_input_enabled;
    if p.manure_fast_input_enabled
        p.external_input_route='manure_fast_dom_remaining_aom_v1';
    end
    % Change: 2026-10-12 Wenjie Liu -- source fpH0 shape controls for the
    % documented identification perturbations. Defaults reproduce the frozen
    % source response bitwise; they are not new production calibration axes.
    phScale=1.0; phAdapt=0.0;
    if isfield(v,'mend_ph_sensitivity_scale'), phScale=v.mend_ph_sensitivity_scale; end
    if isfield(v,'mend_ph_optimum_adapt_per_ph'), phAdapt=v.mend_ph_optimum_adapt_per_ph; end
    p.ph_sensitivity_scale=phScale;
    p.ph_optimum_adapt_per_ph=phAdapt;
    p.ph_response_enabled=v.ph_response_enabled;
    p.Vm_ref_h=p.Vg_ref_h.*p.alpha./(1-p.alpha);
    p.rMORT_ref_h=min(0.99,p.Vm_ref_h.*p.gamma);
    p.VmD_ref_h=p.Vm_ref_h.*p.beta;
    assert(isfield(built.parameters.soil,'ph'), ...
        'buildSoilMicrobes:missingPh','MEND requires a soil pH profile.');
    p.pH_top_down=flip(built.parameters.soil.ph(:));
end

function p=buildBioparticleParameters(config,soil,enabled)
% Validate PFLOTRAN BIOPARTICLE transport-only adapter parameters.
% Editor: Jizixing Zhu; Date: 2026-08-28.
    if ~isfield(config,'bioparticle')||~isstruct(config.bioparticle)
        if ~enabled
            p=struct('mobile_fraction_initial',0,'diffusion_cm2_s',0, ...
                'transport_substep_s',300,'attachment_rate_s',0, ...
                'detachment_rate_s',0,'straining_rate_s',0,'dispersion_cm',0);
            return;
        end
        error('buildSoilMicrobes:missingBioparticle', ...
            '[bioparticle] is required when microbial_transport=true.');
    end
    c=config.bioparticle;
    required={'mobile_fraction_initial','diffusion_cm2_s', ...
        'transport_substep_s'};
    for i=1:numel(required)
        key=required{i};
        assert(isfield(c,key)&&isnumeric(c.(key))&&isscalar(c.(key)) ...
            &&isfinite(c.(key)),'buildSoilMicrobes:badBioparticle', ...
            'bioparticle.%s must be a finite scalar.',key);
    end
    p=struct('mobile_fraction_initial',double(c.mobile_fraction_initial), ...
        'diffusion_cm2_s',double(c.diffusion_cm2_s), ...
        'transport_substep_s',double(c.transport_substep_s), ...
        'attachment_rate_s',soil.bioparticle_attachment_rate_s(:), ...
        'detachment_rate_s',soil.bioparticle_detachment_rate_s(:), ...
        'straining_rate_s',soil.bioparticle_straining_rate_s(:), ...
        'dispersion_cm',soil.bioparticle_dispersion_cm(:));
    profileValues=[p.attachment_rate_s;p.detachment_rate_s; ...
        p.straining_rate_s;p.dispersion_cm];
    assert(isfinite(p.mobile_fraction_initial)&&isfinite(p.diffusion_cm2_s) ...
        &&isfinite(p.transport_substep_s)&&all(isfinite(profileValues)) ...
        &&p.mobile_fraction_initial>=0&&p.mobile_fraction_initial<=1 ...
        &&p.diffusion_cm2_s>=0&&all(profileValues>=0) ...
        &&p.transport_substep_s>0, ...
        'buildSoilMicrobes:badBioparticle', ...
        'BIOPARTICLE parameters must be finite, nonnegative, and physical.');
    if enabled
        assert(all(p.straining_rate_s>0), ...
            'buildSoilMicrobes:zeroStraining', ...
            ['microbial_transport=true requires a positive straining rate; ', ...
             'otherwise the retained microbial phase is structurally absent.']);
    end
end

function validateParameters(p)
% Validate the explicit MEND configuration without applying calibration.
% Editor: Jizixing Zhu; Date: 2026-09-12.
% Change: 2026-10-17 Wenjie Liu -- validate pH gate and common enzyme C:N.
% Change: 2026-10-31 Wenjie Liu -- validate scalar or layered sorption references.
    sorptionRefs={'Qmax_ref_mg_g','Kba_ref_g_mg','Kdes_ref_mg_g_h'};
    for j=1:numel(sorptionRefs)
        key=sorptionRefs{j};
        if ~isfield(p,key),continue;end
        value=p.(key);
        if j==1,valid=value>0;else,valid=value>=0;end
        assert(all(isfinite(value)&valid,'all'), ...
            'buildSoilMicrobes:badSorption','MEND parameter %s is outside its physical domain.',key);
    end
    assert(islogical(p.ph_response_enabled)&&isscalar(p.ph_response_enabled), ...
        'buildSoilMicrobes:badPhSwitch', ...
        'mend_ph_response must be a scalar logical switch.');
    assert(all(p.CN_ENZP==p.CN_ENZM), ...
        'buildSoilMicrobes:enzymeCN', ...
        'MEND source-hour coupling requires equal ENZP and ENZM C:N.');
    positive = {'VdMOM_ref_h','KsMOM_ref_mg_g','Vg_ref_h','Vm_ref_h', ...
        'KsDOM_ref_mg_g','Yg_ref','reaction_substep_s','CN_MB_min', ...
        'CN_MB_max','CN_POM2','CN_ENZM','epsilon_n_mg_g'};
    for i = 1:numel(positive)
        assert(all(p.(positive{i}) > 0,'all'), 'buildSoilMicrobes:badPositive', ...
            'MEND parameter %s must be positive.', positive{i});
    end
    assert(all(p.VdPOM_ref_h>0,'all')&&all(p.KsPOM_ref_mg_g>0,'all') ...
        &&all(p.rENZP_h>=0)&&p.rENZM_h>=0 ...
        &&all(p.CN_ENZP>0)&&all(p.Yg_ref<1,'all') ...
        &&all(p.alpha>0&p.alpha<0.5,'all') ...
        &&p.frPOM2DOM>=0&&p.frPOM2DOM<=1 ...
        &&p.frMB2DOM>=0&&p.frMB2DOM<=1 ...
        &&p.pENZP>=0&&p.pENZM>=0&&p.beta>=0 ...
        &&all(p.gamma>=0,'all')&&all(p.SWP_A2D_MPa>0,'all') ...
        &&all(p.tau>0&p.tau<=1,'all') ...
        &&all(p.wdorm>=1,'all')&&all(p.VNup_MB_ref_h>=0,'all') ...
        &&all(p.KsNH4_MB_ref_mg_g>0,'all')&&all(p.KsNO3_MB_ref_mg_g>0,'all') ...
        &&p.CN_MB_max>p.CN_MB_min ...
        &&ismember(string(p.biome),["ASM","MGC","MDF","MCF"]) ...
        &&ismember(string(p.som),["SOD","SOL","LIT"]), ...
        'buildSoilMicrobes:badMendConfiguration', ...
        'MEND source parameters are invalid.');
    assert(strcmp(p.rate_time_basis,'hour')&&p.rate_unit_seconds==3600, ...
        'buildSoilMicrobes:badRateClock', ...
        'MEND rate clock must be hourly (3600 s per rate unit).');
    assert(islogical(p.dormancy_enabled)&&isscalar(p.dormancy_enabled), ...
        'buildSoilMicrobes:badDormancySwitch', ...
        'MEND dormancy_enabled must be a scalar logical process switch.');
    assert(ismember(string(p.kinetics),["MM","first_order","second_order"]), ...
        'buildSoilMicrobes:badKinetics', ...
        'Supported MEND kinetics are MM, first_order, and second_order.');
    % Change: 2026-10-12 Wenjie Liu -- pH-response identification bounds.
    % Puissant 2019 (adapt <= 0.5 per unit soil pH) and Min 2014 (activity
    % remains high through pH 8.5) delimit the documented perturbation set.
    assert(isscalar(p.ph_sensitivity_scale)&&isfinite(p.ph_sensitivity_scale) ...
        &&p.ph_sensitivity_scale>=0.5&&p.ph_sensitivity_scale<=4, ...
        'buildSoilMicrobes:badPhScale', ...
        'mend_ph_sensitivity_scale must be in [0.5, 4].');
