function NitrogenFlux = setInitialNitrogenFlux(flux)
% setInitialNitrogenFlux - 从 flux 状态对象构建 NitrogenFlux 结构体
%                          Build NitrogenFlux struct from flux state object

NitrogenFlux = struct( ...
    'RetardBAR', flux.RetardBAR, ...
    'cTop_NH4',  flux.cTop_NH4,  'cBot_NH4',  flux.cBot_NH4,  'cTop_NO3',  flux.cTop_NO3,  'cBot_NO3',  flux.cBot_NO3, ...
    'cvTop', flux.cvTop, 'cvBot', flux.cvBot, 'cvTop1', flux.cvTop1, 'cvBot1', flux.cvBot1, ...
    'cvSnit', flux.cvSnit, 'cvSmin', flux.cvSmin, 'cvSden', flux.cvSden, 'cvSvol', flux.cvSvol, ...
    'cvSinkSnh4', flux.cvSinkSnh4, 'cvSinkSno3', flux.cvSinkSno3, ...
    'Cvnit_N2o', flux.Cvnit_N2o, 'Cvdenit_N2o', flux.Cvdenit_N2o, 'Cvdenit_N2', flux.Cvdenit_N2, ...
    'cvnh4OLD', flux.cvnh4OLD, 'cvno3OLD', flux.cvno3OLD, 'cvnh4', flux.cvnh4, 'cvno3', flux.cvno3);

end
