function parameters = buildLitterParameters(config, enabled)
%BUILDLITTERPARAMETERS Normalize optional CoLM vertical-mixing parameters.
%
%   Coefficients use CoLM source units [m s^-1] and [m^2 s^-1]. The module
%   remains disabled unless switches.litter_input is true.
%
%   Editor: Jizixing Zhu; Date: 2026-08-21.
%   Change: 2026-09-02 Codex -- use vegetation.root_max_depth as the sole
%   maximum-root-depth owner for both live roots and root litter placement.
    parameters = struct('enabled',logical(enabled),'source','plant_cn', ...
        'advection_m_s',0,'diffusivity_m2_s',0, ...
        'root_distribution_beta',0.967,'root_max_depth_cm',200, ...
        'aom_fraction',[0.5;0.5;0]);
    if ~enabled, return; end
    assert(isfield(config,'litter') && isstruct(config.litter), ...
        'buildLitterParameters:missingSection','[litter] is required.');
    c = config.litter;
    required = {'source','advection_m_s','diffusivity_m2_s', ...
        'root_distribution_beta','aom_fraction'};
    for i=1:numel(required)
        assert(isfield(c,required{i}),'buildLitterParameters:missingParameter', ...
            'litter.%s is required.',required{i});
    end
    parameters.source = lower(strtrim(char(string(c.source))));
    parameters.advection_m_s = finiteNonnegative(c.advection_m_s,'advection_m_s');
    parameters.diffusivity_m2_s = finiteNonnegative(c.diffusivity_m2_s,'diffusivity_m2_s');
    parameters.root_distribution_beta = c.root_distribution_beta;
    assert(isfield(config,'vegetation')&&isstruct(config.vegetation) ...
        &&isfield(config.vegetation,'root_max_depth'), ...
        'buildLitterParameters:missingRootDepth', ...
        'vegetation.root_max_depth is required for root litter placement.');
    parameters.root_max_depth_cm = config.vegetation.root_max_depth;
    parameters.aom_fraction = c.aom_fraction(:);
    assert(parameters.root_distribution_beta>0 ...
        &&parameters.root_distribution_beta<=1 ...
        &&parameters.root_max_depth_cm>0 ...
        &&numel(parameters.aom_fraction)==3 ...
        &&all(parameters.aom_fraction>=0) ...
        &&abs(sum(parameters.aom_fraction)-1)<1e-12, ...
        'buildLitterParameters:badInputMapping', ...
        'Litter root distribution and AOM fractions are invalid.');
end

function value=finiteNonnegative(value,name)
    assert(isnumeric(value)&&isscalar(value)&&isfinite(value)&&value>=0, ...
        'buildLitterParameters:badParameter', ...
        'litter.%s must be finite and nonnegative.',name);
    value=double(value);
end
