function request = materializeSurfaceSoilWaterRequest(water_flux)
%MATERIALIZESURFACESOILWATERREQUEST Build the soil-facing liquid boundary request.
%
%   Inputs:
%     water_flux [struct] Current surface candidate with Throughfall, EVAP,
%                and CanopyInterception rates [cm s-1].
%
%   Returns:
%     request [struct] Explicit surface-to-soil liquid supply and evaporation
%             demand.  Positive Throughfall supplies the soil; positive EVAP
%             requests removal by the atmospheric surface process.
%
%   Physical contract:
%     This is a request, not the accepted infiltration/runoff result.  The
%     soil surface-water active set owns ponding, infiltration, runoff, and
%     the actual top flux.  Keeping supply and demand separate preserves the
%     finite-ponding complementarity problem.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
    names = {'Throughfall','EVAP','CanopyInterception'};
    for i = 1:numel(names)
        name = names{i};
        assert(isstruct(water_flux) && isfield(water_flux, name) ...
                && isscalar(water_flux.(name)) ...
                && isfinite(water_flux.(name)), ...
            'coupling:materializeSurfaceSoilWaterRequest:badFlux', ...
            '%s must be a finite scalar [cm s-1].', name);
    end
    request = struct( ...
        'schema_version', 1, ...
        'producer', 'surface', ...
        'receiver', 'soil', ...
        'kind', 'liquid_supply_and_evaporation_demand', ...
        'unit', 'cm s^-1', ...
        'Throughfall', double(water_flux.Throughfall), ...
        'EVAP', double(water_flux.EVAP), ...
        'CanopyInterception', double(water_flux.CanopyInterception));
end
