function exchange = solveRootSoilExchange(root_water_uptake, n_layers)
%SOLVEROOTSOILEXCHANGE Materialize the vegetation-to-soil water-sink request.
%
%   exchange = coupling.solveRootSoilExchange(root_water_uptake, n_layers)
%   maps the vegetation energy/hydraulic solution at soil nodes to the two
%   endpoints of every Richards element:
%
%       Srt(i,:) = [RWU(i), RWU(i+1)].
%
%   Inputs:
%     root_water_uptake [1/s, NNx1] Nodal root-water rate from the accepted
%                       canopy/plant solve; positive removes liquid water
%                       from soil, negative is hydraulic redistribution.
%     n_layers          [-] Number of soil elements, NL = NN - 1.
%
%   Returns:
%     exchange [struct] Typed vegetation-to-soil request.  It is not an
%              observed or post-solve actual uptake result.
%
%   Physical contract:
%     The Richards water equation owns the actual state change.  This function
%     only preserves the plant's source/sink field and its node-to-element
%     discretization; it must not clip negative redistribution or impose a
%     second water-balance limiter.  Future simultaneous root/soil solving can
%     add an actual result beside this request without changing its meaning.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
    assert(isscalar(n_layers) && isfinite(n_layers) ...
        && n_layers >= 1 && n_layers == floor(n_layers), ...
        'coupling:solveRootSoilExchange:badLayerCount', ...
        'n_layers must be a positive integer.');
    root_water_uptake = root_water_uptake(:);
    assert(numel(root_water_uptake) >= n_layers + 1 ...
        && all(isfinite(root_water_uptake(1:n_layers + 1)), 'all'), ...
        'coupling:solveRootSoilExchange:badRootWaterUptake', ...
        'RWU must provide finite values at all NL+1 soil nodes.');
    endpoint_rate = [root_water_uptake(1:n_layers), ...
        root_water_uptake(2:n_layers + 1)];
    exchange = struct( ...
        'schema_version', 1, ...
        'producer', 'vegetation', ...
        'receiver', 'soil', ...
        'kind', 'root_water_sink_request', ...
        'unit', 's^-1', ...
        'positive_direction', 'soil_to_vegetation', ...
        'nodal_rate_1_s', root_water_uptake(1:n_layers + 1), ...
        'element_endpoint_rate_1_s', endpoint_rate);
end
