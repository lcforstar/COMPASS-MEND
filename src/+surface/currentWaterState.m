function state = currentWaterState(built)
%CURRENTWATERSTATE Read the current substep surface-water candidate.
%
%   During a soil active-set trial, surface depression storage is a detached
%   surface-domain candidate under workspace.step.trial. Direct compatibility
%   callers without that candidate fall back to accepted Y.surface_water.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
    assert(isstruct(built) && isfield(built, 'Y') ...
        && isfield(built.Y, 'surface_water'), ...
        'surface:currentWaterState:missingAcceptedState', ...
        'Accepted Y.surface_water is required.');
    state = built.Y.surface_water;
    if isfield(built, 'workspace') && isfield(built.workspace, 'step') ...
            && isfield(built.workspace.step, 'trial') ...
            && isfield(built.workspace.step.trial, 'surface_water') ...
            && isfield(built.workspace.step, 'trial_aux') ...
            && isfield(built.workspace.step.trial_aux, 'surface_water') ...
            && isfield(built.workspace.step.trial_aux.surface_water, 'active') ...
            && logical(built.workspace.step.trial_aux.surface_water.active) ...
            && ~isempty(built.workspace.step.trial.surface_water)
        state = built.workspace.step.trial.surface_water;
    end
    assert(isfield(state, 'DSTOR0') && isscalar(state.DSTOR0) ...
            && isfinite(state.DSTOR0), ...
        'surface:currentWaterState:invalidState', ...
        'Surface-water candidate.DSTOR0 must be one finite scalar [cm].');
end
