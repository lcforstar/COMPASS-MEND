function [distance_AU, distance_km, radiation_intensity] = calculateEarthSunDistance(year, month, day, hour, minute, second)
% calculateEarthSunDistance - 计算高精度的日地距离及大气层顶太阳辐照度
%
% 输入参数:
%   year   : 年份（整数，如 2001）
%   month  : 月份（1-12）
%   day    : 日（1-31）
%   hour   : 时（0-23，可选，默认 12）
%   minute : 分（0-59，可选，默认 0）
%   second : 秒（0-59，可选，默认 0）
%
% 输出参数:
%   distance_AU        : 日地距离（天文单位，AU）
%                        1 AU ≈ 1.496×10⁸ km（近日点约0.983 AU，远日点约1.017 AU）
%   distance_km        : 日地距离（千米）
%   radiation_intensity: 大气层顶太阳辐照度（W/m²）
%                        = 太阳常数 / r_AU²（反平方定律）
%                        年均约1361 W/m²，随季节变化约±3.3%
%
% 算法说明:
%   1. 将输入日期时间转换为儒略日（JD）
%   2. 计算从 J2000.0（2000-01-01 12:00 TT）起算的儒略世纪数 T
%   3. 用太阳平黄经 L0、平近点角 M、轨道偏心率 e 描述地球椭圆轨道
%   4. 迭代求解开普勒方程得到偏近点角 E
%   5. 由 E 计算真近点角 ν 和椭圆轨道径向距离 r = a(1-e²)/(1+e·cosν)
%   6. 叠加金星、木星、月球交点的周期摄动修正项
%
% 参考文献:
%   Meeus, J. (1998). Astronomical Algorithms (2nd ed.). Willmann-Bell.
%   NASA JPL DE430 星历（摄动系数来源）

    % ======================================================================
    % 0. 处理可选时间参数（未提供时默认为正午 12:00:00）
    % ======================================================================
    if nargin < 4
        hour = 12; minute = 0; second = 0;
    elseif nargin < 5
        minute = 0; second = 0;
    elseif nargin < 6
        second = 0;
    end

    % ======================================================================
    % 1. 计算儒略日 JD 和儒略世纪数 T
    %    T = (JD - 2451545.0) / 36525
    %    其中 2451545.0 = J2000.0 历元对应的儒略日
    %    36525 天 = 1 儒略世纪（= 365.25 天/年 × 100 年）
    % ======================================================================
    jd = calculateJulianDay(year, month, day, hour, minute, second);
    T = (jd - 2451545.0) / 36525.0;

    % ======================================================================
    % 2. 地球轨道参数（含长期漂移项，精度适用于 1800-2200 年）
    % ======================================================================

    % 太阳平黄经 L0 (°)：地球在黄道上的平均角位置
    % 以春分点为起算，线性项 36000.76983°/世纪 对应公转周期 365.25 天
    L0 = mod(280.46646 + 36000.76983 * T + 0.0003032 * T^2, 360);    %#ok<NASGU>

    % 太阳平近点角 M (°)：从近日点量起的平均轨道角
    % 线性项 35999.05029°/世纪 ≈ 360°/年（对应恒星年）
    M = mod(357.52911 + 35999.05029 * T - 0.0001537 * T^2, 360);

    % 轨道偏心率 e（无量纲）：描述椭圆的扁率（0=圆形）
    % 地球当前约 0.0167，并因行星摄动而缓慢减小
    e = 0.016708634 - 0.000042037 * T - 0.0000001267 * T^2;

    % 近日点黄经 ω (°)：近日点相对于春分点的黄经
    % 进动速率约 1.72°/世纪（岁差+轨道进动合计）
    w = 282.937348 + 1.7195366 * T + 0.0004569 * T^2;                 %#ok<NASGU>

    % ======================================================================
    % 3. 角度单位换算（度 → 弧度）
    % ======================================================================
    M_rad  = deg2rad(M);
    % L0_rad 和 w_rad 在此版本中未直接用于数值计算（已通过 M 和 e 处理）

    % ======================================================================
    % 4. 迭代求解开普勒方程：M = E - e·sin(E)
    %    其中 E 为偏近点角（椭圆上的辅助角）
    %    采用牛顿-拉弗森迭代：ΔE = (M + e·sinE - E) / (1 - e·cosE)
    %    初始值 E₀ = M + e·sin(M)（一阶近似，误差 O(e²)≈2.8×10⁻⁴ AU）
    %    通常 2-3 次迭代即达 1e-8 rad 精度
    % ======================================================================
    E = M_rad + e * sin(M_rad);        % 初始估计

    max_iter  = 5;
    tolerance = 1e-8;                  % 偏近点角收敛阈值（rad）
    for i = 1:max_iter
        delta_E = (M_rad + e * sin(E) - E) / (1 - e * cos(E));
        E = E + delta_E;
        if abs(delta_E) < tolerance
            break;
        end
    end

    % ======================================================================
    % 5. 由偏近点角 E 计算真近点角 ν 和轨道半径 r
    %
    %   tan(ν/2) = sqrt((1+e)/(1-e)) · tan(E/2)   ← 真偏近点角关系
    %
    %   椭圆极坐标方程：r = a(1-e²) / (1 + e·cosν)
    %   其中半长轴 a = 1 AU（定义），故 r 直接以 AU 给出
    % ======================================================================
    nu   = 2 * atan(sqrt((1 + e) / (1 - e)) * tan(E / 2));
    r_AU = (1 - e^2) / (1 + e * cos(nu));      % 单位：AU

    % ======================================================================
    % 6. 行星摄动修正（周期项）
    %    来自金星、木星对地球轨道的引力摄动及月球交点进动
    %    修正量级：~10⁻⁵ AU（约1500 km），对辐照度影响 <0.002%
    %
    %    摄动项：δr = A·sin(n·T)
    %      A₁ = 8.3×10⁻⁶ AU，n₁ = 149472.515°/世纪  （金星，周期~8个月）
    %      A₂ = 4.7×10⁻⁶ AU，n₂ = 109256.628°/世纪  （木星，周期~12年）
    %      A₃ = 9×10⁻⁷  AU，n₃ = 1934.142°/世纪    （月球交点，周期~18.6年）
    % ======================================================================
    A1 = 0.0000083;   % 金星摄动幅值 (AU)
    A2 = 0.0000047;   % 木星摄动幅值 (AU)
    A3 = 0.0000009;   % 月球交点摄动幅值 (AU)

    venus_angular_velocity    = 149472.515;   % 金星平运动角速度 (°/儒略世纪)
    jupiter_angular_velocity  = 109256.628;   % 木星平运动角速度 (°/儒略世纪)
    moon_node_angular_velocity = 1934.142;    % 月球升交点黄经变化率 (°/儒略世纪)

    period_correction = A1 * sin(deg2rad(venus_angular_velocity   * T)) + ...
                        A2 * sin(deg2rad(jupiter_angular_velocity  * T)) + ...
                        A3 * sin(deg2rad(moon_node_angular_velocity * T));

    r_AU_corrected = r_AU + period_correction;

    % ======================================================================
    % 7. 单位转换和输出
    %    1 AU = 149597870.7 km（IAU 2012 定义值）
    %    大气层顶辐照度：S = S₀ / r_AU²（平方反比定律）
    %    太阳常数 S₀ = 1361 W/m²（TIM/SORCE 卫星测量值，Kopp & Lean 2011）
    % ======================================================================
    AU_in_km = 149597870.7;
    r_km     = r_AU_corrected * AU_in_km;

    distance_AU        = r_AU_corrected;
    distance_km        = r_km;
    solar_constant     = 1361;                          % W/m²
    radiation_intensity = solar_constant / (distance_AU)^2;

end

% =========================================================================
% 本地子函数：计算儒略日 JD
%
%   儒略日（Julian Day）是从公元前4713年1月1日正午起算的连续日数
%   用于天文计算的标准时间基准，消除历法差异
%
%   格里高利历转换公式（Meeus, Chapter 7）：
%     若 month ≤ 2，将上年12月处理（year-1, month+12）
%     A = floor(year/100)
%     B = 2 - A + floor(A/4)   ← 格里高利历修正（跳过世纪年的闰年）
%     JD = floor(365.25*(year+4716)) + floor(30.6001*(month+1)) + day + B - 1524.5
%   时间部分以天的小数加入：time_fraction = (h + m/60 + s/3600) / 24
% =========================================================================
function jd = calculateJulianDay(year, month, day, hour, minute, second)

    if month <= 2
        year  = year  - 1;
        month = month + 12;
    end

    A = floor(year / 100);
    B = 2 - A + floor(A / 4);      % 格里高利历修正项

    jd = floor(365.25 * (year + 4716)) + ...
         floor(30.6001 * (month + 1)) + ...
         day + B - 1524.5;

    time_fraction = (hour + minute/60 + second/3600) / 24;
    jd = jd + time_fraction;

end
