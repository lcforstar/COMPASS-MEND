function tile = partitionGroundRadiation( ...
        spectral, rad, surface_state, bare_temperature_C, snow_temperature_C)
%PARTITIONGROUNDRADIATION  Split one-canopy RT fluxes over bare and snow tiles.
%
%   RTMo/RTMt are each run once using the effective lower boundary. This
%   function diagnoses the two physical ground tiles from the shared
%   downward fields without rerunning canopy transfer. Shortwave plus
%   atmospheric longwave absorption is integrated with each tile's spectrum;
%   canopy thermal exchange uses the common RTMt downward field and each
%   tile's own emissivity and temperature.
%
%   Inputs bare_temperature_C are ordered [shaded; sunlit]. A scalar snow
%   temperature is expanded to both illumination classes. Returned fields use
%   the same order. Positive net radiation is energy absorbed by the tile.
%
% Editor: Jizixing Zhu; Date: 2026-07-18.
% Change: 2026-07-19 Jizixing Zhu -- return exact emitted-longwave
%   temperature tangents for the surface energy-response boundary.

    required = {'Esun_', 'Emin_', 'Emint'};
    for i = 1:numel(required)
        assert(isfield(rad, required{i}), ...
            'partitionGroundRadiation:missingRadiation', ...
            'rad.%s is required.', required{i});
    end
    assert(isfield(surface_state, 'refl_bare') ...
        && isfield(surface_state, 'refl_snow'), ...
        'partitionGroundRadiation:missingTileOptics', ...
        'surface_state.refl_bare and refl_snow are required.');

    bareT = bare_temperature_C(:);
    assert(numel(bareT) == 2, ...
        'partitionGroundRadiation:badBareTemperature', ...
        'bare_temperature_C must contain [shaded; sunlit].');
    snowT = snow_temperature_C(:);
    if isscalar(snowT)
        snowT = repmat(snowT, 2, 1);
    end
    assert(numel(snowT) == 2, ...
        'partitionGroundRadiation:badSnowTemperature', ...
        'snow_temperature_C must be scalar or [shaded; sunlit].');

    wl = spectral.wlS(:);
    direct = rad.Esun_(:);
    diffuse = rad.Emin_(end, :)';
    reflBare = surface_state.refl_bare(:);
    reflSnow = surface_state.refl_snow(:);
    assert(numel(wl) == numel(direct) && numel(wl) == numel(diffuse) ...
        && numel(wl) == numel(reflBare) && numel(wl) == numel(reflSnow), ...
        'partitionGroundRadiation:spectralSizeMismatch', ...
        'RT spectra, wavelengths, and tile reflectances must have equal size.');

    absorbedDiffuseBare = 0.001 .* helpers.Sint( ...
        diffuse .* (1 - reflBare), wl);
    absorbedDirectBare = 0.001 .* helpers.Sint( ...
        direct .* (1 - reflBare), wl);
    absorbedDiffuseSnow = 0.001 .* helpers.Sint( ...
        diffuse .* (1 - reflSnow), wl);
    absorbedDirectSnow = 0.001 .* helpers.Sint( ...
        direct .* (1 - reflSnow), wl);

    epsBare = 1 - surface_state.rs_thermal_bare;
    epsSnow = 1 - surface_state.rs_thermal_snow;
    constants = io.define_constants();
    downwardThermal = rad.Emint(end);
    emittedBare = constants.sigmaSB .* (bareT + 273.15).^4;
    emittedSnow = constants.sigmaSB .* (snowT + 273.15).^4;
    internalThermalBare = epsBare .* (downwardThermal - emittedBare);
    internalThermalSnow = epsSnow .* (downwardThermal - emittedSnow);
    dNetBare = -4 .* epsBare .* constants.sigmaSB ...
        .* (bareT + 273.15).^3;
    dNetSnow = -4 .* epsSnow .* constants.sigmaSB ...
        .* (snowT + 273.15).^3;

    externalBare = [absorbedDiffuseBare; ...
        absorbedDiffuseBare + absorbedDirectBare];
    externalSnow = [absorbedDiffuseSnow; ...
        absorbedDiffuseSnow + absorbedDirectSnow];
    tile = struct( ...
        'bare_external_W_m2', externalBare, ...
        'snow_external_W_m2', externalSnow, ...
        'bare_internal_thermal_W_m2', internalThermalBare, ...
        'snow_internal_thermal_W_m2', internalThermalSnow, ...
        'bare_net_W_m2', externalBare + internalThermalBare, ...
        'snow_net_W_m2', externalSnow + internalThermalSnow, ...
        'bare_dnet_dtemperature_W_m2_K', dNetBare, ...
        'snow_dnet_dtemperature_W_m2_K', dNetSnow, ...
        'bare_emissivity', epsBare, ...
        'snow_emissivity', epsSnow);
end
