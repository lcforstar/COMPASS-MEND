function [state, phase, flux] = predictSurfaceState( ...
        acceptedState, parameters, throughfall_cm_s, ...
        airTemperature_C, relativeHumidity, frozenPond_cm, dt_s)
%PREDICTSURFACESTATE  Predict the current-step snow surface before SCOPE.
%
%   The predictor advances precipitation phase and precipitation enthalpy
%   from the accepted snow state, while setting atmosphere/surface/soil heat
%   and vapor exchanges to zero.  It is an auxiliary SCOPE input only: the
%   prognostic snow state is later recomputed from acceptedState with the
%   completed energy-balance fluxes and is committed only after soil accepts.
%
%   This removes the one-outer-step lag for new snowfall without advancing
%   snow mass twice and without adding a second RTMo/ebal call in ordinary
%   hours.
%
%   Editor: Jizixing Zhu; Date: 2026-07-17.

    if nargin < 6 || isempty(frozenPond_cm)
        frozenPond_cm = 0;
    end
    phase = surface.snow.partitionPrecipitation( ...
        throughfall_cm_s, airTemperature_C, relativeHumidity, parameters);
    drivers = struct( ...
        'rainfall_cm_s', phase.liquid_cm_s, ...
        'snowfall_cm_s', phase.snow_cm_s, ...
        'snow_to_atmosphere_vapor_cm_s', 0, ...
        'surface_closure_flux_W_m2', 0, ...
        'bare_surface_closure_flux_W_m2', 0, ...
        'snow_to_soil_heat_flux_W_m2', 0, ...
        'air_temperature_C', airTemperature_C, ...
        'frozen_pond_transfer_cm', frozenPond_cm);
    [state, flux] = surface.snow.advanceBulkSnow( ...
        acceptedState, parameters, drivers, dt_s);
end
