function response = buildSoilTopHeatResponse( ...
        scopeStep, snowGroundResponse, snowFlux)
%BUILDSOILTOPHEATRESPONSE  Assemble one affine surface-to-soil heat contract.
%
%   The shared soil column receives one grid-mean, inward-positive flux
%
%     q_top(T_s) = q_ref + dq_dT (T_s - T_ref).
%
%   Bare ground contributes its external radiative/turbulent energy balance;
%   covered ground contributes snow-to-soil conduction.  Snow meltout/excess
%   energy terms are retained as temperature-independent transfers.  SCOPE's
%   empirical force-restore G is intentionally absent: it supplied the ebal
%   temperature predictor but is not the authoritative soil boundary.
%
%   Editor: Jizixing Zhu; Date: 2026-07-19.
%   Change: 2026-07-19 Jizixing Zhu -- retain the bare-soil latent demand
%           and tangent so the dry active set can replace potential LE by
%           the realized evaporation without rerunning SCOPE.

    f = min(max(double(snowGroundResponse.cover_fraction), 0), 1);
    Tref = double( ...
        snowGroundResponse.reference_soil_surface_temperature_C);
    assert(isscalar(Tref) && isfinite(Tref), ...
        'buildSoilTopHeatResponse:badReferenceTemperature', ...
        'The accepted soil-surface reference temperature must be finite.');

    fluxes = scopeStep.fluxes;
    thermal = scopeStep.thermal;
    bareFlux = requiredScalar(fluxes, ...
        'bare_ground_external_energy_flux_W_m2');
    dBare = requiredScalar(fluxes, ...
        'bare_ground_external_energy_flux_temperature_derivative_W_m2_K');
    bareTref = requiredScalar(thermal, ...
        'bare_ground_effective_temperature_C');
    bareAtReference = bareFlux + dBare * (Tref - bareTref);

    snowAtReference = requiredScalar( ...
        snowGroundResponse, 'reference_flux_into_soil_W_m2');
    dSnow = requiredScalar(snowGroundResponse, ...
        'dflux_dsoil_surface_temperature_W_m2_K');
    redistribution = 0;
    if isstruct(snowFlux) ...
            && isfield(snowFlux, 'snow_soil_heat_contribution_W_m2') ...
            && isfinite(snowFlux.snow_soil_heat_contribution_W_m2)
        redistribution = snowFlux.snow_soil_heat_contribution_W_m2 ...
            - f * snowAtReference;
    end

    bareContribution = (1 - f) * bareAtReference;
    snowContribution = f * snowAtReference + redistribution;
    derivative = (1 - f) * dBare + f * dSnow;
    referenceFlux = bareContribution + snowContribution;
    assert(all(isfinite([referenceFlux, derivative, bareContribution, ...
            snowContribution, redistribution])), ...
        'buildSoilTopHeatResponse:nonfiniteResponse', ...
        'The assembled soil-top heat response must be finite.');
    assert(derivative <= 1e-10, ...
        'buildSoilTopHeatResponse:destabilizingDerivative', ...
        ['The net inward surface energy flux must not increase with soil ', ...
         'surface temperature.']);

    response = struct( ...
        'schema_version', 1, ...
        'sign_convention', 'flux_into_soil_positive', ...
        'reference_temperature_C', Tref, ...
        'reference_flux_into_soil_W_m2', referenceFlux, ...
        'dflux_dtemperature_W_m2_K', derivative, ...
        'snow_cover_fraction', f, ...
        'bare_ground_flux_contribution_W_m2', bareContribution, ...
        'snow_flux_contribution_W_m2', snowContribution, ...
        'snow_energy_redistribution_W_m2', redistribution, ...
        'bare_ground_linearization_temperature_C', bareTref, ...
        'bare_ground_flux_at_linearization_W_m2', bareFlux, ...
        'bare_ground_dflux_dtemperature_W_m2_K', dBare, ...
        'snow_ground_conductance_W_m2_K', ...
            snowGroundResponse.conductance_W_m2_K, ...
        'snow_temperature_C', snowGroundResponse.snow_temperature_C);
    response.soil_evaporation_demand_cm_s = NaN;
    response.soil_evaporation_latent_heat_flux_W_m2 = max(0, ...
        optionalScalar(fluxes, ...
            'bare_ground_upward_latent_heat_flux_contribution_W_m2', 0));
    response.soil_evaporation_latent_heat_flux_temperature_derivative_W_m2_K = ...
        max(0, optionalScalar(fluxes, ...
            'bare_ground_upward_latent_heat_flux_temperature_derivative_W_m2_K', 0));
end

function value = requiredScalar(container, name)
% Read one finite scalar from the typed surface interface.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    assert(isstruct(container) && isfield(container, name) ...
            && isscalar(container.(name)) && isfinite(container.(name)), ...
        'buildSoilTopHeatResponse:missingField', ...
        '%s must be a finite scalar.', name);
    value = double(container.(name));
end

function value = optionalScalar(container, name, fallback)
% Read one optional finite scalar from a backwards-compatible SCOPE result.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    value = fallback;
    if isstruct(container) && isfield(container, name) ...
            && isscalar(container.(name)) && isfinite(container.(name))
        value = double(container.(name));
    end
end
