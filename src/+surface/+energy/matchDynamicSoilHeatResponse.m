function match = matchDynamicSoilHeatResponse(surfaceResponse, soilResponse)
%MATCHDYNAMICSOILHEATRESPONSE  Match atmospheric and soil affine heat maps.
%
%   The frozen post-ebal surface map is
%       G_s(T) = G_ref + dG_s/dT * (T - T_ref),
%   while the implicit upper-soil predictor is
%       G_g(T) = K_g * (T - T_zero).
%   Their analytic intersection supplies one conservative, inward-positive
%   heat flux for the formal coupled soil solve. The skin temperature remains
%   a radiation/turbulence diagnostic and is never imposed on the soil node.
%
%   Inputs and outputs use degC, W m-2, and W m-2 K-1.
% Editor: Jizixing Zhu; Date: 2026-07-20.

    requiredSurface = {'reference_temperature_C', ...
        'reference_flux_into_soil_W_m2', ...
        'dflux_dtemperature_W_m2_K'};
    requiredSoil = {'K_W_m2_K', 'zero_flux_temperature_C'};
    requireFiniteScalars(surfaceResponse, requiredSurface, ...
        'matchDynamicSoilHeatResponse:badSurfaceResponse');
    requireFiniteScalars(soilResponse, requiredSoil, ...
        'matchDynamicSoilHeatResponse:badSoilResponse');

    K = double(soilResponse.K_W_m2_K);
    Tzero = double(soilResponse.zero_flux_temperature_C);
    Tref = double(surfaceResponse.reference_temperature_C);
    Gref = double(surfaceResponse.reference_flux_into_soil_W_m2);
    slope = double(surfaceResponse.dflux_dtemperature_W_m2_K);
    assert(K > 0, 'matchDynamicSoilHeatResponse:nonpositiveSoilAdmittance', ...
        'The upper-soil dynamic admittance must be positive.');
    assert(slope <= 1e-10, ...
        'matchDynamicSoilHeatResponse:destabilizingSurfaceSlope', ...
        'The inward surface heat flux must not increase with temperature.');

    denominator = K - slope;
    assert(isfinite(denominator) && denominator > 0, ...
        'matchDynamicSoilHeatResponse:singularIntersection', ...
        'Surface and soil heat responses do not have a stable intersection.');
    interfaceTemperature = ...
        (K * Tzero + Gref - slope * Tref) / denominator;
    soilFlux = K * (interfaceTemperature - Tzero);
    surfaceFlux = Gref + slope * (interfaceTemperature - Tref);

    match = struct( ...
        'schema_version', 1, ...
        'sign_convention', 'flux_into_soil_positive', ...
        'interface_temperature_C', interfaceTemperature, ...
        'matched_flux_into_soil_W_m2', soilFlux, ...
        'surface_flux_at_match_W_m2', surfaceFlux, ...
        'linear_closure_residual_W_m2', soilFlux - surfaceFlux, ...
        'soil_K_W_m2_K', K, ...
        'soil_zero_flux_temperature_C', Tzero, ...
        'surface_reference_temperature_C', Tref, ...
        'surface_reference_flux_W_m2', Gref, ...
        'surface_slope_W_m2_K', slope);
    assert(all(isfinite([interfaceTemperature, soilFlux, surfaceFlux, ...
            match.linear_closure_residual_W_m2, K, Tzero, Tref, Gref, slope])), ...
        'matchDynamicSoilHeatResponse:nonfiniteMatch', ...
        'The matched surface-soil heat state must be finite.');
end

function requireFiniteScalars(container, names, identifier)
% Validate one typed affine-response structure.
% Editor: Jizixing Zhu; Date: 2026-07-20.
    assert(isstruct(container), identifier, 'Response must be a struct.');
    for i = 1:numel(names)
        name = names{i};
        assert(isfield(container, name) && isscalar(container.(name)) ...
                && isfinite(container.(name)), identifier, ...
            'Response field %s must be a finite scalar.', name);
    end
end
