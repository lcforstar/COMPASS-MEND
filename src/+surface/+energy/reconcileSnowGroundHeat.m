function [stateNext, fluxNext, diagnostic] = reconcileSnowGroundHeat( ...
        stateAccepted, drivers, groundResponse, parameters, ...
        soilSurfaceTemperature_C, dt_s)
%RECONCILESNOWGROUNDHEAT  Re-evaluate snow with the solved soil interface T.
%
%   The soil top row evaluates an affine snow-to-soil conductive response at
%   the accepted time-mean z=0 soil temperature.  Snow must see that identical
%   flux before the outer transaction commits.  This function therefore
%   reruns the authoritative surface.snow.advanceBulkSnow kernel from the immutable
%   accepted snow state with only snow_to_soil_heat_flux_W_m2 replaced by
%
%     q_si(T_s) = q_ref + dq_si/dT_s (T_s - T_ref).
%
%   Reusing the complete snow kernel preserves its water/energy clipping,
%   phase projection, terminal meltwater routing, and ledgers.  In particular,
%   a meltout event is returned as the new event state even when SCOPE/soil
%   must be restaged; returning the old candidate would repeat the same event.
%   A restage is requested only when the corrected state changes the snow
%   thermodynamic domain, materially changes cover, or changes the
%   temperature-independent snow energy redistribution seen by the soil row.
%
%   Editor: Jizixing Zhu; Date: 2026-07-19.
%   Change: 2026-07-19 Jizixing Zhu -- replace the duplicated enthalpy correction
%     with an exact replay of the single conservative bulk-snow transition.

    assert(isscalar(soilSurfaceTemperature_C) ...
            && isfinite(soilSurfaceTemperature_C) ...
            && isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'reconcileSnowGroundHeat:badInput', ...
        'Finite soil surface temperature and positive dt are required.');
    assert(isstruct(stateAccepted) && isstruct(drivers) ...
            && isstruct(groundResponse) && isstruct(parameters), ...
        'reconcileSnowGroundHeat:badTransaction', ...
        'Accepted snow, drivers, response, and parameters must be structs.');

    f = boundedScalar(groundResponse, 'cover_fraction', 0, 1);
    Tref = requiredScalar(groundResponse, ...
        'reference_soil_surface_temperature_C');
    qref = requiredScalar(groundResponse, ...
        'reference_flux_into_soil_W_m2');
    dTile = requiredScalar(groundResponse, ...
        'dflux_dsoil_surface_temperature_W_m2_K');
    qActual = qref + dTile * (soilSurfaceTemperature_C - Tref);
    correctedDrivers = drivers;
    correctedDrivers.snow_to_soil_heat_flux_W_m2 = qActual;
    [stateNext, fluxNext] = surface.snow.advanceBulkSnow( ...
        stateAccepted, parameters, correctedDrivers, dt_s);

    deltaTileFlux = qActual - qref;
    deltaGridFlux = f * deltaTileFlux;
    deltaEnergyJcm2 = -deltaGridFlux * dt_s / 1e4;
    before = responseSnowState(groundResponse, stateAccepted, parameters);
    after = surface.snow.diagnoseState(stateNext, parameters);
    activeBefore = hasResolvedSnow(before, parameters);
    activeAfter = hasResolvedSnow(after, parameters);
    coverChange = abs(after.cover_fraction - before.cover_fraction);

    originalRedistribution = scalarDriver( ...
        drivers, 'snow_energy_redistribution_W_m2', 0);
    expectedSnowContribution = f * qActual + originalRedistribution;
    redistributionMismatch = ...
        fluxNext.snow_soil_heat_contribution_W_m2 ...
        - expectedSnowContribution;
    redistributionTolerance = max(1e-8, ...
        256 * eps(max([1, abs(expectedSnowContribution), ...
        abs(fluxNext.snow_soil_heat_contribution_W_m2)])));
    regimeChanged = activeBefore ~= activeAfter;
    coverChanged = coverChange > 0.15;
    redistributionChanged = ...
        abs(redistributionMismatch) > redistributionTolerance;
    terminalMeltout = isfield(fluxNext, 'terminal_meltout_triggered') ...
        && logical(fluxNext.terminal_meltout_triggered);
    requiresRestage = regimeChanged || coverChanged ...
        || redistributionChanged || terminalMeltout;

    reason = 'snow_ground_flux_replayed';
    if terminalMeltout
        reason = 'snow_terminal_meltout_event';
    elseif regimeChanged
        reason = 'snow_thermodynamic_domain_changed';
    elseif coverChanged
        reason = 'snow_cover_changed';
    elseif redistributionChanged
        reason = 'snow_energy_redistribution_changed';
    end
    appliedTolerance = 64 * eps(max([1, abs(qActual), abs(qref)]));
    diagnostic = struct( ...
        'applied', abs(deltaTileFlux) > appliedTolerance, ...
        'recomputed_from_accepted_state', true, ...
        'requires_restage', requiresRestage, ...
        'soil_surface_temperature_C', soilSurfaceTemperature_C, ...
        'reference_snow_to_soil_flux_W_m2', qref, ...
        'actual_snow_to_soil_flux_W_m2', qActual, ...
        'snow_ground_flux_increment_W_m2', deltaGridFlux, ...
        'snow_energy_increment_J_cm2', deltaEnergyJcm2, ...
        'surface_snow_active_before', activeBefore, ...
        'surface_snow_active_after', activeAfter, ...
        'cover_fraction_before', before.cover_fraction, ...
        'cover_fraction_after', after.cover_fraction, ...
        'cover_fraction_change', coverChange, ...
        'snow_redistribution_mismatch_W_m2', redistributionMismatch, ...
        'terminal_meltout_triggered', terminalMeltout, ...
        'reason', reason);
end

function state = responseSnowState(response, fallback, parameters)
% Read the exact snow state used to construct the SCOPE/soil response.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    if isfield(response, 'snow_state') && isstruct(response.snow_state) ...
            && isfield(response.snow_state, 'cover_fraction') ...
            && isfield(response.snow_state, 'ice_water_equivalent_cm')
        state = response.snow_state;
    else
        state = surface.snow.diagnoseState(fallback, parameters);
    end
end

function tf = hasResolvedSnow(state, parameters)
% Identify whether a diagnosed state owns the snow thermodynamic surface.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    ice = requiredScalar(state, 'ice_water_equivalent_cm');
    cover = boundedScalar(state, 'cover_fraction', 0, 1);
    resolution = scalarDriver( ...
        parameters, 'solid_phase_energy_resolution_J_cm2', 1e-2);
    solidEnergy = parameters.rho_liquid_kg_m3 ...
        * parameters.latent_heat_fusion_J_kg * max(ice, 0) / 100 / 1e4;
    tf = cover > 64 * eps && solidEnergy > resolution;
end

function value = requiredScalar(container, name)
% Read a finite scalar from the snow-ground transaction.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    assert(isstruct(container) && isfield(container, name) ...
            && isscalar(container.(name)) && isfinite(container.(name)), ...
        'reconcileSnowGroundHeat:missingField', ...
        '%s must be a finite scalar.', name);
    value = double(container.(name));
end

function value = boundedScalar(container, name, lo, hi)
% Read one finite scalar on a closed interval.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    value = requiredScalar(container, name);
    assert(value >= lo && value <= hi, ...
        'reconcileSnowGroundHeat:badBoundedField', ...
        '%s must lie in [%g,%g].', name, lo, hi);
end

function value = scalarDriver(container, name, fallback)
% Read one optional finite scalar driver.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    value = fallback;
    if isstruct(container) && isfield(container, name) ...
            && ~isempty(container.(name))
        value = double(container.(name));
    end
    assert(isscalar(value) && isfinite(value), ...
        'reconcileSnowGroundHeat:badDriver', ...
        '%s must be a finite scalar.', name);
end
