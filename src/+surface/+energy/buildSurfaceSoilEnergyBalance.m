function balance = buildSurfaceSoilEnergyBalance(built, soilAdvance, dt_s)
%BUILDSURFACESOILENERGYBALANCE  Close surface, snow, and soil energy storage.
%
%   The control volume contains the prognostic snow store and the complete
%   U-primary soil column. Snow-to-soil conduction, meltwater enthalpy, and
%   terminal snow redistribution are internal transfers and cancel exactly.
%   External terms are evaluated independently from tile radiation/turbulent
%   exchange, realized bare-soil evaporation, precipitation/runoff enthalpy,
%   dry-air transport, the soil bottom boundary, and root-carried energy.
%
%   All public powers are W m-2 and step energies are J m-2. Positive fluxes
%   enter the named control volume. The ledger is diagnostic and never changes
%   an accepted prognostic state or boundary condition.
%
%   Editor: Jizixing Zhu; Date: 2026-07-19.
%   Change: 2026-07-20 Jizixing Zhu -- use the same authoritative frozen
%           surface evaluator as the atmospheric flux closure instead of a
%           duplicated dry-limit latent-heat reconstruction.

    balance = struct('has_data', false);
    if ~hasRequiredLedgers(built, soilAdvance)
        return;
    end
    boundary = soil.boundary.finalizeFluxSummary( ...
        soilAdvance.boundary_flux_summary);
    if ~boundary.heat.enabled
        return;
    end
    surfaceWater = soilAdvance.surface_boundary_summary;
    soilEnergy = soilAdvance.energy_balance;
    scope = built.workspace.scope_step;
    fluxes = scope.fluxes;
    thermal = scope.thermal;
    snowFlux = built.diagnostics.snow;
    required = {'bare_ground_external_energy_flux_W_m2', ...
        'bare_ground_external_energy_flux_temperature_derivative_W_m2_K', ...
        'bare_ground_upward_latent_heat_flux_contribution_W_m2'};
    if ~all(isfield(fluxes, required)) ...
            || ~isfield(thermal, 'bare_ground_effective_temperature_C')
        return;
    end

    cover = min(max(readFinite(snowFlux, 'surface_cover_fraction', ...
        readFinite(boundary.heat, 'snow_cover_fraction', 0)), 0), 1);
    soilSurfaceTemperature = readFinite(boundary.heat, ...
        'top_response_evaluation_temperature_C', built.Y.T(end));
    bareLinearizationTemperature = ...
        thermal.bare_ground_effective_temperature_C;
    reconstructedBareExternal = (1 - cover) * ( ...
        fluxes.bare_ground_external_energy_flux_W_m2 ...
        + fluxes. ...
            bare_ground_external_energy_flux_temperature_derivative_W_m2_K ...
        * (soilSurfaceTemperature - bareLinearizationTemperature));
    [~, frozenParts] = surface.energy.evaluateFrozenSurfaceSoilHeat( ...
        built, soilAdvance, soilSurfaceTemperature);
    latentHeat = max((2.501 - 0.002361 * soilSurfaceTemperature) * 1e6, 0);
    actualBareLatent = frozenParts.actual_bare_latent_W_m2;
    reconstructedBareActual = frozenParts.bare_W_m2;

    snowExternal = snowExternalEnergyFlux(snowFlux, cover);
    phys = equations.physicalConstants();
    rainRate = max(readFinite(snowFlux, 'rainfall_cm_s', 0), 0);
    liquidSupply = max(surfaceWater.mean_liquid_supply_cm_s, 0);
    qIn = max(surfaceWater.mean_q_in_actual_cm_s, 0);
    infiltrationFraction = min(qIn / max(liquidSupply, eps), 1);
    bareRainInfiltration = (1 - cover) * rainRate * infiltrationFraction;
    precipitationEnergy = bareRainInfiltration * 10 ...
        * phys.Cp_liq_SI * scope.meteo.Ta;
    dryAirEnergy = 0;
    if boundary.dry_air.enabled
        dryAirEnergy = boundary.dry_air.top_flux_into_domain * 1e4 ...
            * phys.c_a * soilSurfaceTemperature;
    end
    soilTop = boundary.heat.top_flux_into_domain * 1e4;
    appliedSurfaceResponse = readFinite(boundary.heat, ...
        'top_response_evaluated_flux_into_domain', NaN) * 1e4;
    snowToSoil = readFinite( ...
        snowFlux, 'snow_soil_heat_contribution_W_m2', 0);
    if isfinite(appliedSurfaceResponse)
        % The accepted response is the total-energy boundary condition
        % actually seen by U-primary. Remove snow-to-soil conduction because
        % it is internal to the combined snow+soil control volume.
        bareExternal = appliedSurfaceResponse - snowToSoil;
    else
        bareExternal = reconstructedBareActual;
    end
    externalFlux = bareExternal + snowExternal;

    soilStorage = soilEnergy.storage_change_J_cm2 * 1e4;
    snowBefore = soilAdvance.surface_energy_storage_before.snow_energy_J_cm2;
    snowAfter = readSnowEnergy(built.Y);
    snowStorage = (snowAfter - snowBefore) * 1e4;
    totalStorage = soilStorage + snowStorage;
    bottomInput = soilEnergy.bottom_input_J_cm2 * 1e4;
    rootSink = soilEnergy.root_sink_J_cm2 * 1e4;
    totalResidual = totalStorage - externalFlux * dt_s ...
        - bottomInput + rootSink;

    expectedSoilTop = bareExternal + snowToSoil;
    surfaceMismatch = (soilTop - expectedSoilTop) * dt_s;
    soilResidual = soilEnergy.residual_J_cm2 * 1e4;
    snowResidual = readFinite( ...
        snowFlux, 'energy_balance_residual_J_cm2', 0) * 1e4;
    cancellationError = totalResidual ...
        - (soilResidual + snowResidual + surfaceMismatch);

    empiricalG = readFinite(fluxes, ...
        'scope_empirical_bare_ground_heat_flux_W_m2', NaN);
    balance = struct( ...
        'has_data', true, 'elapsed_s', dt_s, ...
        'ground_net_radiation_W_m2', readFinite(fluxes, 'Rnstot', NaN), ...
        'ground_sensible_heat_W_m2', readFinite(fluxes, 'Hstot', NaN), ...
        'ground_latent_heat_demand_W_m2', readFinite(fluxes, 'lEstot', NaN), ...
        'ground_latent_heat_actual_W_m2', actualBareLatent ...
            + max(readFinite(fluxes, 'lEstot_snow', 0), 0), ...
        'bare_ground_external_energy_flux_actual_W_m2', bareExternal, ...
        'bare_ground_external_energy_flux_reconstructed_W_m2', ...
            reconstructedBareActual, ...
        'bare_ground_external_energy_flux_reconstruction_error_W_m2', ...
            bareExternal - reconstructedBareActual, ...
        'snow_external_energy_flux_W_m2', snowExternal, ...
        'snow_to_soil_internal_energy_flux_W_m2', snowToSoil, ...
        'diagnosed_bare_liquid_infiltration_sensible_energy_flux_W_m2', ...
            precipitationEnergy, ...
        'diagnosed_dry_air_sensible_energy_transport_W_m2', dryAirEnergy, ...
        'surface_external_energy_flux_W_m2', externalFlux, ...
        'scope_ground_heat_flux_empirical_W_m2', empiricalG, ...
        'scope_ground_ebal_residual_W_m2', readFinite(fluxes, 'Rnstot', 0) ...
            - readFinite(fluxes, 'Hstot', 0) ...
            - readFinite(fluxes, 'lEstot', 0) - empiricalG, ...
        'soil_top_energy_flux_total_actual_W_m2', soilTop, ...
        'surface_to_soil_interface_power_residual_W_m2', ...
            soilTop - expectedSoilTop, ...
        'soil_internal_energy_change_J_m2', soilStorage, ...
        'snow_internal_energy_change_J_m2', snowStorage, ...
        'surface_soil_total_energy_change_J_m2', totalStorage, ...
        'surface_external_energy_J_m2', externalFlux * dt_s, ...
        'surface_to_soil_interface_energy_residual_J_m2', surfaceMismatch, ...
        'soil_energy_residual_J_m2', soilResidual, ...
        'snow_energy_residual_J_m2', snowResidual, ...
        'surface_soil_total_energy_residual_J_m2', totalResidual, ...
        'surface_soil_interface_cancellation_error_J_m2', cancellationError, ...
        'evaporation_latent_heat_J_kg', latentHeat, ...
        'precipitation_temperature_C', scope.meteo.Ta);
end

function tf = hasRequiredLedgers(built, advance)
% Test fixed transaction inputs without manufacturing a partial ledger.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    tf = isstruct(advance) && isfield(advance, 'energy_balance') ...
        && advance.energy_balance.has_data ...
        && isfield(advance, 'boundary_flux_summary') ...
        && advance.boundary_flux_summary.has_data ...
        && isfield(advance, 'surface_boundary_summary') ...
        && advance.surface_boundary_summary.has_data ...
        && isfield(advance, 'surface_energy_storage_before') ...
        && isfield(advance.surface_energy_storage_before, ...
            'snow_energy_J_cm2') ...
        && isfield(built, 'diagnostics') && isfield(built.diagnostics, 'snow') ...
        && isfield(built.workspace, 'scope_step') ...
        && isfield(built.workspace.scope_step, 'fluxes') ...
        && isfield(built.workspace.scope_step, 'thermal') ...
        && isfield(built.workspace.scope_step, 'meteo');
end

function flux = snowExternalEnergyFlux(snowFlux, cover)
% Recover atmospheric/precipitation snow energy with soil conduction removed.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    surface = readFinite( ...
        snowFlux, 'snow_surface_external_energy_flux_W_m2', 0);
    fallingSnow = readFinite( ...
        snowFlux, 'falling_snow_energy_flux_W_m2', 0);
    fallingRain = readFinite( ...
        snowFlux, 'falling_rain_energy_flux_W_m2', 0);
    runoff = readFinite( ...
        snowFlux, 'snow_liquid_runoff_energy_flux_W_m2', 0);
    flux = -fallingSnow + cover * (surface + runoff - fallingRain);
end

function energy = readSnowEnergy(Y)
% Read accepted bulk-snow internal energy [J cm-2].
% Editor: Jizixing Zhu; Date: 2026-07-19.
    energy = 0;
    if isfield(Y, 'snow') && isstruct(Y.snow) ...
            && isfield(Y.snow, 'energy') && isfinite(Y.snow.energy)
        energy = double(Y.snow.energy);
    end
end

function value = readFinite(container, name, fallback)
% Read one optional finite scalar.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    value = fallback;
    if isstruct(container) && isfield(container, name) ...
            && isscalar(container.(name)) && isfinite(container.(name))
        value = double(container.(name));
    end
end
