function [flux_W_m2, parts] = evaluateFrozenSurfaceSoilHeat( ...
        built, soilAdvance, temperature_C)
%EVALUATEFROZENSURFACESOILHEAT  Evaluate the frozen surface heat map.
%
%   Inputs:
%     built         [in] Current staged surface/SCOPE/snow workspace.
%     soilAdvance   [in] One completed Dirichlet soil trial; its surface-water
%                        summary supplies realized evaporation [cm s-1].
%     temperature_C [degC] Frozen soil-interface trial temperature.
%
%   Returns:
%     flux_W_m2 [W m-2] Total frozen surface energy entering soil.
%     parts     struct  Bare, snow, latent-demand, and realized-latent terms
%                       [W m-2], all evaluated without rerunning ebal.
%
%   Method:
%     Evaluate the staged affine bare-plus-snow response at temperature_C.
%     If the soil water active set limits evaporation, replace the frozen
%     potential bare latent loss by the trial's realized latent loss. This is
%     the same physical target audited by buildSurfaceSoilEnergyBalance.
%
%   Reference:
%     docs/plans/soil_interface_temperature_closure_plan.md, sections 3 and 5.
% Editor: Jizixing Zhu; Date: 2026-07-19.

    assert(isstruct(built) && isfield(built, 'workspace') ...
            && isfield(built.workspace, 'surface') ...
            && isfield(built.workspace.surface, 'top_heat_response'), ...
        'evaluateFrozenSurfaceSoilHeat:missingResponse', ...
        'The staged frozen top-heat response is required.');
    assert(isscalar(temperature_C) && isfinite(temperature_C), ...
        'evaluateFrozenSurfaceSoilHeat:badTemperature', ...
        'temperature_C must be a finite scalar.');

    response = built.workspace.surface.top_heat_response;
    required = {'reference_temperature_C', ...
        'reference_flux_into_soil_W_m2', ...
        'dflux_dtemperature_W_m2_K', ...
        'snow_cover_fraction', ...
        'bare_ground_flux_at_linearization_W_m2', ...
        'bare_ground_dflux_dtemperature_W_m2_K', ...
        'bare_ground_linearization_temperature_C'};
    for i = 1:numel(required)
        name = required{i};
        assert(isfield(response, name) && isscalar(response.(name)) ...
                && isfinite(response.(name)), ...
            'evaluateFrozenSurfaceSoilHeat:badResponse', ...
            'top_heat_response.%s must be a finite scalar.', name);
    end

    f = min(max(double(response.snow_cover_fraction), 0), 1);
    potentialTotal = response.reference_flux_into_soil_W_m2 ...
        + response.dflux_dtemperature_W_m2_K ...
        * (temperature_C - response.reference_temperature_C);
    barePotential = (1 - f) * ( ...
        response.bare_ground_flux_at_linearization_W_m2 ...
        + response.bare_ground_dflux_dtemperature_W_m2_K ...
        * (temperature_C ...
            - response.bare_ground_linearization_temperature_C));
    snow = potentialTotal - barePotential;

    potentialLatent = readResponse(response, ...
        'soil_evaporation_latent_heat_flux_W_m2', 0) ...
        + readResponse(response, ...
        'soil_evaporation_latent_heat_flux_temperature_derivative_W_m2_K', 0) ...
        * (temperature_C ...
            - response.bare_ground_linearization_temperature_C);
    potentialLatent = max(potentialLatent, 0);
    actualLatent = potentialLatent;
    [hasSurface, demand, actual] = readRealizedEvaporation(soilAdvance);
    if hasSurface
        actualBare = actual;
        if demand > 0 && isfield(built.workspace, 'scope_step') ...
                && isfield(built.workspace.scope_step, 'fluxes')
            scopeFlux = built.workspace.scope_step.fluxes;
            if isfield(scopeFlux, 'evaporation_bare_kg_m2_s') ...
                    && isscalar(scopeFlux.evaporation_bare_kg_m2_s) ...
                    && isfinite(scopeFlux.evaporation_bare_kg_m2_s)
                bareDemand = min(max( ...
                    scopeFlux.evaporation_bare_kg_m2_s * 0.1, 0), demand);
                actualBare = actual * bareDemand / demand;
            end
        end
        latentHeat_J_kg = max( ...
            (2.501 - 0.002361 * temperature_C) * 1e6, 0);
        actualLatent = actualBare * 10 * latentHeat_J_kg;
    end

    bareActual = barePotential + potentialLatent - actualLatent;
    flux_W_m2 = bareActual + snow;
    assert(isfinite(flux_W_m2), ...
        'evaluateFrozenSurfaceSoilHeat:nonfiniteFlux', ...
        'The frozen surface heat evaluation must be finite.');
    parts = struct( ...
        'bare_W_m2', bareActual, ...
        'snow_W_m2', snow, ...
        'potential_bare_latent_W_m2', potentialLatent, ...
        'actual_bare_latent_W_m2', actualLatent, ...
        'potential_total_W_m2', potentialTotal);
end

function value = readResponse(response, name, fallback)
% Read one optional finite frozen-response field.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    value = fallback;
    if isfield(response, name) && isscalar(response.(name)) ...
            && isfinite(response.(name))
        value = double(response.(name));
    end
end

function [available, demand, actual] = readRealizedEvaporation(advance)
% Read accepted mean evaporation demand and realization [cm s-1].
% Editor: Jizixing Zhu; Date: 2026-07-19.
    available = false;
    demand = 0;
    actual = 0;
    if ~isstruct(advance) || ~isfield(advance, 'surface_boundary_summary')
        return;
    end
    summary = advance.surface_boundary_summary;
    if ~isstruct(summary) || ~isfield(summary, 'has_data') ...
            || ~summary.has_data
        return;
    end
    required = {'mean_evap_demand_cm_s','mean_evap_actual_cm_s'};
    if ~all(isfield(summary, required)) ...
            || ~all(isfinite([summary.mean_evap_demand_cm_s, ...
                summary.mean_evap_actual_cm_s]))
        return;
    end
    demand = max(double(summary.mean_evap_demand_cm_s), 0);
    actual = min(max(double(summary.mean_evap_actual_cm_s), 0), demand);
    available = true;
end
