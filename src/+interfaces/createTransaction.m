function transaction = createTransaction( ...
        pending, soil_candidate, soil_advance, storage_before_mm, dt_s)
%CREATETRANSACTION Materialize one destination-owned outer-step transaction.
%
%   transaction = interfaces.createTransaction(pending, soil_candidate, ...)
%   separates the existing staged process outputs by their physical owner.
%   It preserves current numerical kernels and their values exactly; this is a
%   schema boundary, not a second surface/soil calculation.
%
%   Inputs:
%     pending           [struct] Legacy producer staging payload.
%     soil_candidate    [struct] Uncommitted h/U/P_g endpoint from
%                       interfaces.captureSoilCandidate.
%     soil_advance      [struct] Accepted substep accumulators and residuals.
%     storage_before_mm [mm] Soil-column water storage at outer-step start.
%     dt_s              [s] Accepted outer-step duration.
%
%   Returns:
%     transaction [struct] Candidate state, interface ledger, and accepted
%                 ancillary records; it contains no legacy pending payload.
%
%   Physical contract:
%     State candidates are grouped by the domain that advances them.  The
%     surface-to-soil water request is distinct from the accepted soil flux
%     ledger: it is a prescribed top-boundary request, while `soil_advance`
%     contains the physically applied, adaptive-substep result.  All fluxes
%     retain the existing inward-positive convention at their receiving domain.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
% Change: 2026-07-20 Jizixing Zhu — include the explicit vegetation-to-soil N request.
% Change: 2026-07-20 Jizixing Zhu — expose the realized soil-to-groundwater drainage ledger.
% Change: 2026-07-20 Jizixing Zhu -- consume only typed requests/ledgers; remove the
%   ownerless ancillary flux compatibility bucket.
    step.validatePending(pending);
    assert(isfield(pending, 'candidate') ...
        && isfield(pending.candidate, 'vegetation') ...
        && isfield(pending.candidate, 'surface'), ...
        'interfaces:createTransaction:missingCandidate', ...
        'pending must contain destination-owned vegetation and surface candidates.');

    transaction = struct();
    transaction.candidate = struct( ...
        'vegetation', pending.candidate.vegetation, ...
        'surface', pending.candidate.surface, ...
        'soil', soil_candidate, ...
        'groundwater', struct('has_prognostic_state', false));

    heatClosure = struct();
    if isstruct(soil_advance) && isfield(soil_advance, ...
            'interface_temperature_closure')
        heatClosure = soil_advance.interface_temperature_closure;
    end
    transaction.ledger = struct( ...
        'vegetation_to_soil', struct( ...
            'water_request', pending.request.vegetation_to_soil.water, ...
            'nitrogen_request', pending.request.vegetation_to_soil.nitrogen), ...
        'surface_to_soil', struct( ...
            'water_request', pending.request.surface_to_soil.water, ...
            'energy_request', interfaces.buildSurfaceSoilEnergyLedger( ...
                heatClosure)), ...
        'soil_to_groundwater', interfaces.buildSoilGroundwaterLedger( ...
            soil_advance, dt_s), ...
        'vegetation_to_atmosphere', ...
            pending.ledger.vegetation_to_atmosphere, ...
        'soil', struct( ...
            'advance', soil_advance, ...
            'storage_before_mm', storage_before_mm, ...
            'dt_s', dt_s));
    transaction.ancillary = struct( ...
        'diagnostics', pending.diagnostics, ...
        'management', pending.management);
end
