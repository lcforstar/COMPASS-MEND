function validateTransaction(transaction)
%VALIDATETRANSACTION Validate physical ownership before an atomic outer commit.
%
%   Inputs:
%     transaction [struct] Destination-owned payload from
%                 interfaces.createTransaction.
%
%   The validation deliberately checks structure and ownership, not numerical
%   closure thresholds.  Solver and conservation checks remain attached to the
%   equations that define them; this guard prevents a complete solve from
%   committing an incomplete cross-domain state package.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
% Change: 2026-07-20 Jizixing Zhu — require the typed root-nitrogen interface ledger.
% Change: 2026-07-20 Jizixing Zhu -- require typed carbon exchange and remove generic
%   ancillary flux containers.
    required = {'candidate','ledger','ancillary'};
    for i = 1:numel(required)
        assert(isfield(transaction, required{i}), ...
            'interfaces:validateTransaction:missingField', ...
            'Transaction is missing %s.', required{i});
    end
    candidateNames = {'vegetation','surface','soil','groundwater'};
    for i = 1:numel(candidateNames)
        name = candidateNames{i};
        assert(isfield(transaction.candidate, name), ...
            'interfaces:validateTransaction:missingCandidate', ...
            'Transaction is missing candidate.%s.', name);
    end
    assert(isfield(transaction.candidate.soil, 'trial') ...
        && isfield(transaction.candidate.soil, 'derived') ...
        && isfield(transaction.candidate.soil, 'nitrogen'), ...
        'interfaces:validateTransaction:incompleteSoilCandidate', ...
        'Soil candidate must retain trial and derived endpoint fields.');
    forbiddenSoilFields = {'surface_water','surface','snow','scope_soil', ...
        'canopy_air','vegetation','plant_hydraulic','plant_cn'};
    for i = 1:numel(forbiddenSoilFields)
        name = forbiddenSoilFields{i};
        assert(~isfield(transaction.candidate.soil.trial, name), ...
            'interfaces:validateTransaction:foreignSoilState', ...
            'Soil candidate must not contain foreign domain state %s.', name);
    end
    assert(isfield(transaction.ledger, 'surface_to_soil') ...
        && isfield(transaction.ledger.surface_to_soil, 'water_request') ...
        && isstruct(transaction.ledger.surface_to_soil.water_request) ...
        && isfield(transaction.ledger.surface_to_soil.water_request, 'Throughfall') ...
        && isfield(transaction.ledger.surface_to_soil.water_request, 'EVAP'), ...
        'interfaces:validateTransaction:missingSurfaceSoilLedger', ...
        'Surface-to-soil water request must be explicit in the ledger.');
    assert(isfield(transaction.ledger, 'vegetation_to_soil') ...
        && isfield(transaction.ledger.vegetation_to_soil, 'water_request') ...
        && isstruct(transaction.ledger.vegetation_to_soil.water_request) ...
        && isfield(transaction.ledger.vegetation_to_soil.water_request, ...
            'element_endpoint_rate_1_s'), ...
        'interfaces:validateTransaction:missingRootSoilLedger', ...
        'Vegetation-to-soil root-water request must be explicit in the ledger.');
    assert(isfield(transaction.ledger.vegetation_to_soil, 'nitrogen_request') ...
        && isstruct(transaction.ledger.vegetation_to_soil.nitrogen_request) ...
        && isfield(transaction.ledger.vegetation_to_soil.nitrogen_request, ...
            'sink_nh4') ...
        && isfield(transaction.ledger.vegetation_to_soil.nitrogen_request, ...
            'sink_no3') ...
        && isfield(transaction.ledger.vegetation_to_soil.nitrogen_request, ...
            'enabled'), ...
        'interfaces:validateTransaction:missingRootSoilNitrogenLedger', ...
        'Vegetation-to-soil root-nitrogen request must be explicit in the ledger.');
    nitrogenRequest = transaction.ledger.vegetation_to_soil.nitrogen_request;
    if ~logical(nitrogenRequest.enabled)
        assert(all(nitrogenRequest.sink_nh4(:) == 0) ...
            && all(nitrogenRequest.sink_no3(:) == 0), ...
            'interfaces:validateTransaction:disabledRootNitrogenNonzero', ...
            'A disabled vegetation-to-soil N request must not remove soil N.');
    end
    assert(isfield(transaction.ledger, 'soil_to_groundwater') ...
        && isstruct(transaction.ledger.soil_to_groundwater) ...
        && isfield(transaction.ledger.soil_to_groundwater, 'rate_cm_s') ...
        && isfield(transaction.ledger.soil_to_groundwater, 'amount_mm'), ...
        'interfaces:validateTransaction:missingSoilGroundwaterLedger', ...
        'The actual soil-to-groundwater water exchange must be explicit.');
    assert(isfield(transaction.ledger, 'vegetation_to_atmosphere') ...
        && isfield(transaction.ledger.vegetation_to_atmosphere, ...
            'carbon_result'), ...
        'interfaces:validateTransaction:missingVegetationAtmosphereLedger', ...
        'Vegetation-to-atmosphere carbon exchange must be typed.');

    ancillary = transaction.ancillary;
    requiredAncillary = {'diagnostics','management'};
    for i = 1:numel(requiredAncillary)
        name = requiredAncillary{i};
        assert(isfield(ancillary, name), ...
            'interfaces:validateTransaction:missingAncillary', ...
            'Transaction ancillary.%s is required.', name);
    end
end
