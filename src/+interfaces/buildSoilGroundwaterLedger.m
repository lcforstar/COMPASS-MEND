function ledger = buildSoilGroundwaterLedger(soil_advance, dt_s)
%BUILDSOILGROUNDWATERLEDGER  Publish the realized lower soil-water exchange.
%
%   ledger = interfaces.buildSoilGroundwaterLedger(soil_advance, dt_s)
%   converts the accepted Richards lower-boundary flux into the five-domain
%   soil-to-groundwater ledger.  COMPASS currently has no groundwater storage
%   state, so this is an audit result rather than a groundwater candidate.
%
%   Inputs:
%     soil_advance [in] struct Accepted adaptive soil solve and water fluxes.
%     dt_s [in] [s] Accepted outer-step duration.
%
%   Returns:
%     ledger [out] struct Actual water exchange. Positive `rate_cm_s` and
%       `amount_mm` mean water leaves the soil column at its lower boundary.
%
%   Sign conversion:
%     The retained Richards kernel reports QMB [cm s^-1] positive into soil at
%   the lower boundary. Therefore soil-to-groundwater drainage is -QMB. This
%   is the same sign used by solver.computeWaterBalanceResidual.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
    assert(isstruct(soil_advance) && isfield(soil_advance, 'water_flux_accum') ...
        && isfield(soil_advance.water_flux_accum, 'QMB'), ...
        'interfaces:buildSoilGroundwaterLedger:missingBottomFlux', ...
        'Accepted soil advance must contain its realized bottom QMB flux.');
    assert(isscalar(dt_s) && isfinite(dt_s) && dt_s > 0, ...
        'interfaces:buildSoilGroundwaterLedger:badDuration', ...
        'dt_s must be a finite positive accepted duration.');
    qmbIntoSoil = soil_advance.water_flux_accum.QMB;
    assert(isscalar(qmbIntoSoil) && isfinite(qmbIntoSoil), ...
        'interfaces:buildSoilGroundwaterLedger:badBottomFlux', ...
        'The realized bottom QMB flux must be finite and scalar.');
    rate = -qmbIntoSoil;
    ledger = struct( ...
        'schema_version', 1, ...
        'producer', 'soil', ...
        'receiver', 'groundwater_boundary', ...
        'has_prognostic_receiver', false, ...
        'kind', 'realized_lower_water_exchange', ...
        'unit', 'cm s^-1', ...
        'positive_direction', 'soil_to_groundwater', ...
        'rate_cm_s', rate, ...
        'amount_mm', rate * dt_s * 10, ...
        'source_kernel_flux_into_soil_cm_s', qmbIntoSoil);
end
