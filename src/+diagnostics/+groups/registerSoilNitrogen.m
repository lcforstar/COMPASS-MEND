% Editor: Wenjie Liu; Date: 2026-09-21.
% Change: 2026-09-22 Wenjie Liu -- include accepted gross paths and phase pools.
    sourceCode='src/+soil/+nitrogen/+tracer/advanceCandidate.m';
    commonComment=['Passive aggregate label for all mineral-fertilizer ', ...
        'schedule events; perfect mixing, no source preference or isotope ', ...
        'fractionation; output profiles are ordered surface to bottom.'];
    nodes={ ...
        'fertilizer_tracer_nh4_liquid','Fertilizer-source ammonium liquid concentration','nh4'; ...
        'fertilizer_tracer_no3_liquid','Fertilizer-source nitrate liquid concentration','no3'; ...
