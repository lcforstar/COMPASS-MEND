        reg.register(struct('name',nodes{i,1},'long_name',nodes{i,2}, ...
            'units','ug N cm-3','dims',{{'time','node'}},'group',group, ...
            'source',['Y.soil_fertilizer_n_tracer.' nodes{i,3}], ...
            'source_code',sourceCode,'transform','none', ...
            'comment',commonComment));
    end

    layers={ ...
        'fertilizer_tracer_don_profile','Fertilizer-source dissolved organic nitrogen','dom.don_total_g_cm3'; ...
        'fertilizer_tracer_pon1_profile','Fertilizer-source POM1-associated organic nitrogen','organic_n.PON1'; ...
