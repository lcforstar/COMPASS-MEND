        'source','workspace.fertilizer_n_tracer.step.din_closure_residual_g_cm2', ...
        'source_code',sourceCode,'transform','scalar','comment',commonComment));
    reg.register(struct('name','fertilizer_tracer_cumulative_closure_residual', ...
        'long_name','Fertilizer-source cumulative column-balance residual', ...
        'units','g N cm-2','dims',{{'time'}},'group','conservation', ...
        'source','workspace.fertilizer_n_tracer.cumulative_closure_residual_g_cm2', ...
        'source_code',sourceCode,'transform','scalar','comment',commonComment));
    diagnostics.groups.registerFertilizerTracerDetails(reg,group);
end

