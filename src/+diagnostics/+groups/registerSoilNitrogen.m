            'units','g N cm-2','dims',{{'time'}},'group',group, ...
            'source',['Y.soil_fertilizer_n_tracer.cumulative.' key '_g_cm2'], ...
            'source_code',sourceCode,'transform','scalar', ...
            'comment',routeComment));
    end
    reg.register(struct('name','fertilizer_tracer_mend_closure_residual_step', ...
        'long_name','Fertilizer-source MEND replay closure residual during accepted step', ...
