function registerSoilNitrogen(reg, cfg)
%REGISTERSOILNITROGEN  N module diagnostics (group: soil_nitrogen).
% Only when cfg.lNefc == 1.
% Output: data/output_<tag>/soil_nitrogen.nc
% Source-of-truth: src/+soil/+nitrogen/*
% Editor: Jizixing Zhu; Date: 2026-09-14.
% Change: 2026-09-14 Codex -- expose accepted O2 storage, consumption and closure.

    if ~helpers.isfield_or_prop_true(cfg, 'lNefc')
        return;
    end
    g = 'soil_nitrogen';
    reg.register(struct('name','oxygen_concentration', ...
        'long_name','Accepted gas-phase oxygen concentration','units','mol cm-3', ...
        'dims',{{'time','node'}},'group',g,'source','Y.soil_gas.C_O2','transform','none'));
    for key={'storage_before','storage_after','consumed','top_input','bottom_input','balance_residual'}
        name=key{1};
        reg.register(struct('name',['oxygen_' name], ...
            'long_name',['Accepted oxygen ' name],'units','mol cm-2', ...
            'dims',{{'time'}},'group',g,'source','workspace.nitrogen.oxygen','transform','scalar'));
    end
    reg.register(struct('name','oxygen_reaction_factor', ...
        'long_name','Applied MEND reaction factor from oxygen supply','units','1', ...
        'dims',{{'time','layer'}},'group',g,'source','workspace.nitrogen', ...
        'transform','none'));

    % ---- 浓度场 ----
    reg.register(struct('name', 'nh4_liquid', ...
        'long_name', 'Ammonium NH4+ liquid-phase concentration', ...
        'standard_name', 'mass_concentration_of_ammonium_in_soil_water', ...
        'units', 'ug cm-3', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.C_NH4_new', ...
        'transform', 'none'));

    reg.register(struct('name', 'no3_liquid', ...
        'long_name', 'Nitrate NO3- liquid-phase concentration', ...
        'standard_name', 'mass_concentration_of_nitrate_in_soil_water', ...
        'units', 'ug cm-3', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.C_NO3_new', ...
        'transform', 'none'));

    reg.register(struct('name', 'urea_liquid', ...
        'long_name', 'Urea liquid-phase concentration', ...
        'units', 'ug cm-3', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.C_Urea', ...
        'transform', 'none'));

    reg.register(struct('name', 'nh4_total', ...
        'long_name', 'NH4 total concentration (liquid + adsorbed)', ...
        'units', 'ug g-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', '(theta_LL + RHOKG) * C_NH4 / RHO_bulk', ...
        'transform', 'none', ...
        'when', 'cfg.lNtotal=1'));

    reg.register(struct('name', 'no3_total', ...
        'long_name', 'NO3 total concentration (liquid phase)', ...
        'units', 'ug g-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'theta_LL * C_NO3 / RHO_bulk', ...
        'transform', 'none', ...
        'when', 'cfg.lNtotal=1'));

    % ---- 反应剖面 [μg/(cm³ soil·s)] — NL×2 在节点上聚合, 画反应深度云图用 ----
    reg.register(struct('name', 'nitrification_profile', ...
        'long_name', 'Nitrification rate per layer (NH4→NO3 source/sink density)', ...
        'units', 'ug cm-3 s-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'NitrogenVariables.Snit', ...
        'source_code','src/+soil/+nitrogen/+chemistry/nitrification.m', ...
        'transform', 'edge_to_node_reversed_layer', ...
        'comment','Volumetric source density per soil layer; depth-integrate to get column flux'));

    % [2026-05-16 dir-fix] NitrogenVariables.Snit/Sden/Smin/SinkS NL×2 也是 Dtrmn_Z
    % bottom-up convention, 跟 SoilVariables 一致. _reversed_layer 让输出顶→底.
    reg.register(struct('name', 'denitrification_profile', ...
        'long_name', 'Denitrification rate per layer', ...
        'units', 'ug cm-3 s-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'NitrogenVariables.Sden', ...
        'source_code','src/+soil/+nitrogen/+chemistry/denitrification.m', ...
        'transform', 'edge_to_node_reversed_layer'));

    reg.register(struct('name', 'mineralization_profile', ...
        'long_name', 'Mineralization rate per layer (SOM→NH4 source density)', ...
        'units', 'ug cm-3 s-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'NitrogenVariables.Smin', ...
        'transform', 'edge_to_node_reversed_layer'));

    reg.register(struct('name', 'root_sink_profile', ...
        'long_name', 'Root nitrogen uptake density per layer', ...
        'units', 'ug cm-3 s-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'NitrogenVariables.SinkS', ...
        'transform', 'edge_to_node_reversed_layer', ...
        'comment','Combined NH4+NO3 sink density; root-area weighted'));

    % ---- 反应/边界通量 [μg/(cm²·s)] ----
    reg.register(struct('name', 'nitrification_flux', ...
        'long_name', 'Nitrification flux (NH4 → NO3)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvSnit(KT)', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/nitrification.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'denitrification_flux', ...
        'long_name', 'Denitrification flux (NO3 → N2/N2O)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvSden(KT)', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/denitrification.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'mineralization_flux', ...
        'long_name', 'SOM mineralization flux (SOM → NH4)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvSmin(KT)', ...
        'source_code', 'src/+soil/+nitrogen/+organic/mineralization.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'urea_hydrolysis_flux', ...
        'long_name', 'Urea hydrolysis flux (Urea → NH4)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'DeltZ x Shys_avg', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/ureaHydrolysis.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'ammonia_volatilization', ...
        'long_name', 'NH3 volatilization (atmospheric efflux)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvSvol(KT)', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'root_sink_nh4', ...
        'long_name', 'Root uptake of NH4', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvSinkSnh4(KT)', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'root_sink_no3', ...
        'long_name', 'Root uptake of NO3', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvSinkSno3(KT)', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'bot_flux_nh4', ...
        'long_name', 'Bottom NH4 flux', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvBot(KT)', ...
        'transform', 'scalar', ...
        'comment','Positive = NH4 leaving column via bottom boundary'));

    reg.register(struct('name', 'bot_flux_no3', ...
        'long_name', 'Bottom NO3 flux', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvBot1(KT)', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'top_flux_nh4', ...
        'long_name', 'Top boundary NH4 flux (atmospheric deposition + fertilizer surface input)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvTop(KT)', ...
        'source_code','src/+soil/+nitrogen/+transport/calculateBoundaryFlux.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'top_flux_no3', ...
        'long_name', 'Top boundary NO3 flux', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvTop1(KT)', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'n2o_from_nitrification', ...
        'long_name', 'N2O production from nitrification pathway (NH4→...→N2O)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.Cvnit_N2o(KT)', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/nitrification.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'n2o_from_denitrification', ...
        'long_name', 'N2O production from denitrification pathway (NO3→...→N2O)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.Cvdenit_N2o(KT)', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/denitrification.m', ...
        'transform', 'scalar', ...
        'comment', 'Anaerobic pathway; complete to N2 only when O2 very low'));

    reg.register(struct('name', 'n2_from_denitrification', ...
        'long_name', 'N2 production from complete denitrification (NO3→...→N2)', ...
        'units', 'ug cm-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.Cvdenit_N2(KT)', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/denitrification.m', ...
        'transform', 'scalar', ...
        'comment', 'Terminal step of denitrification; dominant under strict anaerobic conditions'));

    % ---- 总储量 ----
    reg.register(struct('name', 'nh4_storage', ...
        'long_name', 'NH4 column total storage (liquid + adsorbed + ice)', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvnh4(KT)', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'no3_storage', ...
        'long_name', 'NO3 column total storage (liquid + ice)', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'NitrogenFlux.cvno3(KT)', ...
        'transform', 'scalar'));

    % ---- 守恒残差 (放到 conservation group) ----
    reg.register(struct('name', 'nh4_cum_residual', ...
        'long_name', 'NH4 cumulative balance residual (ΔS − Σ in + Σ out)', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', 'conservation', ...
        'source', 'NitrogenDiagnostics.cum_residual_nh4', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'no3_cum_residual', ...
        'long_name', 'NO3 cumulative balance residual', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', 'conservation', ...
        'source', 'NitrogenDiagnostics.cum_residual_no3', ...
        'transform', 'scalar'));

    % ---- 施肥事件 ----
    reg.register(struct('name', 'fert_nh4_added', ...
        'long_name', 'Fertilizer NH4 mass added this KT', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'FertDiagBuffer.nh4_added', ...
        'source_code', 'src/+soil/+nitrogen/applyFertilizer.m', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'fert_no3_added', ...
        'long_name', 'Fertilizer NO3 mass added this KT', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'FertDiagBuffer.no3_added', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'fert_urea_added', ...
        'long_name', 'Fertilizer urea mass added this KT', ...
        'units', 'ug cm-2', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'FertDiagBuffer.urea_added', ...
        'transform', 'scalar'));

    % ---- [2026-05-16] DAISY-MM 硝化诊断字段 ----
    reg.register(struct('name', 'nit_mm_factor', ...
        'long_name', 'Nitrification Michaelis-Menten saturation factor', ...
        'units', '1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'NitrogenVariables.nit_mm_factor', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/nitrification.m', ...
        'transform', 'edge_to_node_reversed_layer', ...
        'comment', 'M_total/(K_m+M_total); 1 = substrate-rich, ~0.15 = substrate-limited'));

    reg.register(struct('name', 'nh4_substrate_total', ...
        'long_name', 'NH4 total substrate (liquid + sorbed) per soil volume', ...
        'units', 'ug cm-3', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'NitrogenVariables.nit_M_total', ...
        'source_code', 'src/+soil/+nitrogen/+chemistry/nitrification.m', ...
        'transform', 'edge_to_node_reversed_layer', ...
        'comment', 'M = (theta + rho*Kd) * C_NH4_liq; DAISY-style substrate definition'));

    % ---- [2026-05-19] M2-B.2 demand-driven uptake diagnostics ----
    reg.register(struct('name', 'root_demand_nh4', ...
        'long_name', 'Plant N demand for NH4 sent to root uptake', ...
        'units', 'g m-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'demand_NH4_g_m2_s', ...
        'source_code', 'src/COMPASS.m M2-B.2 block', ...
        'transform', 'scalar', ...
        'comment', 'D_N_total × Vmax_NH4/(Vmax_NH4+Vmax_NO3); 0 when N_labile ≥ target'));

    reg.register(struct('name', 'root_demand_no3', ...
        'long_name', 'Plant N demand for NO3 sent to root uptake', ...
        'units', 'g m-2 s-1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', 'demand_NO3_g_m2_s', ...
        'transform', 'scalar'));

    reg.register(struct('name', 'nitrogen_supply_limit_factor', ...
        'long_name', 'Actual uptake / demand ratio (0=soil-limited, 1=demand-met)', ...
        'units', '1', ...
        'dims', {{'time'}}, ...
        'group', g, ...
        'source', '(SPUptake_NH4+SPUptake_NO3) × 1e-2 / demand_total', ...
        'transform', 'scalar', ...
        'comment', '<1 = soil bottleneck; =1 = demand satisfied; M2-B.2 路径'));
end
