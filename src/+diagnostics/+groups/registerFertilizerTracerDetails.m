function registerFertilizerTracerDetails(reg,group)
%REGISTERFERTILIZERTRACERDETAILS Register accepted label path/phase data.
% Amounts are per accepted outer step, never per-second rates. Cumulative
% detailed routes are obtained by summing step values once across all output
% segments. Gross recycling can exceed applied N and is not unique recovery.
% Editor: Wenjie Liu; Date: 2026-09-22.
% Change: 2026-09-29 Wenjie Liu -- document DON and particle bottom exports.
    schema=diagnostics.fertilizerTracerDetailSchema();
    common=['Aggregate mineral-fertilizer source label, not an isotope or ', ...
        'individual application cohort. Surface-to-bottom layer order. ', ...
        'Gross internal routes include repeated recycling; not terminal loss ', ...
        'or first-passage release. No age/residence-time interpretation.'];
    code='src/+diagnostics/writeFertilizerTracerDetails.m';
    for i=1:size(schema.groups,1)
        for j=1:numel(schema.phases)
            phase=schema.phases{j};key=[schema.groups{i,1} '_' phase '_n'];
            source=['Y.soil_fertilizer_n_tracer.organic_n.' ...
                schema.groups{i,2} '_' phase '_N'];
            register([key '_profile'],[key ' fertilizer-source inventory'], ...
                'g N cm-3',{'time','layer'},source, ...
                [common ' Phase subpool; do not add to its aggregate pool.']);
        end
    end
    for i=1:size(schema.routes,1)
        key=['route_' schema.routes{i,1}];
        source=['workspace.fertilizer_n_tracer.mend_routes.nitrogen_flux.' ...
            schema.routes{i,2}];
        comment=[common ' Accepted replay mg N g-1 dry soil converted ', ...
            'with the current layer bulk density / 1000.'];
        if contains(key,'decomposition')
            comment=[comment ' Aggregate of DON/MOM branches; do not double count.'];
        end
        register([key '_profile_step'],[schema.routes{i,3} ' per accepted step'], ...
            'g N cm-3',{'time','layer'},source,comment);
        register([key '_step'],[schema.routes{i,3} ' column amount per accepted step'], ...
            'g N cm-2',{'time'},source,[comment ' Integrate profile times layer thickness.']);
    end
    for i=1:size(schema.phase_routes,1)
        for j=1:numel(schema.phases)
            key=['route_' schema.phase_routes{i,1} '_' schema.phases{j}];
            source=['workspace.fertilizer_n_tracer.mend_routes.' ...
                schema.phase_routes{i,2} '.' schema.phase_routes{i,3}];
            register([key '_profile_step'],[key ' per accepted step'], ...
                'g N cm-3',{'time','layer'},source, ...
                [common ' Phase branch of the corresponding aggregate route.']);
        end
    end
    for phase={'free','sorbed'}
        key=['don_' phase{1} '_profile'];
        register(key,['Fertilizer-source equilibrium ' phase{1} ' DON inventory'], ...
            'g N cm-3',{'time','layer'},'Accepted tracer DON partition', ...
            [common ' Algebraic phase of DON total, not an additional owner.']);
    end
    register('don_aqueous_profile','Fertilizer-source DON concentration in water', ...
        'g N cm-3 water',{'time','layer'},'Accepted tracer DON partition',common);
    for key={'don','pon1','pon2','mon','active_microbe_n','dormant_microbe_n', ...
            'pom1_enzyme_n','pom2_enzyme_n','mom_enzyme_n','intracellular_enzyme_n'}
        register([key{1} '_storage'],[key{1} ' fertilizer-source column inventory'], ...
            'g N cm-2',{'time'},'Accepted tracer layer inventory times dz',common);
    end
    carriers=[{'don','don_transport'};schema.groups];
    for i=1:size(carriers,1)
        for direction={'upward','downward','net_upward'}
            key=['transport_' carriers{i,1} '_' direction{1} '_face_step'];
            register(key,[carriers{i,1} ' effective ' direction{1} ' face exchange'], ...
                'g N cm-2',{'time','node'},'Accepted implicit label transport exchanges', ...
                [common ' Interface amounts, surface-to-bottom face order. ', ...
                'Upward is physically toward the surface; net_upward is signed. ', ...
                'Top faces are zero; DON and mobile particle bottom faces ', ...
                'carry accepted exports when their respective boundary is open. ', ...
                'Includes directed advective and dispersive exchange; not a ', ...
                'separate explicit tracer operator.']);
        end
    end
    for i=1:size(schema.groups,1)
        for process={'attachment','detachment','straining'}
            key=['transport_' schema.groups{i,1} '_' process{1}];
            source=['workspace.fertilizer_n_tracer.bioparticle_transport.' ...
                schema.groups{i,2} '.' process{1} '_g_cm3'];
            comment=[common ' Actual donor-labelled phase transfer: attachment ', ...
                'mobile->attached, detachment attached->mobile, straining ', ...
                'mobile->retained. An internal transfer, not a terminal loss.'];
            register([key '_profile_step'],[key ' gross layer amount per accepted step'], ...
                'g N cm-3',{'time','layer'},source,comment);
            register([key '_step'],[key ' gross column amount per accepted step'], ...
                'g N cm-2',{'time'},source,comment);
        end
    end

    function register(key,label,units,dims,source,comment)
        reg.register(struct('name',['fertilizer_tracer_' key], ...
            'long_name',label,'units',units,'dims',{dims},'group',group, ...
            'source',source,'source_code',code,'transform','none','comment',comment));
    end
end
