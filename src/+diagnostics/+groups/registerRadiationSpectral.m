function registerRadiationSpectral(reg, cfg) %#ok<INUSD>
%REGISTERRADIATIONSPECTRAL  Per-wavelength TOC radiance / SIF / incident (group: radiation_spectral).
%
% Output: data/output_<tag>/radiation_spectral.nc
% Source-of-truth: RTMo (rad.Lo_/Esun_/Esky_) + RTMf (rad.LoF_).
%
% 物理问题 (中文说明):
%   为做"SIF 对红边叶绿素指数 (IMCI) 的污染量化", 需要逐波长保存:
%     - TOC 反射辐亮度 Lo_   (不含 SIF, RTMo)
%     - SIF 辐亮度       LoF_  (RTMf)
%     - 入射太阳/天空    Esun_/Esky_ (归一化成反射因子用)
%   离线: R_pure = Lo_/(Esun+Esky)/π ; R_app = (Lo_+LoF_)/(Esun+Esky)/π
%         IMCI(R_pure) vs IMCI(R_app) 之差 = SIF 对 IMCI 的污染。
%
%   只保存红边段 590-850nm (261 波长), 避免全波段 (2162) 的大内存占用。
%   SCOPE LoF_ 仅在 640-850nm 有值; 590-639nm 段 SIF 写 0 (write-time padding).
%
% Inputs:
%   reg  diagnostics.Registry  registry handle
%   cfg  struct                config (only used to gate on calc_fluor if present)
%
% Note: always registered; if fluorescence is off at run-time, sif_radiance_re
%   simply stays NaN (write-time guard in COMPASS.m skips it). Reflectance and
%   incident bands are still valid without SIF.
%
% Author: Zhu Jizixing 2026-06-02 (IMCI SIF-contamination study)

    g = 'radiation_spectral';

    % Red-edge wavelength grid 590-850 nm, 1 nm step → 261 bins
    n_wl = 261;
    if ~reg.custom_dims.isKey('wl_rededge')
        reg.registerDim('wl_rededge', n_wl);
    end

    reg.register(struct('name','toc_radiance_re', ...
        'long_name','TOC reflected radiance (no SIF), red-edge band 590-850nm', ...
        'units','mW m-2 um-1 sr-1', ...
        'dims',{{'time','wl_rededge'}}, 'group',g, ...
        'source','rad.Lo_(IwlP_re)', ...
        'source_code','src/+surface/+radiation/RTMo.m', ...
        'transform','none', ...
        'comment','IMCI numerator/denominator reflectance source; pair with esun+esky'));

    reg.register(struct('name','sif_radiance_re', ...
        'long_name','SIF emitted radiance, red-edge band 590-850nm (0 below 640nm)', ...
        'units','mW m-2 um-1 sr-1', ...
        'dims',{{'time','wl_rededge'}}, 'group',g, ...
        'source','rad.LoF_ padded onto 590-850nm grid', ...
        'source_code','src/+surface/+radiation/RTMf.m', ...
        'transform','none', ...
        'comment','SCOPE LoF_ spans wlF 640-850nm; 590-639nm padded 0'));

    reg.register(struct('name','esun_re', ...
        'long_name','Incident direct solar irradiance, red-edge band 590-850nm', ...
        'units','mW m-2 um-1', ...
        'dims',{{'time','wl_rededge'}}, 'group',g, ...
        'source','rad.Esun_(IwlP_re)', ...
        'transform','none'));

    reg.register(struct('name','esky_re', ...
        'long_name','Incident diffuse sky irradiance, red-edge band 590-850nm', ...
        'units','mW m-2 um-1', ...
        'dims',{{'time','wl_rededge'}}, 'group',g, ...
        'source','rad.Esky_(IwlP_re)', ...
        'transform','none'));
end
