function registerCarbonFluxes(reg, cfg) %#ok<INUSD>
%REGISTERCARBONFLUXES  Photosynthesis / respiration / GPP / NEE (group: carbon_fluxes).
% Output: data/output_<tag>/carbon_fluxes.nc
% Source-of-truth: SCOPE canopy exchange; final PlantCN/AOM/MEND C ledgers.
% Change: 2026-09-30 Wenjie Liu -- publish actual CO2 owner components.
% Change: 2026-07-18 Jizixing Zhu -- mark ecosystem respiration as
%   unavailable unless the soil-N and PlantCN respiration chain is active.

    g = 'carbon_fluxes';

    reg.register(struct('name','gross_primary_productivity', 'long_name','Gross primary productivity', ...
        'standard_name','gross_primary_productivity_of_biomass_expressed_as_carbon', ...
        'units','kg C m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.GPP', 'transform','scalar', ...
        'comment','With coupled PlantCN, the accepted cumulative GPP increment divided by duration; otherwise SCOPE Actot*12/1e9. Units kg C m-2 s-1.'));
    reg.register(struct('name','net_ecosystem_exchange', 'long_name','Net ecosystem exchange', ...
        'units','kg C m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.NEE', 'transform','scalar', ...
        'comment','NEE = actual PlantCN Ra + actual AOM Rh + actual MEND Rh - actual GPP; positive is a source to the atmosphere.'));
    reg.register(struct('name','assimilation_canopy', 'long_name','Canopy net assimilation', ...
        'units','umol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.Actot', 'transform','scalar'));
    reg.register(struct('name','assimilation_total', 'long_name','Total assimilation (canopy + soil)', ...
        'units','umol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.Atot', 'transform','scalar'));
    reg.register(struct('name','respiration_ecosystem', 'long_name','Ecosystem respiration', ...
        'standard_name','ecosystem_respiration_carbon_flux', ...
        'units','umol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.Resp', 'transform','scalar', ...
        'comment',['Written when lPlantCN=1 and lNefc=1: actual plant Ra + ', ...
        'surface AOM CO2 + MEND IC increment, converted to umol CO2.']))
    components={'Ra_plant','Rh_aom','Rh_mend','Rh','Reco'};
    names={'respiration_plant','respiration_aom','respiration_mend', ...
        'respiration_heterotrophic','respiration_ecosystem_carbon'};
    descriptions={'Actual plant autotrophic respiration', ...
        'Actual direct AOM heterotrophic respiration', ...
        'Actual MEND heterotrophic respiration', ...
        'Actual total heterotrophic respiration','Actual ecosystem respiration as carbon'};
    for j=1:numel(components)
        reg.register(struct('name',names{j},'long_name',descriptions{j}, ...
            'units','kg C m-2 s-1','dims',{{'time'}},'group',g, ...
            'source',['fluxes.' components{j}],'transform','scalar', ...
            'comment','Final accepted owner cumulative increment / actual duration; no empirical soil respiration.'));
    end
    % [Phase C M2-B.1a 2026-05-19] Canopy leaf dark respiration (Rdtot)
    % Used by +vegetation/+nitrogen/computeNPP.m as LPJ R_m,leaf component
    reg.register(struct('name','leaf_dark_respiration', 'long_name','Canopy total leaf dark respiration', ...
        'units','kg C m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.Rd_leaf', 'transform','scalar', ...
        'comment','= GPP - canopy A_net (= Σ LAI × Rd_leaf_per_unit_leaf_area, biochem Ag=A+Rd)'));
    % [gs output 2026-06-13] Canopy-mean leaf stomatal conductance (sunlit/shaded), gs=1/rcw
    %   (biochem_out.rcw). For examining the gs response to T/VPD (e.g. the Medlyn high-T closure).
    %   Leaf-level canopy-mean (mol m-2 s-1 ~ 41.6/rcw), NOT canopy-integrated. Set in ebal_clm45.m.
    reg.register(struct('name','stomatal_conductance_sun', 'long_name','Canopy-mean sunlit leaf stomatal conductance', ...
        'units','mol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.gs_sun', 'transform','scalar', ...
        'comment','gs = 1/rcw (SCOPE biochem stomatal resistance), sunlit leaf canopy-mean'));
    reg.register(struct('name','stomatal_conductance_sha', 'long_name','Canopy-mean shaded leaf stomatal conductance', ...
        'units','mol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.gs_sha', 'transform','scalar', ...
        'comment','gs = 1/rcw (SCOPE biochem stomatal resistance), shaded leaf canopy-mean'));
end
