function registerCanopyAerodynamics(reg, cfg) %#ok<INUSD>
%REGISTERCANOPYAERODYNAMICS  Aerodynamic resistances + surface temperatures (group: canopy_aerodynamics).
% Output: data/output_<tag>/canopy_aerodynamics.nc
% Source-of-truth: SCOPE thermal + ebal

    g = 'canopy_aerodynamics';

    % ---- Temperatures (canopy / soil surface / air) ----
    reg.register(struct('name','air_temperature', 'long_name','Reference air temperature', ...
        'standard_name','air_temperature', 'units','degC', ...
        'dims',{{'time'}}, 'group',g, 'source','thermal.Ta', 'transform','scalar'));
    reg.register(struct('name','soil_surface_temperature_avg', 'long_name','Soil surface temperature (canopy-weighted)', ...
        'units','degC', 'dims',{{'time'}}, 'group',g, 'source','thermal.Tsave', 'transform','scalar'));
    reg.register(struct('name','canopy_temperature_avg', 'long_name','Canopy temperature (LAI-weighted)', ...
        'units','degC', 'dims',{{'time'}}, 'group',g, 'source','thermal.Tcave', 'transform','scalar'));
    reg.register(struct('name','air_density', 'long_name','Air density at reference height', ...
        'standard_name','air_density', 'units','kg m-3', ...
        'dims',{{'time'}}, 'group',g, 'source','thermal.rhoa', 'transform','scalar'));

    % ---- Aerodynamic resistances ----
    reg.register(struct('name','resistance_aa', 'long_name','Aerodynamic resistance (above canopy)', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.raa', 'transform','scalar'));
    reg.register(struct('name','resistance_ah', 'long_name','Aerodynamic resistance (heat)', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.rah', 'transform','scalar'));
    reg.register(struct('name','resistance_aw', 'long_name','Aerodynamic resistance (water vapor)', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.raw', 'transform','scalar'));
    reg.register(struct('name','resistance_canopy_bulk', 'long_name','Canopy bulk resistance', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.rawc', 'transform','scalar'));
    reg.register(struct('name','resistance_soil_aero', 'long_name','Soil aerodynamic resistance', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.raws', 'transform','scalar'));
    reg.register(struct('name','resistance_soil_surface', 'long_name','Soil surface resistance', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.rss', 'transform','scalar'));
    reg.register(struct('name','resistance_leaf_boundary', 'long_name','Leaf boundary layer resistance', ...
        'units','s m-1', 'dims',{{'time'}}, 'group',g, 'source','thermal.rbc', 'transform','scalar'));

    % ---- Friction velocity + roughness ----
    reg.register(struct('name','friction_velocity', 'long_name','Friction velocity', ...
        'standard_name','wind_friction_velocity_at_sea_level', 'units','m s-1', ...
        'dims',{{'time'}}, 'group',g, 'source','thermal.ustar', 'transform','scalar'));
    reg.register(struct('name','roughness_length_momentum', 'long_name','Roughness length (momentum)', ...
        'units','m', 'dims',{{'time'}}, 'group',g, 'source','thermal.zo', 'transform','scalar'));
    reg.register(struct('name','roughness_length_heat', 'long_name','Roughness length (heat)', ...
        'units','m', 'dims',{{'time'}}, 'group',g, 'source','thermal.z0h', 'transform','scalar'));
    reg.register(struct('name','displacement_height', 'long_name','Zero-plane displacement height', ...
        'units','m', 'dims',{{'time'}}, 'group',g, 'source','thermal.d', 'transform','scalar'));

    % ---- Stand structure (kept from thermal_*) ----
    reg.register(struct('name','stem_area_index', 'long_name','Stem area index', ...
        'units','m2 m-2', 'dims',{{'time'}}, 'group',g, 'source','thermal.SAI', 'transform','scalar'));
    reg.register(struct('name','plant_area_index', 'long_name','Plant area index (L + S)', ...
        'units','m2 m-2', 'dims',{{'time'}}, 'group',g, 'source','thermal.L_plus_S', 'transform','scalar'));
    reg.register(struct('name','soil_surface_saturation', 'long_name','Soil surface saturation', ...
        'units','1', 'dims',{{'time'}}, 'group',g, 'source','thermal.Sat_surf', 'transform','scalar', ...
        'comment','Used by ebal soil surface resistance model'));
end
