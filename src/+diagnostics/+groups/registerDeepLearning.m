function registerDeepLearning(reg, cfg) %#ok<INUSD>
%REGISTERDEEPLEARNING  Deep-learning training diagnostics (group: deep_learning).
% Output file: data/output_<tag>/deep_learning.nc
%
% 注意: 这个 group 跟其他 group 不一样——其他 group 是 COMPASS 主循环每 KT 写一行,
% 而 DL group 的"时间轴" = epoch / training step, 而不是 KT.
%
% 实际写入路径不是从 COMPASS.m 调 reg.write, 而是:
%   - tools/deep_learning/warmstart/train_transolver.py 训练完后导出 JSON
%   - 后处理脚本读 JSON, 调 reg.write 把 epoch metrics 写进 NetCDF
%
% 时间维度: 用 'epoch' (custom dim, 训练时声明 size = N_epochs)
%
% Author: Zhu Jizixing, 2026-05-15

    g = 'deep_learning';

    % Declare 'epoch' as a custom dimension. Caller (Python side) decides size.
    if ~reg.custom_dims.isKey('epoch')
        reg.registerDim('epoch', 1);   % placeholder; overridden at write-time
    end

    % ---- 训练 loss (核心 PINO 训练目标) ----
    reg.register(struct('name','train_loss_total', ...
        'long_name','Total training loss per epoch', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py epoch summary', ...
        'comment','L_total = L_supervised + λ_pino × L_pino + λ_noharm × L_noharm'));

    reg.register(struct('name','train_loss_supervised', ...
        'long_name','Supervised MSE loss', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','train_loss_pino', ...
        'long_name','PINO Richards residual loss', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','||A·hh_pred - RHS||² from COMPASS linear residual or Python Richards form'));

    reg.register(struct('name','val_loss_total', ...
        'long_name','Validation total loss', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ---- 验证集物理指标 (warm-start 实际用) ----
    reg.register(struct('name','val_rmse_h_cm', ...
        'long_name','RMSE of predicted hh on validation set', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','val_kge_h', ...
        'long_name','Kling-Gupta Efficiency on validation hh', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','KGE = 1 - sqrt((r-1)² + (α-1)² + (β-1)²); perfect=1'));

    reg.register(struct('name','val_kge_r', ...
        'long_name','KGE correlation component', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','val_kge_alpha', ...
        'long_name','KGE variability ratio σ_pred/σ_true', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','val_kge_beta', ...
        'long_name','KGE bias ratio μ_pred/μ_true', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ---- Hard-event 子集指标 (Jizixing Zhu 加的) ----
    reg.register(struct('name','val_hard_rmse_h_cm', ...
        'long_name','RMSE on hard transition events (rain/freeze-thaw/dry-down)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','Top-10% RMSE samples; classifier in tools/deep_learning/warmstart/train_transolver.py'));

    reg.register(struct('name','val_noharm_rmse_h_cm', ...
        'long_name','No-harm RMSE on stable periods (|Δh| < threshold)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','Measures whether model "damages" stable periods that need no correction'));

    % ---- δh 目标 RMSE (训练的真实优化目标, h-space 的导数) ----
    reg.register(struct('name','val_target_rmse', ...
        'long_name','RMSE of predicted target (delta_h or delta_log_suction)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py row.val_target_rmse', ...
        'comment','Direct optimization target; val_rmse_h_cm is its h-space projection'));

    reg.register(struct('name','test_target_rmse', ...
        'long_name','RMSE of predicted target on held-out test set', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py row.test_target_rmse'));

    % ---- MAE 补充 (h-space, 跟 RMSE 配套看 outlier 影响) ----
    reg.register(struct('name','val_mae_h_cm', ...
        'long_name','MAE of predicted hh on validation set', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py row.val_mae_h_cm'));

    reg.register(struct('name','test_rmse_h_cm', ...
        'long_name','RMSE of predicted hh on test set', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py row.test_rmse_h_cm'));

    reg.register(struct('name','test_mae_h_cm', ...
        'long_name','MAE of predicted hh on test set', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py row.test_mae_h_cm'));

    % ---- vs default baseline 改进率 (warm-start 是否真"赚"了的核心指标) ----
    reg.register(struct('name','val_rmse_improvement_vs_default_pct', ...
        'long_name','Val RMSE improvement vs default h(t) initial guess', ...
        'units','%', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','100*(1 - rmse_model/rmse_default); positive = model beats default'));

    reg.register(struct('name','test_rmse_improvement_vs_default_pct', ...
        'long_name','Test RMSE improvement vs default h(t)', ...
        'units','%', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ---- δh clamp 上限 (训练集 percentile, 防止 NN 输出极端 δh) ----
    reg.register(struct('name','delta_limit_target', ...
        'long_name','Per-epoch delta clamp limit (training-set percentile)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'source','train_transolver.py row.delta_limit_target', ...
        'comment','Predicted target delta clipped by this percentile before h-space eval'));

    % ---- No-harm p95 (稳定期 |Δh_pred| 95 分位, 衡量"破坏稳定期"程度) ----
    reg.register(struct('name','val_noharm_pred_p95_abs_h_cm', ...
        'long_name','Val no-harm pred |Δh| p95 (on stable periods)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','test_noharm_rmse_h_cm', ...
        'long_name','Test no-harm RMSE on stable periods', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','test_noharm_pred_p95_abs_h_cm', ...
        'long_name','Test no-harm pred |Δh| p95', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ---- Hard-event 样本数 + baseline RMSE (与 val_hard_rmse 配对) ----
    reg.register(struct('name','val_hard_n', ...
        'long_name','Hard-event sample count in val set', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','val_hard_default_rmse_h_cm', ...
        'long_name','Default-init RMSE on val hard events (baseline for improvement)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','test_hard_n', ...
        'long_name','Hard-event sample count in test set', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','test_hard_rmse_h_cm', ...
        'long_name','Model RMSE on test hard events', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','test_hard_default_rmse_h_cm', ...
        'long_name','Default-init RMSE on test hard events', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','val_hard_improvement_vs_default_pct', ...
        'long_name','Val hard-event RMSE improvement vs default', ...
        'units','%', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','test_hard_improvement_vs_default_pct', ...
        'long_name','Test hard-event RMSE improvement vs default', ...
        'units','%', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ---- Checkpoint selection score (越小越好; 综合 val + hard + noharm 风险) ----
    reg.register(struct('name','selection_score', ...
        'long_name','Composite checkpoint selection score', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','score = val_rmse + w_hard*val_hard_rmse + w_noharm*val_noharm_rmse + w_p95*max(0, p95-thr)'));

    reg.register(struct('name','selection_noharm_p95_excess_cm', ...
        'long_name','No-harm p95 excess above threshold (penalty term)', ...
        'units','cm', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ---- Checkpoint metadata (scalar attrs, one per training run) ----
    reg.register(struct('name','best_epoch', ...
        'long_name','Epoch index of best checkpoint', ...
        'units','1', 'dims',{{'epoch'}}, 'group',g, 'transform','none', ...
        'comment','Stored as time series so we can see when it crystallised; identical value after best_epoch'));

    reg.register(struct('name','train_duration_s', ...
        'long_name','Cumulative training time', ...
        'units','s', 'dims',{{'epoch'}}, 'group',g, 'transform','none'));

    % ===================================================================
    % 留位 (将来加): per-batch loss / gradient norm / lr schedule /
    %                Picard speedup factor / residual gate hit rate
    % ===================================================================
end
