function registerSoilAir(reg, cfg)
%REGISTERSOILAIR  Soil dry air pressure (group: soil_air).
% Only when cfg.lSoilairefc == 1.
% Output: data/output_<tag>/soil_air.nc
% Editor: Jizixing Zhu; Date: 2026-07-15.
% Change: 2026-07-15 Jizixing Zhu -- register accepted top and bottom dry-air
%         mass fluxes using the public inward-positive convention.
% Change: 2026-07-15 Jizixing Zhu -- point pressure and flux metadata at the
%         active U-primary state and complete coupled boundary reaction.
% Change: 2026-07-16 Jizixing Zhu -- register the accepted dry-air column
%         mass, boundary inputs, and discrete conservation residual.

    if ~helpers.isfield_or_prop_true(cfg, 'lSoilairefc')
        return;
    end
    g = 'soil_air';

    reg.register(struct('name', 'air_pressure', ...
        'long_name', 'Soil air pressure', ...
        'standard_name', 'air_pressure', ...
        'units', 'Pa', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'Y.p_gas', ...
        'source_code', 'src/+solver/attemptSolveSoilEquations.m', ...
        'transform', 'none', ...
        'comment', ['Total soil-gas pressure used by the dry-air mass ', ...
                    'balance; not the dry-air partial pressure.']));

    reg.register(struct('name', 'top_dry_air_mass_flux', ...
        'long_name', 'Dry-air mass flux entering through the soil surface', ...
        'units', 'g cm-2 s-1', 'dims', {{'time'}}, 'group', g, ...
        'source', 'workspace.flux.soil_boundary_hourly.dry_air.top_flux_into_domain', ...
        'source_code', 'src/+soil/+gas/calculateCoupledBoundaryFlux.m', ...
        'transform', 'scalar', ...
        'comment', 'Positive into the soil domain.'));
    reg.register(struct('name', 'bottom_dry_air_mass_flux', ...
        'long_name', 'Dry-air mass flux entering through the bottom boundary', ...
        'units', 'g cm-2 s-1', 'dims', {{'time'}}, 'group', g, ...
        'source', 'workspace.flux.soil_boundary_hourly.dry_air.bottom_flux_into_domain', ...
        'source_code', 'src/+soil/+gas/calculateCoupledBoundaryFlux.m', ...
        'transform', 'scalar', ...
        'comment', 'Positive into the soil domain.'));

    registerColumnMass(reg, 'soil_dry_air_mass', ...
        'Soil-column dry-air mass', 'soil_air');
    registerColumnMass(reg, 'soil_dry_air_mass_change', ...
        'Accepted-step change in soil-column dry-air mass', 'soil_air');
    registerColumnMass(reg, 'soil_dry_air_top_input', ...
        'Dry-air mass entering through the top boundary', 'soil_air');
    registerColumnMass(reg, 'soil_dry_air_bottom_input', ...
        'Dry-air mass entering through the bottom boundary', 'soil_air');
    registerColumnMass(reg, 'soil_dry_air_boundary_net_input', ...
        'Net boundary dry-air mass entering the soil column', 'soil_air');
    registerColumnMass(reg, 'soil_dry_air_mass_balance_residual', ...
        'Soil dry-air mass conservation residual', 'conservation');
end

function registerColumnMass(reg, name, longName, group)
% Register one scalar accepted-step dry-air mass diagnostic [g m^-2].
% Editor: Jizixing Zhu; Date: 2026-07-16.
    reg.register(struct('name', name, 'long_name', longName, ...
        'units', 'g m-2', 'dims', {{'time'}}, 'group', group, ...
        'source', 'workspace.flux.soil_dry_air_mass_balance', ...
        'source_code', 'src/+soil/+gas/computeColumnMassBalance.m', ...
        'transform', 'scalar', ...
        'comment', 'Positive boundary terms enter the soil column.'));
end
