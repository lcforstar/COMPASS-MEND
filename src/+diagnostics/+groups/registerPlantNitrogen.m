    %   theta = resp_theta_actual (= actual R_m / potential R_m, incl nodebt cap). These close on the SAME
    %   basis as autotrophic_respiration / NEE / Reco / plant C conservation, unlike the *potential*
    %   maintenance_respiration_* diagnostics below (which are the pre-turn-down organ R_m).
    reg.register(struct('name','r_m_leaf_actual','long_name','Leaf maintenance respiration ACTUAL (theta*potential)','units','kg m-2 s-1','dims',{{'time'}},'group',g,'source','NitrogenVariables.plantN_diag(KT).r_m_leaf_actual','transform','scalar'));
