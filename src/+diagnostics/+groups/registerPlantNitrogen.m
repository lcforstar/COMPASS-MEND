    reg.register(struct('name','ra_above_actual','long_name','Aboveground autotrophic respiration ACTUAL (leaf+stem+fruit Rm*theta + R_g)','units','kg m-2 s-1','dims',{{'time'}},'group',g,'source','NitrogenVariables.plantN_diag(KT).ra_above_actual','transform','scalar'));
    reg.register(struct('name','ra_below_actual','long_name','Belowground autotrophic respiration ACTUAL (root+livecroot Rm*theta)','units','kg m-2 s-1','dims',{{'time'}},'group',g,'source','NitrogenVariables.plantN_diag(KT).ra_below_actual','transform','scalar'));
    reg.register(struct('name','resp_theta_actual','long_name','Effective maintenance throttle = actual R_m / potential R_m (incl nodebt cap; >=0, 1=none, <1 turn-down, >1 under substitution schemes e.g. jones; organ-actual split closes exactly)','units','1','dims',{{'time'}},'group',g,'source','NitrogenVariables.nsc_diag(KT).resp_theta_actual','transform','scalar'));

    reg.register(struct('name','maintenance_respiration_leaf', ...
        'long_name','Leaf maintenance respiration (Farquhar Rd, from SCOPE biochem)', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).R_m_leaf', ...
        'transform','scalar'));

    reg.register(struct('name','maintenance_respiration_root', ...
        'long_name','Fine-root maintenance respiration (LPJ Q10, T_soil-driven)', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).R_m_root', ...
        'transform','scalar'));

    reg.register(struct('name','maintenance_respiration_stem', ...
        'long_name','Stem/wood maintenance respiration (LPJ Q10, T_air-driven)', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).R_m_stem', ...
        'transform','scalar'));

