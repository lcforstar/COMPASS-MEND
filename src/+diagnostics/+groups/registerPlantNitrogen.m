        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).R_m_livecroot', ...
        'transform','scalar'));

    reg.register(struct('name','maintenance_respiration_fruit', ...
        'long_name','Fruit maintenance respiration (LPJ Q10, T_air-driven, perennial fruit trees)', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).R_m_fruit', ...
        'transform','scalar'));

