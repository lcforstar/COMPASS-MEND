    reg.register(struct('name','plant_n_livestem', ...
        'long_name','Live stem N pool (live wood, respires; 0 for annual/grass PFTs)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.N_livestem(KT)', ...
        'transform','scalar'));

    reg.register(struct('name','plant_n_deadstem', ...
        'long_name','Dead stem N pool (heartwood, ~N-free; 0 for annual/grass PFTs)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.N_deadstem(KT)', ...
        'transform','scalar'));

    reg.register(struct('name','plant_n_fruit', ...
        'long_name','Fruit/seed N pool (DOY 150-290 growing season)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.N_fruit(KT)', ...
        'transform','scalar'));

    % ---- C fluxes: NPP and component respiration [kg C m-2 s-1] ----
    reg.register(struct('name','net_primary_productivity', ...
        'long_name','Net primary productivity ACTUAL, clamped >=0 = max(GPP - R_a_actual, 0) (substrate-throttled basis, closes with autotrophic_respiration/NEE/Reco)', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).NPP', ...
        'source_code','src/+vegetation/+nitrogen/computeNPP.m', ...
        'transform','scalar'));

