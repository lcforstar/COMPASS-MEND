        'long_name','N allocated to leaf this KT', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).A_leaf', ...
        'transform','scalar'));

    reg.register(struct('name','plant_n_alloc_root', ...
        'long_name','N allocated to fine-root this KT', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).A_root', ...
