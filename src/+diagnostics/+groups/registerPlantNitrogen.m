        'units','g m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.cum_N_root_litter', 'transform','scalar'));

    % [prune/mortality diag 2026-06-14] N counterparts of the woody-litter outflows in
    %   plant_n_residual (COMPASS.m:2712-2713); see cum_c_prune_litter / cum_c_mortality above.
    reg.register(struct('name','cum_n_prune_litter', ...
        'long_name','Cumulative N to pruning woody-litter (M3 SOM/CWD 入口)', ...
