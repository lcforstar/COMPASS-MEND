function registerPlantNitrogen(reg, cfg)
%REGISTERPLANTNITROGEN  Plant N pools + NPP/respiration diagnostics (group: plant_nitrogen).
%
% Phase C M2-B.1b (2026-05-19): 5 prognostic organ pools + 11 NPP/allocation diag.
% Output: data/output_<tag>/plant_nitrogen.nc
% Source-of-truth: src/+vegetation/+nitrogen/{computeNPP, computeOrganDemand, allocatePlantN}.m
%
% Only when cfg.lNefc == 1.

    if ~helpers.isfield_or_prop_true(cfg, 'lNefc')
        return;
    end
    g = 'plant_nitrogen';

    % ---- 5 prognostic organ N pools [g N/m²] (end-of-KT value) ----
    reg.register(struct('name','plant_n_labile', ...
        'long_name','Plant labile N pool (transient supply, DAISY luxury-threshold)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.N_labile(KT)', ...
        'source_code','src/+vegetation/+nitrogen/allocatePlantN.m', ...
        'transform','scalar'));

    reg.register(struct('name','plant_n_leaf', ...
        'long_name','Leaf N pool (LUNA feedback driver, M2-B.3)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.N_leaf(KT)', ...
        'transform','scalar'));

    reg.register(struct('name','plant_n_root_fine', ...
        'long_name','Fine-root N pool', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.N_root_fine(KT)', ...
        'transform','scalar'));

