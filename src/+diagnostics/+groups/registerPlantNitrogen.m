    % The clamped NPP above drops night/winter deficits and biases the annual sum.
    reg.register(struct('name','npp_net', ...
        'long_name','Net primary productivity ACTUAL unclamped = GPP - R_a_actual (may be negative; for true CUE in the substrate-throttled basis)', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).NPP_net', ...
        'source_code','src/+vegetation/+nitrogen/computeNPP.m', ...
        'transform','scalar'));

