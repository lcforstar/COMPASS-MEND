        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).A_stem', ...
        'transform','scalar'));

    reg.register(struct('name','plant_n_alloc_fruit', ...
        'long_name','N allocated to fruit this KT (active during DOY 150-290 for apple)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).A_fruit', ...
        'transform','scalar'));

    % --- [v8 2026-05-29] C 各器官分配 (NPP×f_alloc, fruit gate DOY 150-290; computeCarbonAllocation) ---
    reg.register(struct('name','plant_c_alloc_leaf', ...
        'long_name','C allocated to leaf this KT', ...
