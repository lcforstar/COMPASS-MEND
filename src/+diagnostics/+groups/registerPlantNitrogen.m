        'dims',{{'time'}}, 'group',g, ...
        'source','luna_state.Jmax25_z(1)', ...
        'transform','scalar'));

    reg.register(struct('name','luna_fnca', ...
        'long_name','Functional N per leaf area (FNCa, = leaf N - structural N)', ...
        'units','g m-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','lunaOut.FNCa_z(1)', ...
        'transform','scalar', ...
        'comment','CLM5 LunaMod.F90:Eq.44 (Ali 2016 GMD 9:587)'));

    reg.register(struct('name','luna_pnlc', ...
        'long_name','LUNA light-capture N proportion (PNlc, optimization variable)', ...
        'units','1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','lunaOut.PNlc_z(1)', ...
        'transform','scalar'));

    reg.register(struct('name','luna_pncb', ...
        'long_name','LUNA carboxylation N proportion (PNcb = N_cb/FNCa, determines Vcmax25)', ...
        'units','1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','lunaOut.PNcb_z(1)', ...
        'transform','scalar'));

