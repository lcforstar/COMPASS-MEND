        'long_name','Growth respiration (R_g = R_g_fraction × max(GPP-R_m, 0))', ...
        'units','kg m-2 s-1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).R_g', ...
        'transform','scalar'));

    % ---- N allocation diag (kg N/m² for this KT) ----
    reg.register(struct('name','plant_n_growth_factor', ...
        'long_name','N-limited growth factor (0=N-starved, 1=N-replete)', ...
        'units','1', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.plantN_diag(KT).f_N_growth', ...
        'source_code','src/+vegetation/+nitrogen/allocatePlantN.m', ...
        'transform','scalar'));

