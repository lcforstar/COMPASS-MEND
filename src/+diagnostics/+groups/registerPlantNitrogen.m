    reg.register(struct('name','cab_from_nlc', ...
        'long_name','Leaf chlorophyll Cab from LUNA dynamic light-capture N (N_lc 50:1)', ...
        'units','ug cm-2', ...
        'dims',{{'time'}}, 'group',g, ...
        'source','NitrogenVariables.luna_last_Cab_nlc', ...
        'source_code','src/+vegetation/+integrated/+LUNA/nLeafToCab.m', ...
        'transform','scalar', ...
        'comment','Evans 1989 Oecologia 78:9 p.12 (50 mol thylakoid N/mol Chl); carries LUNA N-allocation signal'));

    % --- [M2-B.4 2026-05-21] Turnover + Harvest + N_storage diagnostics (9 fields) ---
    reg.register(struct('name','plant_n_storage', ...
        'long_name','Seasonal N storage pool, total (root+stem; perennials only)', ...
        'units','g m-2', 'dims',{{'time'}}, 'group',g, ...
