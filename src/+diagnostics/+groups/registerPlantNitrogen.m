    % --- [M2-B.8 2026-05-21] Plant C 6 池 + cum_C diagnostics (11 fields) ---
    reg.register(struct('name','plant_c_labile', ...
        'long_name','Plant labile C pool (NSC, Non-Structural Carbohydrates)', ...
