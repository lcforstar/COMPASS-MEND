function registerSoilOxygen(reg, cfg)
%REGISTERSOILOXYGEN  O2 transport + aerobic/anaerobic fraction (group: soil_oxygen).
% Only when cfg.lNefc == 1 (O2 is solved as part of the N coupling pipeline).
% Output: data/output_<tag>/soil_oxygen.nc
% Source-of-truth: src/+soil/+gas/solveO2Transport.m, calcO2Sink.m
% Change: 2026-10-23 Wenjie Liu -- register accepted gas-on O2 state and
%   exact replay sink; correct retired field sources and equation metadata.

    if ~helpers.isfield_or_prop_true(cfg, 'lNefc') ...
            || ~helpers.isfield_or_prop_true(cfg, 'lSoilairefc')
        return;
    end
    g = 'soil_oxygen';

    reg.register(struct('name','o2_concentration', 'long_name','Soil O2 concentration', ...
        'units','mol m-3', 'dims',{{'time','node'}}, 'group',g, ...
        'source','Y.soil_gas.C_O2 * 1e6', ...
        'source_code','src/+soil/+gas/solveO2Transport.m', ...
        'transform','none', ...
        'comment','Derived gas concentration from accepted dry mole fraction; typed O2 boundaries'));

    reg.register(struct('name','aerobic_fraction', 'long_name','Aerobic micro-site fraction', ...
        'units','1', 'dims',{{'time','node'}}, 'group',g, ...
        'source','Y.soil_nitrogen.variables.f_aerobic', ...
        'source_code','src/+soil/+gas/solveO2Transport.m', ...
        'transform','edge_to_node_reversed_layer', ...
        'comment','Accepted-tile dt mean driving nitrification; 1 = fully aerobic'));

    reg.register(struct('name','anaerobic_fraction', 'long_name','Anaerobic micro-site fraction', ...
        'units','1', 'dims',{{'time','node'}}, 'group',g, ...
        'source','Y.soil_nitrogen.variables.f_anaerobic', ...
        'transform','edge_to_node_reversed_layer', ...
        'comment','Drives denitrification rate; = 1 - aerobic_fraction'));

    reg.register(struct('name','soil_gas_phase_fraction', 'long_name','Soil gas phase volumetric fraction', ...
        'units','m3 m-3', 'dims',{{'time','node'}}, 'group',g, ...
        'source','Y.soil_gas.oxygen_phase.theta_gas', ...
        'source_code','src/+soil/+gas/captureOxygenPhase.m', ...
        'transform','edge_to_node_reversed_layer', ...
        'comment','θ_air = POR - Theta_LL - Theta_II'));

    reg.register(struct('name','o2_sink_total', 'long_name','O2 sink (nitrification + heterotrophic respiration)', ...
        'units','mol m-3 s-1', 'dims',{{'time','node'}}, 'group',g, ...
        'source','workspace.nitrogen.oxygen.actual_sink_mol_cm3_s * 1e6', ...
        'source_code','src/+soil/+gas/calcO2Sink.m', ...
        'transform','edge_to_node_reversed_layer', ...
        'comment','Actually applied accepted-tile mean O2 sink: original nitrification plus same-hour respiratory C'));
end
