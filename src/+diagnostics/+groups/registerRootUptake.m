function registerRootUptake(reg, cfg) %#ok<INUSD>
%REGISTERROOTUPTAKE  Root water uptake + hydraulic lift (group: root_uptake).
% Output: data/output_<tag>/root_uptake.nc
    g = 'root_uptake';

    reg.register(struct('name','water_uptake_profile', 'long_name','Root water uptake (per layer)', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, 'transform','none', ...
        'comment','Negative downward; sum of layers ≈ Transpiration'));

    reg.register(struct('name','rwu_pos_profile', 'long_name','Positive RWU (per layer)', ...
        'units','mm h-1', 'dims',{{'time','layer'}}, 'group',g, 'transform','none'));
    reg.register(struct('name','rwu_neg_profile', 'long_name','Negative RWU (hydraulic lift)', ...
        'units','mm h-1', 'dims',{{'time','layer'}}, 'group',g, 'transform','none'));

    reg.register(struct('name','hydraulic_lift_pos', 'long_name','Positive hydraulic lift (column total)', ...
        'units','mm h-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','hydraulic_lift_net', 'long_name','Net hydraulic lift', ...
        'units','mm h-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','hydraulic_lift_intensity', 'long_name','Hydraulic lift intensity index', ...
        'units','1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','root_sink_srt_pos', 'long_name','Srt positive component (Σ)', ...
        'units','mm h-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','root_sink_srt_neg', 'long_name','Srt negative component (Σ)', ...
        'units','mm h-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','root_sink_srt_net', 'long_name','Srt net (Σ)', ...
        'units','mm h-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','root_sink_minus_transpiration', 'long_name','Srt - Transpiration (closure check)', ...
        'units','mm h-1', 'dims',{{'time'}}, 'group','conservation', 'transform','scalar'));
end
