function registerCanopyProfiles(reg, cfg) %#ok<INUSD>
%REGISTERCANOPYPROFILES  Vertical profiles inside the canopy (group: canopy_profiles).
% Output: data/output_<tag>/canopy_profiles.nc
% Source-of-truth: SCOPE profiles + thermal.{Ta_layer, ea_layer, ...}
%
% Canopy is discretized into 30 layers (SCOPE convention). Each variable has
% dimensions (time, canopy_layer = 30).

    g = 'canopy_profiles';

    % Declare canopy_layer dim if not yet registered (SCOPE uses 30 by default)
    if ~reg.custom_dims.isKey('canopy_layer')
        reg.registerDim('canopy_layer', 30);
    end

    % ---- Microclimate inside canopy ----
    reg.register(struct('name','air_temperature_layer', 'long_name','Air temperature per canopy layer', ...
        'units','degC', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Ta_layer', 'transform','none'));
    reg.register(struct('name','vapor_pressure_layer', 'long_name','Vapor pressure per canopy layer', ...
        'units','hPa', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.ea_layer', 'transform','none'));
    reg.register(struct('name','co2_layer', 'long_name','CO2 mixing ratio per canopy layer', ...
        'units','umol mol-1', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.CO2_layer', 'transform','none'));
    reg.register(struct('name','eddy_diffusivity_layer', 'long_name','Eddy diffusivity per canopy layer', ...
        'units','m2 s-1', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Kh_layer', 'transform','none'));

    % ---- Leaf state per layer ----
    reg.register(struct('name','leaf_temperature_layer', 'long_name','Leaf temperature per canopy layer', ...
        'units','degC', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Tleaf_layer', 'transform','none'));
    reg.register(struct('name','canopy_temperature_layer', 'long_name','Canopy element T per layer', ...
        'units','degC', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Tch', 'transform','none'));

    % ---- LAI / weights ----
    reg.register(struct('name','lai_layer', 'long_name','Leaf area index per canopy layer', ...
        'units','m2 m-2', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.LAI_layer', 'transform','none'));
    reg.register(struct('name','layer_weight', 'long_name','Vertical weight for canopy averaging', ...
        'units','1', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.layer_weight', 'transform','none'));

    % ---- Photosynthesis / fluorescence per layer ----
    reg.register(struct('name','net_photosynthesis_layer', 'long_name','Net photosynthesis per canopy layer', ...
        'units','umol m-2 s-1', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Pn1d', 'transform','none'));
    reg.register(struct('name','net_photosynthesis_cab_layer', 'long_name','Pn × Cab share per layer', ...
        'units','umol m-2 s-1', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Pn1d_Cab', 'transform','none'));
    reg.register(struct('name','sensible_heat_layer', 'long_name','Sensible heat per canopy layer', ...
        'units','W m-2', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.Hc1d', 'transform','none'));
    reg.register(struct('name','latent_heat_layer', 'long_name','Latent heat per canopy layer', ...
        'units','W m-2', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.lEc1d', 'transform','none'));
    reg.register(struct('name','assimilation_layer', 'long_name','Assimilation per canopy layer', ...
        'units','umol m-2 s-1', 'dims',{{'time','canopy_layer'}}, 'group',g, ...
        'source','profiles.A1d', 'transform','none'));

    % ---- Tcave summary scalar (compatibility w/ ebal_*) ----
    reg.register(struct('name','canopy_avg_temperature_3d', ...
        'long_name','Canopy average temperature (Tchave)', ...
        'units','degC', 'dims',{{'time'}}, 'group',g, ...
        'source','profiles.Tchave', 'transform','scalar'));
end
