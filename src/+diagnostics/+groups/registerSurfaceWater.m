function registerSurfaceWater(reg, cfg) %#ok<INUSD>
%REGISTERSURFACEWATER  Canonical atmospheric and soil-water boundary outputs.
% Output: data/output_<tag>/surface_water.nc
%
% Rates use [cm s-1]; accepted-step amounts use [mm]. Public water fluxes
% have one sign convention: positive into the soil for top/bottom soil flux,
% and positive away from the surface for runoff. The removed legacy names
% infiltration_potential/infiltration_actual/top_mass_flux mixed potential,
% clipped, and signed interface quantities and are not registered here.
%
% Editor: Jizixing Zhu; Date: 2026-07-17.
% Change: 2026-07-17 Jizixing Zhu -- replace ambiguous infiltration aliases
%         and mislabeled rate/amount pairs with one canonical boundary schema.
% Change: 2026-07-17 Jizixing Zhu -- document the automatic dry-head
%         evaporation-limited state in the public boundary code.
% Change: 2026-07-17 Jizixing Zhu -- define mode 3 by residual-water state rather
%         than an unconditional hcrit threshold.
    g = 'surface_water';

    registerRateAmount(reg, g, 'precipitation', ...
        'Atmospheric precipitation before canopy and snow partition');
    registerRateAmount(reg, g, 'surface_liquid_water_supply', ...
        'Post-canopy and post-snow liquid water delivered to the surface');
    registerRateAmount(reg, g, 'wet_canopy_evaporation', ...
        'Net wet-canopy evaporation; negative values denote dew deposition');
    registerRateAmount(reg, g, 'soil_top_water', ...
        'Solved water exchange through the soil surface; positive into soil');
    registerRateAmount(reg, g, 'soil_bottom_water', ...
        'Solved water exchange through the lower soil boundary; positive into soil');
    registerRateAmount(reg, g, 'surface_runoff', ...
        'Capacity-overflow runoff leaving the surface reservoir');

    reg.register(struct('name','surface_water_storage', ...
        'long_name','Accepted retained liquid surface-water depth', ...
        'units','cm', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','surface_water_storage_change', ...
        'long_name','Accepted-step change in retained surface water', ...
        'units','mm', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','surface_pressure_head', ...
        'long_name','Mean top-node pressure head', 'units','cm', ...
        'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'comment','Accepted-substep time mean; positive head is retained pond depth'));
    reg.register(struct('name','surface_water_available_flux', ...
        'long_name','Mean gross surface-water availability', 'units','cm s-1', ...
        'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'comment','Liquid supply plus accepted substep-start storage divided by substep dt'));
    reg.register(struct('name','surface_boundary_mode', ...
        'long_name','Final accepted surface active-set code', 'units','1', ...
        'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'comment',['0=supply_limited, 1=storage, 2=capacity_limited, ', ...
                   '3=residual-water dry_evaporation_limited']));
    reg.register(struct('name','surface_mass_residual_max', ...
        'long_name','Maximum absolute surface-reservoir mass residual', ...
        'units','cm', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
    reg.register(struct('name','surface_lower_complementarity_residual_max', ...
        'long_name','Maximum pond-contact complementarity product', ...
        'units','cm2', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'comment','max abs(DSTOR*(DSTOR-psi_top)) over accepted substeps'));
    reg.register(struct('name','surface_upper_complementarity_residual_max', ...
        'long_name','Maximum overflow-capacity complementarity product', ...
        'units','cm2 s-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'comment','max abs(runoff*(DSTMAX-DSTOR)) over accepted substeps'));
end

function registerRateAmount(reg, group, prefix, longName)
% Register one unambiguous rate [cm s-1] and accepted-step amount [mm].
% Editor: Jizixing Zhu; Date: 2026-07-17.
    reg.register(struct('name',[prefix '_flux'], ...
        'long_name',[longName ' flux'], 'units','cm s-1', ...
        'dims',{{'time'}}, 'group',group, 'transform','scalar'));
    reg.register(struct('name',[prefix '_amount'], ...
        'long_name',[longName ' amount'], 'units','mm', ...
        'dims',{{'time'}}, 'group',group, 'transform','scalar', ...
        'comment','Time integral over the accepted outer step.'));
end
