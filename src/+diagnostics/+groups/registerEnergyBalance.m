function registerEnergyBalance(reg, cfg) %#ok<INUSD>
%REGISTERENERGYBALANCE  Surface energy balance components (group: energy_balance).
% Output: data/output_<tag>/energy_balance.nc
% Source-of-truth: SCOPE ebal + fluxes struct
%
% This is the paper-standard "Rn = LE + H + G" closure quartet. Migrated from
% Scope_output.fluxes_* (which had 22 mixed fields) into a focused group.
% Editor: Jizixing Zhu; Date: 2026-07-18.
% Change: 2026-07-18 Jizixing Zhu -- publish explicit bare/snow tile
%   temperatures and grid-contribution Rn/H/LE/qv/G contracts.
% Change: 2026-07-19 Jizixing Zhu -- distinguish the physical bare-ground
%   external-energy response from SCOPE's empirical force-restore predictor.

    g = 'energy_balance';

    % ---- Total components (paper headlines) ----
    reg.register(struct('name','land_surface_upward_latent_heat_flux', ...
        'long_name','Land-surface upward latent heat flux', ...
        'standard_name','surface_upward_latent_heat_flux', 'units','W m-2', ...
        'dims',{{'time'}}, 'group',g, 'source','fluxes.lEtot', 'transform','scalar'));
    reg.register(struct('name','land_surface_upward_sensible_heat_flux', ...
        'long_name','Land-surface upward sensible heat flux', ...
        'standard_name','surface_upward_sensible_heat_flux', 'units','W m-2', ...
        'dims',{{'time'}}, 'group',g, 'source','fluxes.Htot', 'transform','scalar'));
    reg.register(struct('name','soil_top_downward_energy_flux', ...
        'long_name','Total energy flux entering the shared soil column', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.soil_top_downward_energy_flux_W_m2', ...
        'transform','scalar', 'comment','Positive downward into soil.'));
    reg.register(struct('name','bare_ground_external_energy_flux', ...
        'long_name','Bare-ground external energy available to the soil surface', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.bare_ground_external_energy_flux_W_m2', ...
        'transform','scalar', 'comment', ...
        ['Per unit bare-ground area; net radiation minus upward sensible ', ...
         'and latent heat. This is the physical soil-boundary driver.']));
    reg.register(struct( ...
        'name','bare_ground_external_energy_flux_temperature_sensitivity', ...
        'long_name','Temperature derivative of bare-ground external energy flux', ...
        'units','W m-2 K-1', 'dims',{{'time'}}, 'group',g, ...
        'source', ...
        'fluxes.bare_ground_external_energy_flux_temperature_derivative_W_m2_K', ...
        'transform','scalar'));
    reg.register(struct('name','scope_empirical_bare_ground_heat_flux', ...
        'long_name','SCOPE empirical bare-ground heat-flux predictor', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.scope_empirical_bare_ground_heat_flux_W_m2', ...
        'transform','scalar', 'comment', ...
        ['Force-restore predictor used inside SCOPE ebal; diagnostic only ', ...
         'and never imposed as the production soil heat boundary.']));
    reg.register(struct('name','soil_top_energy_flux_reference', ...
        'long_name','Reference flux of the affine soil-top energy boundary', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.soil_top_energy_flux_reference_W_m2', ...
        'transform','scalar', 'comment','Positive downward into soil.'));

    registerTileFlux(reg, g, 'bare_ground_net_radiation_flux_contribution', ...
        'Bare-ground contribution to grid net downward radiation', ...
        'fluxes.bare_ground_net_radiation_contribution_W_m2', 'downward');
    registerTileFlux(reg, g, 'snow_net_radiation_flux_contribution', ...
        'Snow-covered contribution to grid net downward radiation', ...
        'fluxes.snow_net_radiation_contribution_W_m2', 'downward');
    registerTileFlux(reg, g, 'bare_ground_upward_latent_heat_flux_contribution', ...
        'Bare-ground contribution to grid upward latent heat', ...
        'fluxes.bare_ground_upward_latent_heat_flux_contribution_W_m2', 'upward');
    registerTileFlux(reg, g, 'snow_upward_latent_heat_flux_contribution', ...
        'Snow-covered contribution to grid upward latent heat', ...
        'fluxes.snow_upward_latent_heat_flux_contribution_W_m2', 'upward');
    registerTileFlux(reg, g, 'bare_ground_upward_sensible_heat_flux_contribution', ...
        'Bare-ground contribution to grid upward sensible heat', ...
        'fluxes.bare_ground_upward_sensible_heat_flux_contribution_W_m2', 'upward');
    registerTileFlux(reg, g, 'snow_upward_sensible_heat_flux_contribution', ...
        'Snow-covered contribution to grid upward sensible heat', ...
        'fluxes.snow_upward_sensible_heat_flux_contribution_W_m2', 'upward');
    registerTileFlux(reg, g, 'bare_ground_downward_soil_heat_flux_contribution', ...
        'Bare-ground contribution to grid heat entering soil', ...
        'fluxes.bare_ground_downward_soil_heat_flux_contribution_W_m2', 'downward');
    registerTileFlux(reg, g, 'snow_downward_soil_energy_flux_contribution', ...
        'Snow-covered contribution to grid energy entering soil', ...
        'fluxes.snow_downward_soil_energy_flux_contribution_W_m2', 'downward');
    registerMassFlux(reg, g, 'bare_ground_upward_water_vapor_flux', ...
        'Bare-ground upward water-vapor mass flux contribution');
    registerMassFlux(reg, g, 'snow_upward_water_vapor_flux', ...
        'Snow-surface upward water-vapor mass flux contribution');
    registerTemperature(reg, g, 'bare_ground_skin_temperature', ...
        'Bare-soil skin temperature solved by SCOPE ebal');
    registerTemperature(reg, g, 'snow_surface_temperature', ...
        'Snow temperature diagnosed from prognostic snow enthalpy');
    registerTemperature(reg, g, 'ground_radiative_temperature', ...
        'Fourth-power effective ground temperature supplied to RTMt');

    % ---- Canopy / soil partitioning ----
    reg.register(struct('name','latent_heat_canopy', 'long_name','Latent heat from canopy', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','fluxes.lEctot', 'transform','scalar'));
    reg.register(struct('name','latent_heat_canopy_wet', 'long_name','Latent heat from wet canopy intercept', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','fluxes.lE_wet_canopy', 'transform','scalar'));
    reg.register(struct('name','latent_heat_canopy_dry', 'long_name','Latent heat from dry canopy (stomatal)', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','fluxes.lE_dry_canopy', 'transform','scalar'));

    % ---- 4-quadrant breakdown (single/4q canopy intercept latent heat分流) ----
    % Both single-zone and 4-quadrant schemes split wet/dry × sun/sha; same field
    % names hold for both — value defaults to 0 in unused branch.
    reg.register(struct('name','latent_heat_wet_sun', 'long_name','Latent heat from wet sunlit canopy intercept', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','lE_wet_sun', ...
        'source_code','src/COMPASS.m', 'transform','scalar', ...
        'comment','4-quadrant scheme; sun-leaf wet branch. Single-zone aggregates into lE_wet_canopy.'));
    reg.register(struct('name','latent_heat_wet_sha', 'long_name','Latent heat from wet shaded canopy intercept', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','lE_wet_sha', ...
        'source_code','src/COMPASS.m', 'transform','scalar', ...
        'comment','4-quadrant scheme; shaded-leaf wet branch (can be negative when dew forms).'));
    reg.register(struct('name','latent_heat_dry_sun', 'long_name','Latent heat from dry sunlit canopy (stomatal)', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','lE_dry_sun', 'transform','scalar'));
    reg.register(struct('name','latent_heat_dry_sha', 'long_name','Latent heat from dry shaded canopy (stomatal)', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','lE_dry_sha', 'transform','scalar'));
    reg.register(struct('name','ground_upward_latent_heat_flux', ...
        'long_name','Ground upward latent heat flux from bare soil and snow', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.ground_upward_latent_heat_flux_W_m2', 'transform','scalar'));
    reg.register(struct('name','sensible_heat_canopy', 'long_name','Sensible heat from canopy', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','fluxes.Hctot', 'transform','scalar'));
    reg.register(struct('name','ground_upward_sensible_heat_flux', ...
        'long_name','Ground upward sensible heat flux from bare soil and snow', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.ground_upward_sensible_heat_flux_W_m2', 'transform','scalar'));

    % ---- Closure residual (paper卖点 paper sell-point) ----
    % Rn - LE - H - G should ≈ 0 at every KT; we'd compute this in post-processing,
    % but adding a slot makes the closure plot easy.
    reg.register(struct('name','energy_balance_residual', 'long_name','Energy balance residual (Rn - LE - H - G)', ...
        'units','W m-2', 'dims',{{'time'}}, 'group','conservation', ...
        'source','computed from Rntot - lEtot - Htot - Gtot', ...
        'transform','scalar', ...
        'comment',['With snow this includes snow storage/phase energy because G is the ', ...
            'actual shared-soil interface flux; use the snow and total-energy ledgers ', ...
            'for conservation acceptance.']));
end

function registerTileFlux(reg, group, name, longName, source, direction)
% Register one grid-area contribution with the common ground-flux signs.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    reg.register(struct('name',name, 'long_name',longName, ...
        'units','W m-2', 'dims',{{'time'}}, 'group',group, ...
        'source',source, 'transform','scalar', ...
        'comment',sprintf(['This is already weighted by tile area; bare plus ', ...
            'snow contribution equals the grid total. Positive %s.'], direction)));
end

function registerMassFlux(reg, group, name, longName)
% Register one signed physical water-vapor mass contribution.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    reg.register(struct('name',name, 'long_name',longName, ...
        'units','kg m-2 s-1', 'dims',{{'time'}}, 'group',group, ...
        'transform','scalar', ...
        'comment','Positive is surface-to-atmosphere; negative is condensation or deposition.'));
end

function registerTemperature(reg, group, name, longName)
% Register one scalar ground-tile or radiative temperature.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    reg.register(struct('name',name, 'long_name',longName, ...
        'units','degC', 'dims',{{'time'}}, 'group',group, ...
        'transform','scalar'));
end
