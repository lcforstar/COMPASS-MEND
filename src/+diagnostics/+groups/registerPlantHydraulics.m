function registerPlantHydraulics(reg, cfg) %#ok<INUSD>
%REGISTERPLANTHYDRAULICS  Plant hydraulic conductances (group: plant_hydraulics).
% Output: data/output_<tag>/plant_hydraulics.nc
%
% 物理背景:
%   植物水力网络 = 土壤 → 根 → 茎 → 叶 串联电路。每段有一个导度 K (单位 mm/s/MPa
%   表示水势差 1 MPa 时单位时间内单位面积通过的水量)。COMPASS 4-quadrant 把冠层分
%   阳叶 (sun) / 阴叶 (sha)，所以叶端 K 也分两条平行支路。
%
% 两种导度定义 (paper 上都报告):
%   App (Apparent, 视导度):  K_app = Tr / (ψ_soil - ψ_leaf)   —— 实际通量 / 总驱动力
%   Diff (Differential, 切线导度): K_diff = dT/dψ_leaf       —— 局部斜率
%
%   Diff 在数学上是 ODE 系数, App 是事后观测; 两者数值上 K_diff > K_app 在弱胁迫,
%   反之在强胁迫. 都要保留方便对比.
%
% 命名约定 (为将来植被含水动态留位):
%   k_*  = 导度 (conductance)            ← 当前已有
%   c_*  = 容量 (capacitance, dW/dψ)     ← 将来加 stem/leaf 动态时用
%   w_*  = 含水量 (water content)         ← 将来加 plant capacitance 时用
%   q_*  = 通量 (flux)                   ← 将来 stem→leaf 通量
%
% Source-of-truth: src/+vegetation/+hydraulics/solveEbalHydraulics.m

    g = 'plant_hydraulics';

    % ===== Apparent (视导度): 实际通量 / 总水势差 =====
    reg.register(struct('name','k_plant_sun_app', ...
        'long_name','Plant hydraulic conductance, sunlit (apparent K = Tr/Δψ)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kplant_app_sun', ...
        'source_code','src/+vegetation/+hydraulics/solveEbalHydraulics.m:126', ...
        'comment','Sunlit branch: Tp_sun / (ψ_stem - ψ_leaf_sun)'));

    reg.register(struct('name','k_plant_sha_app', ...
        'long_name','Plant hydraulic conductance, shaded (apparent)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kplant_app_sha', ...
        'comment','Shaded branch: Tp_sha / (ψ_stem - ψ_leaf_sha)'));

    reg.register(struct('name','k_plant_canopy_app', ...
        'long_name','Plant hydraulic conductance, whole canopy (apparent)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kplant_app_total', ...
        'comment','Combined sun+sha; equivalent to whole-canopy K_plant in single-zone models'));

    % ===== Differential (切线导度): dT/dψ, 用于 ODE 解 =====
    reg.register(struct('name','k_plant_sun_diff', ...
        'long_name','Plant hydraulic conductance, sunlit (differential dT/dψ)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kplant_diff_sun', ...
        'source_code','VulnerabilityCurve(psil_sun, gpmax, p50, aa)', ...
        'comment','Tangent slope used inside SPAC ODE; differs from apparent under stress'));

    reg.register(struct('name','k_plant_sha_diff', ...
        'long_name','Plant hydraulic conductance, shaded (differential)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kplant_diff_sha'));

    reg.register(struct('name','k_plant_canopy_diff', ...
        'long_name','Plant hydraulic conductance, whole canopy (flux-weighted differential)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kplant_diff_flux_weighted', ...
        'comment','Σ Tp_i × K_diff_i / Σ Tp_i; effective whole-canopy K for diagnostics'));

    % ===== Soil-root and whole-pathway =====
    reg.register(struct('name','k_soil_root', ...
        'long_name','Soil-to-root conductance (apparent)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Ksoilroot_app_total', ...
        'comment','Tp / (ψ_soil - ψ_root); rhizosphere + root radial path'));

    reg.register(struct('name','k_soil_leaf', ...
        'long_name','Soil-to-leaf whole-pathway conductance (apparent)', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.Kwhole_app_total', ...
        'comment','Series sum: 1/k_soil_leaf = 1/k_soil_root + 1/k_plant_canopy'));

    % ===== Sum of node-level conductances (math closure check) =====
    reg.register(struct('name','gsr_node_sum', ...
        'long_name','Sum of node-level soil-to-root conductances', ...
        'units','mm s-1 MPa-1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.gsr_total = sum(gsr)', ...
        'source_code','src/+vegetation/+hydraulics/Plantrootconductivity.m', ...
        'comment','Σ gsr_j over root zone; should equal 1/R_total (= k_soil_root inverse)'));

    % ===================================================================
    % Dynamic scheme — inverse linear retention from v1 ψ
    %   Activated when hydraulic_scheme is storage_from_psi or storage_dynamic.
    %   Source: src/+vegetation/+hydraulics/updateOrganStorageFromPsi.m

    %             W = W_cap × (1 + a × ψ_v1), no time integration.
    % ===================================================================
    reg.register(struct('name','w_root_v2', ...
        'long_name','Prognostic root water storage', ...
        'units','m', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.W_root from solveEbalHydraulics_dynamic', ...
        'comment','Root compartment liquid water storage per ground area (ClimaLand Eq. 32)'));

    reg.register(struct('name','w_stem_v2', ...
        'long_name','Prognostic stem water storage', ...
        'units','m', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.W_stem', ...
        'comment','Stem compartment liquid water storage, key driver of VOD_stem'));

    reg.register(struct('name','w_leaf_v2', ...
        'long_name','Prognostic leaf water storage', ...
        'units','m', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.W_leaf', ...
        'comment','Leaf compartment storage; reverse-mapped to psi_leaf via linear retention'));

    reg.register(struct('name','psi_leaf_v2', ...
        'long_name','Leaf water potential (dynamic scheme, prognostic)', ...
        'units','MPa', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.psil (when scheme=dynamic)', ...
        'comment','Prognostic leaf ψ; compare with leaf_potential (equilibrium steady-state)'));

    reg.register(struct('name','psi_root_v2', ...
        'long_name','Root water potential (dynamic scheme, prognostic)', ...
        'units','MPa', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.psir (when scheme=dynamic)', ...
        'comment','Compare with root_potential (equilibrium scheme)'));

    reg.register(struct('name','psi_stem_v2', ...
        'long_name','Stem water potential (dynamic scheme exposes stem)', ...
        'units','MPa', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','hydraulic.pstem (when scheme=dynamic)', ...
        'comment','Stem is implicit in equilibrium scheme; dynamic resolves it explicitly'));

    reg.register(struct('name','rwc_stem_v2', ...
        'long_name','Stem relative water content (dynamic scheme)', ...
        'units','-', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','W_stem / W_capacity_stem', ...
        'comment','Drought signal: RWC<1 = drier than capacity; used as VOD_stem driver'));

    reg.register(struct('name','rwc_leaf_v2', ...
        'long_name','Leaf relative water content (dynamic scheme)', ...
        'units','-', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'source','W_leaf / W_capacity_leaf', ...
        'comment','Leaf capacitance RWC; modulates carbon-driven VOD_leaf water (M_leaf = C_leaf*WDR*rwc_leaf), symmetric with rwc_stem_v2'));

end
