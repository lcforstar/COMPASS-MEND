function registerSoilWater(reg, cfg) %#ok<INUSD>
%REGISTERSOILWATER  Register soil-water diagnostics (group: soil_water).
%
% Variables in this group land in: data/output_<tag>/soil_water.nc
%
% Inputs:
%   reg  [inout]  diagnostics.Registry — entries added here
%   cfg  [in]     legacy ModelSettings — currently unused, kept for symmetry
%
% Source-of-truth: src/+soil/+water/* (Richards solver outputs)
%
% Editor: Jizixing Zhu; Date: 2026-05-15.
% Change: 2026-07-16 Jizixing Zhu -- define soil_moisture as the effective
%         total water state used by the accepted Richards storage equation.
% Change: 2026-07-17 Jizixing Zhu -- fix per-step water-ledger units and
%         register the combined surface-reservoir plus soil-column closure.

    g = 'soil_water';

    % ---- Effective total water content theta_u ----
    reg.register(struct( ...
        'name',          'soil_moisture', ...
        'long_name',     'Effective total volumetric soil water content', ...
        'standard_name', 'mass_content_of_water_in_soil_layer', ...
        'units',         'm3 m-3', ...
        'dims',          {{'time', 'node'}}, ...
        'group',         g, ...
        'source',        'workspace.derived.Theta_UU', ...
        'source_code',   'src/+soil/+water/calculateMatricCoefficients.m', ...
        'comment',       'theta_u = theta_l + (rho_i/rho_l) theta_i; liquid and ice are exported separately', ...
        'transform',     'edge_to_node_reversed_layer' ...
    ));

    % ---- Soil matric head hh ----
    reg.register(struct( ...
        'name',          'soil_matric_head', ...
        'long_name',     'Soil matric pressure head', ...
        'standard_name', 'soil_matric_potential', ...
        'units',         'cm', ...
        'dims',          {{'time', 'node'}}, ...
        'group',         g, ...
        'source',        'SoilVariables.hh', ...
        'source_code',   'src/+soil/+water/solveTridiagonalMatrixEquations.m', ...
        'comment',       'Negative under unsaturated conditions; sign convention follows Richards equation', ...
        'transform',     'none' ...
    ));

    reg.register(struct( ...
        'name',          'soil_saturated_node_mask', ...
        'long_name',     'Saturated soil node mask from signed pressure head', ...
        'standard_name', '', ...
        'units',         '1', ...
        'dims',          {{'time', 'node'}}, ...
        'group',         g, ...
        'source',        'soil.water.computeZeroHeadDiagnostics.node_saturated', ...
        'source_code',   'src/+soil/+water/computeZeroHeadDiagnostics.m', ...
        'comment',       'One where accepted h is greater than or equal to zero; zero otherwise', ...
        'transform',     'none' ...
    ));

    reg.register(struct( ...
        'name',          'zero_head_crossing_depth', ...
        'long_name',     'Depths of all zero-pressure-head crossings', ...
        'standard_name', '', ...
        'units',         'cm', ...
        'dims',          {{'time', 'layer'}}, ...
        'group',         g, ...
        'source',        'soil.water.computeZeroHeadDiagnostics.crossing_depth_cm', ...
        'source_code',   'src/+soil/+water/computeZeroHeadDiagnostics.m', ...
        'comment',       'Crossings sorted shallowest to deepest and padded with missing values; supports perched saturation', ...
        'transform',     'none' ...
    ));

    reg.register(struct( ...
        'name',          'zero_head_crossing_count', ...
        'long_name',     'Number of zero-pressure-head crossings', ...
        'standard_name', '', ...
        'units',         '1', ...
        'dims',          {{'time'}}, ...
        'group',         g, ...
        'source',        'soil.water.computeZeroHeadDiagnostics.crossing_count', ...
        'source_code',   'src/+soil/+water/computeZeroHeadDiagnostics.m', ...
        'comment',       'Can exceed one when perched saturated zones are present', ...
        'transform',     'scalar' ...
    ));

    reg.register(struct( ...
        'name',          'shallowest_zero_head_depth', ...
        'long_name',     'Shallowest zero-pressure-head crossing depth', ...
        'standard_name', 'depth_below_geopotential_datum', ...
        'units',         'cm', ...
        'dims',          {{'time'}}, ...
        'group',         g, ...
        'source',        'soil.water.computeZeroHeadDiagnostics.shallowest_crossing_depth_cm', ...
        'source_code',   'src/+soil/+water/computeZeroHeadDiagnostics.m', ...
        'comment',       'Missing when no h equals zero or changes sign inside the modeled column', ...
        'transform',     'scalar' ...
    ));

    reg.register(struct( ...
        'name',          'saturated_profile_fraction', ...
        'long_name',     'Fraction of soil-profile thickness with h greater than or equal to zero', ...
        'standard_name', '', ...
        'units',         '1', ...
        'dims',          {{'time'}}, ...
        'group',         g, ...
        'source',        'soil.water.computeZeroHeadDiagnostics.saturated_fraction', ...
        'source_code',   'src/+soil/+water/computeZeroHeadDiagnostics.m', ...
        'comment',       'Integrated with the same piecewise-linear head interpolation used for crossings', ...
        'transform',     'scalar' ...
    ));

    % ---- Soil water capacity C(h) ----
    % [2026-05-16 dir-fix] SoilVariables.DTheta_LLh 来自 Dtrmn_Z 网格 (NL×2 bottom-up).
    reg.register(struct( ...
        'name',          'soil_water_capacity', ...
        'long_name',     'Soil specific water capacity dθ/dh', ...
        'standard_name', '', ...
        'units',         'cm-1', ...
        'dims',          {{'time', 'node'}}, ...
        'group',         g, ...
        'source',        'MatricCoeff.Chh', ...
        'source_code',   'src/+soil/+water/calculateMatricCoefficients.m', ...
        'comment',       'VG analytic derivative; capped at 0.02 cm-1 in calculateMatricCoefficients', ...
        'transform',     'edge_to_node_reversed_layer' ...
    ));

    % ---- Hydraulic conductivity K(h) ----
    % [2026-05-16 dir-fix] SoilVariables.KL_h 来自 Dtrmn_Z 网格 (NL×2, 层方向 bottom-up).
    % 用 _reversed_layer transform 让输出 NN 节点顶→底, 跟 soil_moisture 一致.
    reg.register(struct( ...
        'name',          'hydraulic_conductivity', ...
        'long_name',     'Unsaturated hydraulic conductivity', ...
        'standard_name', 'soil_hydraulic_conductivity_at_saturation', ...
        'units',         'cm s-1', ...
        'dims',          {{'time', 'node'}}, ...
        'group',         g, ...
        'source',        'MatricCoeff.Khh', ...
        'source_code',   'src/+soil/+water/calculateMatricCoefficients.m', ...
        'comment',       'Mualem-VG with ice impedance correction (Lundin 1990) when lFreezing=1', ...
        'transform',     'edge_to_node_reversed_layer' ...
    ));

    % ---- Effective saturation (VG) ----
    % [2026-05-16 dir-fix] Se_VG 在 COMPASS.m line 1966 现算 = SoilVariables.Theta_LL 直接派生.
    % Theta_LL NL×2 是 Dtrmn_Z bottom-up convention, 所以 Se 也是底→顶, 需要 _reversed_layer.
    reg.register(struct( ...
        'name',          'effective_saturation_vg', ...
        'long_name',     'Effective saturation (van Genuchten)', ...
        'standard_name', '', ...
        'units',         '1', ...
        'dims',          {{'time', 'node'}}, ...
        'group',         g, ...
        'source',        'SoilVariables.Se', ...
        'source_code',   'src/+soil/+water/calculateMatricCoefficients.m', ...
        'comment',       '(θ - θ_r) / (θ_s - θ_r), clamped to [0, 1]', ...
        'transform',     'edge_to_node_reversed_layer' ...
    ));

    % ---- Column water storage ----
    reg.register(struct( ...
        'name',          'water_storage_column', ...
        'long_name',     'Depth-integrated soil water storage', ...
        'standard_name', '', ...
        'units',         'mm', ...
        'dims',          {{'time'}}, ...
        'group',         g, ...
        'source',        'solver.calculateSoilWaterStorageMm', ...
        'source_code',   'src/+solver/calculateSoilWaterStorageMm.m', ...
        'comment',       'Σ θ × DeltZ × 10 (cm → mm); used in WaterBalanceResidual closure check', ...
        'transform',     'scalar' ...
    ));

    % ---- Water storage change ----
    reg.register(struct( ...
        'name',          'water_storage_change', ...
        'long_name',     'Per-step soil water storage change', ...
        'standard_name', '', ...
        'units',         'mm', ...
        'dims',          {{'time'}}, ...
        'group',         g, ...
        'source',        'water_storage(KT) - water_storage(KT-1)', ...
        'source_code',   'src/+solver/computeWaterBalanceResidual.m', ...
        'comment',       'Accepted-step after-minus-before storage change', ...
        'transform',     'scalar' ...
    ));

    % ---- Water balance residual ----
    reg.register(struct( ...
        'name',          'water_balance_residual', ...
        'long_name',     'Actual-flux water balance residual (TopBoundaryInput - RootSink - BottomFlow - dS)', ...
        'standard_name', '', ...
        'units',         'mm', ...
        'dims',          {{'time'}}, ...
        'group',         'conservation', ...
        'source',        '-QMT - integral(Srt) - (-QMB) - storage change', ...
        'source_code',   'src/+solver/computeWaterBalanceResidual.m', ...
        'comment',       'New water path uses actual solved top and bottom fluxes, exact FE root sink, and total Theta_UU plus vapor storage', ...
        'transform',     'scalar' ...
    ));

    registerCombinedWater(reg, 'surface_soil_liquid_input', ...
        'Post-canopy and post-snow liquid input to the surface-soil domain');
    registerCombinedWater(reg, 'surface_soil_evaporation_loss', ...
        'Soil-surface evaporation loss from the surface-soil domain');
    registerCombinedWater(reg, 'surface_soil_runoff_loss', ...
        'Surface runoff loss from the surface-soil domain');
    registerCombinedWater(reg, 'surface_soil_bottom_loss', ...
        'Signed lower-boundary loss from the surface-soil domain');
    registerCombinedWater(reg, 'surface_soil_root_sink', ...
        'Signed root water sink from the surface-soil domain');
    registerCombinedWater(reg, 'surface_soil_storage_change', ...
        'Combined surface-reservoir and soil-column storage change');
    registerCombinedWater(reg, 'surface_soil_water_balance_residual', ...
        'Combined surface-reservoir and soil-column water residual');

end

function registerCombinedWater(reg, name, longName)
% Register one accepted-step combined water-ledger component [mm].
% Editor: Jizixing Zhu; Date: 2026-07-17.
    reg.register(struct('name', name, 'long_name', longName, ...
        'units', 'mm', 'dims', {{'time'}}, 'group', 'conservation', ...
        'source', 'workspace.flux.surface_soil_water_balance', ...
        'source_code', 'src/+solver/computeSurfaceSoilWaterBalance.m', ...
        'transform', 'scalar', ...
        'comment', ['The post-canopy/post-snow surface-soil ledger excludes ', ...
                    'canopy and snow storage and cancels QMT internally.']));
end
