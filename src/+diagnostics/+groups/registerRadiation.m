function registerRadiation(reg, cfg) %#ok<INUSD>
%REGISTERRADIATION  Radiation diagnostics from SCOPE module (group: radiation).
% Output file: data/output_<tag>/radiation.nc
% Source-of-truth: SCOPE radiation_balance + ebal
%
% Migrates Scope_output.rad_* and the radiation-related fluxes_* fields from
% the legacy 123-field Scope_output.mat dump into a clean per-paper-relevance
% group. Fields kept here are the ones papers typically report.
%
% Author: Zhu Jizixing, 2026-05-15
% Change: 2026-07-18 Jizixing Zhu -- document the mol-to-umol conversion
%   performed by diagnostics.writeScopeStructs.

    g = 'radiation';

    % ---- Net radiation components (paper standard) ----
    reg.register(struct('name','net_radiation_total', 'long_name','Net radiation (total)', ...
        'standard_name','surface_net_downward_radiative_flux', 'units','W m-2', ...
        'dims',{{'time'}}, 'group',g, 'source','fluxes.Rntot', 'transform','scalar'));
    reg.register(struct('name','net_radiation_canopy', 'long_name','Net radiation absorbed by canopy', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','fluxes.Rnctot', 'transform','scalar'));
    reg.register(struct('name','net_radiation_soil', 'long_name','Net radiation absorbed at soil surface', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','fluxes.Rnstot', 'transform','scalar'));

    % ---- Longwave outgoing ----
    reg.register(struct('name','longwave_outgoing', 'long_name','Outgoing longwave radiation (total)', ...
        'standard_name','toa_outgoing_longwave_flux', 'units','W m-2', ...
        'dims',{{'time'}}, 'group',g, 'source','rad.Eoutt + rad.Eoutte', 'transform','scalar'));
    reg.register(struct('name','longwave_thermal_emission', 'long_name','Thermal longwave emission', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','rad.Eoutte', 'transform','scalar'));

    % ---- Shortwave outgoing ----
    reg.register(struct('name','shortwave_outgoing_hemis', 'long_name','Hemispherical outgoing shortwave', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','rad.Eouto', 'transform','scalar'));
    reg.register(struct('name','shortwave_outgoing_obs', 'long_name','Observer-direction outgoing SW', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'source','rad.Eouto', 'transform','scalar'));

    % ---- PAR + aPAR (SIF / GPP coupling) ----
    reg.register(struct('name','par_at_canopy_top', 'long_name','PAR at canopy top', ...
        'standard_name','surface_downwelling_photosynthetic_photon_flux_in_air', ...
        'units','umol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','rad.PAR', 'transform','scalar', ...
        'comment','rad.PAR is mol m-2 s-1 internally; writer multiplies by 1e6'));
    reg.register(struct('name','apar_canopy', 'long_name','Absorbed PAR by canopy', ...
        'units','umol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.aPAR', 'transform','scalar', ...
        'comment','fluxes.aPAR is mol m-2 s-1 internally; writer multiplies by 1e6'));
    reg.register(struct('name','apar_cab', 'long_name','Absorbed PAR by chlorophyll', ...
        'units','umol m-2 s-1', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.aPAR_Cab', 'transform','scalar', ...
        'comment','fluxes.aPAR_Cab is mol m-2 s-1 internally; writer multiplies by 1e6'));
    reg.register(struct('name','apar_canopy_wm2', 'long_name','Absorbed PAR by canopy (energy)', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','fluxes.aPAR_Wm2', 'transform','scalar'));

    % ---- Fluorescence ----
    reg.register(struct('name','fluorescence_outgoing', 'long_name','Outgoing fluorescence (hemispheric)', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, ...
        'source','rad.Eoutf', 'transform','scalar', ...
        'comment','SIF integrated over fluorescence wavelengths; per-wavelength spectrum still in Scope_output.mat'));
end
