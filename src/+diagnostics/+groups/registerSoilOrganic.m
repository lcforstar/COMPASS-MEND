end

function registerScalar(reg,group,name,longName,units)
% Register one material-resolved scalar diagnostic.
% Editor: Codex; Date: 2026-08-28.
    reg.register(struct('name',name,'long_name',longName,'units',units, ...
        'dims',{{'time'}},'group',group, ...
        'source','accepted native AOM material ledger', ...
        'source_code','src/+diagnostics/writeStep.m','transform','scalar'));
end
