function registerSurfaceEnergy(reg, cfg) %#ok<INUSD>
%REGISTERSURFACEENERGY  Register accepted surface-snow-soil energy diagnostics.
%
% Output files: surface_energy.nc and conservation.nc.
% The SCOPE ground heat is explicitly labelled empirical; the accepted soil
% reaction is the complete h/U/P_g top-boundary total-energy flux.
% Editor: Jizixing Zhu; Date: 2026-07-18.
% Change: 2026-07-18 Jizixing Zhu -- retain initialization compatibility diagnostics
%         after removing the non-beneficial A1 correction experiment.
% Change: 2026-07-19 Jizixing Zhu -- generalize the ledger to prognostic snow
%         storage and explicit internal-interface cancellation.
% Change: 2026-07-19 Jizixing Zhu -- expose the accepted affine-response authority,
%         keep SCOPE reconstruction separate, and remove ambiguous component
%         names that implied double addition to the total-energy boundary.
% Change: 2026-07-19 Jizixing Zhu -- expose bounded outer Dirichlet closure.
% Change: 2026-07-20 Jizixing Zhu -- expose strict/refined/bounded atmospheric heat
%         acceptance and its actual temporal and residual thresholds.

    g = 'surface_energy';
    registerFlux(reg, 'ground_net_radiation', ...
        'Ground net radiation used by the surface ledger', g);
    registerFlux(reg, 'ground_sensible_heat', ...
        'Ground sensible heat loss used by the surface ledger', g);
    registerFlux(reg, 'ground_latent_heat_demand', ...
        'SCOPE ground latent-heat demand', g);
    registerFlux(reg, 'ground_latent_heat_actual', ...
        'Accepted water-active-set ground latent heat', g);
    registerFlux(reg, ...
        'diagnosed_bare_liquid_infiltration_sensible_energy_flux', ...
        ['Diagnosed bare-liquid infiltration sensible-energy component; ', ...
         'not added separately to the prescribed total-energy response'], g);
    registerFlux(reg, 'diagnosed_dry_air_sensible_energy_transport', ...
        ['Diagnosed dry-air sensible-energy transport component; not added ', ...
         'separately to the prescribed total-energy response'], g);
    registerFlux(reg, 'bare_ground_external_energy_flux_actual', ...
        'Accepted bare-ground external energy entering the combined control volume', g);
    registerFlux(reg, 'bare_ground_external_energy_flux_reconstructed', ...
        'Bare-ground external energy reconstructed from SCOPE component diagnostics', g);
    registerFlux(reg, ...
        'bare_ground_external_energy_flux_reconstruction_error', ...
        'Accepted minus SCOPE-reconstructed bare-ground external energy flux', g);
    registerFlux(reg, 'snow_external_energy_flux', ...
        'Net external atmospheric and precipitation energy entering snow', g);
    registerFlux(reg, 'snow_to_soil_internal_energy_flux', ...
        'Internal snow-to-soil energy transfer within the combined control volume', g);
    registerFlux(reg, 'surface_external_energy_flux', ...
        'Net external energy entering the combined snow-surface-soil control volume', g);
    registerFlux(reg, 'scope_ground_heat_flux_empirical', ...
        'Empirical SCOPE force-restore ground-heat closure', g);
    registerFlux(reg, 'scope_ground_ebal_residual', ...
        'SCOPE algebraic ground energy residual', g);
    registerFlux(reg, 'soil_top_energy_flux_total_actual', ...
        'Accepted total-energy reaction entering the soil top', g);
    registerFlux(reg, 'surface_to_soil_interface_power_residual', ...
        'Accepted soil-top flux minus the applied surface response', g);
    registerClosureScalar(reg, 'soil_interface_closure_initial_temperature', ...
        'Initial guarded soil-interface temperature', 'degC');
    registerClosureScalar(reg, 'soil_interface_closure_final_temperature', ...
        'Accepted outer-closure soil-interface temperature', 'degC');
    registerClosureScalar(reg, 'soil_interface_closure_initial_residual', ...
        'Initial soil-reaction minus frozen-surface heat residual', 'W m-2');
    registerClosureScalar(reg, 'soil_interface_closure_final_residual', ...
        'Final soil-reaction minus frozen-surface heat residual', 'W m-2');
    registerClosureScalar(reg, 'soil_interface_closure_soil_flux', ...
        'Soil reaction at the accepted closure temperature', 'W m-2');
    registerClosureScalar(reg, 'soil_interface_closure_surface_flux', ...
        'Frozen surface heat at the accepted closure temperature', 'W m-2');
    registerClosureScalar(reg, 'soil_interface_closure_iterations', ...
        'Guarded secant updates used by the outer closure', '1');
    registerClosureScalar(reg, 'soil_interface_closure_evaluations', ...
        'Total strict-Dirichlet evaluations used by the outer closure', '1');
    registerClosureScalar(reg, 'soil_interface_closure_converged', ...
        'Outer soil-interface temperature closure convergence flag', '1');
    registerClosureScalar(reg, 'soil_interface_closure_acceptance_mode', ...
        ['Closure mode: -1 rejected rollback, 0 disabled, 1 strict, ', ...
         '2 refined-substep strict, 3 bounded residual'], '1');
    registerClosureScalar(reg, ...
        'soil_interface_closure_accepted_bounded_residual', ...
        'Flag for accepted non-strict but bounded interface residual', '1');
    registerClosureScalar(reg, 'soil_interface_closure_bounded_tolerance', ...
        'Actual combined absolute-relative fallback tolerance', 'W m-2');
    registerClosureScalar(reg, 'soil_interface_closure_substep_retry_used', ...
        'Flag that the accepted trial used finer soil time tiles', '1');
    registerClosureScalar(reg, 'soil_interface_closure_chosen_substep_cap', ...
        'Maximum requested soil tile for the chosen closure trial', 's');

    registerEnergy(reg, 'snow_internal_energy_change', ...
        'Accepted snowpack internal-energy change', 'conservation');
    registerEnergy(reg, 'surface_soil_total_energy_change', ...
        'Combined snowpack and soil internal-energy change', 'conservation');
    registerEnergy(reg, 'surface_external_energy', ...
        'Net external energy supplied through the land surface', 'conservation');

    registerEnergy(reg, 'surface_to_soil_interface_energy_residual', ...
        'Surface-to-soil interface energy residual', 'conservation');
    registerEnergy(reg, 'surface_soil_total_energy_residual', ...
        'Combined surface-snow-soil total energy residual', ...
        'conservation');
    registerEnergy(reg, 'surface_soil_interface_cancellation_error', ...
        'Internal surface-soil heat-interface cancellation error', ...
        'conservation');

    reg.register(struct( ...
        'name', 'surface_energy_precipitation_temperature', ...
        'long_name', 'Temperature used for liquid precipitation enthalpy', ...
        'units', 'degC', 'dims', {{'time'}}, 'group', g, ...
        'source', 'workspace.flux.surface_soil_energy_balance', ...
        'source_code', 'src/+surface/+energy/buildSurfaceSoilEnergyBalance.m', ...
        'transform', 'scalar', ...
        'comment', ['Air temperature is the explicit fallback until a ', ...
            'measured precipitation-temperature forcing is available.']));
    registerInitializationScalar(reg, ...
        'initial_bottom_temperature_mismatch_before_alignment', ...
        'Initial bottom-node temperature minus same-time Dirichlet boundary before alignment');
    registerInitializationScalar(reg, ...
        'initial_bottom_temperature_mismatch_after_alignment', ...
        'Initial bottom-node temperature minus same-time Dirichlet boundary after alignment');
end

function registerClosureScalar(reg, name, longName, units)
% Register one outer soil-interface temperature-closure diagnostic.
% Editor: Jizixing Zhu; Date: 2026-07-19.
    reg.register(struct('name', name, 'long_name', longName, ...
        'units', units, 'dims', {{'time'}}, 'group', 'surface_energy', ...
        'source', 'workspace.surface.soil_interface_temperature_closure', ...
        'source_code', ...
            'src/+solver/advanceSoilWithInterfaceTemperatureClosure.m', ...
        'transform', 'scalar', ...
        'comment', ['The surface map is frozen after ebal; each evaluation ', ...
            'uses the existing strict-Dirichlet soil solve.']));
end

function registerInitializationScalar(reg, name, longName)
% Register one first-step thermal-initialization provenance diagnostic.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    reg.register(struct('name', name, 'long_name', longName, ...
        'units', 'K', 'dims', {{'time'}}, 'group', 'surface_energy', ...
        'source', 'p.initialization.thermal_bottom_alignment', ...
        'source_code', 'src/+init/alignInitialThermalBoundary.m', ...
        'transform', 'scalar', ...
        'comment', 'Defined at the first output step for temperature Dirichlet bottom boundaries.'));
end

function registerFlux(reg, name, longName, group)
% Register one inward-positive surface energy-flux diagnostic [W m-2].
% Editor: Jizixing Zhu; Date: 2026-07-18.
    reg.register(struct('name', name, 'long_name', longName, ...
        'units', 'W m-2', 'dims', {{'time'}}, 'group', group, ...
        'source', 'workspace.flux.surface_soil_energy_balance', ...
        'source_code', 'src/+surface/+energy/buildSurfaceSoilEnergyBalance.m', ...
        'transform', 'scalar', ...
        'comment', 'Defined for every accepted natural-surface heat solve.'));
end

