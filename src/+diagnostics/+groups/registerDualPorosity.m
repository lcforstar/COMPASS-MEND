function registerDualPorosity(reg, cfg)
%REGISTERDUALPOROSITY  HYDRUS-style dual porosity diagnostics (group: dual_porosity).
% Only when cfg.lDualPor == 1.
    if ~helpers.isfield_or_prop_true(cfg, 'lDualPor')
        return;
    end
    g = 'dual_porosity';

    reg.register(struct('name','mobile_water', 'long_name','Mobile water content', ...
        'units','m3 m-3', 'dims',{{'time','node'}}, 'group',g, ...
        'transform','edge_to_node_reversed_layer', ...
        'source_code','src/+soil/+water/+dualporosity/'));
    reg.register(struct('name','immobile_water', 'long_name','Immobile water content', ...
        'units','m3 m-3', 'dims',{{'time','node'}}, 'group',g, ...
        'transform','edge_to_node_reversed_layer'));
    reg.register(struct('name','sink_immobile', 'long_name','Mobile↔immobile exchange sink', ...
        'units','s-1', 'dims',{{'time','node'}}, 'group',g, 'transform','edge_to_node_reversed_layer'));
end
