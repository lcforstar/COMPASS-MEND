function registerPlantCanopy(reg, cfg) %#ok<INUSD>
%REGISTERPLANTCANOPY  Canopy state + leaf/root potentials (group: plant_canopy).
% Output: data/output_<tag>/plant_canopy.nc
    g = 'plant_canopy';

    reg.register(struct('name','leaf_area_index', 'long_name','Leaf area index', ...
        'standard_name','leaf_area_index', 'units','m2 m-2', ...
        'dims',{{'time'}}, 'group',g, 'source','LAI(KT)', 'transform','scalar'));

    reg.register(struct('name','leaf_potential', 'long_name','Leaf water potential', ...
        'units','MPa', 'dims',{{'time'}}, 'group',g, ...
        'source','Sim_output.Leafpotential', 'transform','scalar'));

    reg.register(struct('name','root_potential', 'long_name','Root water potential', ...
        'units','MPa', 'dims',{{'time'}}, 'group',g, ...
        'source','Sim_output.Rootpotential', 'transform','scalar'));

    reg.register(struct('name','soil_potential_weighted', 'long_name','Soil potential, gsr-weighted', ...
        'units','MPa', 'dims',{{'time'}}, 'group',g, ...
        'source','Sim_output.Soilpotential', 'transform','scalar'));

    reg.register(struct('name','fwet', 'long_name','Whole canopy wet fraction', ...
        'units','1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','fwet_sun', 'long_name','Sunlit leaf wet fraction (4-quadrant)', ...
        'units','1', 'dims',{{'time'}}, 'group',g, 'transform','scalar', ...
        'comment','4-quadrant scheme only'));

    reg.register(struct('name','fwet_sha', 'long_name','Shaded leaf wet fraction (4-quadrant)', ...
        'units','1', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','h2ocan', 'long_name','Canopy water content', ...
        'units','mm', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','h2ocan_sun', 'long_name','Sunlit canopy water', ...
        'units','mm', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','h2ocan_sha', 'long_name','Shaded canopy water', ...
        'units','mm', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','canopy_water_residual', 'long_name','Canopy water balance residual', ...
        'units','mm', 'dims',{{'time'}}, 'group','conservation', 'transform','scalar'));

    reg.register(struct('name','lE_canopy_intercept', 'long_name','Latent heat from canopy interception', ...
        'units','W m-2', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));

    reg.register(struct('name','vapor_pressure_deficit', 'long_name','VPD', ...
        'standard_name','water_vapor_partial_pressure_deficit_in_air', ...
        'units','kPa', 'dims',{{'time'}}, 'group',g, 'transform','scalar'));
end
