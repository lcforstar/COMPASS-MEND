function registerSoilFreezing(reg, cfg)
%REGISTERSOILFREEZING  Soil ice phase diagnostics (group: soil_freezing).
% Only registered if cfg.lFreezing == 1.
% Output: data/output_<tag>/soil_freezing.nc
% Editor: Jizixing Zhu; Date: 2026-07-16.
% Change: 2026-07-16 Jizixing Zhu -- map bottom-up endpoint fields through
%         the corrected endpoint-to-node transform used by the new state.

    if ~helpers.isfield_or_prop_true(cfg, 'lFreezing')
        return;
    end
    g = 'soil_freezing';

    reg.register(struct('name', 'soil_ice', ...
        'long_name', 'Soil ice volumetric fraction', ...
        'standard_name', 'volume_fraction_of_frozen_water_in_soil', ...
        'units', 'm3 m-3', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.Theta_II', ...
        'source_code', 'src/+soil/+thermal/solveThermalEquations.m', ...
        'transform', 'edge_to_node_reversed_layer'));

    reg.register(struct('name', 'soil_unfrozen_water', ...
        'long_name', 'Soil unfrozen liquid water', ...
        'units', 'm3 m-3', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.Theta_LL (during freezing)', ...
        'transform', 'edge_to_node_reversed_layer'));

    % Ratio_ice and KfL_h are NL-by-2 bottom-up endpoint fields.
    reg.register(struct('name', 'ice_ratio', ...
        'long_name', 'Ice to effective total water ratio', ...
        'units', '1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.Ratio_ice', ...
        'transform', 'edge_to_node_reversed_layer'));

    reg.register(struct('name', 'frozen_matric_head', ...
        'long_name', 'Matric head induced by freezing', ...
        'units', 'cm', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.hh_frez', ...
        'transform', 'none', ...
        'comment', 'Writer converts the bottom-up node vector to surface-to-bottom order.'));

    reg.register(struct('name', 'frozen_hydraulic_conductivity', ...
        'long_name', 'Hydraulic conductivity with ice impedance', ...
        'units', 'cm s-1', ...
        'dims', {{'time','node'}}, ...
        'group', g, ...
        'source', 'SoilVariables.KfL_h', ...
        'source_code', 'src/+soil/+water/calculateMatricCoefficients.m', ...
        'transform', 'edge_to_node_reversed_layer', ...
        'comment', 'Lundin 1990 impedance factor applied'));
end
