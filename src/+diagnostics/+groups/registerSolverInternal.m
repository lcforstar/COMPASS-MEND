function registerSolverInternal(reg, cfg) %#ok<INUSD>
%REGISTERSOLVERINTERNAL  Picard internal quantities (group: solver_internal).
% Output: data/output_<tag>/solver_internal.nc
% Source-of-truth: flux_vars struct populated in COMPASS.m main loop
%
% These are the per-layer Q/grad/conductivity fields used inside the Picard
% iteration (vapor decomposition, multi-component liquid flux, etc.). Live
% under solver_internal because they're a diagnostic of the numerical solver,
% not state.
%
% All fields are layer-resolved (NL) along the soil profile.
% Change: 2026-07-18 Jizixing Zhu -- distinguish the heat/dry-air kernel
%   liquid reconstruction from conservative Richards flux and expose the air
%   pressure gradient in physical Pa cm-1.

    g = 'solver_internal';

    % ---- Constitutive liquid-flux reconstruction + components ----
    liquidComment = ['Accepted-state reconstruction from the heat/dry-air ', ...
        'coefficient kernel; may include freeze-head, temperature, and air-', ...
        'pressure terms. Not the conservative Richards mass flux or top ', ...
        'boundary infiltration flux. Positive downward.'];
    reg.register(struct('name','constitutive_liquid_flux', ...
        'long_name','Constitutive liquid-flux reconstruction per layer', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QLiquid', 'source_code','src/COMPASS.m', ...
        'transform','none', 'comment',liquidComment));
    reg.register(struct('name','constitutive_liquid_flux_h', ...
        'long_name','Constitutive liquid-flux head component', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QLiquid_h', 'transform','none', 'comment',liquidComment));
    reg.register(struct('name','constitutive_liquid_flux_t', ...
        'long_name','Constitutive liquid-flux thermal component', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QLiquid_T', 'transform','none', 'comment',liquidComment));
    reg.register(struct('name','constitutive_liquid_flux_a', ...
        'long_name','Constitutive liquid-flux air-pressure component', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QLiquid_A', 'transform','none', 'comment',liquidComment));

    % ---- Vapor flux + components ----
    reg.register(struct('name','q_vapor', 'long_name','Vapor flux per layer (h+T+A)', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QVapor', 'transform','none'));
    reg.register(struct('name','q_vapor_h', 'long_name','Vapor flux from h gradient', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QVapor_h', 'transform','none'));
    reg.register(struct('name','q_vapor_t', 'long_name','Vapor flux from T gradient', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QVapor_T', 'transform','none'));
    reg.register(struct('name','q_vapor_a', 'long_name','Vapor flux from air-pressure gradient', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QVapor_A', 'transform','none'));

    % ---- Air flux ----
    reg.register(struct('name','q_air', 'long_name','Dry air flux per layer', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.QAir', 'transform','none', ...
        'comment','Only when cfg.lSoilairefc=1'));

    % ---- Gradients (for diagnostic plotting) ----
    reg.register(struct('name','gradient_matric_head', 'long_name','Matric head gradient per layer', ...
        'units','cm cm-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.Grad_h', 'transform','none'));
    reg.register(struct('name','gradient_temperature', 'long_name','Temperature gradient per layer', ...
        'units','K cm-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.Grad_T', 'transform','none'));
    reg.register(struct('name','gradient_air_pressure', 'long_name','Air pressure gradient per layer', ...
        'units','Pa cm-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.GradPg', 'transform','none', ...
        'comment','Writer divides the internal 10 Pa pressure scale by 10.'));

    % ---- Element-average conductivities ----
    reg.register(struct('name','cond_hydraulic_avg', 'long_name','Element-average hydraulic conductivity', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.CondHydraulicAvg', 'transform','none'));
    reg.register(struct('name','cond_thermal_avg', 'long_name','Element-average thermal conductivity for water', ...
        'units','cm K-1 s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.CondThermalAvg', 'transform','none'));
    reg.register(struct('name','cond_vapor_avg', 'long_name','Element-average vapor conductivity', ...
        'units','cm s-1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.CondVaporAvg', 'transform','none'));

    % ---- Saturation diagnostics ----
    reg.register(struct('name','saturation_water_layer', 'long_name','Effective water saturation per layer', ...
        'units','1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.SatWater', 'transform','none'));
    reg.register(struct('name','saturation_air_layer', 'long_name','Effective air saturation per layer', ...
        'units','1', 'dims',{{'time','layer'}}, 'group',g, ...
        'source','flux_vars.SatAir', 'transform','none'));
end
