function writeSolverInternalStep(registry, built, kt)
%WRITESOLVERINTERNALSTEP  Export accepted-state constitutive-kernel diagnostics.
%
%   The heat/dry-air coefficient kernels evaluate these quantities at the
%   converged state. Their liquid-flux reconstruction is not the accepted
%   conservative Richards mass flux; it may include freeze-head, temperature,
%   and air-pressure terms. The scheduler retains the final accepted tile,
%   and this function only converts public units and reverses the internal
%   bottom-to-surface layer order. No constitutive relation is recomputed.
%   Editor: Jizixing Zhu; Date: 2026-07-16.
%   Change: 2026-07-18 Jizixing Zhu -- rename the liquid reconstruction and
%     convert the internal air-pressure gradient scale to Pa cm-1.
    if ~isfield(built.workspace, 'solver_diagnostics') ...
            || isempty(fieldnames(built.workspace.solver_diagnostics))
        return;
    end
    source = built.workspace.solver_diagnostics;
    mappings = { ...
        'constitutive_liquid_flux', 'QL'; ...
        'constitutive_liquid_flux_h', 'QL_h'; ...
        'constitutive_liquid_flux_t', 'QL_T'; ...
        'constitutive_liquid_flux_a', 'QL_a'; ...
        'q_vapor_h', 'QVH'; ...
        'q_vapor_t', 'QVT'; ...
        'q_vapor_a', 'QVa'; ...
        'q_air', 'Qa'; ...
        'gradient_matric_head', 'DhDZ'; ...
        'gradient_temperature', 'DTDZ'; ...
        'gradient_air_pressure', 'DPgDZ'; ...
        'cond_hydraulic_avg', 'KLhBAR'; ...
        'cond_thermal_avg', 'KLTBAR'; ...
        'cond_vapor_avg', 'DTDBAR'; ...
        'saturation_water_layer', 'Se'; ...
        'saturation_air_layer', 'Sa'};
    for i = 1:size(mappings, 1)
        sourceName = mappings{i, 2};
        if isfield(source, sourceName) ...
                && numel(source.(sourceName)) == built.domain.NL
            value = source.(sourceName)(:);
            if strcmp(sourceName, 'DPgDZ')
                value = value ./ 10;
            end
            registry.write(mappings{i, 1}, flip(value), kt);
        end
    end
    if all(isfield(source, {'QVH','QVT','QVa'}))
        vaporTotal = source.QVH(:) + source.QVT(:) + source.QVa(:);
        registry.write('q_vapor', flip(vaporTotal), kt);
    end
end
