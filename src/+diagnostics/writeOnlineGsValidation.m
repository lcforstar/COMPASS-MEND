function writeOnlineGsValidation(reg, diag, KT)
%WRITEONLINEGSVALIDATION  Write temporary online Medlyn/thermal diagnostics.
%
% Inputs:
%   reg   [inout] diagnostics.Registry
%   diag  [in]    scalar diagnostic struct from fluxes.online_gs_diag
%   KT    [in]    [-] outer time-step index
%
% [DIAG 2026-06-19] Temporary validation support. Delete after the annual
% Medlyn/SOX/thermal-acclimation validation is archived.

    fields = { ...
        'medlyn_gs_model_sun', 'medlyn_gs_model_sha', ...
        'medlyn_gs_from_rcw_sun', 'medlyn_gs_from_rcw_sha', ...
        'medlyn_gs_residual_sun', 'medlyn_gs_residual_sha', ...
        'medlyn_a_sun', 'medlyn_a_sha', ...
        'medlyn_ag_sun', 'medlyn_ag_sha', ...
        'medlyn_cs_sun', 'medlyn_cs_sha', ...
        'medlyn_ci_sun', 'medlyn_ci_sha', ...
        'medlyn_vpd_sun', 'medlyn_vpd_sha', ...
        'medlyn_tleaf_sun', 'medlyn_tleaf_sha', ...
        'medlyn_q_sun', 'medlyn_q_sha', ...
        'medlyn_sfactor_sun', 'medlyn_sfactor_sha', ...
        'medlyn_g0', 'medlyn_g1', ...
        'thermal_tgrowth', 'thermal_tgrowth_clamped', ...
        'thermal_delta_s_vcmax', 'thermal_delta_s_jmax', ...
        'thermal_topt_vcmax', 'thermal_topt_jmax', ...
        'thermal_vcmax25_sun', 'thermal_vcmax25_sha', ...
        'thermal_jmax25_sun', 'thermal_jmax25_sha', ...
        'thermal_rd25_sun', 'thermal_rd25_sha', ...
        'thermal_vcmax_sun', 'thermal_vcmax_sha', ...
        'thermal_jmax_sun', 'thermal_jmax_sha', ...
        'thermal_rd_sun', 'thermal_rd_sha'};

    if isempty(diag) || ~isstruct(diag)
        return
    end

    for i = 1:numel(fields)
        name = fields{i};
        if isfield(diag, name)
            reg.write(name, diag.(name), KT);
        end
    end
end
