function writePlantNitrogenStep(registry, built, kt)
%WRITEPLANTNITROGENSTEP  Export accepted vegetation C/N state and diagnostics.
%
%   The writer reads only Y.plant_cn and diagnostic rows committed by
%   init.scatterNitrogenVariables after the outer step is accepted. It does
%   not reconstruct the legacy NitrogenVariables time-series container and
%   does not feed any value back into vegetation physics.
%
%   Plant C and N closure use the same cumulative in/out terms and complete
%   pool inventory as the legacy audit, including transfer, storage, coarse
%   root, and carbon-debt pools.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.

    if ~isfield(built, 'control') ...
            || ~isfield(built.control, 'switches') ...
            || ~isfield(built.control.switches, 'lPlantCN') ...
            || ~isfield(built.control.switches, 'lNefc') ...
            || built.control.switches.lPlantCN ~= 1 ...
            || built.control.switches.lNefc ~= 1
        return;
    end
    if ~isfield(built, 'Y') || ~isfield(built.Y, 'plant_cn') ...
            || ~isstruct(built.Y.plant_cn) ...
            || ~isfield(built.Y.plant_cn, 'C') ...
            || ~isfield(built.Y.plant_cn, 'N')
        return;
    end
    pc = built.Y.plant_cn;

    writeMappings(registry, pc.N, { ...
        'plant_n_labile', 'labile'; ...
        'plant_n_leaf', 'leaf'; ...
        'plant_n_root_fine', 'root_fine'; ...
        'plant_n_livestem', 'livestem'; ...
        'plant_n_deadstem', 'deadstem'; ...
        'plant_n_fruit', 'fruit'; ...
        'plant_n_root_storage', 'root_storage'; ...
        'plant_n_stem_storage', 'stem_storage'}, kt);
    writeScalar(registry, 'plant_n_storage', ...
        fieldValue(pc.N, 'root_storage') + fieldValue(pc.N, 'stem_storage'), kt);

    writeMappings(registry, pc.C, { ...
        'plant_c_labile', 'labile'; ...
        'plant_c_leaf', 'leaf'; ...
        'plant_c_root_fine', 'root_fine'; ...
        'plant_c_livestem', 'livestem'; ...
        'plant_c_deadstem', 'deadstem'; ...
        'plant_c_livecroot', 'livecroot'; ...
        'plant_c_deadcroot', 'deadcroot'; ...
        'plant_c_fruit', 'fruit'; ...
        'plant_c_root_storage', 'root_storage'; ...
        'plant_c_stem_storage', 'stem_storage'; ...
        'plant_c_xsmr', 'xsmr'}, kt);
    writeScalar(registry, 'plant_c_storage', ...
        fieldValue(pc.C, 'root_storage') + fieldValue(pc.C, 'stem_storage'), kt);

    if isfield(pc, 'accum') && isstruct(pc.accum)
        writeMappings(registry, pc.accum, { ...
            'cum_n_harvest', 'cum_N_harvest'; ...
            'cum_n_leaf_litter', 'cum_N_leaf_litter'; ...
            'cum_n_root_litter', 'cum_N_root_litter'; ...
            'cum_n_prune_litter', 'cum_N_prune_litter'; ...
            'cum_n_mortality', 'cum_N_mortality'; ...
            'cum_c_harvest', 'cum_C_harvest'; ...
            'cum_c_leaf_litter', 'cum_C_leaf_litter'; ...
            'cum_c_root_litter', 'cum_C_root_litter'; ...
            'cum_c_prune_litter', 'cum_C_prune_litter'; ...
            'cum_c_mortality', 'cum_C_mortality'; ...
            'cum_c_xsmr_writeoff', 'cum_C_xsmr_writeoff'; ...
            'cum_gpp_plant', 'cum_GPP'; ...
            'cum_r_a_potential', 'cum_R_a_potential'; ...
            'cum_storage_drawdown_count', 'cum_storage_drawdown_count'}, kt);
    end

    if isfield(built, 'diagnostics')
        plantDiag = diagnosticRow(built.diagnostics, 'plantN_diag', kt);
        nscDiag = diagnosticRow(built.diagnostics, 'nsc_diag', kt);
        turnoverDiag = diagnosticRow(built.diagnostics, 'turnover_diag', kt);
        writePlantProcessDiagnostics(registry, plantDiag, nscDiag, kt);
        writeMappings(registry, turnoverDiag, { ...
            'n_harvest_today', 'harvest_today'; ...
            'n_leaf_litter_today', 'leaf_litter_today'; ...
            'n_root_litter_today', 'root_litter_today'; ...
            'n_spring_release_today', 'storage_release_today'}, kt);
        if isfield(built.diagnostics, 'frPHU_diag') ...
                && numel(built.diagnostics.frPHU_diag) >= kt
            writeScalar(registry, 'frphu', built.diagnostics.frPHU_diag(kt), kt);
        end
    end

    writeLunaDiagnostics(registry, built.Y, kt);
    writeConservationResiduals(registry, pc, kt);
end

