        'growth_respiration', 'R_g'; ...
        'r_m_leaf_actual', 'r_m_leaf_actual'; ...
        'r_m_root_actual', 'r_m_root_actual'; ...
        'r_m_stem_actual', 'r_m_stem_actual'; ...
        'r_m_livecroot_actual', 'r_m_livecroot_actual'; ...
        'r_m_fruit_actual', 'r_m_fruit_actual'; ...
        'r_g_actual', 'r_g_actual'; ...
        'ra_above_actual', 'ra_above_actual'; ...
        'ra_below_actual', 'ra_below_actual'; ...
        'plant_n_growth_factor', 'f_N_growth'; ...
