function row = diagnosticRow(diagnosticsState, name, kt)
% Return one committed diagnostic struct or an empty struct.
    row = struct();
    if isfield(diagnosticsState, name) ...
            && numel(diagnosticsState.(name)) >= kt ...
            && isstruct(diagnosticsState.(name)(kt))
        row = diagnosticsState.(name)(kt);
    end
end

function writeMappings(registry, source, mappings, kt)
% Write finite scalar fields using output-name/source-name pairs.
    if ~isstruct(source)
        return;
    end
    for i = 1:size(mappings, 1)
        if isfield(source, mappings{i, 2})
            writeScalar(registry, mappings{i, 1}, source.(mappings{i, 2}), kt);
        end
    end
end

function writeScalar(registry, name, value, kt)
% Registry scalar write guard: missing/unmaterialized values remain fill data.
    if (isnumeric(value) || islogical(value)) && isscalar(value) ...
            && isreal(value) && isfinite(double(value))
        registry.write(name, double(value), kt);
    end
end

function total = sumFields(container, names)
% Sum a required physical inventory without implicit field omission.
    total = 0;
    for i = 1:numel(names)
        total = total + fieldValue(container, names{i});
    end
end

function value = fieldValue(container, name)
% Read one required finite scalar; fail instead of silently changing closure.
    assert(isstruct(container) && isfield(container, name) ...
            && (isnumeric(container.(name)) || islogical(container.(name))) ...
            && isscalar(container.(name)) && isreal(container.(name)) ...
            && isfinite(double(container.(name))), ...
        'diagnostics:writePlantNitrogenStep:invalidAcceptedField', ...
        'Accepted plant C/N field %s must be a finite real scalar.', name);
    value = double(container.(name));
end

