        'resp_beta_sub', 'resp_beta_sub'; ...
        'resp_substrate', 'resp_substrate_g'; ...
        'c_labile_target', 'C_labile_target_g'; ...
        'c_storage_to_labile', 'C_storage_to_labile'}, kt);
end

function writeLunaDiagnostics(registry, Y, kt)
% Export the last accepted daily LUNA result carried in prognostic state.
    if ~isfield(Y, 'plant_acclimation') ...
            || ~isfield(Y.plant_acclimation, 'luna_state')
        return;
    end
    state = Y.plant_acclimation.luna_state;
    writeMappings(registry, state, { ...
        'vcmax25_luna', 'last_Vcmax25'; ...
        'jmax25_luna', 'last_Jmax25'; ...
        'luna_fnca', 'last_FNCa'; ...
        'luna_pnlc', 'last_PNlc'; ...
        'luna_pncb', 'last_PNcb'; ...
        'cab_from_nlc', 'last_Cab_nlc'}, kt);
end

function writeConservationResiduals(registry, pc, kt)
% Reproduce the complete accepted plant C and N inventory ledgers.
    if ~isfield(pc, 'accum') || ~isfield(pc, 'baseline') ...
            || ~isfield(pc, 'transfer')
        return;
    end
    carbonNow = sumFields(pc.C, { ...
        'labile','leaf','root_fine','livestem','deadstem','livecroot', ...
        'deadcroot','fruit','root_storage','stem_storage','xsmr'}) ...
        + sumFields(pc.transfer.C, {'leaf','root','livestem'});
    nitrogenNow = sumFields(pc.N, { ...
        'labile','leaf','root_fine','livestem','deadstem','livecroot', ...
        'deadcroot','fruit','root_storage','stem_storage'}) ...
        + sumFields(pc.transfer.N, {'leaf','root','livestem'});
    a = pc.accum;
    carbonResidual = fieldValue(a, 'cum_GPP') + fieldValue(a, 'cum_C_xsmr_writeoff') ...
        - fieldValue(a, 'cum_R_a') ...
        - fieldValue(a, 'cum_C_harvest') - fieldValue(a, 'cum_C_leaf_litter') ...
        - fieldValue(a, 'cum_C_root_litter') - fieldValue(a, 'cum_C_prune_litter') ...
        - fieldValue(a, 'cum_C_mortality') ...
        - (carbonNow - fieldValue(pc.baseline, 'C_pool_init_const'));
    nitrogenResidual = fieldValue(a, 'cum_U_N') - fieldValue(a, 'cum_N_harvest') ...
        - fieldValue(a, 'cum_N_leaf_litter') - fieldValue(a, 'cum_N_root_litter') ...
        - fieldValue(a, 'cum_N_prune_litter') - fieldValue(a, 'cum_N_mortality') ...
        - (nitrogenNow - fieldValue(pc.baseline, 'N_pool_init_const'));
    writeScalar(registry, 'plant_c_residual', carbonResidual, kt);
    writeScalar(registry, 'plant_n_residual', nitrogenResidual, kt);
end

