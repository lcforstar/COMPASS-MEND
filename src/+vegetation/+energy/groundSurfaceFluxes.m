function flux = groundSurfaceFluxes(surface, atmosphere)
%GROUNDSURFACEFLUXES  Partition ground turbulent fluxes over bare soil and snow.
%
%   Inputs:
%     surface.temperature_C              [degC, n x 1] legacy shared skin-temperature fallback
%     surface.bare_temperature_C         [degC, n x 1] optional bare-soil skin temperature
%     surface.snow_temperature_C         [degC, n x 1] optional snow skin temperature
%     surface.soil_water_potential_J_kg  [J kg-1] bare-soil Kelvin potential
%     surface.soil_resistance_s_m        [s m-1] bare-soil vapor resistance
%     surface.snow                       [struct] optional ClimaLand snow diagnostics
%     atmosphere.ra_heat_s_m             [s m-1] aerodynamic heat resistance
%     atmosphere.ra_water_s_m            [s m-1] aerodynamic vapor resistance
%     atmosphere.vapor_pressure_hPa      [hPa] atmospheric vapor pressure
%     atmosphere.air_temperature_C       [degC] air temperature
%     atmosphere.vapor_to_humidity_hPa_inverse [hPa-1] e-to-q conversion
%     atmosphere.air_density_kg_m3       [kg m-3] moist-air density
%
%   Returns:
%     flux.latent_total_W_m2             [W m-2] grid-mean ground latent heat
%     flux.latent_bare_contribution_W_m2 [W m-2] bare-area contribution
%     flux.latent_snow_contribution_W_m2 [W m-2] snow-area contribution
%     flux.latent_bare_tile_W_m2         [W m-2] flux per bare-soil area
%     flux.latent_snow_tile_W_m2         [W m-2] flux per snow-covered area
%     flux.vapor_bare_contribution_kg_m2_s [kg m-2 s-1] grid-mean bare vapor
%     flux.vapor_snow_contribution_kg_m2_s [kg m-2 s-1] grid-mean snow vapor
%     flux.sensible_total_W_m2           [W m-2] grid-mean sensible heat
%     flux.sensible_bare_tile_W_m2       [W m-2] flux per bare-soil area
%     flux.sensible_snow_tile_W_m2       [W m-2] flux per snow-covered area
%     flux.dlatent_dT_W_m2_K              [W m-2 K-1] Picard tangent
%
%   Method:
%     Bare soil and snow are parallel turbulent-exchange pathways: bare soil
%     keeps its matric-potential and surface resistance, whereas snow uses a
%     saturated surface with zero soil resistance. Snow latent heat blends
%     vaporization and sublimation by the diagnosed liquid fraction. The two
%     pathways are area-weighted exactly once, so their mass and energy can be
%     handed to the separate soil and snow ledgers without reconstructing them
%     from mixed H/LE values. Signed vapor flux is retained: positive values
%     evaporate/sublimate toward the atmosphere and negative values represent
%     dew/deposition into the owning surface store.
%
%   Reference implementation:
%     ClimaLand src/standalone/Snow/snow_parameterizations.jl,
%     snow_surface_specific_humidity; and boundary_fluxes.jl,
%     snow_boundary_fluxes! (Apache-2.0).
%
%   Editor: Jizixing Zhu; Date: 2026-07-17.
%   Change: 2026-07-18 Jizixing Zhu -- separate bare-soil and snow skin
%           temperatures, sensible heat, latent heat, and vapor mass fluxes.
%   Change: 2026-07-19 Jizixing Zhu -- expose tile sensible-heat temperature
%           tangents for the CLM-style soil-top energy-response boundary.

    requiredSurface = {'soil_water_potential_J_kg', 'soil_resistance_s_m'};
    requiredAtmosphere = {'ra_heat_s_m', 'ra_water_s_m', ...
        'vapor_pressure_hPa', 'air_temperature_C', ...
        'vapor_to_humidity_hPa_inverse', 'air_density_kg_m3'};
    requireFields(surface, requiredSurface, 'surface');
    requireFields(atmosphere, requiredAtmosphere, 'atmosphere');

    bareTemperature = resolveTemperature(surface, ...
        'bare_temperature_C', 'temperature_C', 'bare soil');
    snowTemperature = resolveSnowTemperature(surface, bareTemperature);
    snowFraction = 0;
    liquidFraction = 0;
    if isfield(surface, 'snow') && isstruct(surface.snow) ...
            && isfield(surface.snow, 'cover_fraction')
        snowFraction = min(max(double(surface.snow.cover_fraction), 0), 1);
        if isfield(surface.snow, 'liquid_fraction')
            liquidFraction = min(max(double(surface.snow.liquid_fraction), 0), 1);
        end
    end

    [latentBare, sensibleBare, ~, ~, lambdaVapor, slopeBare] = ...
        vegetation.energy.heatFluxesClm45( ...
            atmosphere.ra_heat_s_m, surface.soil_resistance_s_m, ...
            bareTemperature, atmosphere.vapor_pressure_hPa, ...
            atmosphere.air_temperature_C, ...
            atmosphere.vapor_to_humidity_hPa_inverse, ...
            surface.soil_water_potential_J_kg, 0, 0, ...
            atmosphere.ra_water_s_m, atmosphere.air_density_kg_m3, 0);

    [latentSnowVapor, sensibleSnow, ~, ~, lambdaSnowVapor, slopeSnow] = ...
        vegetation.energy.heatFluxesClm45( ...
        atmosphere.ra_heat_s_m, 0, snowTemperature, ...
        atmosphere.vapor_pressure_hPa, atmosphere.air_temperature_C, ...
        atmosphere.vapor_to_humidity_hPa_inverse, 0, 0, 0, ...
        atmosphere.ra_water_s_m, atmosphere.air_density_kg_m3, 0);

    phys = equations.physicalConstants();
    fusionHeat = phys.lambda_sub - phys.lambda_vap;
    lambdaSnow = lambdaSnowVapor + (1 - liquidFraction) * fusionHeat;
    latentSnow = latentSnowVapor .* lambdaSnow ./ max(lambdaSnowVapor, eps);

    bareContribution = (1 - snowFraction) .* latentBare;
    snowContribution = snowFraction .* latentSnow;
    sensibleBareContribution = (1 - snowFraction) .* sensibleBare;
    sensibleSnowContribution = snowFraction .* sensibleSnow;
    bareVaporContribution = bareContribution ./ max(lambdaVapor, eps);
    snowVaporContribution = snowContribution ./ max(lambdaSnow, eps);
    dBare = atmosphere.air_density_kg_m3 .* lambdaVapor ...
        .* atmosphere.vapor_to_humidity_hPa_inverse .* slopeBare ...
        ./ (atmosphere.ra_water_s_m + surface.soil_resistance_s_m);
    dSnow = atmosphere.air_density_kg_m3 .* lambdaSnow ...
        .* atmosphere.vapor_to_humidity_hPa_inverse .* slopeSnow ...
        ./ atmosphere.ra_water_s_m;
    dSensible = atmosphere.air_density_kg_m3 .* phys.Cp_air_SI ...
        ./ atmosphere.ra_heat_s_m;

    % Compatibility aliases in the second half of this struct are not
    % cross-domain interfaces; they remain only for legacy SCOPE callers.
    flux = struct( ...
        'cover_fraction', snowFraction, ...
        'ground_upward_latent_heat_flux_W_m2', ...
            bareContribution + snowContribution, ...
        'bare_ground_upward_latent_heat_flux_contribution_W_m2', ...
            bareContribution, ...
        'snow_upward_latent_heat_flux_contribution_W_m2', ...
            snowContribution, ...
        'bare_ground_upward_latent_heat_flux_tile_W_m2', latentBare, ...
        'snow_upward_latent_heat_flux_tile_W_m2', latentSnow, ...
        'bare_ground_upward_water_vapor_flux_contribution_kg_m2_s', ...
            bareVaporContribution, ...
        'snow_upward_water_vapor_flux_contribution_kg_m2_s', ...
            snowVaporContribution, ...
        'ground_upward_water_vapor_flux_kg_m2_s', ...
            bareVaporContribution + snowVaporContribution, ...
        'ground_upward_sensible_heat_flux_W_m2', ...
            sensibleBareContribution + sensibleSnowContribution, ...
        'bare_ground_upward_sensible_heat_flux_contribution_W_m2', ...
            sensibleBareContribution, ...
        'snow_upward_sensible_heat_flux_contribution_W_m2', ...
            sensibleSnowContribution, ...
        'bare_ground_upward_sensible_heat_flux_tile_W_m2', sensibleBare, ...
        'snow_upward_sensible_heat_flux_tile_W_m2', sensibleSnow, ...
        'latent_total_W_m2', bareContribution + snowContribution, ...
        'latent_bare_contribution_W_m2', bareContribution, ...
        'latent_snow_contribution_W_m2', snowContribution, ...
        'latent_bare_tile_W_m2', latentBare, ...
        'latent_snow_tile_W_m2', latentSnow, ...
        'vapor_bare_contribution_kg_m2_s', bareVaporContribution, ...
        'vapor_snow_contribution_kg_m2_s', snowVaporContribution, ...
        'vapor_total_kg_m2_s', bareVaporContribution ...
            + snowVaporContribution, ...
        'sensible_total_W_m2', sensibleBareContribution ...
            + sensibleSnowContribution, ...
        'sensible_bare_contribution_W_m2', sensibleBareContribution, ...
        'sensible_snow_contribution_W_m2', sensibleSnowContribution, ...
        'sensible_bare_tile_W_m2', sensibleBare, ...
        'sensible_snow_tile_W_m2', sensibleSnow, ...
        'dlatent_bare_tile_dT_W_m2_K', dBare, ...
        'dlatent_snow_tile_dT_W_m2_K', dSnow, ...
        'dlatent_bare_contribution_dT_W_m2_K', ...
            (1 - snowFraction) .* dBare, ...
        'dlatent_snow_contribution_dT_W_m2_K', ...
            snowFraction .* dSnow, ...
        'dlatent_dT_W_m2_K', (1 - snowFraction) .* dBare ...
            + snowFraction .* dSnow, ...
        'dsensible_bare_tile_dT_W_m2_K', dSensible, ...
        'dsensible_snow_tile_dT_W_m2_K', dSensible, ...
        'dsensible_bare_contribution_dT_W_m2_K', ...
            (1 - snowFraction) .* dSensible, ...
        'dsensible_snow_contribution_dT_W_m2_K', ...
            snowFraction .* dSensible, ...
        'dsensible_dT_W_m2_K', dSensible, ...
        'lambda_bare_J_kg', lambdaVapor, ...
        'lambda_snow_J_kg', lambdaSnow);
end

function temperature = resolveTemperature(surface, preferred, fallback, label)
% Resolve a tile temperature while retaining the legacy shared input.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    if isfield(surface, preferred) && ~isempty(surface.(preferred))
        temperature = surface.(preferred);
    elseif isfield(surface, fallback) && ~isempty(surface.(fallback))
        temperature = surface.(fallback);
    else
        error('groundSurfaceFluxes:missingTemperature', ...
            'surface.%s or surface.%s is required for %s.', ...
            preferred, fallback, label);
    end
end

function temperature = resolveSnowTemperature(surface, bareTemperature)
% Resolve prognostic snow temperature before falling back to the bare skin.
% Editor: Jizixing Zhu; Date: 2026-07-18.
    if isfield(surface, 'snow_temperature_C') ...
            && ~isempty(surface.snow_temperature_C)
        temperature = surface.snow_temperature_C;
    elseif isfield(surface, 'snow') && isstruct(surface.snow) ...
            && isfield(surface.snow, 'temperature_C') ...
            && ~isempty(surface.snow.temperature_C)
        temperature = surface.snow.temperature_C;
    elseif isfield(surface, 'temperature_C') ...
            && ~isempty(surface.temperature_C)
        temperature = surface.temperature_C;
    else
        temperature = bareTemperature;
    end
    if isscalar(temperature) && ~isscalar(bareTemperature)
        temperature = repmat(temperature, size(bareTemperature));
    end
end

function requireFields(container, names, label)
% Validate the small typed input structs.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    for i = 1:numel(names)
        assert(isfield(container, names{i}), ...
            'groundSurfaceFluxes:missingField', ...
            '%s.%s is required.', label, names{i});
    end
end
