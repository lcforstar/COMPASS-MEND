function in = assembleEbalInput(model, kt, dt_s)
%ASSEMBLEEBALINPUT  Build new-chain energy-balance input from model containers.
%
%   in = vegetation.energy.assembleEbalInput(model, kt, dt_s) packs the target-name
%   struct defined in EBAL_IO_CONTRACT.md §5. Pure read of model; no mutation.
%
%   Returns:
%     in [struct]  Target input groups: time, soil, domain, control,
%                  canopy_params, iteration, scope_static, scope_step, plant_hydro
%
%   Inputs:
%     model  [in]  struct  COMPASS model with built.Y / workspace / parameters
%     kt     [in]  [-]     One-based outer-step index
%     dt_s   [in]  [s]     Outer-step duration
%
%   Method:
%     Map built containers onto snake_case target paths. Does not call ebal.
%     See plant/+energy/EBAL_IO_CONTRACT.md §5.2.
%
%   Editor: Jizixing Zhu; Date: 2026-07-16.
%   Change: 2026-07-18 Jizixing Zhu -- remove the retired Fourier-G ebal input.

    built = model.built;
    domain = built.domain;
    numerics = built.control.numerics;
    switches = built.control.switches;
    canopy_parameters = built.parameters.veg.canopy;
    structure = built.parameters.veg.structure;
    soil_parameters = built.parameters.soil;
    soil_optical = built.parameters.scope.soil_optical;
    scope_static = built.p.scope_static;
    scope_step = built.workspace.scope_step;

    in = struct();
    in.time = struct( ...
        'kt', kt, ...
        'dt_s', dt_s);

    in.soil = struct();
    in.soil.state = struct( ...
        'h', built.Y.h, ...
        'theta_liquid', built.workspace.derived.Theta_LL, ...
        'root_sink', built.workspace.flux.Srt);
    in.soil.params = struct( ...
        'theta_s', soil_parameters.theta_s, ...
        'theta_r', soil_parameters.theta_r, ...
        'field_capacity', soil_parameters.field_capacity, ...
        'rho_thermal_dry', soil_optical.Rho_Thermal_Soil_Dry, ...
        'rho_thermal_wet', soil_optical.Rho_Thermal_Soil_Wet);
    in.soil.conductivity = built.workspace.derived.KfL_h;

    in.domain = struct( ...
        'nl', domain.NL, ...
        'nn', domain.NN, ...
        'dz_cm', domain.dz, ...
        'latitude_deg', domain.site.latitude, ...
        'longitude_deg', domain.site.longitude);

    in.control = struct( ...
        'tol_eb_W_m2', numerics.Tol_EB, ...
        'max_iter', numerics.Max_Iter_EB, ...
        'use_anderson', logical(switches.lEbalAnderson), ...
        'canopy_air_profile_eb', logical(readField(canopy_parameters, ...
            'canopy_air_profile_eb', false)), ...
        'use_canopy_air_ta_feedback', logical(readField(canopy_parameters, ...
            'canopy_air_ta_feedback', true)), ...
        'use_canopy_air_ea_feedback', logical(readField(canopy_parameters, ...
            'canopy_air_ea_feedback', false)), ...
        'use_canopy_air_co2_feedback', logical(readField(canopy_parameters, ...
            'canopy_air_co2_feedback', false)), ...
        'defer_nonconvergence_warning', true);

    in.canopy_params = struct( ...
        'lai_max', canopy_parameters.LAI_max, ...
        'w_leaf_max_m', structure.w_leaf_max, ...
        'crop_code', structure.CropCode);

    in.iteration = struct( ...
        'max_iter', numerics.Max_Iter_EB, ...
        'tol_W_m2', numerics.Tol_EB, ...
        'relax_weight', 1);

    in.scope_static = struct( ...
        'options', scope_static.options, ...
        'spectral', scope_static.spectral);

    in.scope_step = struct( ...
        'rad', scope_step.rad, ...
        'gap', scope_step.gap, ...
        'leafopt', scope_step.leafopt, ...
        'angles', scope_step.angles, ...
        'meteo', scope_step.meteo, ...
        'soil_surface', scope_step.Soil, ...
        'canopy', scope_step.canopy, ...
        'leafbio', scope_step.leafbio, ...
        'xyt', scope_step.xyt, ...
        'profiles', scope_step.profiles, ...
        'interception', scope_step.interception);

    in.plant_hydro = built.p.plantHydro;
end

function value = readField(container, name, fallback)
    value = fallback;
    if isfield(container, name) && ~isempty(container.(name))
        value = container.(name);
    end
end
