function in = assembleEbalFromLegacy( ...
        iter, options, spectral, rad, gap, leafopt, angles, meteo, Soil, canopy, leafbio, ...
        xyt, k, profiles, Delt_t, SoilVariables, VanGenuchten, cfg, KT, plantHydro, KL_h, interception)
%ASSEMBLEEBALFROMLEGACY  Build target-name ebal input from legacy COMPASS workspace.
%
%   in = vegetation.energy.assembleEbalFromLegacy(...) packs the EBAL_IO_CONTRACT
%   target struct so vegetation.energy.ebal / ebalProfile can run from COMPASS.m
%   (legacy multi-arg workspace). Pure packing; no physics.
%
%   Editor: Jizixing Zhu; Date: 2026-07-16.
%   Change: 2026-07-16 Jizixing Zhu — add legacy adapter after deleting root ebal_clm45*.
%   Change: 2026-07-18 Jizixing Zhu -- remove the retired Fourier-G ebal input.

    if nargin < 22 || isempty(interception)
        interception = struct();
    end

    in = struct();
    in.time = struct('kt', KT, 'dt_s', Delt_t);

    srt = [];
    if isstruct(SoilVariables) && isfield(SoilVariables, 'Srt')
        srt = SoilVariables.Srt;
    end

    in.soil = struct();
    in.soil.state = struct( ...
        'h', SoilVariables.hh, ...
        'theta_liquid', SoilVariables.Theta_LL, ...
        'root_sink', srt);
    in.soil.params = struct( ...
        'theta_s', VanGenuchten.Theta_s, ...
        'theta_r', VanGenuchten.Theta_r, ...
        'field_capacity', VanGenuchten.Theta_f, ...
        'rho_thermal_dry', readOpt(cfg, 'Env', 'Rho_Thermal_Soil_Dry', 0.086), ...
        'rho_thermal_wet', readOpt(cfg, 'Env', 'Rho_Thermal_Soil_Wet', 0.020));
    in.soil.conductivity = KL_h;

    in.domain = struct( ...
        'nl', cfg.Grid.NL, ...
        'nn', cfg.Grid.NN, ...
        'dz_cm', cfg.Grid.DeltZ, ...
        'latitude_deg', cfg.Latitude, ...
        'longitude_deg', cfg.Longitude);

    in.control = struct( ...
        'tol_eb_W_m2', readOpt(cfg, 'Env', 'Tol_EB', iter.maxEBer), ...
        'max_iter', iter.maxit, ...
        'use_anderson', logical(readOptFlat(cfg, 'lEbalAnderson', true)), ...
        'canopy_air_profile_eb', false, ...
        'use_canopy_air_ta_feedback', logical(readOpt(cfg, 'Env', 'Use_Canopy_Air_Ta_Feedback', true)), ...
        'use_canopy_air_ea_feedback', logical(readOpt(cfg, 'Env', 'Use_Canopy_Air_ea_Feedback', false)), ...
        'use_canopy_air_co2_feedback', logical(readOpt(cfg, 'Env', 'Use_Canopy_Air_CO2_Feedback', false)), ...
        'defer_nonconvergence_warning', false);

    in.canopy_params = struct( ...
        'lai_max', readOpt(cfg, 'Veg', 'LAI_max', []), ...
        'w_leaf_max_m', readOpt(cfg, 'Veg', 'w_leaf_max', []), ...
        'crop_code', readOpt(cfg, 'Veg', 'CropCode', []));

    in.iteration = struct( ...
        'max_iter', iter.maxit, ...
        'tol_W_m2', iter.maxEBer, ...
        'relax_weight', iter.Wc);

    in.scope_static = struct('options', options, 'spectral', spectral);
    in.scope_step = struct( ...
        'rad', rad, 'gap', gap, 'leafopt', leafopt, 'angles', angles, ...
        'meteo', meteo, 'soil_surface', Soil, 'canopy', canopy, ...
        'leafbio', leafbio, 'xyt', xyt, 'profiles', profiles, ...
        'interception', interception);
    in.plant_hydro = plantHydro;

    % k and KT are the same time index in the legacy call site
    if ~isempty(k)
        in.time.kt = k;
    end
end

function value = readOpt(cfg, group, name, fallback)
    value = fallback;
    if ~isstruct(cfg) && ~isobject(cfg)
        return
    end
    if isobject(cfg) && isprop(cfg, group)
        g = cfg.(group);
    elseif isstruct(cfg) && isfield(cfg, group)
        g = cfg.(group);
    else
        return
    end
    if (isobject(g) && isprop(g, name)) || (isstruct(g) && isfield(g, name))
        value = g.(name);
    end
end

function value = readOptFlat(cfg, name, fallback)
    value = fallback;
    if (isobject(cfg) && isprop(cfg, name)) || (isstruct(cfg) && isfield(cfg, name))
        value = cfg.(name);
    end
end
