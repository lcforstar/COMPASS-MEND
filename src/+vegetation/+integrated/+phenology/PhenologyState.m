function state = PhenologyState()
%PHENOLOGYSTATE  Construct per-PFT phenology state container (CLM5 _patch style).
%
%   Returns:
%     state    struct with all phenology state variables initialised to dormant
%              values. Caller persists this across timesteps (mutable).
%
%   State variables:
%     chilldays      [days]   Accumulated days with T_avg < T_chill_base (5°C).
%                             Increment in dormant period; reset on cold-month
%                             cycle gated by ifsensechill flag.
%                             Source: LPJ-GUESS driver.cpp:550-551 + 583-586.
%     gdd5           [°C·d]   Accumulated growing degree days with T_base=5°C.
%                             gdd5 += max(0, T_avg - 5). Reset jointly with
%                             chilldays at cold-month onset.
%                             Source: LPJ-GUESS driver.cpp:548.
%     mtemp_last     [°C]     Previous-day monthly running-mean temperature
%                             (used for cold-month reset detection).
%     ifsensechill   [bool]   Latches true on warmest day of year, gates
%                             cold-month reset to prevent premature reset.
%                             Source: LPJ-GUESS driver.cpp:540-545.
%     phen           [-]      Current leaf-on fraction [0, 1]. Driven by Sykes
%                             1996 ramp (season_decid) or analogous formulas
%                             for other branches.
%                             Source: LPJ-GUESS growth.cpp:96-99.
%     aphen          [days]   Cumulative leaf-on days this season (Σ phen daily).
%                             Capped at APHEN_MAX=210 (LPJ-GUESS growth.cpp:50).
%                             Reset on coldest day of year.
%                             Source: LPJ-GUESS growth.cpp:150-152.
%     onset_flag     [bool]   True between budburst onset and full leaf cover
%                             (phen monotonically rising).
%                             Source: CLM5 CNVegStateType.F90:81 onset_flag_patch.
%     offset_flag    [bool]   True between senescence onset and dormancy.
%                             Source: CLM5 CNVegStateType.F90:87 offset_flag_patch.
%     dormant_flag   [bool]   True during winter dormancy (initial state).
%                             Source: CLM5 CNVegStateType.F90:79 dormant_flag_patch.
%     budburst_doy   [DOY]    Day-of-year of budburst this year (diagnostic).
%                             Set when phen first exceeds 0 from dormant.
%     senescence_doy [DOY]    Day-of-year of senescence onset (diagnostic).
%                             Set when offset_flag flips true.
%
%   Architecture:
%     CLM5 maintains these as per-patch _patch arrays in CNVegStateType.F90:79-88.
%     COMPASS site-level: each PFT has its own state struct (e.g.,
%     state_apple = PhenologyState(); state_grass = PhenologyState();).
%
%   References:
%     LPJ-GUESS v4.1.1 source:
%       D:/OneDrive/LPJ-GUESS-v4.1.1/guess_4.1/modules/growth.cpp:50,96-99,150-152
%       D:/OneDrive/LPJ-GUESS-v4.1.1/guess_4.1/modules/driver.cpp:540-551,583-586
%       (Sykes MT, Prentice IC, Cramer W (1996) J Biogeogr 23:203-233 cited at
%        growth.cpp:89; original PDF not available locally — source-code citation)
%     CLM5 CTSM release-clm5.0.37:
%       D:/OneDrive/CTSM-release-clm5.0.37/src/biogeochem/CNVegStateType.F90:79-88
%       (Lawrence DM et al. (2019) JAMES 11:4245, CLM5 Tech Note)
% Change: 2026-09-30 Wenjie Liu -- distinguish the crop thermal-maturity
%   marker from observed-canopy harvest; retain one-shot event and season memory.

% Field descriptions (full doc per field — placed here to avoid struct() syntax break):
%   prev_dayl       [h]    Yesterday's daylength. Used by CLM5 ws_flag computation
%                          (CNPhenologyMod.F90:802: dayl(g) >= prev_dayl(g)).
%   ws_flag         [0/1]  Winter→summer solstice flag (CLM5 line 802-807):
%                          1 = dayl rising (after winter solstice),
%                          0 = dayl falling (after summer solstice).
%   onset_gddflag   [0/1]  CLM5 line 718 / 885-898: GDD accumulator active flag.
%                          Turns ON at ws_flag flip 0→1 (winter solstice).
%                          Turns OFF at ws_flag flip 1→0 (summer solstice) if
%                          threshold not reached this season.
%   onset_gdd       [°C·d] CLM5 onset_gdd_patch (line 719): spring GDD accumulator,
%                          gated by ws_flag + onset_gddflag.

state = struct( ...
    'chilldays',      0, ...
    'chill_day',      0, ...    % [13b] Cesaraccio chill-day accumulator (apple)
    'anti_chill_day', 0, ...    % [13b] Cesaraccio anti-chill-day accumulator (apple)
    'gdd5',           0, ...
    'mtemp_last',     NaN, ...
    'ifsensechill',   false, ...
    'prev_dayl',      NaN, ...
    'ws_flag',        0, ...
    'onset_gddflag',  0, ...
    'onset_gdd',      0, ...
    'phen',           0, ...
    'aphen',          0, ...
    'onset_flag',     false, ...
    'onset_counter',  0, ...
    'offset_flag',    false, ...
    'offset_counter', 0, ...
    'leaf_flush_pending', false, ...    % [leaf-flush 2026-06-08] one-shot: cold-month reset interrupted leaf-fall -> turnover drains residual leaf C/N this step
    'dormant_flag',   true, ...
    'budburst_doy',   NaN, ...
    'senescence_doy', NaN, ...
    'gdd5_at_budburst', NaN, ...
    'bloom_doy',      NaN, ...
    'gdd5_at_bloom',  NaN, ...
    'DS_fruit',       0, ...
    'harvested_flag', false, ...
    'harvest_doy',    NaN, ...
    ... % CoLM/CLM5 winter-wheat crop state (inactive for every non-crop PFT)
    'crop_live',             false, ...
    'crop_phase',            0, ...
    'crop_planting_event',   false, ...
    'crop_emergence_event',  false, ...
    'crop_harvest_event',    false, ...
    'crop_grainfill_event',  false, ...
    'crop_maturity_event',   false, ...
    'crop_mature_flag',      false, ...
    'crop_season_id',        0, ...
    'crop_days_after_planting', 0, ...
    'crop_gddplant',         0, ...
    'crop_gddmaturity',      NaN, ...
    'crop_hui',              0, ...
    'crop_cumvd',            0, ...
    'crop_vf',               0, ...
    'crop_a_leaf',           0, ...
    'crop_a_root',           0, ...
    'crop_a_stem',           0, ...
    'crop_a_repr',           0);

end
