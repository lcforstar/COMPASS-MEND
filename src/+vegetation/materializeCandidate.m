function candidate = materializeCandidate(input_stage, post_ebal, daily_stage)
%MATERIALIZECANDIDATE Build the vegetation-owned accepted-state candidate.
%
%   Inputs:
%     input_stage [struct] Pre-energy LAI and acclimation candidate.
%     post_ebal   [struct] Finalized cross-zone energy/hydraulic result.
%     daily_stage [struct] Phenology, root-N, and optional plant-C/N result.
%
%   Returns:
%     candidate [struct] Plant water storage, canopy water, vegetation
%               phenology/LAI, plant C/N, and acclimation memories.
%
%   Physical contract:
%     Cross-zone energy and root--soil exchange may produce values used here,
%     but their result is copied into one vegetation-owned candidate only at
%     the acceptance boundary.  This function neither advances soil state nor
%     installs a candidate into accepted state.
%
%   Editor: Jizixing Zhu; Date: 2026-07-20.
%   Change: 2026-08-09 Jizixing Zhu -- allow empty organ storage for the
%           steady_spac scheme while validating storage-enabled candidates.
    assert(isstruct(input_stage) && isfield(input_stage, 'leaf_resp_Ta'), ...
        'vegetation:materializeCandidate:missingInputStage', ...
        'input_stage.leaf_resp_Ta is required.');
    requiredPost = {'lai_state', 'canopy_water', 'luna_climate_entry'};
    for i = 1:numel(requiredPost)
        name = requiredPost{i};
        assert(isstruct(post_ebal) && isfield(post_ebal, name) ...
                && ~isempty(post_ebal.(name)), ...
            'vegetation:materializeCandidate:missingPostEbalField', ...
            'Final energy result.%s is required.', name);
    end
    assert(isstruct(post_ebal) ...
            && isfield(post_ebal, 'plant_hydraulic_W'), ...
        'vegetation:materializeCandidate:missingPostEbalField', ...
        'Final energy result.plant_hydraulic_W is required.');
    plantWater = post_ebal.plant_hydraulic_W;
    assert(isempty(plantWater) ...
            || (isnumeric(plantWater) && numel(plantWater) == 3 ...
                && all(isfinite(plantWater(:)))), ...
        'vegetation:materializeCandidate:badHydraulicStorage', ...
        ['plant_hydraulic_W must be empty for steady_spac or contain ', ...
         'finite root, stem, and leaf water storage.']);
    assert(isstruct(daily_stage) && isfield(daily_stage, 'phenology') ...
            && ~isempty(daily_stage.phenology), ...
        'vegetation:materializeCandidate:missingDailyStage', ...
        'daily_stage.phenology is required.');
    candidate = struct( ...
        'plant_cn', daily_stage.plant_cn, ...
        'plant_hydraulic_W', plantWater, ...
        'canopy_water', post_ebal.canopy_water, ...
        'vegetation', struct( ...
            'phenology', daily_stage.phenology, ...
            'lai_state', post_ebal.lai_state), ...
        'leaf_resp_Ta', input_stage.leaf_resp_Ta, ...
        'luna_climate_entry', post_ebal.luna_climate_entry);
end
