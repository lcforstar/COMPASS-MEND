function schedule=recordAcceptedTransportTile(schedule,diagnostics,thetaEndpoint,dt_s,bottomFace)
%RECORDACCEPTEDTRANSPORTTILE Append one accepted liquid-transport driver.
%
%   schedule stores accepted soil-solver tiles in chronological order. Each
%   column is one piecewise-constant driver segment: dt_s [s], liquid water
%   content thetaEndpoint [-], and the coupled liquid-flux reconstruction
%   QL/QL_h/QL_T/QL_a [cm s^-1]. Arrays use COMPASS bottom-to-surface element
%   order. thetaEndpoint and QL come from the same converged tile endpoint;
%   downstream split transport therefore uses a consistent first-order time
%   level and converges as the accepted soil tile is refined.
%
%   Rejected trials must never call this function. An empty input schedule
%   initializes schema version 1; subsequent calls require the same NL.
%
% Editor: Wenjie Liu; Date: 2026-09-21.
% Change: 2026-09-29 Wenjie Liu -- optionally retain a water-owned physical
% bottom liquid-face record; never reconstruct it from element-centre QL.
    if nargin<5,bottomFace=[];end
    required={'QL','QL_h','QL_T','QL_a'};
    assert(isstruct(diagnostics)&&isscalar(diagnostics), ...
        'solver:transportScheduleDiagnostics', ...
        'Accepted transport diagnostics must be a scalar struct.');
    for i=1:numel(required)
        name=required{i};
        assert(isfield(diagnostics,name)&&isnumeric(diagnostics.(name)) ...
            &&isvector(diagnostics.(name))&&all(isfinite(diagnostics.(name)(:))), ...
            'solver:transportScheduleFlux', ...
            'Accepted transport tile requires finite vector field %s.',name);
    end
    thetaEndpoint=thetaEndpoint(:);
    nl=numel(thetaEndpoint);
    assert(nl>=1&&all(isfinite(thetaEndpoint))&&all(thetaEndpoint>=0) ...
        &&isnumeric(dt_s)&&isscalar(dt_s)&&isfinite(dt_s)&&dt_s>0, ...
        'solver:transportScheduleDriver', ...
        'Accepted transport theta and dt must be finite and physical.');
    for i=1:numel(required)
        assert(numel(diagnostics.(required{i}))==nl, ...
            'solver:transportScheduleShape', ...
            'Accepted transport flux and theta arrays must share NL.');
    end

    if isempty(schedule)
        schedule=struct('schema_version',1, ...
            'time_representation','piecewise_constant_accepted_endpoint', ...
            'spatial_order','bottom_to_surface_elements', ...
            'tile_count',0,'elapsed_s',0,'dt_s',zeros(1,0), ...
            'theta_liquid_endpoint',zeros(nl,0), ...
            'QL',zeros(nl,0),'QL_h',zeros(nl,0), ...
            'QL_T',zeros(nl,0),'QL_a',zeros(nl,0));
    else
        assert(isstruct(schedule)&&isscalar(schedule) ...
            &&isfield(schedule,'schema_version')&&schedule.schema_version==1 ...
            &&isfield(schedule,'theta_liquid_endpoint') ...
            &&size(schedule.theta_liquid_endpoint,1)==nl, ...
            'solver:transportScheduleSchema', ...
            'Accepted transport schedule schema or NL changed within an outer step.');
    end

    column=schedule.tile_count+1;
    if ~isempty(bottomFace)
        assert(isstruct(bottomFace)&&isscalar(bottomFace) ...
            &&bottomFace.dt_s==dt_s ...
            &&abs(bottomFace.t_end_s-bottomFace.t_start_s-dt_s)<=1e-9*max(1,dt_s), ...
            'solver:bottomFaceTime','Bottom-face record must cover its accepted tile.');
        if column==1,schedule.bottom_liquid_faces={};end
        assert(isfield(schedule,'bottom_liquid_faces') ...
            &&numel(schedule.bottom_liquid_faces)==column-1, ...
            'solver:bottomFaceCoverage','Missing earlier accepted bottom-face tile.');
        if column>1
            previous=schedule.bottom_liquid_faces{end};
            assert(abs(previous.t_end_s-bottomFace.t_start_s)<=1e-9*max(1,dt_s), ...
                'solver:bottomFaceTime','Accepted bottom-face intervals must be contiguous.');
        end
        schedule.bottom_liquid_faces{column}=bottomFace;
    else
        assert(~isfield(schedule,'bottom_liquid_faces'),'solver:bottomFaceCoverage', ...
            'Every accepted tile must retain the open bottom-face record.');
    end
    schedule.dt_s(column)=dt_s;
    schedule.theta_liquid_endpoint(:,column)=thetaEndpoint;
    for i=1:numel(required)
        name=required{i};
        schedule.(name)(:,column)=diagnostics.(name)(:);
    end
    schedule.tile_count=column;
    schedule.elapsed_s=schedule.elapsed_s+dt_s;
end
