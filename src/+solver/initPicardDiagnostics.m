function [saveHistory, summary, history] = initPicardDiagnostics(tS, cfg)
%INITPICARDDIAGNOSTICS Allocate compact Picard diagnostics.

saveHistory = true;
if isstruct(cfg) && isfield(cfg, 'lSavePicardHistory')
    saveHistory = logical(cfg.lSavePicardHistory);
elseif isobject(cfg) && isprop(cfg, 'lSavePicardHistory')
    saveHistory = logical(cfg.lSavePicardHistory);
end

summary = repmat(struct( ...
    'converged', false, ...
    'iterations', 0, ...
    'water_error', NaN, ...
    'energy_error', NaN, ...
    'reason', '', ...
    'aa_used', 0), tS, 1);

history = repmat(struct( ...
    'water_error', [], ...
    'energy_error', [], ...
    'hh_surface', [], ...
    'TT_surface', [], ...
    'aa_applied', [], ...
    'bc_switch', [], ...
    'stage', {{}}), tS, 1);
end
