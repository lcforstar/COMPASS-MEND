function transformed = transformDryAirStorageCoordinate( ...
        row, mass_h, mass_T, mass_P)
%TRANSFORMDRYAIRSTORAGECOORDINATE Change P_g to nodal dry-air mass.
%
%   The lumped nodal dry-air mass tangent is
%
%     dM_a = M_h dh + M_T dT + M_P dP_g,
%
%   so a correction row in (h,T,P_g) coordinates is transformed exactly to
%   (h,T,M_a) with
%
%     dP_g = -(M_h/M_P)dh -(M_T/M_P)dT +(1/M_P)dM_a.
%
%   M_a [g cm^-2] remains a defined conservative coordinate when gas-filled
%   pore volume vanishes. The transform is algebraic and does not alter the
%   constitutive storage, spatial operator, boundary row, or residual.
%
%   Editor: Jizixing Zhu; Date: 2026-08-12.

    mass_h = mass_h(:);
    mass_T = mass_T(:);
    mass_P = mass_P(:);
    n = numel(mass_P);
    assert(numel(mass_h) == n && numel(mass_T) == n ...
            && all(isfinite(mass_h)) && all(isfinite(mass_T)) ...
            && all(isfinite(mass_P)) && all(mass_P > 0), ...
        'transformDryAirStorageCoordinate:badMassDerivative', ...
        'M_h/M_T/M_P must be finite nodal vectors and M_P must be positive.');
    validateRow(row, n);

    p_h = -mass_h ./ mass_P;
    p_T = -mass_T ./ mass_P;
    p_M = 1 ./ mass_P;
    transformed = struct( ...
        'h', addBanks(row.h, ...
            solver.scaleTridiagonalColumns(row.P, p_h)), ...
        'T', addBanks(row.T, ...
            solver.scaleTridiagonalColumns(row.P, p_T)), ...
        'M', solver.scaleTridiagonalColumns(row.P, p_M), ...
        'rhs', row.rhs(:), ...
        'transform', struct('p_h', p_h, 'p_T', p_T, 'p_M', p_M));
end

function validateRow(row, n)
% Validate the common h/T/P correction-row contract.
    assert(isstruct(row) && all(isfield(row, {'h','T','P','rhs'})) ...
            && numel(row.rhs) == n && all(isfinite(row.rhs(:))), ...
        'transformDryAirStorageCoordinate:badRow', ...
        'row must contain finite h/T/P banks and an n-vector rhs.');
    for name = {'h','T','P'}
        bank = row.(name{1});
        assert(isstruct(bank) && isfield(bank, 'matrix') ...
                && isfield(bank, 'lower') ...
                && isequal(size(bank.matrix), [n,2]) ...
                && numel(bank.lower) == max(n-1,0) ...
                && all(isfinite(bank.matrix(:))) ...
                && all(isfinite(bank.lower(:))), ...
            'transformDryAirStorageCoordinate:badBank', ...
            'Every row bank must use the finite tridiagonal bank contract.');
    end
end

function out = addBanks(a, b)
% Add compact tridiagonal banks with identical shapes.
    out = struct('matrix', a.matrix + b.matrix, ...
        'lower', a.lower(:) + b.lower(:));
end
