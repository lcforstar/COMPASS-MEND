%
%   Return:
%     balance [struct] Fixed water-balance schema with NaN values [mm].
%
%   A rejected hour has no accepted storage change or boundary integral, so
%   NaN is required; zero would fabricate a closed physical budget.
%   Editor: Jizixing Zhu; Date: 2026-07-16.
%   Change: 2026-07-17 Jizixing Zhu -- use the canonical realized-flux soil
%           water ledger without infiltration aliases.
    balance = struct( ...
        'residual_mm', NaN, ...
        'soil_top_input_mm', NaN, ...
        'soil_bottom_loss_mm', NaN, ...
        'root_sink_mm', NaN, ...
        'soil_storage_change_mm', NaN, ...
        'soil_storage_before_mm', NaN, ...
        'soil_storage_after_mm', NaN);
end
