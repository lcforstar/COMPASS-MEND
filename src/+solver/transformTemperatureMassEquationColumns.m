function transformed = transformTemperatureMassEquationColumns( ...
        row, U_h, U_T, U_M)
%TRANSFORMTEMPERATUREMASSEQUATIONCOLUMNS Change T to U beside dry-air mass.
%
%   For a row in (h,T,M_a) coordinates and internal-energy tangent
%
%     dU = U_h dh + U_T dT + U_M dM_a,
%
%   return the exact (h,U,M_a) coordinate representation. This is the
%   dry-air-mass counterpart of transformTemperatureEquationColumns.
%
%   Editor: Jizixing Zhu; Date: 2026-08-12.

    U_h = U_h(:);
    U_T = U_T(:);
    U_M = U_M(:);
    n = numel(U_T);
    assert(numel(U_h) == n && numel(U_M) == n ...
            && all(isfinite(U_h)) && all(isfinite(U_T)) ...
            && all(isfinite(U_M)) && all(U_T > 0), ...
        'transformTemperatureMassEquationColumns:badEnergyDerivative', ...
        'U_h/U_T/U_M must be finite and U_T must be positive.');
    assert(isstruct(row) && all(isfield(row, {'h','T','M','rhs'})), ...
        'transformTemperatureMassEquationColumns:badRow', ...
        'row must contain h/T/M banks and rhs.');

    a_h = U_h ./ U_T;
    a_U = 1 ./ U_T;
    a_M = U_M ./ U_T;
    transformed = struct( ...
        'h', subtractBanks(row.h, ...
            solver.scaleTridiagonalColumns(row.T, a_h)), ...
        'U', solver.scaleTridiagonalColumns(row.T, a_U), ...
        'M', subtractBanks(row.M, ...
            solver.scaleTridiagonalColumns(row.T, a_M)), ...
        'rhs', row.rhs(:), ...
        'transform', struct('a_h', a_h, 'a_U', a_U, 'a_M', a_M));
end

function out = subtractBanks(a, b)
% Subtract compact tridiagonal banks with identical shapes.
    out = struct('matrix', a.matrix - b.matrix, ...
        'lower', a.lower(:) - b.lower(:));
end
