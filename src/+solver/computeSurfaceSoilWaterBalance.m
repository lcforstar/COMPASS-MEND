function balance = computeSurfaceSoilWaterBalance(surface, soilBalance)
%COMPUTESURFACESOILWATERBALANCE  Close surface storage plus the soil column.
%
%   QMT is the internal interface between the surface reservoir and soil, so
%   it cancels from this combined ledger and is never counted twice:
%
%     residual = liquid supply - surface evaporation - runoff
%                - bottom loss - root sink
%                - Delta(surface storage) - Delta(soil storage).
%
%   All returned terms are accepted outer-step amounts [mm]. Positive supply
%   enters the combined domain; positive evaporation, runoff, bottom loss, and
%   root sink leave it. Storage changes are signed after-minus-before values.
%
%   Editor: Jizixing Zhu; Date: 2026-07-17.
%   Change: 2026-07-17 Jizixing Zhu -- close the combined ledger with the
%           accepted evaporation reaction, never the unmet atmospheric demand.
    requiredSurface = {'has_data','liquid_supply_integral_cm', ...
        'evap_actual_integral_cm','runoff_integral_cm', ...
        'storage_tendency_integral_cm','q_in_actual_integral_cm'};
    for i = 1:numel(requiredSurface)
        assert(isfield(surface, requiredSurface{i}), ...
            'computeSurfaceSoilWaterBalance:missingSurfaceField', ...
            'Surface summary lacks %s.', requiredSurface{i});
    end
    assert(surface.has_data, ...
        'computeSurfaceSoilWaterBalance:noSurfaceData', ...
        'A combined ledger requires accepted atmospheric surface data.');
    requiredSoil = {'soil_top_input_mm','soil_bottom_loss_mm', ...
        'root_sink_mm','soil_storage_change_mm','residual_mm'};
    for i = 1:numel(requiredSoil)
        assert(isfield(soilBalance, requiredSoil{i}) ...
                && isfinite(soilBalance.(requiredSoil{i})), ...
            'computeSurfaceSoilWaterBalance:badSoilField', ...
            'Soil balance lacks finite %s.', requiredSoil{i});
    end

    balance = solver.emptySurfaceSoilWaterBalance();
    balance.has_data = true;
    balance.liquid_supply_mm = surface.liquid_supply_integral_cm * 10;
    balance.surface_evaporation_mm = ...
        surface.evap_actual_integral_cm * 10;
    balance.runoff_mm = surface.runoff_integral_cm * 10;
    balance.bottom_loss_mm = soilBalance.soil_bottom_loss_mm;
    balance.root_sink_mm = soilBalance.root_sink_mm;
    balance.surface_storage_change_mm = ...
        surface.storage_tendency_integral_cm * 10;
    balance.soil_storage_change_mm = ...
        soilBalance.soil_storage_change_mm;
    balance.total_storage_change_mm = ...
        balance.surface_storage_change_mm ...
        + balance.soil_storage_change_mm;
    balance.residual_mm = balance.liquid_supply_mm ...
        - balance.surface_evaporation_mm - balance.runoff_mm ...
        - balance.bottom_loss_mm - balance.root_sink_mm ...
        - balance.total_storage_change_mm;

    qinMm = surface.q_in_actual_integral_cm * 10;
    interfaceMismatch = qinMm - soilBalance.soil_top_input_mm;
    assert(abs(interfaceMismatch) <= max(1e-8, ...
            abs(soilBalance.residual_mm) + 1e-8), ...
        'computeSurfaceSoilWaterBalance:interfaceMismatch', ...
        ['Surface qin and soil QMT ledger disagree by %.6g mm; the ', ...
         'internal interface must cancel before publishing a combined budget.'], ...
        interfaceMismatch);
end
