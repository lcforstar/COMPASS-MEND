function [model, result] = advanceSoilEquationOuterStep(model, kt, dtOuter_s, dtMin_s, ...
        strategy, solveCtl, currentFlux, tOuterStart_s, solveFn)
%ADVANCESOILEQUATIONOUTERSTEP  Shared tile/retry scheduler for soil equations.
%
%   This function owns trial tiling, retry shrink, substep rollback, accepted
%   mid-tile carry, per-trial BoundaryRequest materialization, and accepted
%   water-flux accumulation. It does not commit the final tile, outer-step
%   payloads, or the model clock; those remain driver-owned transactions.
%   Natural runOneStep and standalone experiments therefore share the same
%   scheduler and the same solver.attemptSolveSoilEquations entry point.
%
%   solveFn has the contract [model,outcome] = solveFn(model,kt,dt,solveCtl).
%   Boundary requests are re-materialized immediately before every call, so a
%   rejected retry keeps the same physical start time and evaluates its new dt
%   without a mutable provider cursor.  The heat request therefore sees the
%   finalized current-outer-step snow candidate on every tile, while water may
%   change its atmospheric active set at fixed dt and dry air keeps the same
%   forcing slice; all three requests feed one coupled h/U/P_g attempt.
%
%   Editor: Jizixing Zhu; Date: 2026-07-11.
%   Change: 2026-10-06 Wenjie Liu -- keep the optional particle bottom-face
%           gate closed when disabled soil microbes have no transport flag.
%   Change: 2026-07-12 Jizixing Zhu -- size the audit record for disabled
%           adaptation; decideSubstep now owns the single-attempt policy.
%   Change: 2026-07-13 Jizixing Zhu -- accumulate optional accepted heat
%           boundary fluxes while retaining the water-boundary scheduler.
%   Change: 2026-07-13 Jizixing Zhu -- rename the scheduler for all supported
%           water/heat/dry-air switch combinations; water-only is one mode.
%   Change: 2026-07-14 Jizixing Zhu -- allow earned timestep growth between
%           accepted tiles while preserving accepted-dt and rollback semantics.
%   Change: 2026-07-14 Jizixing Zhu -- preserve a larger next-step suggestion
%           when the accepted final tile is clipped by the hour remainder.
%   Change: 2026-07-15 Jizixing Zhu -- accumulate an accepted-substep soil
%           internal-energy ledger; rejected trials contribute no storage,
%           boundary energy, or root-carried energy.
%   Change: 2026-07-15 Jizixing Zhu -- materialize one immutable soil boundary
%           request per attempt and accumulate accepted water/heat/dry-air
%           actual fluxes with a shared inward-positive convention.
%   Change: 2026-07-15 Jizixing Zhu -- require the complete accepted energy
%           closure whenever heat is enabled; never silently omit a tile.
%   Change: 2026-07-16 Jizixing Zhu -- accumulate an exact accepted-substep
%           dry-air mass ledger from endpoint storage and coupled fluxes.
%   Change: 2026-07-16 Jizixing Zhu -- retain the final accepted tile's
%           already-computed layer flux diagnostics for output only.
%   Change: 2026-07-17 Jizixing Zhu -- resolve atmospheric supply/storage/runoff
%           active sets at fixed dt before invoking numerical timestep shrink.
%   Change: 2026-07-17 Jizixing Zhu -- accept the Picard-internal surface
%           active set and degrade unresolved outer fallback cycles to dt shrink.
%   Change: 2026-07-17 Jizixing Zhu -- aggregate accepted finite-ponding
%           complementarity diagnostics over the outer step.
%   Change: 2026-07-17 Jizixing Zhu -- use a first-trial wet-feasibility
%           predictor for abrupt liquid-supply increases.
%   Change: 2026-07-17 Jizixing Zhu -- keep non-atmospheric water requests
%           outside the surface-summary accumulator.
%   Change: 2026-07-17 Jizixing Zhu -- retain each rejected trial's timestep
%           and coupled gate residuals so outer-step failures are diagnosable.
%   Change: 2026-07-17 Jizixing Zhu -- aggregate the applied soil heat mode
%           and requested temperature/flux separately from the solved flux.
%   Change: 2026-07-17 Jizixing Zhu -- aggregate realized and unmet dry-limit
%           evaporation separately from the upstream evaporation demand.
%   Change: 2026-07-17 Jizixing Zhu -- document same-step snow heat-boundary
%           materialization inside the shared h/U/P_g tile scheduler.
%   Change: 2026-07-19 Jizixing Zhu -- aggregate the affine surface-energy
%           response metadata and distinguish its Robin top-row mode.
%   Change: 2026-08-12 Jizixing Zhu -- require the solver's dry-air physical
%           admissibility gate before accepting or carrying a soil tile.
%   Change: 2026-08-15 Jizixing Zhu -- consume the solver's exact candidate
%           surface-state record in the compatibility fallback path.
%   Change: 2026-09-12 Codex -- grow the attempt audit buffer from a small
%           initial capacity instead of allocating the multi-million-entry
%           theoretical worst case on every ordinary outer step.
%   Change: 2026-09-21 Wenjie Liu -- retain every accepted tile's matched
%           QL and liquid-water endpoint with its true dt for chronological
%           split-transport replay; rejected trials remain absent.

    if nargin < 9 || isempty(solveFn), solveFn = @solver.attemptSolveSoilEquations; end
    assert(isa(solveFn, 'function_handle'), ...
        'advanceSoilEquationOuterStep:badSolveFn', 'solveFn must be a function handle.');
    assert(isnumeric(dtOuter_s) && isscalar(dtOuter_s) && isfinite(dtOuter_s) ...
        && isnumeric(dtMin_s) && isscalar(dtMin_s) && isfinite(dtMin_s) ...
        && dtOuter_s > 0 && dtMin_s > 0 && dtMin_s <= dtOuter_s, ...
        'advanceSoilEquationOuterStep:badTimeStep', ...
        'Require finite 0 < dtMin_s <= dtOuter_s.');

    sub = model.runtime.substep;
    [sub, startOut] = solver.decideSubstep(sub, strategy, dtOuter_s, dtMin_s, 'start', struct());
    subDtNext = startOut.dt;
    tol_s = 1e-9;
    elapsed_s = 0;
    residual = 0;
    iters = 0;
    waterAccum = solver.initWaterFluxAccum();
    surfaceAccum = emptySurfaceBoundarySummary();
    heatAccum = struct('QET', 0, 'QEB', 0, 'weight_sum', 0);
    energyBalance = soil.thermal.emptyColumnEnergyBalance();
    dryAirMassBalance = soil.gas.emptyColumnMassBalance();
    boundarySummary = soil.boundary.emptyFluxSummary();
    solverDiagnostics = struct();
    acceptedTransportSchedule = [];
    acceptedTileCount = 0;
    attemptLimit = maxAttemptCount(dtOuter_s, dtMin_s, strategy);
    attemptCells = cell(min(64, attemptLimit), 1);
    attemptCount = 0;

    while elapsed_s < dtOuter_s - tol_s
        dt_s = solver.substepTimeSlice(subDtNext, elapsed_s, dtOuter_s);
        if dt_s == 0, break; end
        subSnapshot = solver.snapshotSubstepState(model.built);
        acceptedSubstep = false;
        surfaceRegime = '';
        surfaceSwitchCount = 0;

        while true
            soilRequest = solver.materializeSoilBoundaryTrial( ...
                model.built, currentFlux, kt, ...
                tOuterStart_s + elapsed_s, dt_s);
            predictWetStart = isempty(surfaceRegime) ...
                && elapsed_s <= tol_s;
            soilRequest.water = soil.water.boundary.attachSurfaceState( ...
                soilRequest.water, model.built, surfaceRegime, ...
                predictWetStart);
            request = soilRequest.water;  % retained audit view for water-only callers
            trialCtl = solveCtl;
            trialCtl.water_boundary_request = request;
            trialCtl.soil_boundary_request = soilRequest;
            [model, outcome] = solveFn(model, kt, dt_s, trialCtl);
            residual = outcome.residual;
            iters = outcome.iters;
            if isfield(outcome, 'waterBoundaryRequest') ...
                    && ~isempty(outcome.waterBoundaryRequest)
                request = outcome.waterBoundaryRequest;
                soilRequest.water = request;
            end
            if isfield(outcome, 'heatBoundaryRequest') ...
                    && isstruct(outcome.heatBoundaryRequest) ...
                    && ~isempty(fieldnames(outcome.heatBoundaryRequest))
                soilRequest.heat = outcome.heatBoundaryRequest;
            end
            surfaceDecision = struct();
            if isfield(outcome, 'surfaceWater') ...
                    && isstruct(outcome.surfaceWater) ...
                    && ~isempty(fieldnames(outcome.surfaceWater))
                surfaceDecision = outcome.surfaceWater;
            elseif outcome.converged && isfield(outcome, 'waterFlux') ...
                    && ~isempty(outcome.waterFlux)
                candidateSurface = struct('head_cm', ...
                    model.built.workspace.step.trial.h(end), ...
                    'dry_state_depleted', false, ...
                    'water_flux', outcome.waterFlux);
                if isfield(outcome, 'surfaceState') ...
                        && isstruct(outcome.surfaceState) ...
                        && ~isempty(fieldnames(outcome.surfaceState))
                    candidateSurface = outcome.surfaceState;
                end
                surfaceDecision = soil.water.boundary.evaluateSurfaceTrial( ...
                    request, candidateSurface, ...
                    surfaceToleranceCm(solveCtl), struct());
            end
            surfaceAccepted = isempty(fieldnames(surfaceDecision)) ...
                || surfaceDecision.valid;
            if isfield(outcome, 'surface_converged')
                surfaceAccepted = surfaceAccepted ...
                    && logical(outcome.surface_converged);
            elseif surfaceAccepted && isfield(surfaceDecision, 'residual_cm') ...
                    && isfinite(surfaceDecision.residual_cm)
                surfaceAccepted = surfaceDecision.complementarity_valid ...
                    && abs(surfaceDecision.residual_cm) ...
                    <= surfaceToleranceCm(solveCtl);
            end
            airPhysicallyAdmissible = ~soilRequest.dry_air.enabled ...
                || (isfield(outcome, 'dry_air_admissible') ...
                    && logical(outcome.dry_air_admissible));
            trialAccepted = logical(outcome.converged) && surfaceAccepted ...
                && airPhysicallyAdmissible;
            if trialAccepted && ~isempty(fieldnames(surfaceDecision))
                [model, outcome] = commitAcceptedSurfaceTrial( ...
                    model, outcome, request, surfaceDecision);
            end
            actual = [];
            soilActual = [];
            if isfield(outcome, 'waterFlux') && ~isempty(outcome.waterFlux)
                applied = struct();
                if isfield(outcome, 'waterBoundaryApplied')
                    applied = outcome.waterBoundaryApplied;
                end
                actual = soil.water.boundary.buildResult( ...
                    request, outcome.waterFlux, trialAccepted, applied);
            end
            if isfield(outcome, 'waterFlux')
                auditOutcome = outcome;
                auditOutcome.converged = trialAccepted;
                requestForAudit = soilRequest;
                if isfield(outcome, 'heatBoundaryRequest') ...
                        && isstruct(outcome.heatBoundaryRequest) ...
                        && ~isempty(outcome.heatBoundaryRequest)
                    requestForAudit.heat = outcome.heatBoundaryRequest;
                end
                soilActual = soil.boundary.buildResult( ...
                    requestForAudit, auditOutcome);
            end
            attemptCount = attemptCount + 1;
            assert(attemptCount <= attemptLimit, ...
                'advanceSoilEquationOuterStep:attemptCapacity', ...
                'Internal attempt-record capacity was exceeded.');
            if attemptCount > numel(attemptCells)
                nextCapacity=min(attemptLimit,max(attemptCount, ...
                    2*numel(attemptCells)));
                attemptCells{nextCapacity}=[];
            end
            attemptCells{attemptCount} = struct( ...
                'dt_s', dt_s, ...
                'request', request, 'actual', actual, ...
                'soil_boundary_request', soilRequest, ...
                'soil_boundary_result', soilActual, ...
                'surface', surfaceDecision, ...
                'surface_converged', outcomeField( ...
                    outcome, 'surface_converged', surfaceAccepted), ...
                'surface_switch_count', outcomeField( ...
                    outcome, 'surface_switch_count', 0), ...
                'surface_initial_regime', string(outcomeField( ...
                    outcome, 'surface_initial_regime', '')), ...
                'surface_final_regime', string(outcomeField( ...
                    outcome, 'surface_final_regime', '')), ...
                'surface_trace', string(outcomeField( ...
                    outcome, 'surface_trace', '')), ...
                'termination_reason', outcomeField( ...
                    outcome, 'termination_reason', ''), ...
                'accepted', trialAccepted, ...
                'converged', logical(outcome.converged), ...
                'residual', residual, 'iters', iters, ...
                'nonlinear_converged', outcomeField( ...
                    outcome, 'nonlinear_converged', false), ...
                'mass_converged', outcomeField( ...
                    outcome, 'mass_converged', false), ...
                'theta_increment', outcomeField( ...
                    outcome, 'final_theta_increment', NaN), ...
                'head_increment_cm', outcomeField( ...
                    outcome, 'final_saturated_head_increment_cm', NaN), ...
                'water_mass_residual_mm', outcomeField( ...
                    outcome, 'final_mass_residual_mm', NaN), ...
                'heat_increment_C', outcomeField( ...
                    outcome, 'final_energy_equivalent_increment_C', NaN), ...
                'energy_balance_residual_J_cm2', outcomeField( ...
                    outcome, 'final_energy_balance_residual_J_cm2', NaN), ...
                'air_relative_increment', outcomeField( ...
                    outcome, 'final_air_relative_increment', NaN), ...
                'air_mass_residual_g_cm2', outcomeField( ...
                    outcome, 'final_air_mass_residual_g_cm2', NaN), ...
                'dry_air_admissible', outcomeField( ...
                    outcome, 'dry_air_admissible', ...
                    ~soilRequest.dry_air.enabled), ...
                'minimum_dry_air_density_g_cm3', outcomeField( ...
                    outcome, 'minimum_dry_air_density_g_cm3', NaN), ...
                'minimum_dry_air_storage_g_cm3', outcomeField( ...
                    outcome, 'minimum_dry_air_storage_g_cm3', NaN), ...
                'surface_mass_residual_cm', outcomeField( ...
                    outcome, 'final_surface_mass_residual_cm', NaN));

            if trialAccepted
                acceptedSubstep = true;
                break;
            end
            if outcome.converged
                model.built = solver.restoreSubstepState( ...
                    model.built, subSnapshot);
                surfaceRegime = surfaceDecision.next_regime;
                surfaceSwitchCount = surfaceSwitchCount + 1;
                if surfaceSwitchCount <= 3
                    continue;
                end
                outcome.converged = false;
                outcome.termination_reason = 'surface_active_set_cycle';
            end
            model.built = solver.restoreSubstepState(model.built, subSnapshot);
            [sub, rejectOut] = solver.decideSubstep( ...
                sub, strategy, dtOuter_s, dtMin_s, 'reject', struct('dt', dt_s));
            dt_s = rejectOut.dt;
            surfaceRegime = '';
            surfaceSwitchCount = 0;
            if rejectOut.give_up, break; end
        end

        if ~acceptedSubstep, break; end
        elapsed_s = elapsed_s + dt_s;

        % Update trial.U = U(h,T,P_g) from the accepted state's endpoint
        % internal energy, so Y.U stays consistent with the prognostic
        % (h,T,P_g) through carrySubstepState.
        if isfield(outcome, 'energyStorage') && ~isempty(outcome.energyStorage)
            NL = model.built.domain.NL;
            dz = model.built.domain.dz;
            U_nodal = soil.thermal.assembleNodalInternalEnergy( ...
                outcome.energyStorage, zeros(NL,2), zeros(NL,2), zeros(NL,2), dz);
            model.built.workspace.step.trial.U = U_nodal;
        end
        if isfield(outcome, 'waterFlux')
            waterAccum = solver.accumulateWaterFluxAccum( ...
                waterAccum, outcome.waterFlux, dt_s / dtOuter_s);
        end
        if isfield(outcome, 'surfaceWater') ...
                && isstruct(outcome.surfaceWater) ...
                && isfield(outcome.surfaceWater, 'valid') ...
                && isfield(outcome.surfaceWater, 'complementarity_valid') ...
                && outcome.surfaceWater.valid ...
                && outcome.surfaceWater.complementarity_valid
            surfaceAccum = accumulateSurfaceBoundarySummary( ...
                surfaceAccum, outcome.surfaceWater, dt_s);
        end
        if isfield(outcome, 'solverDiagnostics')
            solverDiagnostics = outcome.solverDiagnostics;
        end
        acceptedTileCount = acceptedTileCount + 1;
        hasTransportDriver = isfield(outcome, 'solverDiagnostics') ...
            && isstruct(outcome.solverDiagnostics) ...
            && isfield(outcome.solverDiagnostics, 'QL');
        if hasTransportDriver
            assert(isfield(model.built.workspace, 'derived') ...
                    && isfield(model.built.workspace.derived, 'Theta_LL'), ...
                'advanceSoilEquationOuterStep:missingTransportTheta', ...
                ['An accepted QL tile requires its matching accepted ', ...
                 'liquid-water endpoint.']);
            thetaEndpoint = mean( ...
                model.built.workspace.derived.Theta_LL, 2);
            % Change: 2026-09-29 Wenjie Liu -- water-owned accepted bottom
            % face under the explicitly configured zero-vapor phase closure.
            bottomFace=[];
            % Change: 2026-09-29 Wenjie Liu -- numbered organic modes need
            % the same accepted physical face; no water/DIN equation change.
            domOpen=isfield(model.built.parameters,'soil_dom') ...
                &&isfield(model.built.parameters.soil_dom,'boundary') ...
                &&~strcmp(model.built.parameters.soil_dom.boundary.bottom_kind,'closed');
            % Change: 2026-09-29 Wenjie Liu -- particle-only opening also
            % requires the same physical bottom face; never inherit DOM mode.
            particleOpen=isfield(model.built.parameters,'soil_microbes') ...
                &&isfield(model.built.parameters.soil_microbes,'transport_enabled') ...
                &&model.built.parameters.soil_microbes.transport_enabled ...
                &&isfield(model.built.parameters.soil_microbes.bioparticle,'boundary') ...
                &&~strcmp(model.built.parameters.soil_microbes.bioparticle.boundary.bottom_kind,'closed');
            if domOpen||particleOpen
                firstNode=solver.activeRichardsFirstNode(model.built);
                bottomFace=soil.water.bottomLiquidBoundaryForSolutes( ...
                    soilRequest.water,outcome.waterFlux,firstNode);
            end
            acceptedTransportSchedule = solver.recordAcceptedTransportTile( ...
                acceptedTransportSchedule, outcome.solverDiagnostics, ...
                thetaEndpoint, dt_s, bottomFace);
        else
            assert(isempty(acceptedTransportSchedule), ...
                'advanceSoilEquationOuterStep:partialTransportSchedule', ...
                ['Every accepted tile in an outer step must either expose ', ...
                 'QL with matching theta or expose no transport driver.']);
        end
        if isfield(outcome, 'heatFlux') && ~isempty(outcome.heatFlux)
            weight = dt_s / dtOuter_s;
            heatAccum.QET = heatAccum.QET + outcome.heatFlux.QET * weight;
            heatAccum.QEB = heatAccum.QEB + outcome.heatFlux.QEB * weight;
            heatAccum.weight_sum = heatAccum.weight_sum + weight;
        end
        if ~isempty(soilActual)
            boundarySummary = accumulateBoundarySummary( ...
                boundarySummary, soilActual, dt_s / dtOuter_s, ...
                model.built.workspace.step.trial.T(end));
        end
        if soilRequest.heat.enabled
            assert(isfield(outcome, 'energyStorage') ...
                    && ~isempty(outcome.energyStorage) ...
                    && isfield(outcome, 'rootEnergySink') ...
                    && ~isempty(outcome.rootEnergySink) ...
                    && isfield(outcome, 'heatFlux') ...
                    && ~isempty(outcome.heatFlux), ...
                'advanceSoilEquationOuterStep:missingEnergyClosure', ...
                ['Every accepted heat tile must provide final internal ', ...
                 'energy, root-carried energy, and boundary heat fluxes.']);
            tileBalance = soil.thermal.computeColumnEnergyBalance( ...
                subSnapshot.Y.U, model.built.workspace.step.trial.U, ...
                outcome.rootEnergySink, model.built.domain.dz, ...
                outcome.heatFlux, dt_s);
            energyBalance = accumulateEnergyBalance(energyBalance, tileBalance);
        end
        if soilRequest.dry_air.enabled
            assert(isfield(outcome, 'dryAirStorageBefore') ...
                    && ~isempty(outcome.dryAirStorageBefore) ...
                    && isfield(outcome, 'dryAirStorageAfter') ...
                    && ~isempty(outcome.dryAirStorageAfter) ...
                    && isfield(outcome, 'airFlux') ...
                    && ~isempty(outcome.airFlux), ...
                'advanceSoilEquationOuterStep:missingDryAirMassClosure', ...
                ['Every accepted dry-air tile must provide endpoint storage ', ...
                 'before/after and the complete boundary mass flux.']);
            assert(outcome.dry_air_admissible ...
                    && all(outcome.dryAirStorageAfter(:) >= 0), ...
                'advanceSoilEquationOuterStep:inadmissibleDryAirCandidate', ...
                ['A dry-air tile must remain inside the nonnegative ', ...
                 'density/storage domain before carry or ledger commit.']);
            tileAirBalance = soil.gas.computeColumnMassBalance( ...
                outcome.dryAirStorageBefore, outcome.dryAirStorageAfter, ...
                model.built.domain.dz, outcome.airFlux, dt_s);
            dryAirMassBalance = accumulateDryAirMassBalance( ...
                dryAirMassBalance, tileAirBalance);
        end
        [sub, acceptOut] = solver.decideSubstep( ...
            sub, strategy, dtOuter_s, dtMin_s, 'accept', ...
            struct('iters', iters, 'dt', dt_s));
        subDtNext = acceptOut.dt;
        if elapsed_s < dtOuter_s - tol_s
            model.built = solver.carrySubstepState(model.built);
        end
    end

    attempts = emptyAttempts();
    if attemptCount > 0
        attempts = [attemptCells{1:attemptCount}];
    end
    if ~isempty(acceptedTransportSchedule)
        assert(acceptedTransportSchedule.tile_count == acceptedTileCount ...
                && abs(acceptedTransportSchedule.elapsed_s-elapsed_s) ...
                <= 1e-9*max(1,elapsed_s), ...
            'advanceSoilEquationOuterStep:incompleteTransportSchedule', ...
            ['Accepted liquid-transport schedule must cover every accepted ', ...
             'soil tile and its exact elapsed time.']);
        solverDiagnostics.accepted_transport_schedule = ...
            acceptedTransportSchedule;
    end
    liquidFluxOuterMean = solver.finalizeAcceptedTransportSchedule( ...
        acceptedTransportSchedule,elapsed_s);
    result = struct( ...
        'accepted', elapsed_s >= dtOuter_s - tol_s, ...
        'elapsed_s', elapsed_s, ...
        'residual', residual, ...
        'iters', iters, ...
        'substep', sub, ...
        'water_flux_accum', waterAccum, ...
        'surface_boundary_summary', finalizeSurfaceBoundarySummary( ...
            surfaceAccum), ...
        'heat_flux_accum', heatAccum, ...
        'energy_balance', energyBalance, ...
        'dry_air_mass_balance', dryAirMassBalance, ...
        'boundary_flux_summary', boundarySummary, ...
        'liquid_flux_outer_mean', liquidFluxOuterMean, ...
        'solver_diagnostics', solverDiagnostics, ...
        'attempts', attempts);
end

% -------------------------------------------------------------------------
function summary = emptySurfaceBoundarySummary()
% Accepted-tile accumulator for the finite-ponding complementarity boundary.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    summary = struct('has_data', false, 'elapsed_s', 0, ...
        'psi_top_integral_cm_s', 0, ...
        'q_available_integral_cm', 0, ...
        'liquid_supply_integral_cm', 0, ...
        'evap_demand_integral_cm', 0, ...
        'evap_actual_integral_cm', 0, ...
        'evap_unmet_integral_cm', 0, ...
        'q_in_actual_integral_cm', 0, ...
        'storage_tendency_integral_cm', 0, ...
        'runoff_integral_cm', 0, ...
        'excess_reaction_integral_cm', 0, ...
        'final_mode_code', NaN, 'final_mode', '', ...
        'final_psi_top_cm', NaN, ...
        'max_abs_mass_residual_cm', 0, ...
        'max_lower_complementarity_cm2', 0, ...
        'max_upper_complementarity_cm2_s', 0);
end

% -------------------------------------------------------------------------
function summary = accumulateSurfaceBoundarySummary(summary, decision, dt_s)
% Time-integrate accepted rates; retain the last state and worst residuals.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    required = {'psi_top_cm','q_available_cm_s','liquid_supply_cm_s', ...
        'evap_demand_cm_s','evap_actual_cm_s','evap_unmet_cm_s', ...
        'q_in_actual_cm_s', ...
        'storage_tendency_cm_s','excess_reaction_cm_s','mode_code', ...
        'residual_cm','lower_complementarity_cm2', ...
        'upper_complementarity_cm2_s'};
    for i = 1:numel(required)
        assert(isfield(decision, required{i}) ...
                && isfinite(decision.(required{i})), ...
            'advanceSoilEquationOuterStep:badSurfaceDiagnostic', ...
            'Accepted surface decision lacks finite field %s.', required{i});
    end
    summary.has_data = true;
    summary.elapsed_s = summary.elapsed_s + dt_s;
    summary.psi_top_integral_cm_s = summary.psi_top_integral_cm_s ...
        + decision.psi_top_cm * dt_s;
    summary.q_available_integral_cm = summary.q_available_integral_cm ...
        + decision.q_available_cm_s * dt_s;
    summary.liquid_supply_integral_cm = ...
        summary.liquid_supply_integral_cm ...
        + decision.liquid_supply_cm_s * dt_s;
    summary.evap_demand_integral_cm = ...
        summary.evap_demand_integral_cm ...
        + decision.evap_demand_cm_s * dt_s;
    summary.evap_actual_integral_cm = ...
        summary.evap_actual_integral_cm ...
        + decision.evap_actual_cm_s * dt_s;
    summary.evap_unmet_integral_cm = ...
        summary.evap_unmet_integral_cm ...
        + decision.evap_unmet_cm_s * dt_s;
    summary.q_in_actual_integral_cm = summary.q_in_actual_integral_cm ...
        + decision.q_in_actual_cm_s * dt_s;
    summary.storage_tendency_integral_cm = ...
        summary.storage_tendency_integral_cm ...
        + decision.storage_tendency_cm_s * dt_s;
    summary.runoff_integral_cm = summary.runoff_integral_cm ...
        + decision.runoff_cm_s * dt_s;
    summary.excess_reaction_integral_cm = ...
        summary.excess_reaction_integral_cm ...
        + decision.excess_reaction_cm_s * dt_s;
    summary.final_mode_code = decision.mode_code;
    summary.final_mode = decision.regime;
    summary.final_psi_top_cm = decision.psi_top_cm;
    summary.max_abs_mass_residual_cm = max( ...
        summary.max_abs_mass_residual_cm, abs(decision.residual_cm));
    summary.max_lower_complementarity_cm2 = max( ...
        summary.max_lower_complementarity_cm2, ...
        decision.lower_complementarity_cm2);
