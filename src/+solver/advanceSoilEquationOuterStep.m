function total = accumulateDryAirMassBalance(total, tile)
% Add one accepted tile while retaining the outer-step storage endpoints.
%
%   For adjacent accepted tiles, M_after(k)=M_before(k+1). Therefore the
%   outer-step storage change is the sum of tile changes, while the public
%   before/after fields retain the first/last accepted storage values.
%   Editor: Jizixing Zhu; Date: 2026-07-16.
    if ~total.has_data
        total = tile;
        return;
    end
    total.elapsed_s = total.elapsed_s + tile.elapsed_s;
    total.storage_after_g_cm2 = tile.storage_after_g_cm2;
    for name = {'storage_change_g_cm2','top_input_g_cm2', ...
            'bottom_input_g_cm2','boundary_net_input_g_cm2', ...
            'residual_g_cm2'}
        field = name{1};
        total.(field) = total.(field) + tile.(field);
    end
end

