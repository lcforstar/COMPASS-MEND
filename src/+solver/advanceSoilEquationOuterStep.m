function tolCm = surfaceToleranceCm(solveCtl)
% Convert the soil-water mass tolerance to the default surface depth ruler.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    tolMassMm = 1e-4;
    if isfield(solveCtl, 'tol_water_mass_mm') ...
            && ~isempty(solveCtl.tol_water_mass_mm)
        tolMassMm = solveCtl.tol_water_mass_mm;
    end
    tolCm = max(1e-10, tolMassMm / 10);
    if isfield(solveCtl, 'tol_surface_water_cm') ...
            && ~isempty(solveCtl.tol_surface_water_cm)
        tolCm = solveCtl.tol_surface_water_cm;
    end
end

