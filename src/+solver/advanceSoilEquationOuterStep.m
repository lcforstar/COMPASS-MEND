end

% -------------------------------------------------------------------------
function summary = accumulateBoundarySummary( ...
        summary, result, weight, soilSurfaceTemperature_C)
% Accumulate accepted boundary rates and their response-evaluation state.
% Editor: Jizixing Zhu; Date: 2026-07-15.
% Change: 2026-07-19 Jizixing Zhu -- time-average the accepted soil-surface
%         temperature used by the affine top-energy response.
    summary.water = addProcess(summary.water, result.water, weight, ...
        'actual_flux_into_domain_cm_s');
    summary.heat = addProcess(summary.heat, result.heat, weight, ...
        'actual_flux_into_domain_J_cm2_s');
    summary.heat = addHeatRequestMetadata( ...
        summary.heat, result.heat, weight, soilSurfaceTemperature_C);
    summary.dry_air = addProcess(summary.dry_air, result.dry_air, weight, ...
        'actual_flux_into_domain_g_cm2_s');
    summary.has_data = summary.water.enabled || summary.heat.enabled ...
        || summary.dry_air.enabled;
end

function process = addHeatRequestMetadata( ...
        process, result, weight, soilSurfaceTemperature_C)
% Retain the immutable heat request shared by accepted tiles in this hour.
% Editor: Jizixing Zhu; Date: 2026-07-17.
% Change: 2026-07-17 Jizixing Zhu -- retain bottom requested/applied heat mode and value.
% Change: 2026-07-19 Jizixing Zhu -- accumulate the accepted response-evaluation
%         temperature so hourly affine fluxes are reconstructed consistently.
% Change: 2026-07-19 Jizixing Zhu -- evaluate an attached affine audit at
%         the prescribed temperature when the applied top is Dirichlet.
    if isempty(fieldnames(result)), return; end
    responseTemperature_C = soilSurfaceTemperature_C;
    if strcmp(result.top.applied_kind, 'fixed_temperature') ...
            && isfinite(result.top.requested_temperature_C)
        responseTemperature_C = result.top.requested_temperature_C;
    end
    if isfinite(responseTemperature_C)
        qReference = result.top.requested_flux_into_domain_J_cm2_s;
        referenceTemperature = result.top.reference_temperature_C;
        derivative = result.top.flux_temperature_derivative_J_cm2_s_K;
        if all(isfinite([qReference, referenceTemperature, derivative]))
            process.top_response_weight_sum = ...
                process.top_response_weight_sum + weight;
            process.top_response_evaluation_temperature_weighted_sum_C = ...
                process.top_response_evaluation_temperature_weighted_sum_C ...
                + weight * responseTemperature_C;
            qEvaluated = qReference + derivative ...
                * (responseTemperature_C - referenceTemperature);
            process.top_response_evaluated_flux_weighted_sum = ...
                process.top_response_evaluated_flux_weighted_sum ...
                + weight * qEvaluated;
        end
    end
    code = heatModeCode(result.top.applied_kind, 'top');
    if isnan(process.top_boundary_mode_code)
        process.top_boundary_mode_code = code;
        process.top_requested_kind = result.top.requested_kind;
        process.top_applied_kind = result.top.applied_kind;
        process.top_requested_temperature_C = ...
            result.top.requested_temperature_C;
        process.top_requested_flux_into_domain = ...
            result.top.requested_flux_into_domain_J_cm2_s;
        process.top_reference_temperature_C = ...
            result.top.reference_temperature_C;
        process.top_flux_temperature_derivative = ...
            result.top.flux_temperature_derivative_J_cm2_s_K;
        process.surface_skin_temperature_C = ...
            result.top.surface_skin_temperature_C;
        process.snow_cover_fraction = result.top.snow_cover_fraction;
    elseif process.top_boundary_mode_code ~= code
        process.top_boundary_mode_code = 4;
        process.top_requested_kind = 'mixed_within_outer_step';
        process.top_applied_kind = 'mixed';
        process.top_requested_temperature_C = NaN;
        process.top_requested_flux_into_domain = NaN;
        process.top_reference_temperature_C = NaN;
        process.top_flux_temperature_derivative = NaN;
    end
    bottomCode = heatModeCode(result.bottom.applied_kind, 'bottom');
    if isnan(process.bottom_boundary_mode_code)
        process.bottom_boundary_mode_code = bottomCode;
        process.bottom_requested_kind = result.bottom.requested_kind;
        process.bottom_applied_kind = result.bottom.applied_kind;
        process.bottom_requested_temperature_C = ...
            result.bottom.requested_temperature_C;
        process.bottom_requested_flux_into_domain = ...
            result.bottom.requested_flux_into_domain_J_cm2_s;
    elseif process.bottom_boundary_mode_code ~= bottomCode
        process.bottom_boundary_mode_code = 4;
        process.bottom_requested_kind = 'mixed_within_outer_step';
        process.bottom_applied_kind = 'mixed';
        process.bottom_requested_temperature_C = NaN;
        process.bottom_requested_flux_into_domain = NaN;
    end
end

function code = heatModeCode(appliedKind, side)
% Map applied heat conditions to stable diagnostic codes for one endpoint.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    if strcmp(appliedKind, 'fixed_temperature')
        code = 1;
    elseif strcmp(appliedKind, 'fixed_total_energy_flux')
        code = 2;
    elseif strcmp(side, 'top') ...
            && strcmp(appliedKind, 'linearized_surface_energy_flux')
        code = 3;
    elseif strcmp(side, 'bottom') ...
            && strcmp(appliedKind, 'free_drainage_internal_energy')
        code = 3;
    else
        code = 0;
    end
end

function process = addProcess(process, result, weight, fluxField)
% Add one process only when its equation returned an actual solved flux.
    if isempty(fieldnames(result)), return; end
    if ~process.enabled
        process.enabled = true;
        process.top_flux_into_domain = 0;
        process.bottom_flux_into_domain = 0;
    end
    process.top_flux_into_domain = process.top_flux_into_domain ...
        + result.top.(fluxField) * weight;
    process.bottom_flux_into_domain = process.bottom_flux_into_domain ...
        + result.bottom.(fluxField) * weight;
    process.weight_sum = process.weight_sum + weight;
end

