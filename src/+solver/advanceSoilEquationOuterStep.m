% -------------------------------------------------------------------------
function [model, outcome] = commitAcceptedSurfaceTrial( ...
        model, outcome, request, decision)
% Commit one valid atmospheric surface state to the substep transaction.
%
% This is called only after the nonlinear solve and the surface
% complementarity checks both pass. The result remains a trial surface-domain
% candidate until the outer multi-domain transaction commits.
% Editor: Jizixing Zhu; Date: 2026-07-17.
% Change: 2026-07-20 Jizixing Zhu -- stop writing accepted Y from the soil scheduler;
%   stage the surface-owned storage/runoff result in trial state.
    if ~isfield(request.top, 'surface')
        return;
    end
    depth = decision.storage_end_cm;
    runoff = decision.runoff_cm_s;
    model.built.workspace.step.trial.surface_water.DSTOR = depth;
    model.built.workspace.step.trial.surface_water.DSTOR0 = depth;
    model.built.workspace.step.trial.surface_water.RS = runoff;
    model.built.workspace.step.trial_aux.surface_water.active = true;

    flux = outcome.waterFlux;
    available = request.top.liquid_supply_cm_s ...
        + request.top.surface.storage_start_cm / request.dt_s;
    flux.AVAIL0 = available;
    flux.Infiltration = available;
    flux.Infiltration_act = max(-flux.QMT, 0);
    flux.TopFlux_potential = request.top.evap_demand_cm_s - available;
    flux.runoffHort = runoff; % compatibility field now carries realized overflow
    outcome.waterFlux = flux;
    outcome.surfaceWater = decision;
end
