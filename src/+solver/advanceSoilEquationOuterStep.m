% -------------------------------------------------------------------------
function capacity = maxAttemptCount(dtOuter_s, dtMin_s, strategy)
% Conservative finite bound for preallocating audit records without state growth.
    if isfield(strategy, 'enabled') && ~logical(strategy.enabled)
        capacity = 4; % one nonlinear attempt plus up to three physical active sets
        return;
    end
    shrink = strategy.shrink_factor;
    assert(isnumeric(shrink) && isscalar(shrink) && shrink > 0 && shrink < 1, ...
        'advanceSoilEquationOuterStep:badShrinkFactor', ...
        'strategy.shrink_factor must be in (0,1).');
    acceptedTileBound = ceil(dtOuter_s / dtMin_s) + 1;
    retryLevelBound = ceil(log(dtMin_s / dtOuter_s) / log(shrink)) + 2;
    capacity = 4 * acceptedTileBound * max(2, retryLevelBound);
end

