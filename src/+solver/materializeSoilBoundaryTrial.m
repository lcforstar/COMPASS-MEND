function request = materializeSoilBoundaryTrial( ...
        built, currentFlux, kt, tStart_s, dt_s)
%MATERIALIZESOILBOUNDARYTRIAL  Freeze water, heat, and dry-air BCs for one trial.
%
%   One immutable request is created immediately before every solver attempt.
%   Retrying with a smaller dt creates a new request at the same physical start
%   time. Process solvers receive their own typed subsection; no solver reads a
%   moving forcing cursor or independently chooses a boundary value.
%
%   Heat-boundary ownership is state-dependent but not independently lagged:
%   the atmospheric surface supplies one affine, grid-mean energy-flux
%   response to the z=0 soil temperature for bare, partial-snow, and full-snow
%   states. The staged
%   workspace.snow.boundary_state has priority during this transaction, while
%   accepted Y.snow is only the standalone/fallback view.  Water, heat, and
%   dry-air requests are frozen together for the same h/U/P_g trial interval.
%
%   Editor: Jizixing Zhu; Date: 2026-07-15.
%   Change: 2026-07-17 Jizixing Zhu -- pass the accepted snow-cover state so
%           surface-temperature policy becomes a snow-insulated flux policy
%           whenever Tss is a snow/composite skin rather than exposed soil.
%   Change: 2026-07-17 Jizixing Zhu -- pass accepted snow thermodynamic energy and
%           the coupled energy tolerance to suppress unresolved phase tails.
%   Change: 2026-07-17 Jizixing Zhu -- prefer the staged current-step snow
%           candidate so snowfall/melt switches the soil heat BC in the same
%           transaction; accepted Y.snow remains the rollback fallback.
%   Change: 2026-07-17 Jizixing Zhu -- require and read harmonic Tbh only for the
%           seasonal bottom-temperature policy; other modes leave it undefined.
%   Change: 2026-07-18 Jizixing Zhu -- pass snow ice content and reserve the shared
%           column flux boundary for full, solid snow cover.
%   Change: 2026-07-19 Jizixing Zhu -- materialize the CLM-style affine
%           surface-energy response for every atmospheric top-heat trial.
%   Change: 2026-07-19 Jizixing Zhu -- give the nested scalar closure's
%           frozen interface-temperature trial priority over SCOPE Tss.
%   Change: 2026-07-20 Jizixing Zhu — fail before solve when a water-only
%           MODFLOW interface is combined with undefined heat, gas, or N BCs.

    assert(isnumeric(kt) && isscalar(kt) && kt >= 1, ...
        'materializeSoilBoundaryTrial:badIndex', 'kt must be a positive scalar index.');
    request = struct('schema_version', 1, ...
        't_start_s', tStart_s, 't_end_s', tStart_s + dt_s, 'dt_s', dt_s);
    atmospheric = atmosphere.sliceForcing(built.forcing, kt);
    request.atmosphere = atmospheric;
    groundwaterDriver = struct('GroundwaterCoupling', 0);
    if isfield(built.workspace, 'boundary') ...
            && isfield(built.workspace.boundary, 'groundwater_driver')
        groundwaterDriver = built.workspace.boundary.groundwater_driver;
    end
    request.groundwater = groundwater.stageBoundary( ...
        built, kt, tStart_s, dt_s, groundwaterDriver);
    request.water = solver.materializeWaterBoundaryTrial( ...
        built, currentFlux, tStart_s, dt_s);
    if request.groundwater.modflow.enabled
        request.water.bottom = struct( ...
            'kind', 'modflow_fixed_head', ...
            'head_cm', request.groundwater.modflow.fixed_head_cm, ...
            'requested_flux_into_domain_cm_s', NaN, ...
            'modflow', request.groundwater.modflow);
        unsupported = strings(0, 1);
        if switchEnabled(built, 'lThmrlefc'), unsupported(end + 1) = "heat"; end
        if switchEnabled(built, 'lSoilairefc'), unsupported(end + 1) = "dry_air"; end
        if switchEnabled(built, 'lNefc'), unsupported(end + 1) = "nitrogen"; end
        assert(isempty(unsupported), ...
            'materializeSoilBoundaryTrial:unsupportedModflowPhysics', ...
            ['MODFLOW currently defines only water_only_external_boundary; ', ...
             'disable %s or define their groundwater interface contracts.'], ...
            strjoin(cellstr(unsupported), ', '));
    end

    heatOn = switchEnabled(built, 'lThmrlefc');
    request.heat = disabledRequest(tStart_s, dt_s);
    if heatOn
        assert(isfield(built.boundary, 'heat'), ...
            'materializeSoilBoundaryTrial:missingHeatSpec', ...
            'built.boundary.heat is required when soil heat is enabled.');
        bottomTemperature = NaN;
        if strcmp(built.boundary.heat.bottom.kind, ...
                'seasonal_bottom_temperature')
            thermal = built.workspace.boundary.thermal;
            assert(numel(thermal.Tbh) >= kt && isfinite(thermal.Tbh(kt)), ...
                'materializeSoilBoundaryTrial:missingBottomTemperature', ...
                ['The runtime bottom temperature must be available before ', ...
                 'a seasonal bottom-temperature trial.']);
            bottomTemperature = thermal.Tbh(kt);
        end
        surfaceTemperature = built.boundary.T_top;
        if isfield(built.workspace, 'scope_step') ...
                && isfield(built.workspace.scope_step, 'thermal') ...
                && isfield(built.workspace.scope_step.thermal, 'Tss') ...
                && isfinite(built.workspace.scope_step.thermal.Tss)
            surfaceTemperature = built.workspace.scope_step.thermal.Tss;
        end
        if isfield(built.workspace, 'surface') ...
                && isfield(built.workspace.surface, ...
                    'soil_interface_temperature_C') ...
                && isscalar(built.workspace.surface. ...
                    soil_interface_temperature_C) ...
                && isfinite(built.workspace.surface. ...
                    soil_interface_temperature_C)
            surfaceTemperature = built.workspace.surface. ...
                soil_interface_temperature_C;
        end
        groundHeatFlux = NaN;
        if isfield(built.workspace, 'scope_step') ...
                && isfield(built.workspace.scope_step, 'fluxes') ...
                && isfield(built.workspace.scope_step.fluxes, ...
                    'soil_top_downward_energy_flux_W_m2') ...
                && isfinite(built.workspace.scope_step.fluxes. ...
                    soil_top_downward_energy_flux_W_m2)
            groundHeatFlux = built.workspace.scope_step.fluxes. ...
                soil_top_downward_energy_flux_W_m2;
        elseif isfield(built.workspace, 'scope_step') ...
                && isfield(built.workspace.scope_step, 'fluxes') ...
                && isfield(built.workspace.scope_step.fluxes, 'Gtot') ...
                && isfinite(built.workspace.scope_step.fluxes.Gtot)
            groundHeatFlux = built.workspace.scope_step.fluxes.Gtot;
        end
        snowCoverFraction = 0;
        snowIceWaterEquivalent = 0;
        snowThermalEnergy = 0;
        snowForBoundary = [];
        if isfield(built.workspace, 'snow') ...
                && isfield(built.workspace.snow, 'boundary_state')
            snowForBoundary = built.workspace.snow.boundary_state;
        elseif isfield(built.Y, 'snow')
            snowForBoundary = built.Y.snow;
        end
        if ~isempty(snowForBoundary) && isfield(built.parameters, 'snow')
            snowState = surface.snow.diagnoseState( ...
                snowForBoundary, built.parameters.snow);
            snowCoverFraction = snowState.cover_fraction;
            snowIceWaterEquivalent = snowState.ice_water_equivalent_cm;
            snowThermalEnergy = snowState.energy_J_cm2;
        end
        snowThermalTolerance = readNumerics( ...
            built.control.numerics, 'tol_energy_balance_J_cm2', 1e-2);
        topHeatResponse = [];
        if isfield(built.workspace, 'surface') ...
                && isfield(built.workspace.surface, 'top_heat_response')
            topHeatResponse = built.workspace.surface.top_heat_response;
        end
        heatDrivers = struct( ...
            'surface_temperature_C', surfaceTemperature, ...
            'bottom_temperature_C', bottomTemperature, ...
            'air_temperature_C', atmospheric.temperature_C, ...
            'ground_heat_flux_into_soil_W_m2', groundHeatFlux, ...
            'snow_cover_fraction', snowCoverFraction, ...
            'snow_ice_water_equivalent_cm', snowIceWaterEquivalent, ...
            'snow_thermal_energy_J_cm2', snowThermalEnergy, ...
            'snow_thermal_tolerance_J_cm2', snowThermalTolerance, ...
            'top_heat_response', topHeatResponse);
        request.heat = soil.thermal.boundary.materializeRequest( ...
            built.boundary.heat, heatDrivers, tStart_s, dt_s);
    end

    airOn = switchEnabled(built, 'lSoilairefc');
    request.dry_air = disabledRequest(tStart_s, dt_s);
    if airOn
        assert(isfield(built.boundary, 'dry_air'), ...
            'materializeSoilBoundaryTrial:missingDryAirSpec', ...
            'built.boundary.dry_air is required when soil dry air is enabled.');
        pressurePa = atmospheric.pressure_Pa;
        assert(isfinite(pressurePa), ...
            'materializeSoilBoundaryTrial:missingAtmosphericPressure', ...
            'Atmospheric pressure must be finite for a dry-air trial.');
        airDrivers = struct('atmospheric_pressure_Pa', pressurePa, ...
            'column_depth_cm', built.domain.grid.Tot_Depth);
        request.dry_air = soil.gas.boundary.materializeRequest( ...
            built.boundary.dry_air, airDrivers, tStart_s, dt_s);
    end
end

function value = readNumerics(numerics, name, fallback)
% Read one optional immutable numerical control.
% Editor: Jizixing Zhu; Date: 2026-07-17.
    value = fallback;
    if isfield(numerics, name) && ~isempty(numerics.(name))
        value = numerics.(name);
    end
end

function value = switchEnabled(built, name)
% Read one explicit model switch.
% Editor: Jizixing Zhu; Date: 2026-07-15.
    value = isfield(built.control.switches, name) ...
        && built.control.switches.(name) == 1;
end

function request = disabledRequest(tStart_s, dt_s)
% Keep a fixed shape for disabled process requests.
% Editor: Jizixing Zhu; Date: 2026-07-15.
    request = struct('schema_version', 1, 'enabled', false, ...
        't_start_s', tStart_s, 't_end_s', tStart_s + dt_s, 'dt_s', dt_s, ...
        'top', struct(), 'bottom', struct());
end
