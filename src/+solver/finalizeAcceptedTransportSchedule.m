function result=finalizeAcceptedTransportSchedule(schedule,expectedElapsed_s)
%FINALIZEACCEPTEDTRANSPORTSCHEDULE Time-average accepted liquid-flux tiles.
%
%   schedule is the schema emitted by solver.recordAcceptedTransportTile.
%   result retains QL/QL_h/QL_T/QL_a [cm s^-1] as accepted-dt-weighted outer
%   means for an outer-step transport solve. The final-tile constitutive
%   diagnostics remain a separate output contract.
%
% Editor: Wenjie Liu; Date: 2026-09-21.
    if nargin<2,expectedElapsed_s=[];end
    result=struct();
    if isempty(schedule),return;end
    assert(isstruct(schedule)&&isscalar(schedule) ...
        &&isfield(schedule,'schema_version')&&schedule.schema_version==1 ...
        &&isfield(schedule,'dt_s')&&isfield(schedule,'tile_count') ...
        &&schedule.tile_count==numel(schedule.dt_s), ...
        'solver:transportScheduleFinalizeSchema', ...
        'Accepted liquid-transport schedule schema is invalid.');
    weights=schedule.dt_s(:);
    elapsed=sum(weights);
    assert(elapsed>0&&isfinite(elapsed)&&all(isfinite(weights))&&all(weights>0), ...
        'solver:transportScheduleFinalizeTime', ...
        'Accepted liquid-flux averaging requires positive finite tile times.');
    if ~isempty(expectedElapsed_s)
        assert(isnumeric(expectedElapsed_s)&&isscalar(expectedElapsed_s) ...
            &&isfinite(expectedElapsed_s)&&expectedElapsed_s>0 ...
            &&abs(elapsed-expectedElapsed_s)<=1e-9*max(1,expectedElapsed_s), ...
            'solver:transportScheduleFinalizeCoverage', ...
            'Accepted liquid-transport tiles do not cover the outer duration.');
    end
    result=struct('schema_version',1,'elapsed_s',elapsed, ...
        'tile_count',schedule.tile_count, ...
        'time_representation','accepted_tile_dt_weighted_mean', ...
        'spatial_order','bottom_to_surface_elements');
    for name={'QL','QL_h','QL_T','QL_a'}
        key=name{1};
        assert(isfield(schedule,key)&&size(schedule.(key),2)==numel(weights) ...
            &&all(isfinite(schedule.(key)(:))), ...
            'solver:transportScheduleFinalizeFlux', ...
            'Accepted transport schedule lacks valid %s tiles.',key);
        result.(key)=schedule.(key)*weights/elapsed;
    end
end
