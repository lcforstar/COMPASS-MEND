function balance = emptySurfaceSoilWaterBalance()
%EMPTYSURFACESOILWATERBALANCE  Undefined combined boundary water ledger.
%
%   The ledger begins at post-canopy/post-snow liquid supply delivered to the
%   surface reservoir and ends at soil storage, bottom loss, root uptake, and
%   surface runoff. It is intentionally not labelled a whole-land budget.
%
%   Editor: Jizixing Zhu; Date: 2026-07-17.
    balance = struct('has_data', false, ...
        'liquid_supply_mm', NaN, ...
        'surface_evaporation_mm', NaN, ...
        'runoff_mm', NaN, ...
        'bottom_loss_mm', NaN, ...
        'root_sink_mm', NaN, ...
        'surface_storage_change_mm', NaN, ...
        'soil_storage_change_mm', NaN, ...
        'total_storage_change_mm', NaN, ...
        'residual_mm', NaN);
end
